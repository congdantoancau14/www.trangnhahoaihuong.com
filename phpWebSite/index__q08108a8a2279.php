		Vỹ dạ thôn có lão Vương tôn là Thúc Giạ,<br />
		Ưng ca ưng hát, ưng giã gạo hò khoan,<br />
		Ham vui điệu cổ thi đàn,<br />
		Nghe câu tuyệt xướng muôn vàng cũng mua.<br />
<br />
		Sông Vị ngồi câu, vuốt chòm râu ông Lữ Vọng ,<br />
		Lên dù xuống võng đã phá tan giấc mộng phiền ba;<br />
		Nghêu ngao thú vị yên hà,<br />
		Tám mươi xuân vẫn đượm đà với xuân.<br />
<br />
Bài thơ họa sau đây là của Cụ Ngư  Xuyên  Hoàng Xuân Vịnh <br />
<br />
		Còn biết bao xuân với nụ cười<br />
		Tám mươi, rồi tới chín mười mươi...<br />
		Nào thơ, nào rượu, ham vui bạn,<br />
		Vì nước,  vì non, phải mến đời<br />
		Vầy tiệc đình hưu nhiều chuyện thú,<br />
		Xem tuồng sân khấu lắm trò chơi<br />
		"Thọ bôi" một chén đường muôn dặm<br />
		Mượn cánh hồng mang đến tận nơi.<br />
<br />
	Cuối mùa xuân năm Mậu tuất 1958 (82 tuổi) Tiên sinh bỗng bị đau nặng. Trong khi ngọa bịnh, Tiên sinh vẫn thiết tha với  bạn thơ, cho nên đã có bài“Bệnh trung ngâm” như sau đây :<br />
<br />
		Lão phu đà vướng bệnh tương ty,<br />
		Mơ mộng khôn khuây bởi cớ gì ?<br />
		Đã biết  nhà Nho theo chánh đạo<br />
		Thường mong cửa Phật đến qui y <br />
		Đường xa cậy có tin thanh điểu<br />
		Xuân muộn còn nghe tiếng tử qui<br />
		Duyên nợ văn chương tình hữu ái<br />
		Dễ gây thương nhớ bạn làng thi.<br />
<br />
	Các bạn làng thơ xa gần  đều rất đổi băn khoăn: nào săn sóc thuốc thang, ân cần thăm hỏi, nào lập đàn tụng kinh niệm Phật để cầu an cho Tiên sinh.<br />
	<br />
Cụ An Đình  Trần Kinh đã họa lại bài thơ trên như sau :<br />
<br />
		Thiếu chi thi bá dưới âm ty<br />
		Thúc Giạ xin ông chớ vội gì<br />
		Rán ở lại đây  nơi bạch xã<br />
		Để cùng vui với bạn ô y <br />
		Câu văn lành mạnh lời kim thạch<br />
		Chén rượu thơm nồng vị thục qui<br />
		"Bình phục" hôm nay mừng chúc Cụ<br />
		Tấc thành kính họa mấy vần thi<br />
<br />
Cụ Quì Ưu Nguyễn Đôn Dư cũng họa như sau :<br />
<br />
		Mái tóc đài gương nặng tuyết ty<br />
		Phong sương dẫu nhuốm chửa can gì<br />
		Tâm hồn đau khổ nào ai biết <br />
		Dung mạo nhân từ thấy vẫn y<br />
		Mỏi gối còn  đua tài thất bộ<br />
		Nhức đầu vẫn nhớ  nguyện tam qui<br />
		Ơn Trời, ơn Phật phù trì Cụ<br />
		Khỏe cánh bền quai  với bạn thi<br />
<br />
	Khi bình phục, nhân được các thi hữu đặt tiệc rượu mừng, Tiên sinh có tạ lại bằng một bài thơ :<br />
<br />
		Nâng cao chén rượu của làng thi<br />
		Gây tấm yêu đương dạ kỉnh vì<br />
		Đông đủ khéo vầy duyên hội ngộ,<br />
		Âu sầu đã ngớt bệnh tương ty<br />
		Tai ương, Phật độ đà qua khỏi<br />
		Phước lộc ,Trời cho nỏ thiếu chi<br />
		Bi, hỷ, tương quan tình bạn hữu<br />
		Tiệc trà thân ái lão xin ghi <br />
<br />
	Đến  tết Kỷ hợi 1959, bên cạnh phu nhân tuổi đà tám chục, xung quanh có thứ thiếp và con cháu đầy đàn, Tiên sinh lại nhắp chén rượu mừng xuân mà ngâm câu tự thuật:<br />
<br />
		Đình hưu vách mảy lại ngâm nga<br />
		Tức cảnh câu thi Tết gọi là <br />
		Khỏe cánh tìm hương con bướm liệng<br />
		Vui lòng rủ bạn tiếng oanh ca <br />
		Ngàùnh cây cổ thụ đương sây lá<br />
		Ngọn bút tao đàn cứ trổ hoa<br />
		Tuổi thọ trời cho ai có hỏi<br />
		Thưa rằng: nay đã tám mươi ba.<br />
<br />
	Cụ Đông Viên Phạm Huy Toại đã họa vần như sau:<br />
	<br />
		Nhớ khách đêm hằng tựa bóng Nga<br />
		Tiếp thơ mừng rỡ biết bao là<br />
		Du dương án ngọc gieo vần Lý<br />
		Réo rắt oanh vàng họa tiếng ca<br />
		Nhã khúc tưởng văn Tiềụn Xích Bích<br />
		U hoài khác điệu Hậu Đình Hoa<br />
		Tao đàn nguyên soái lừng Hương Ngự<br />
		Một đấng tam tôn đủ cả ba<br />
<br />
	Đến tết Canh tý 1960 Tiên sinh lại có bài thơ khai bút sau nay:<br />
<br />
		Nửa đêm Trừ tịch đốt lò hương<br />
		Giởũ sách xưa xem chuyện Tống Đường<br />
		Nghe tiếng chuột reo khi sởn gió<br />
		Nhìn con bướm liệng buổi tan sương <br />
		Liễu dăng trước cửa khoe màu lục<br />
		Mai nở quanh sân đượm sắc vàng<br />
		Đề vịnh có đôi câu chuyết thảo<br />
		Gởi thăm thi sĩ bạn  từ chương<br />
<br />
	Những bài thơ làm gần đây nhất, phần nhiều là để tỏ lòng mộ đạo:<br />
			NGUYỆN  TU<br />
<br />
		Cứ loanh quoanh mãi cuộc phiền ba<br />
		Tuổi tám mươi tư cũng đã già<br />
		Chưa mến quyển kinh và quyển kệ<br />
		Vì ham câu  lý với câu ca <br />
		Nếu trò ổi lỗi không xem lại<br />
		Thì chuyện luân hồi khó hiểu qua<br />
		Chữ Phật trong lòng tôi có sẵn <br />
		Rồi đây tôi cũng áo cà sa<br />
<br />
					Mùa hạ Canh tý 1960<br />
<br />
<br />
			TIẾNG CHUÔNG LÒNG (bài tuyệt bút)<br />
<br />
		Tiếng chuông lòng dội buổi tan sương<br />
		Đỉnh lễ qui y trước Phật đường<br />
		Soi tỏ tâm linh nhờ đuốc tuệ<br />
		Rưới tan tục lụy sẵn cành dương<br />
		Giữ niềm bác ái không sai chậy<br />
		Thời bệnh sân si khỏi vấn vương<br />
		Tôi cũng như ai phường đạo hữu<br />
		Mong vào cửa Phật đến Tây phương<br />
<br />
					Mùa Thu Canh tý 1960<br />
<br />
	Đầu mùa Thu năm Canh tý 1960, Tiên sinh bị bệnh kết thạch  rất trầm trọng, và phải vào bệnh viện Huế để mổ, Nhờ Bác sĩ tận tâm  lấy được viên đá trong bàng quang, Tiên sinh lại tỉnh dần. Nhìn viên đá ấy, Tiên sinh có thốt ra một câu thơ: Viên đá ba sinh chặn giữa đường. Các thi hữu trước kia lo ngại cho Tiên sinh bao nhiêu, thì lúc bấy giờ mừng rỡ bấy nhiêu; nhiều người đã làm tiếp 7 câu thành những bài luật thi để mừng ngày khỏi bệnh.<br />
<br />
Thực ra, từ đó bệnh Tiên sinh khi tăng khi giảm không chừng, rồi bỗng trở nên nguy kịch vào hồi trung tuần tháng hai âm lịch này. Tuy nhiên, Tiên sinh vẫn tỉnh táo vui vẻ, vẫn niềm nở hỏi han các thi hữu vào thăm viếng, vẫn ưng nghe cô Tôn Nữ Hỷ Khương hầu bên cạnh lần lần ngâm hết các bài thơ của Tiên sinh: nhiều câu đã đưọc Tiên sinh mỉm cười mà khen thưởng. Chiều ngày 3-4-1961, con cháu được phép đưa Tiên sinh trở về Vỹ dạ, Khi nhìn thấy ngõ tre vàng nên thơ, chốn hưu đình ấm cúng, Tiên sinh rất đổi vui sướng và mỉm cười. Thế rồi thi hữu tới thăm phải ngâm thơ, đào nương tới thăm phải ca hát, Tiên sinh vỗ tay mà khen hay. Đến 2 giờ sáng ngày 4-4-1961, tức 19 tháng 2 năm Tân sửu, nhằm ngày vía Đức Quán Thế Âm, Tiên sinh lặng lẽ nhắm mắt, trút hơi thở cuối cùng, để lại một mối tiếc thương vô hạn trong giới văn nhân thi sĩ Việt Nam .<br />
<br />
	Từ trước đến nay, những thơ xướng họa của Tiên sinh, vừa Nôm vừa chữ, kể có trên nghìn bài. Thơ Nôm trước hồi đại chiến, có tập Tình Thúc Giạ, đã trích in năm 1942; sau hồi đại chiến có tập Đời Thúc Giạ, sắp xuất bản. Thơ chữ Hán đã góp thành Lộc Minh thi thảo cũng chưa in.<br />
<br />
	Những khúc hát góp, đã trích in năm 1954 thành tập Bán Buồn Mua Vui và được truyền tụng rất nhiều: những câu tình tứ lâm ly, văn chương chải chuốt, ta thường được vẳng nghe nơi núi Ngự sông Hương, trong ấy có rất nhiều câu của Tiên sinh, đã biến thành ca dao từ lâu và rất được  phổ thông trong quần chúng.<br />
<br />
	Hài kịch thì có  tập Tào Lao, viết phỏng theo truyện cổ . Còn quyển Tuồng Lộ Địch thì Tiên sinh đã phỏng theo sự tích quyển tuồng Le Cid của nhà văn nước Pháp là Corneille, mà đặt thành vở tuồng cổ Việt Nam; ngày trước đã có đăng ở các báo Đông Phong, Thần Kinh tạp chí vân vân, và đã được rất nhiều  thi ca đề tặng của các thi hữu xa gần; thường đã được diễn  nhiều lần trên sân khấu ở các tỉnh Thanh Hóa, Bình Định, Quảng Nam vân vân, và nhiều nhất là ở  Huế. Buổi diễn lần đầu tiên tại rạp Xuân Kinh Đài ở Kinh đô, Tiên sinh có làm một bài thi kỷ niệm nhan đề là “Khai diễn tuồng Lộ Địch” như sau:<br />
<br />
		Rạp hát Vương tôn đã khóac màn<br />
		Đã ra sân khấu giữa Trường an<br />
		Hiếu tình ngắm rõ gương bi kịch<br />
		Thanh sắc mừng thêm vẻ lạc quan<br />
		Giá ngọc treo cho đào Hữu Hạnh<br />
		Nhà vàng dựng để kép Phương Lan<br />
		Ham vui điệu cũ câu tuồng mới<br />
		Tri kỷ xin chào bạn khán quan<br />
<br />
	Tuồng này đã xuất bản năm 1936, va mới tái bản năm 1959.<br />
	Ngoài Bắc trong Nam, tao nhân mặc khách mà biết tiếng Tiên sinh cũng là nhờ có những tác phẩm nói trên. Cụ Phú Khê Đoàn Tá, Chủ súy Liên Thành thi xã ở Phan Thiết đã có bài sau này:<br />
<br />
		Thơ "Tình Thúc Giạ" nhớ từng câu,<br />
		Lộ Địch tuồng xem cũng thuộc làu.<br />
		Đạo lý cương thường  gương vạn thuở<br />
		Văn chương đức hạnh tiếng ngàn thu <br />
		Nguồn Tiên lá ngọc là thân trước<br />
		Cõi Phật mình vàng hẹn kiếp sau<br />
		Cầu chúc hưu ông thêm thọ mãi<br />
		Giữ nền quốc túy đặng dài lâu<br />
<br />
	Cuộc đời của Tiên sinh là cả một bài thơ diễm lệ, thân thế của Tiên sinh là nơi kết hợp tài ba, Tiên sinh là một bậc thi bá, một đấng vương tôn, một vị trọng thần, một nhà học giả, một nghệ sĩ, một Phật gia; liêm khiết mà phong lưu, cao quí mà khiêm nhường, trong nói năng cử chỉ không hề lộ vẻ công hầu khanh tướng, lá ngọc cành vàng...<br />
<br />
	Năm 1957, để giới thiệu Tiên sinh với các  bạn làng thơ Saigon tôi đã lạm có mấy câu :<br />
<br />
		Vui thú đình hưu chốn cựu kinh<br />
		Tám mươi xuân lẻ bậc tài danh<br />
		Cầm, ca, thi, tửu, quên đầu bạc<br />
		Phong, nguyệt, giang, sơn, nhớ tuổi xanh<br />
		Thúc Giạ Vương tôn ngành Vỹ Dạ<br />
		Ưng Bình chủ súy xã Hương Bình<br />
		Thừa nhan chạnh nhớ gia nghiêm trước<br />
		Thanh khí còn ghi một mối tình<br />
<br />
	Nay được tin Tiên sinh tạ thế, tôi vô cùng xúc động, nên lại xin có mấy vần thơ để khóc Tiên sinh:<br />
<br />
		Mây phủ sông Hương núi Ngự Bình<br />
		Thôi, đà che khuất bóng văn tinh! <br />
		Câu thơ điệu cổ càng thêm hiếm<br />
		Khúc hát thời xưa khó lựa thành<br />
		Dở mấy phong thơ mà gạt lệ<br />
		Ngắm vài bức ảnh đến tàn canh<br />
		Sao cho khuây khỏa niềm thương nhớ ?<br />
		Thúc Giạ thi ông có thấu tình ?<br />
<br />
Saigon, tháng 4 năm 1961<br />
<br />
Phù Giang PHAN THÊ ROANH<br />
(Giám Đốc Trường Đại Học Sư Phạm Sài gòn, tháng 4, 1961)<br />
