<h3><h3>Tiểu sử Ưng Bình Thúc Giạ Thị (1877-1961)</h3></h3>


<br />
<h3>Một Đại Thi Gia Miền Trung</h3>
<h3>Phan Thê Roanh</H3>
<br />
<br />
Bên con đường rộng qua thôn Vỹ Dạ, gần kinh thành Huế, trước một khu vườn rậm rạp thuộc phủ Tuy Lý, trên bờ sông Hương, khách qua lại thương nhìn thấy một cái cổng xây trên đề ba chữ: "Chu hương viên", hai bên có kèm một đôi câu đối chữ Hán:<br />
<br />
<i>Khoái mã trưòng chu đông tây đắc lộ,<br />
Hầu môn cự thất tả hữu vi lân.</i><br />
<br />
Và một đôi câu đối Nôm:<br />
<br />
<i>Ưng học thi tiên, thẳng đó một đường lên Vỹ Dạ<br />
Muốn nghe kinh Phật, cách đây vài cửa đến Ba La.</i><br />
<br />
Từ cổng vào mấy chục thước, giữa đám cây xanh, ẩn hiện một  tòa nhà ngói, không tráng lệ nguy nga, nhưng đầy ý thơ dấu cổ, với  sân lát bến xây, tường hoa non bộ, bên trong thì viện sách, hiên đàn, lầu thơ, đài Phật, hoành phi, câu đối, sập gụ, ghế bành. Chủ nhân, đầu tóc bạc phơ, vóc người mảnh khảnh, dáng điệu ung dung, mắt sáng như gương, miệng cười như hoa nở. Đó là Thúc Giạ Ưng Bình lão tiên sinh, một thi ông nức tiếng của làng nho nước nhà.<br />
  <br />
Tiên sinh là con Cụ Hiệp tá Tiểu Thảo Hồng Thiết, mẹ là bà Nguyễn Thị Huệ, cũng thông thạo chữ Hán, có những bài thơ truyền tụng: Nhớ quê, thượng cầm hạ thú, xuất gia ..., Tiên sinh là cháu nội Đức ông Tuy Lý Vương (một  đại thi hào Việt Nam, tác giả Vỹ Dạ hợp tập). <br />
  <br />
Tiên sinh sinh năm Đinh Sửu, 1877, tốt nghiệp trường Quốc học Huế, đỗ đầu kỳ thi ký lục năm 1904, đỗ Cử nhân Hán học năm Kỷ Dậu,1909 (33 tuổi).<br />
  <br />
Tiên sinh bắt đầu làm Ký lục năm 1904, sau bổ Tri huyện, lần lượt<br />
thăng Tri phủ, Viên ngoại, Thị lang, Bố chánh, Tuần vũ, Phủ Doãn Thừa Thiên, rồi về hưu và thăng Thượng thư trí sự năm 1933 (57 tuổi)<br />
  <br />
Sau đó, Tiên sinh có làm Hội trưởng hội Truyền bá Quốc-ngữ  Trung kỳ năm 1939-1940, viện trưởng Viện Dân biểu Trung kỳ năm 1940-1945, thăng Hiệp Tá Đại Học Sĩ năm 1943 (67 tuổi ).<br />
  <br />
Tiên sinh đã từng được thưởng nhiều huy chương, như  Đệ nhị hạng  Long bội tinh, Đệ nhị hạng Kim Khánh, Đệ ngũ hạng Bắc đẩu bội tinh, Huy chương Hàn lâm viện... Tính người vui vẻ, cử chỉ tự nhiên, đức độ khác thường, lại thêm hiếu khách, cho nên Tiên sinh đã được bạn hữu nể vì, nhân dân mến phục. <br />
