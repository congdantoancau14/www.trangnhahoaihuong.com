      Đọc bài 001 “Ðộng Huyền Không” thấy phần trình bày khá chu đáo . <br />
Dịch giả có phổ biến bản viết tay (nhưng không ghi tên người viết, hoặc giả có mà tôi chưa đọc tới) lại có bản Unicode.  Người xử dụng, sau khi so sánh hai bản chữ Hán có thể tin vào bản Unicode và dùng rất tiện lợi.<br />
Kế đó là phần dịch thơ, dịch nghĩa và chú thích;  phần chú thích khá phong phú.<br />
Tiện đây xin ghi lại vài lỗi TYPO:<br />
1) Phần phiên Hán-Việt, câu 4: TÚNG hữu Vương Duy (2) họa bất thành.<br />
