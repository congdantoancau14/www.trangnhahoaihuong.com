<h3>Ngày Tháng Bồng Bềnh</h3>



<b>NGUYỄN VĂN SÂM</b><br />
<br />
1. <i>Những người muôn năm cũ, Hồn ở đâu bây giờ?</i> Câu thơ xót xa cho hình ảnh quá khứ bị vùi chôn chợt hiện lên như phép lạ đánh bật dậy dĩ vãng lâu nay lấp kín dưới sâu thẳm của địa tầng ký ức khi người ca sĩ có vẻ mặt rất trẻ thơ vừa mới được hoan nghênh nồng nhiệt trên sân khấu một hai màn trước rụt rè hỏi tên tôi, rồi mừng rỡ xác nhận nàng từng ngồi trong giảng đường nghe thầy thao thao trên bục giảng.<br />
<br />
"Thầy giảng hay lắm." Cách nói xác định, trang phục lộng lẫy nổi bật vẻ sang trọng đối diện bộ quần áo bình thường, bày bán trong những tiệm bình dân nhan nhản khắp nước Mỹ trên mình tôi lúc đó, cộng với bộ mặt bơ thờ - chợt nhớ lại khi mình chắc lưỡi chải vội mái tóc trước khi đến đây - khiến tôi mỉm cười, vừa tội nghiệp vừa chua xót. Tội nghiệp cô học trò cũ, thật thà như đếm. Chua xót mình, tang thương, lạc lõng, vẫn còn mang bộ mặt ngái ngủ, dật dờ trong cuộc mộng du mười năm dưới lời trù ếm của những tên phù thủy thời đại.<br />
<br />
Người ca sĩ vẫn đứng im trong vị thế cũ, ké né, khép nép, tay chân như thừa thải, trái hẵn với vẻ mặt tươi mát, tự tin lúc trình diễn. Thấy một chút gì đó hãnh diện về quá khứ. Ít ra điều mình nói đã có người nghe, thời gian làm tròn vai trò người thầy đã tạo được hảo tượng – hay nhờ nền giáo dục, luân lý Việt Nam? Tôi lại mỉm cười. Câu nói thiệt tình, nhưng chuyện xưa đã nhạt nhòa, mất hút theo những thay đổi. Chỉ còn chuyện có thật là là nãy giờ tôi đã ngồi im, mắt dán chặt lên sân khấu, đắm chìm trong âm thanh ngọt ngào, tưới trẻ, phủ tràn không khí tình tứ của những điệu ngâm, chẻ, láy duyên dáng, ngọt lịm. Tiếng hát thuần túy quê hương, tiếng hát của tuổi trẻ yêu đời, của duyên hải nên thơ rót thành chuỗi âm thanh sóng vỗ rì rào trong đêm thanh lặng gió, trên bờ cát hun hút dài, hòa điệu tiếng thùy dương xào xạc gợi nhớ bãi dứa thân mật, bãi dâu sang trọng, bãi cát mộng mơ trong những đêm thức suốt sáng thưởng thức nhạc sóng bất tận, mơ làm một con tàu băng mình vào những cuộc hải hành… Lời ca đam mê, hóa thân vào hoàn cảnh, đã đùa giỡn, xô đuổi, lả lướt, mê hoặc lòng tôi sau thời gian dài chai đá, kéo hồn ra khỏi xác, lâng lâng với nỗi buồn nhè nhẹ, xao xuyến về cuộc tình tan vỡ xa xưa…<br />
