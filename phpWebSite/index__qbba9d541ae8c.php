"Sư anh, nói dóc vừa vừa chứ, muốn tạo cho mình lại nói là vì con. Con nó thèm vào cái nhà của anh? Tốt nghiệp, đi làm chỗ nào nó mua nhà chỗ đó vừa ý hơn căn nhà anh đổi mấy chục năm đời đứng tiệm."<br />
<br />
Tôi nói một mình nhưng để phân trần với hai cô học trò cũ:<br />
<br />
- Vậy không! Mời họp mặt văn nghệ thì từ chối, tối ngày đứng đằng tiệm, nhưng hễ động dao động thớt chủ tịch, đại diện này nọ thì có mặt có mặt có tên. Phải phục là họ hay, nhanh chân, lẹ miệng.<br />
<br />
Tôi trở lại phòng khách. Câu chuyện vẫn dòn tan về tình hình văn nghệ hải ngoại, về thị trường băng nhạc, về những bài viết mới, về những người viết về ý thức trách nhiệm và vì ước muốn thủ đắc một điều gì đó trong cuộc sống.<br />
<br />
Tốt hơn mình nên nghe. Nhân tâm tùy ý thích, tùy bản tính và khả năng từng người. Sự tốt xấu không thể nói hết trong một buổi họp mặt ngắn. Tôi lơ đãng hút thuốc, để hồn theo điệu nhạc êm đềm của những bản nhạc tình phát ra từ hai cái loa đặt ở hai góc phòng đối diện. Tiếng hát nức nở, thê lương, réo rắt phảng phất từng chút của những tiếng ca nổi danh.<br />
<br />
Tôi hỏi T., người luôn hãnh diện khi kể về những phi vụ nguy hiểm và những công tác khó khăn lúc chịu trách nhiệm phi đoàn ở miền Trung. T. lắc đầu. Tôi chịu. Người bạn văn nhăn trán như để phân biệt hơn âm thanh. K. đợi cho mọi người có một thời khoảng đủ để chú ý mới thong thả:<br />
<br />
- Ca sĩ X. đó xuất hiện từ lâu rồi nhưng không lên, cứ ở hạng B hoài.<br />
<br />
Tôi cười: <br />
<br />
- Như T. mới tài. Dạy vợ thế nào không biết mà ca càng ngày càng hay. Bây giờ Hải là một giọng ca ăn khách ở hải ngoại đó.<br />
<br />
T. được dịp kể công, giọng một chút gì đó hãnh diện:<br />
<br />
- Ca hay thì có, nhưng mình giữ hai đứa nhỏ mệt đứ đừ. Mỗi tuần mấy tối. Mới đây nàng lại làm một vòng Cali thâu băng cả tháng, hamburger làm chuẩn. Chán tới cổ họng.<br />
<br />
K. chọc:<br />
<br />
- Cái khổ không phải ở chỗ coi con một tháng. Khổ ở chỗ vắng nàng 30 đêm. Hèn chi lúc Hải đi Cali, cứ nghe ông than thiếu tiền. Ăn hamburger làm sao thiếu tiền được. Sợ trách nhiệm, tôi đâu dám cho mượn.<br />
<br />
Người bạn văn nhìn tôi, trao đổi ý. Có sự thân mật trong sự châm chọc. Cười cho quên đời. Hai người chồng của hai cô học trò thường nhắc lại điều này.<br />
<br />
Người bạn hội nhập vào không khí vui của gian phòng thật nhanh:<br />
<br />
- Còn có khả năng để mượn tiền, đời còn chút nào có ý nghĩa, ông nầy từ lâu không còn khả năng để mượn tiền nữa. Đời hiu hắt từ lâu.<br />
<br />
Cả bọn cười vang vui vẻ. Chợt nhớ đến hoàn cảnh mình. Người đi hẵn có lý do, nhưng người ở lại đối diện với nhiều vấn đề. Câu đùa trên là một. Con cái là hai. Đứa con gái lớn, nhiều khi có những chuyện không nói được với cha, nằm khóc rấm rứt trong phòng. Đang tuổi lớn, nguyên tắc căn bản của con gái, phải tự khám phá, không có một người đàn bà để giảng dạy. Cô đơn và tủi phận thiệt thòi. Tại ai? Vì sao? Tôi đưa tay sờ vào túi áo trên. Cái thư đứa nhỏ viết cho bạn, bỏ không gửi, tình cờ thấy được, giữ như một tài liệu chứng minh sự thiếu sót bổn phận của mình với con, như một sự thúc thủ trước hoàn cảnh. Theo thời gian rồi hai đứa sẽ lớn lên, bắt chộp được đó đây vài điều khôn, nhưng chắc chắn sẽ thiếu sự tế nhị cần thiết của thiếu nữ Việt, không đủ niềm tự tin và tính phớt tỉnh rất dễ sống của phụ nữ Mỹ. Tội nghiệp của những nụ hoa đương nở thiếu bàn tay chăm sóc vun phân, tưới nước , tỉa cành. Từng chịu đựng và coi đời như không như tôi lắm khi còn xót xa lúc tự mình tìm viên thuốc khi bịnh hay về nhà nửa khuya sau buổi học muộn phải ăn quây quá miếng cơm lạnh tanh, huống chi tuổi trẻ dễ dao động và nhiều mặc cảm?<br />
<br />
Tôi hết hứng thú góp chuyện, ngã lưng vào ghế trường kỷ, đốt điếu thuốc, thả trí lông bông theo tiếng nhạc. Cuộc thảo luận bàn tán vẫn sôi nổi. Mấy đứa nhỏ vẫn cãi nhau chí chóe bằng thứ tiếng Mỹ 100%. Không ai ngạc nhiên trước chuyện đó, trừ tôi, với một nỗi niềm tiêng tiếc và một sự bi quan vô bờ về nền tảng gia đình và tương lai cộng đồng Việt.<br />
<br />
Bưng hộp sữa ra tiếp tế thêm cho nhóm đàn ông. Dung nói với mấy đứa nhỏ:<br />
<br />
- Lại gambling, các con nên chơi gì khác hơn là trò chơi đó. Cãi nhau ồn quá!<br />
<br />
Mấy đứa được dịp nhao nhao:<br />
<br />
- This isn’t gambling, Mom! You see, this is something that helps us with our studying.<br />
<br />
Tiếng ai đó nhận xét:<br />
<br />
- Tụi nhỏ bay giờ như vậy không, nói tiếng Mỹ tối ngày!<br />
<br />
Có trời mà cản nổi! Tụi nó đâu muốn bị rầy la, cũng không muốn cha mẹ bực mình, có đứa còn mắc cỡ khi phải nói với người lớn bằng tiếng Mỹ nữa, nhưng lỡ bị nhét vào vị trí 8 giờ mỗi ngày ở trường, độ 3, 4 giờ được kèm ở tư gia bằng mấy cái đài truyền hình, do một hệ thống giáo chức lẫy lừng, với một ngân khoảng vô tận giảng bài cho mấy trăm triệu người thì tất nhiên không muốn chúng cũng khó lòng không quên tiếng Việt.<br />
<br />
Tôi thấy mình nên góp ý:<br />
<br />
- Đó là tình trạng thoát qua. Như bọn mình qua đây trên dưới ba mươi, lưỡi  cứng, tế bào ngôn ngữ trong não đã định hình khó sửa chữa nên phải nói ngọng nghịu – tôi tán rộng chuyện tế bào ngôn ngữ - cuối cùng thích yên lặng với người Mỹ cũng sở hơn là tía lia như gặp Việt Nam. Tụi nhỏ cũng vậy, nói, nghe tiếng Mỹ ở nhà, ở trường từ lúc còn bé thì nó sợ tiếng Việt là chuyện đương nhiên.<br />
<br />
Người bạn bi quan:<br />
<br />
- Điệu nầy ngại cộng đồng Việt Nam sau nầy bị hòa tan quá. Người mình mà thua những cộng đồng Á châu khác trong việc bảo tồn thì đáng buồn thiệt.<br />
<br />
Tiếng T. hăng hái:<br />
<br />
- Phải viết bài kêu gọi các bậc cha mẹ ngăn chận và sửa chữa chuyện con cái mất gốc. Vẽ cho họ thấy tương lai, gia đình ai lo cho con cái nấy thì chuyện có thể giải quyết được.<br />
<br />
Vâng, ai cũng thấy điều đó, không ai muốn cho con cái mình trở thành Tây, thành Mỹ, nhưng còn công ăn chuyện làm? Rồi thành ra những điều viết lách hôm nay có thể trở thành vô ích. Biết vậy, nhưng làm được gì khác hơn! Đứa con gái nhỏ của mình đó. Tôi cười trong đau khổ:<br />
<br />
- Anh em coi bức thư của con nhà văn nè. Mấy ông nghĩ sao? Cha làm thầy con bán sách? Nhiều nguyên nhân lắm, chuyện không dễ như mình tưởng đâu.<br />
<br />
Tôi lúi húi đọc lớn cho mọi người nghe:<br />
<br />
<i>Dear Hà, Hà có mạnh khỏe không? Vân thì same as usual. Summer nầy Vân và family của Vân sẽ đi vacation ở Illinois, chỗ nhà cousin của ba Vân để thăm họ hàng. Vân don’t like it, nhưng mà ba Vân đi đâu Vân phải đi theo đó. Gần bãi trường Vân fell sad vì… thằng Jack cute với thằng John baby face đó mà. Tụi nó nice với Vân lắm. Hổng có gì, you know, nhưng mà, sometimes, I’m proud of myself. Tuần trước Vân took some pictures trong lớp, this is on of them… Cho Vân xin lỗi cái gà bới hand writing của Vân… </i><br />
<br />
Mấy ông thấy đó, đâu có thể qui lỗi tại một ai! Cha mẹ, con cái, hoàn cảnh, lòng tham lam, tình quê hương càng ngày càng héo hon, và cả “tụi nó” ở quê nhà nữa, đã đẩy chúng ta ở đây nên mới có vấn đề.<br />
<br />
Mọi người xì xào bàn tán, mỗi người một ý. Bức thư buồn cười thiệt, nhưng không ai cười. Tôi mệt mỏi đứng dậy thay băng mới vào tape. Chữ viết tay “Những chuyện tình bé bỏng”, băng mẫu, chưa mix. À thì ra tác phểm thai nghén mấy tháng nay. Tôi trở về ghế mơ màng trong không khí nhạc.<br />
<br />
Từng tiếng bass, tiếng trống nâng âm thanh bài ca mới… giọng ca véo von tái tạo những cuộc tình đẹp ngày xưa. Người tình áo tím, tóc thề, má hồng như nụ hoa buổi sớm mơn mởn những lông tơ, thẹn thùng nắm tay nhau trên đường phố Chợ Lớn của tôi. Người tình áo trắng nữ sinh rạng rỡ khi người lính về phép của bạn, của anh. Những mối tình có thật hay ước vọng, đau đớn xót xa hay kết thúc viên mãn, nhưng chắc chắn tiếng hát đã tạo trong trí tôi một người tình để nhớ về, để quên muộn phiền tự mang hiện tại. Những ray rứt chập chờn về người vợ phiêu hốt, đứa con lớn thiếu bàn tay mẫu từ, đứa con nhỏ trên đường quên tiếng Việt, sự mất hút đã hé mở trong viễn tượng của cộng đồng, tiếng ồn ào nhức đầu trong xưởng máy, những nhố nhăng của người chung quanh, những tiếng kêu chới với trên biển, tiếng thở dài vọng lại từ quê nhà ngục tù. Tất cả tan biến theo tiếng hát thênh thang.  Mười năm bềnh bồng với tảng đá ưu tư mang nặng trong hồn một phút nào đó như được trút bỏ.<br />
<br />
Tôi uống cạn ly cà phê bỏ dở lạnh tanh nãy giờ. Chưa bao giờ thấy ngon lạ lùng như vậy.<br />
<br />
- Thời gian thiệt ngộ nghĩnh, mười năm trước mình đâu có ngờ ngày hôm nay, lạc lõng ở quê người, ngồi nghe tiếng học trò cũ để tạm quên thân phận phiêu bạc.<br />
<br />
Không ai chú ý đến câu triết lý vụn không phải chỗ của tôi. Tiếng hát vẫn tiếp tục ru mọi người vào thời gian tươi đẹp xa xưa, âm thanh dao động không gian ấm cúng của căn phòng. Trên tường, bức ảnh chủ nhân vẫn mỉm cười, nụ cười bức họa La Joconde.<br />
