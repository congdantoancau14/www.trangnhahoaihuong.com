<h3><div align="center">***</div></h3>


Tại sao sự lờ mờ, mông lung lại có nét đẹp quyến rũ và có chiều sâu như vậy?  Có phải chăng vì từ xưa đến nay, đã có biết bao nhiêu nghệ sĩ hăng say đi tìm kiếm một phương thức để biểu hiện  thực tại của khách thể một cách khách quan, nhưng sự tìm kiếm đó, cuối cùng, chỉ rơi vào vô vọng, vì có cố gắng cách mấy cũng chỉ có thể thể hiện được cái ảo ảnh của cái “có thực” mà thôi?  Sản phẩm của tư tưởng duy lý này là những tác phẩm nghệ thuật khô khan, bất động, là một sự sao chép nguyên xi những gì tầm mắt có thể thấy được.  Trong khi đó, một người nghệ sĩ biết sử dụng cả trí năng lẫn tàng thức, cả bộ óc lẫn tâm hồn của mình, mới thực sự sống với tác phẩm — chứ không phải chỉ “biểu hiện” nó — nhờ đó mang theo những rung động của sự sống (sinh khí) và sự biến chuyển không ngừng của tạo vật (sự linh động) vào trong tác phẩm của mình.  Nói cách khác, sự mơ hồ và mông lung là một sự biểu hiện chính xác nhất của cái “dường như là”: dường như là cuộc sống, dường như là giấc mơ, dường như là anh, dường như là tôi, dường như là gió, dường như là mây...  Đây chính là bản chất nguyên sơ cuả sự vật:  Nó không hiện diện, mà cũng không khiếm diện, không "có" cũng không "không". Nó luôn luôn vận hành, biến đổi, không bao giờ đứng yên, bất động.<br />
<br />
Không phải ngẫu nhiên mà Nguyễn Trãi, nhân nhìn lại cuộc kháng chiến vĩ đại chống quân Minh, sau một hồi ngẫm nghĩ về sức mạnh của lòng dân (dân mạnh như nước, có thể chở thuyền, cũng có thể lật thuyền), về duyên nghiệp của <i>hoạ</i> và <i>phúc (hoạ phúc đều có manh mối sâu xa, không chỉ một ngày mà có được)</i>, đã thốt lên:<br />
<br />
乾坤今古無窮意<br />
卻在滄浪遠樹煙<br />
Càn khôn kim cổ vô cùng ý,<br />
Khước tại Thương Lang   viễn thụ yên.<br />
(Bài “Quan Hải”)<br />
<br />
Hai câu thơ chữ Hán vô cùng cô đọng trên đây của Nguyễn Trãi phải phóng dịch dài dòng lôi thôi như sau mới mong diễn trọn ý:<br />
<br />
<I>Cái ý nghĩa vô cùng trong trời đất từ xưa đến nay,<br />
Lại ở nơi đám khói trên ngọn cây lờ mờ nẻo xa, bên dòng sông lặng lờ</I><br />
<br />
Bất định, trống rỗng, và mơ hồ, như sương, như khói, như mộng, như tia chớp: đó chính là cái lẽ huyền vi, uyên thâm của vạn vật mà Nguyễn Trãi, hơn 500 năm về trước, đã bắt gặp nơi một đám khói lởn vởn trên ngọn cây lờ mờ xa tít đằng kia.  Giản dị và tự nhiên vậy thôi.  Không phải cái <i>thấy</i> đó có được là nhờ ở kiến thức thông kim bác cổ của Nguyễn Trãi, mà chính là nhờ những gì ông đã chứng nghiệm được qua bao nhiêu thăng trầm, được mất, vinh nhục của cuộc đời ông và của cả dân tộc trong một giai đoạn lịch sử đầy biến động.<br />
<br />
Đây là một bài thơ nổi tiếng trong làng Thiền, tương truyền là của Tô Đông Pha:<br />
<br />
盧山煙鎖浙江潮<br />
未到生平恨不消<br />
到得還來無別事<br />
盧山煙鎖浙江潮<br />
<br />
Lô Sơn yên tỏa Chiết Giang triều,<br />
Vị đáo sinh bình  hận bất tiêu, <br />
Đáo đắc hoàn lai vô biệt sự,<br />
Lô Sơn yên tỏa Chiết Giang triều.<br />
<br />
<I>Mù toả Lô Sơn sóng Chiết Giang,<br />
Khi chưa đến đó hận muôn vàn,<br />
Đến rồi về lại không gì lạ,<br />
Mù toả Lô Sơn sóng Chiết Giang.</I><br />
<br />
Lô Sơn thấp thoáng ẩn hiện sau đám sương mù dày đặc, biến hoá thiên hình vạn trạng, nhìn từ góc độ nào cũng thấy khác nhau, cho nên thấy được cái “chân diện mục” (Tuệ Sỹ) của nó là chuyện khó khăn cực kỳ.  Sự quyến rũ của Lô Sơn là ở nơi những bí ẩn ở đằng sau những đám khói mù mịt kia.  Sự thách thức của Lô Sơn là ở nơi những vách núi cheo leo, những con đường ngoằn ngoèo khó đi kia.  Nhưng ta vẫn liều mạng, một hai phải đến đó cho bằng được.  Và đến nơi rồi, thì sao?  Ta mới vỡ lẽ: “có gì lạ đâu?”, ở trong đó cũng có nước, có đất, có gió, có lửa... như tất cả những nơi khác, vậy thôi.  Và ta quay về.  Quay về với chính mình, với cái tâm của ta. Có điều, cảnh vật thì vẫn vậy — Lô Sơn vẫn toả sóng mịt mù khi ta đến và khi ta đi— nhưng cái người bước ra khỏi Lô Sơn đó đã là một người khác rồi.<br />
<br />
Từ xưa đến nay, những chốn có sương mù, sóng toả, khói bay... , như Lô Sơn, như Đà Lạt, luôn luôn là một nàng tiên nga quyến rũ, không những đối với khách du lịch, mà còn là nguồn cảm hứng bất tận của thi ca và nghệ thuật, phải chăng là vì nó là một sự biểu hiện chính xác nhất cái tự tánh muôn đời của vạn vật: vô thường và rỗng không?<br />
<br />
