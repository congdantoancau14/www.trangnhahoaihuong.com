<h3>***</h3>


Năm 1933, thi sĩ Hàn Mặc Tử đến Đà Lạt và đã cùng với người bạn tri kỷ của mình là nhà thơ Quách Tấn tham quan khắp các thắng cảnh, từ thác Cam Ly đến rừng Ái Ân, đến hồ Than Thở...  Một đêm sáng trăng, đôi bạn thơ nắm tay nhau, thong thả dạo chơi, vừa đi vừa nói chuyện thơ chuyện thẩn, thì đột nhiên được chứng kiến một cảnh tượng huyền ảo chưa từng thấy.  Nhà thơ Quách Tấn kể lại trong quyển <i>Đôi Nét Về Hàn Mặc Tử</i> như sau:<br />
<br />
<i>“[...]Chúng tôi đang nói chuyện thì dường như  có một luồng ánh sáng từ trong hồ bay ra và thoáng nhẹ ở trước mắt. Chúng tôi chú mục: Một đám sương lớn bằng một chiếc chiếu chõng nổi lềnh bềnh trên mặt hồ. Sương mỗi lúc mỗi vun cao và lan rộng, phản chiếu ánh trăng sáng hực cả bốn bên. Trong phút chốc mặt hồ bị khuất hẳn và trước mặt chúng tôi nổi lên một ngọn “núi bông gòn” trắng phau và sáng ánh. Rồi một ngọn gió thổi nhẹ, sương ùn ùn toả ra khắp nơi và cuốn cả trời đất muôn vật. Chúng tôi không còn thấy gì ngoài ánh trăng. Đến nỗi chúng tôi đứng sát bên nhau mà chúng tôi nhìn cũng không thấy rõ được nhau!<br />
<br />
Chúng tôi có cảm giác là trời đất đã tan ra thành  thuỷ tinh và chúng tôi đương đứng lơ lửng giữa hư vô... Sương bay thấm má và một luồng hơi mát chạy khắp châu thân, gây một cảm khoái dìu dịu...<br />
<br />
Tôi nói khẽ cùng Tử:<br />
<br />
“ Mình đương chìm vào mộng hay mộng đương lắng vào mình?”<br />
<br />
 [Tử nói]:<br />
“ Hư thực phân biệt làm sao được! Nhưng chớ nói nhiều... Hãy lắng nghe... Dường như có tiếng thì thầm từ đáy hồ vọng đến. Tôi không mơ đâu nhé! Hãy lắng nghe...” (tr. )</i><br />
<br />
Nhờ “chú mục” cảnh tượng huyền ảo đó, sau này hai thi sĩ đã để lại hai bài thơ có thể nói là hay nhất về Đà Lạt:<br />
<br />
<b>Đà Lạt Đêm Sương<br />
QUÁCH TẤN</B><br />
<br />
<I>Bóng trăng lóng lánh mặt hồ im, <br />
Thời khắc theo nhau lải rải chìm. <br />
Đứng dựa non sao bờ suối ngọc,<br />
Hồn say dịu dịu, mộng êm êm.<br />
<br />
Một luồng sương bạc bỗng từ mô,<br />
Lẻn cuốn vầng trăng cuốn mặt hồ,<br />
Cuốn cả non sao bờ suối ngọc:<br />
Người lơ lửng đứng giữa hư vô.<br />
<br />
Trời đất tan ra thành thuỷ tinh,<br />
Một bàn tay ngọc đẫm hương trinh,<br />
Âm thầm mơn trớn bên đôi má,<br />
Hơi mát đê mê chạy khắp mình.</I><br />
<br />
Bốn câu đầu, đã có thể sánh vai với một bài Đường thi, và có phần tân kỳ.  Hay nhất là câu “thời khắc theo nhau lải rải chìm”.  Ta đã từng nghe âm thanh rơi: “Tiếng vàng rơi xuống giếng / Trăng vàng rơi bờ ao” (Hàn Mặc Tử), nhưng thời gian — một phạm trù phi hình thể — cũng theo bóng trăng rơi chầm chậm xuống mặt hồ, thì thực là độc đáo!  Trong giây phút này chứa đựng cái thiên thu.<br />
 <br />
Nhưng bài thơ sẽ không có gì đặc biệt hơn nữa, nếu không có sương mù.  Khi luồng sương bạc xuất hiện, ở đoạn thứ hai, như cánh tay áo của một tiên nga, cuốn cả vừng trăng, mặt hồ, non sao, bờ suối ngọc, và cả thi nhân, cuốn lên giữa hư không, thì đó cũng là lúc bài thơ chắp cánh bay cao, là lúc cảnh vật và con người hoà thành một, là lúc trời và đất hoà vào nhau và tan ra thành thuỷ tinh.  Hiện hữu hay là không hiện hữu? Thực hay là mộng?  Nếu nói là thực, thì sao không thấy tăm dạng đâu?  Còn nếu nói là mộng, thì sao có bàn tay của tiên nga mơn trớn lên má, khiến cho khắp mình một nỗi đê mê chạy rần rật?  <br />
<br />
Còn đây là bài <B>“Đà Lạt Trăng Mờ”</B> của <B>Hàn Mặc Tử</B>:<br />
<br />
<I>Đây phút thiêng liêng đã khởi đầu,<br />
Trời mơ trong cảnh thực huyền mơ,<br />
Trăng sao đắm đuối trong sương nhạt,<br />
Như đón từ xa một ý thơ.<br />
<br />
Ai hãy làm thinh, chớ nói nhiều!<br />
Để nghe dưới đáy nước hồ reo,<br />
Để nghe tơ liễu run trong gió,<br />
Và để xem trời giải nghĩa yêu. <br />
<br />
Hàng thông lấp loáng đứng trong im,<br />
Cành lá in như đã lặng chìm,<br />
Hư, thực làm sao phân biệt được?<br />
Sông Ngân Hà nổi giữa màn đêm. <br />
<br />
Cả trời say nhuộm một màu trăng,<br />
Và cả lòng tôi cũng nói rằng:<br />
Không một tiếng gì nghe động chạm,<br />
Dẫu là tiếng vỡ của sao băng!</I><br />
<br />
Cũng như bài thơ của Quách Tấn, chất liệu làm cho cảnh vật mờ nhạt đi trong bài thơ này là sương. Sương làm cho muôn ngàn tinh tú trở nên lung linh huyền ảo, làm cho những rặng thông xanh chìm đắm trong mơ màng, trầm lắng và mông mênh. Và, chính ngay lúc đó, là giây phút mối giao cảm thiêng liêng giữa con người và tạo vật bắt đầu nảy nở.<br />
<br />
Tôi thích nhất là tiếng “suỵt!” thầm thì dễ thương của thi sĩ họ Hàn: “Ai hãy làm thinh, chớ nói nhiều!  Để nghe dưới đáy nước hồ reo / Để nghe tơ liễu run trong gió...”  Nói chi cho nhiều!  Cái đẹp và chân lý luôn vượt thoát mọi ngôn từ (dù là ngôn từ của thi nhân).  Hãy lắng lòng lại, hãy buông bỏ hết những định kiến, những ý niệm, những đám mây mù trong tâm hồn để còn trơ lại một bầu trời xanh trong vắt, lúc đó mới có thể ôm trọn và phản chiếu được thực tại một cách trọn vẹn và chính xác nhất, như nó là (as it is).<br />
<br />
"Cả trời say nhuộm một màu trăng."  Chữ say ở đây là một “nhãn tự”, nó làm cho con rồng được điểm xong mắt và muốn rùng mình bay ra khỏi bức tranh.  Đâu là tiếng tơ liễu run run trong gió?  Đâu là tiếng nước thầm thì dưới khe?  Tất cả bây giờ bỗng im bặt.  Cả trời đất ngất ngư, mơ màng.  Vì say! Say trăng!  "Không một tiếng gì nghe động chạm" nữa hết.  Ánh trăng nuốt hết mọi âm thanh, thâu tóm hết mọi sự xao động.  Ở vào khoảnh khắc thiêng liêng kỳ diệu này, dù cho cả tảng sao băng có vỡ tung thành từng mảnh đi nữa, thì tiếng vỡ của nó cũng sẽ tan ngay vào trong luồn ánh sáng đang bàng bạc mênh mông trải khắp nhân gian mà thôi!<br />
<br />
Tôi ngờ rằng nếu hai bài thơ trên đây không có nét mờ nhạt do <i>sương mù</i> mang lại, thì sẽ không có cái <i>thần hồn</i> đó.  <br />
<br />
Thôi Hiệu, trong một buổi chiều chạng vạng, tranh tối tranh sáng, bắt gặp một đám khói nổi bồng bềnh trên mặt sông, không phải đã chạnh nỗi sầu nhớ quê vời vợi đó sao!  Những đám cây ven bến Hán Dương lồng bóng dưới dòng sông lững lờ trôi, những thảm cỏ mơn mởn xanh tươi trên bãi Anh Vũ… đó là là phong cảnh ở đây (nơi đất khách), hay ở quê nhà?  Dường như ta đã từng bắt gặp một cảnh tượng như vậy, ở đâu đó, trong một khoảnh khắc nào đó, trong thời thơ ấu… lúc vừa biết yêu… hay trong một kiếp xa xôi nào đó... Qua làn khói sóng mịt mờ, hình ảnh cố hương càng hiện ra rõ mồn một trước mắt, khiến trong lòng người lữ khách dâng lên một nỗi u hoài mông mênh. 

