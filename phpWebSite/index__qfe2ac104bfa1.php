<h3>Vài Suy Nghĩ Về Truyện Ngắn</h3>



<b>NGUYỄN VĂN SÂM</B><br />
<br />
Ai đã từng đọc sách thế nào cũng biết phân biệt truyện ngắn, truyện dài. Thế nhưng bảo chính ngay nhà văn phát biểu cho biết truyện ngắn là gì, ta sẽ được những câu trả lời không rõ nét, thậm chí còn thay đổi rất khác biệt theo từng tác giả.<br />
<br />
Tại sao vậy? Bởi vì truyện ngắn là đứa con sinh chậm do với các dạng khác của văn chương. Ở Âu Châu kịch - thơ - truyện dài - xuất hiện rất lâu rồi mới tới truyện ngắn trong vòng hai trăm năm nay, hiện tại nó vẫn chưa ở trạng thái định hình, mỗi người quan niệm và viết truyện ngắn theo cách thế của mình. Ở Việt Nam, truyện ngắn viết bằng Quốc Ngữ tuy chỉ mới xuất hiện hồi đầu thế kỷ nhưng đã đi hia bảy đặm trên con đường của mình. Các truyện ngắn Việt Nam khoảng bốn mươi năm trở lại đây có giá trị nghệ thuật và tư tưởng không thua gì các truyện lừng danh ở những xứ đã có truyền thống truyện ngắn lâu đời.<br />
<br />
Một trong những truyện nổi tiếng còn sót lại là truyện ngắn rất gợi cảm "Câu Chuyện Một Tối Tân Hôn" của Phạm Duy Tốn, rõ ràng trong điều cần được trình bày; kỹ thuật dựng truyện và cách sắp xếp điều cần thiết của một truyện ngắn theo cách thế của các truyện ngắn Pháp chớ không bắt nguồn từ truyện ngắn Việt Nam (viết bằng chữ Nôm hay chữ Hán trước đó) như "Truyền Kỳ Mạn Lục Giải Âm", chữ Nôm thế kỷ XVII, hay "Lĩnh Nam Chích Quái" của Trần Thế Pháp" hoặc "Việt Điện U Linh" của Lý Tế Xuyên, chữ Hán, thế kỷ XIV. Với loại viết bằng chữ Nôm thì câu văn khó hiểu, kết cấu truyện lượm thượm và còn đang ở trong hình thức truyện kể. Với loại viết bằng chữ Hán thì người đọc không thấy được tính chất thời đại cũng như đặc tính của ngôn ngữ Việt trong đó vì khi thực hiện các tập này, tác giả chỉ thuần nhắm phần thâu thập các truyện cổ truyền trong dân gian, phần sáng tác cá nhân của tác giả và phần văn chương không được coi là quan trọng, khác với trường hợp tương tự của Sir Walter Scott ở Anh và Washington Irving ở Mỹ sau nầy đã dùng kho tàng truyện kể dân gian làm chất liệu cho các truyện ngắn của mình. <br />
<br />
Một vài nhà văn Việt thời chữ Nôm có sáng tác loại truyện kể nặng tính chất truyền kỳ — một hình thức truyện ngắn tương đối gần với dạng phôi thai của truyện ngắn ngày nay — như Đoàn Thị Điểm, với sáu truyện trong tập "Truyền Kỳ Tân Phả", như Cao Bá Quát với mười truyện trong văn cảo của ông. Các truyện này cho tới ngày nay vẫn chưa có điều kiện để được lưu hành rộng rãi cho nên không có ảnh hưởng trong văn chương.<br />
<br />
Nhìn chung các mặt ngôn ngữ, không khí cũng như hình thức các truyện ngắn cũ đều khác xa với truyện ngắn gần đây. Nói cách khác, ở Âu Mỹ truyện ngắn tuy mới xuất hiện chỉ hai thế kỷ nhưng truyền thống truyện ngắn của họ cũng đã được hai trăm năm trong khi ở Việt Nam truyện ngắn xuất hiện cả bốn năm trăm nay nhưng mới chỉ có truyền thống truyện ngắn như chúng ta có theo khái niệm ngày nay từ thập niên ba mươi của thế kỷ nầy.<br />
<br />
Trong khi đó, truyện dài Việt Nam đã xuất hiện và rất phong phú trước thời gian có hình thức truyện dài hiện đại khá lâu, dưới dạng truyện thơ Nôm như Trê Cóc, Phan Trần, Hoa Tiên, Nhị Độ Mai, Đoạn Trường Tân Thanh... hay dưới dạng một chuỗi nhiều bài thơ (người bên nhà gọi là một chùm (!) thơ) diễn tả một câu chuyện như thơ Vương Tường, Bạch Viên Tôn Các. Ở đây ngôn ngữ dùng rất gần với ngôn ngữ hiện đại. Sự kiện lại diễn thành một câu chuyện có đầu đuôi, ý nghĩa. Thêm vào đó, trong dân gian, lại có vô số truyện thơ. Có thể nói dân tộc Việt Nam đã thấm nhuần không khí truyện dài từ lâu.<br />
<br />
Ta không có truyền thống truyện dài viết bằng chữ Hán. (Cuốn "Lĩnh Nam Dật Sử" trước đây một nhân vật túng tiền chép lại một truyện dài tầm thường của đời Thanh bán cho trường Viễn Đông Bác Cổ thác là truyện dài Việt Nam xưa viết bằng tiếng Mường, tác giả là Ma Văn Cao, anh hùng Trần Nhật Duật đời Trần dịch ra chữ Hán, sự giả trá đó trong văn chương cần phải được quên đi, không nên nhắc đến nữa).<br />
<br />
Cuốn "Hoàng Lê Nhất Thống Chí" của nhóm Ngô Gia văn phải viết theo lối Tam Quốc Chí là một cuốn truyện dài lịch sử khá đặc biệt trong văn chương Việt, nhưng tiếc thay một con én lạc loài không tạo được mùa Xuân truyện dài chữ Hán mà chỉ tạo được mùa Xuân truyện dài lịch sử ở các trường hợp Tân Dân Tử (Nguyễn Hữu Ngỡi) trong Nam, Nguyễn Triệu Luật, Lan Khai, Tchya ở Bắc sau nầy... <br />
<br />
Dầu sao truyện dài Việt Nam cũng phát sinh từ truyền thống truyện dài Nôm và ít ra cũng từ thế kỷ XIV. Nhờ đó khi chữ quốc ngữ bắt đầu ổn định trong Nam, Nguyễn Trọng Quản có "Truyện Thầy Lazaro Phiền" 1887 đặt bước chân đầu tiên vào lãnh vực truyện dài mới và thập niên thứ nhì của thế kỷ này, truyện dài "Chăng Cà Mum" 1910 của Nguyễn Chánh Sắt, Hoàng Tố Anh hàm oan 1910 của Trần Chánh Chiếu, Phan Yên ngoại sử 1910 của Phan Duy Toản đã vang dội một thời. Ngoài Bắc, những cuốn Tố Tâm, Nho Phong, Người Quay Tơ sau đó góp phần xây dựng những bước tiến vững chãi cho nền văn học Việt Nam. Ngay đến tinh thần coi trọng truyện dài của người viết và câu nói thường lập lại trong giới cầm bút "nhà văn chưa phải là nhà văn nếu chưa viết được truyện dài" cũng có nguồn gốc từ dòng lịch sử lâu đời của truyện dài Việt. <br />
<br />
Sinh muộn, vốn chưa định hình rõ rệt nên tùy theo quan điểm từng người viết, khái niệm truyện ngắn biến thiên. Dầu sao trước một truyện ngắn ai cũng đều có thể vạch mặt chỉ tên đó là một truyện ngắn nhờ căn cứ một vài điểm hiển nhiên nào đó.<br />
<br />
Những điểm chung đó nằm trên mặt hình thức, như độ dài ngắn, sự liên hệ của những sự kiện được trình bày. Cho đến ngày nay quan niệm truyện ngắn đã khác với lúc nó mới phát sinh. Nhiều người đồng ý như cái tên của nó, đó là một sáng tác phẩm ngắn kể lại một câu chuyện, một mảnh vụn đặc biệt của đời sống, hoặc — như quan niệm mới gần đây —chỉ là một tâm trạng không cần thành truyện, không cần đầu đuôi, không nhất thiết phải theo thứ tự thời gian. <br />
<br />
Nhưng ngắn đến thế nào, chữ này thiệt là tương đối. Có nhà giáo, ông X.J. Kennedy, trong quyển Literature thường dùng ở năm đầu của văn chương Anh Mỹ ở đại học Mỹ nhắc đến một truyện ngắn của Thomas Bailey Aldrich chỉ dài độc có ba dòng: <br />
<br />
<i>"Một thiếu phụ đang ngồi trong căn nhà cũ kỹ, đóng kín, biết rằng chỉ có mình mình trơ trọi trên thế giới này. Tất cả đều đã bị tiêu hủy.<br />
<br />
Chuông cửa reo".</i><br />
<br />
Ít người đồng ý với ông giáo sư nọ để coi đây là một truyện ngắn. Không có truyện trong đó mà chỉ là một mảnh đời. Cũng được đi, nhưng cả truyện nhìn chung không "nói" được điều gì mặc dầu ta có thể tưởng tượng được vài điều về hoàn cảnh và tâm trạng của thiếu phụ đó. Ngắn quá, truyện không thể hội đủ những yếu tính cấu thành nó, không thể thực hiện được nhiệm vụ tương thông giữa người đọc và người viết, yếu tính căn bản của sáng tạo phẩm.<br />
<br />
Nguyên tử không thể là vật chất, một tế bào của con người không thể là con người. Truyện cũng vậy, phải dài ở mức độ tối thiểu nào đó, dưới mức đó, sẽ bị biến thể thành một thứ gì khác. Truyện ngăn ngắn của Việt Nam do các người viết có chút tên tuổi thường là bốn trang (khổ sách hay tạp chí Văn, Văn Học) ngắn quá, chỉ được viết bởi người mới vô nghề, chưa đủ dài hơi, chưa đủ sức phân tích những đoạn cần khai triển.<br />
<br />
Người Mỹ có những truyện cụt gọi là short short story, (tôi không muốn dùng chữ truyện ngắn ngắn) trong tuyển tập kiểu này ta gặp rất nhiều truyện chưa dài tới hai trang, mặc dầu viết bởi các cây bút có tên tuổi, Ernest Hemingway chẳng hạn. Những loại này chưa được xếp vào thể loại văn chương thật sự, ít nhất là trong những sách giáo khoa hay các tuyển tập có giá trị vì không đủ yếu tố đem đến thú vị cho người đọc.<br />
<br />
Các truyện dài khoảng ba, bốn trang được kể là truyện hay được chọn trong tuyển truyện quốc tế có quá nhiều. Chẳng hạn:<br />
<br />
"Bức Thư Gửi Cho Thượng Đế" (A Letter To God) của nhà văn Mễ Tây Cơ Gregorio Lopez Y Fuentes đăng trong "Great Short Story of The World" tuyển bởi The Reader's Degest - 1974. Truyện kể về anh nông dân Lencho, quá nghèo, năm nọ bị nạn hạn hán, gia đình sắp chết đói, viết thư gởi lên Thượng Đế xin được cứu giúp. Một nhân viên bưu điện thấy thơ, xúc động bàn với các đồng sự cứu giúp bằng cách cùng nhau góp tiền. Ác thay họ chỉ góp được có bảy chục pesos thay vì một trăm như Lencho xin. Nhận được tiền, Lencho tức giận viết thêm một bức thơ nữa:<br />
<br />
"Thưa Thượng Đế, về chuyện tiền con xin Ngài giúp đỡ, con chỉ nhận được có bảy chục pesos. Xin Ngày gửi đến con số còn lại, con rất cần. Xin Ngài chớ gởi qua đường bưu điện vì nhân viên bưu điện là một bọn ăn chận".<br />
<br />
Truyện chấm dứt ở đó. Tác giả bỏ lửng làm cho truyện mở ra nhiều chiều hướng từ khôi hài - tôi từng thấy người ta mượn ý này viết thành chuyện cười - niềm tin ở khả năng siêu việt của Thượng Đế có thể tác động lên cuộc đời này, đến cái giá phải trả của người thi ơn, đời sống khốn khổ, thất học của nông dân... màta vẫn không hiểu được chính ý của tác giả.<br />
<br />
Vậy thì viết ngắn, bỏ lửng, không nói hết cũng có cái lợi của nó! Cái lợi ở chỗ gợi lên những vấn đề mà tác giả khỏi mất công đi sâu. Tuy nhiên cho tới bây giờ chưa ai chấp nhận truyện ngắn cụt có tuyệt phẩm mặc dầu người ta công nhận có truyện ngắn cụt và các tuyển tập về loại nầy hiện nay không phải là ít. "Kẻ Theo Đuổi" (The Chaser) của John Collier, trích đăng trong quyền IV của bộ sáu cuốn dạy văn chương Anh do Trung Tâm Nghiên Cứu Học Trình Oregon (The Oregon Curriculum; A Sequential Program in English) thực hiện cũng ở vào loại đó, ngắn và mở rộng.<br />
<br />
"Cậu Alan Austen đến một lão già chuyên bán nước đặc biệt để mua "nước yêu" vì cậu đang yêu cô Diana và muốn chiếm cảm tình của cô ta. Trong cuộc đối thoại lão bán nước nói nhiều điều làm cho người đọc suy nghĩ: "nước tẩy đời sống (Life cleaner) giá năm ngàn đồng, nước yêu (Love lotion) thì không vậy. Người trai trẻ cần nước yêu thì rất ít khi có năm ngàn. Nếu có năm ngàn thì đâu có cần nước yêu... nước yêu thì một đồng thôi... Tôi thích phục vụ khách hàng, rồi khách hàng sẽ trở lại khi họ khá hơn và cần những thứ mắc tiền hơn".<br />
<br />
Tác giả kết thúc truyện ngắn của mình bằng câu chào tạm biệt của ông lão bán nước yêu khiến ta thắc mắc về chiều hướng mở ra của truyện: Người yêu hôm nay ngày mai giận ghét? Alan Austen có thể sẽ trở lại sau này vì cần thứ mắc tiền để thanh toán Diana? Không biết. Hay anh ta trở lại để mua nước yêu nữa để săn đuổi một Diana khác? Có thể lắm.<br />
<br />
Vậy truyện ngắn dầu ở trạng thái ngắn tối thiểu cũng phải mở được những chân trời mới cho người đọc, nếu người viết biết mở ra chân trời đó. <br />
<br />
Việt Nam cũng có những truyện ngắn cỡ này, cũng là những truyện có giá trị đầy đủ, và có khả năng mở ra những chân trời mới suy tư cho độc giả. <br />
<br />
"Vệt son" và "Thế giới của Kathy Graham" trong tập Ngọn Hải Đăng Mù của Mai Thảo. "Thư Quê Hương" trong tập Xuôi Dòng của Nguyễn Mộng Giác, những thí dụ điển hình.<br />
<br />
Ngắn thì vậy, khoảng ba, bốn trang. Nhưng dài bao nhiêu mới không bị coi như truyện dài? Ở Việt nam chỉ có truyện dài quá ngắn không có truyện ngắn quá dài. Truyện ngắn "Thác Đổ Sau Nhà" trước năm bảy mươi lăm của Võ Phiến (in trong tập truyện ngắn I- Văn Nghệ) dài bốn mươi bốn trang. Hầu hết những truyện khác dài cỡ này như các truyện của Mai Kim Ngọc trong "Muôn Kiếp Cô Liêu", "Rồi Sau? Niềm Tin Mới", của J. Ngọc (Trong tập truyện cùng tên, xuất bản ở Houston - 1987) "Nụ cười Tre Trúc" của Kiệt Tấn, đều là những truyện dài hụt hơi, truyện vừa, chớ không phải là truyện ngắn dài.<br />
<br />
Văn chương thế giới chấp nhận một vài truyện ngắn dài như "Cái Chết Của Lão Ivan Ilych" của Leo Tolstoi dài bốn mươi trang chữ nhỏ. Truyện "The Heart Of Darkness" của Justave Flaubert dài năm mươi hai trang chữ nhỏ. Đếm chữ sợ còn nhiều hơn truyện dài Bonjour Tristesse của F. Sagan nổi tiếng một thời trước đây. Cũng vậy truyện "Man In The Drawer" của Bernard Malamud dài 46 trang, đọc mà ngán ngẩm khi đầu óc đã quen thuộc với truyện ngắn khoảng hai mươi trang trở lại. Trong khi đó các truyện khác, dài dưới cỡ này hầu hết đều được xếp vào loại truyện vừa (novella). Truyện Neighbour Rosicky của bà Willa Cather, người chuyên viết những điều càng ngày càng biến mất trên quê hương mình, chẳng hạn: in khoảng hai mươi lăm trang chữ nhỏ thế mà các tác giả cuốn "Question And Form In Literature" trong bộ Medaillon Edition-America Reader xếp vào truyện vừa.<br />
<br />
Ở Việt Nam, khái niệm truyện vừa ít được để ý vì loại này đều bị xếp vào chung với truyện ngắn. Nhà văn Bình Nguyên Lộc dường như là người đầu tiên dùng chữ truyện vừa để chỉ khái niệm novella, một thứ truyện phát xuất ở Nga, dài nhưng được viết sao cho in vừa đủ một kỳ báo của các loại tạp chí hồi thế kỷ XIX ở Mạc Tư Khoa. <br />
<br />
Vậy thì truyện ngắn không được dài quá, cũng không được ngắn quá. Từ ba, bốn trang tới bốn, năm, mươi trang là vừa. Người Mỹ tính chữ nói là từ vài ngàn chữ tới năm, sáu chục ngàn chữ. Ở Việt Nam, trước 1954 hầu hết chuyện dài đều vào khoảng một trăm trang chữ, lớn lại in thưa, nếu xếp chữ như ngày nay, chỉ còn độ bốn năm chục trang. Truyện "Hồn Bướm Mơ Tiên" của Khái Hưng, truyện "Bạc Xiu Lìn" của Vũ Anh Khanh là những thí dụ, với quan điểm ngày nay, ta dễ dàng nói đó là một truyện ngắn dài hơi như các truyện của Võ Phiến trước đây. <br />
<br />
Vậy thì quan niệm truyện dài, truyện ngắn không phải chỉ thuần túy nằm ở chỗ giới hạn số trang của truyện mà đòi hỏi thêm một yếu tố khác, đó là cách nói đến điều được nói trong truyện.<br />
<br />
Dở một hai cuốn truyện dài mà giá trị không còn ai đặt thành vấn đề nữa, đã trở thành tác phẩm cổ điển như: "Chiến Tranh và Hòa Bình" của Leo Tolstoi hay "Kiếp Người" (Of Human Bondage) của Somerest Maugham ta thấy tác giả tả tỉ mỉ, chi tiết, có thể nói là đụng gì viết nấy. Chỗ này, gia đình này được giới thiệu chi ly. Địa điểm khác, nhân vật khác cũng xuất hiện với đầy đủ chi tiết, không cần những người này có một sự liên hệ chặt chẽ về những diễn biến của câu chuyện.<br />
<br />
Truyện dài hiện diện quá điều cần thiết, với những tẳn mẳn tỉ mỷ thừa thãi của nó. Truyện dài bắt chụp với đời sống như một ống kính quay phim kéo lê đi khắp nơi, gặp gì thu nấy, hào phóng không rích róng trong sự lựa chọn. Truyện ngắn trái lại, nhân vật đã rất ít lại liên quan với nhau, sự kiện cùng nhau chằng chịt buộc ràng: không gian, thời gian thường cô, quánh lại chớ ít khi mở rộng. Suy nghĩ và hành động của nhân vật cũng chỉ được giới hạn để diễn tả một hai điều tác giả muốn; những điều khác bị hy sinh tối đa. Hiện tượng nhiều chủ đề trong một truyện ngắn thường bị coi như yếu tố đem đến sự thất bại của truyện vì tính chất mông lung của nó, khác với truyện dài, tính chất đa-trọng-tâm thường được coi như phong phú, sâu sắc.<br />
<br />
Chúng ta có thể ví một bàn cờ tướng, cờ tây với một truyện dài: truyện ngắn chỉ giống như một bàn tíc-tắc-toe, một bàn cờ chó, hoặc nhiều nhứt là một bàn cờ mụ, cờ gánh. Đứng trước một cảnh thiên nhiên hùng vĩ, bốn bề núi non rừng rậm, ao đầm, nhìn mọi thứ một chút đó là công việc của người viết truyện dài. Chú mục vào một cảnh nhỏ, một chóp núi với tuyết phủ trắng bạc trên đỉnh, vào vài căn nhà lộng lẫy bên sườn, vào một dòng suối trong có đá cuội trong lành đó là công việc của người viết truyện ngắn. Dĩ nhiên có người chỉ quan sát một vùng tuyết để thấy rõ hơn một vài cây thông bị khuất lấp, vài hòn đá như cố vươn mình lên trên tuyết; hay chỉ chú trọng đến những gì xảy ra trong một căn phòng của gian nhà nọ, hoặc một khúc suối có cô sơn nữ vọc nước, nô đùa....<br />
<br />
Một bức địa đồ chi tiết với đường sá, sông ngòi nước non sông biển của tiểu bang là truyện dài. Một ô vuông nhỏ về một thành phố với lời chú "xem chi tiết ở phía sau", chi tiết phía sau đó là truyện ngắn.<br />
<br />
Ta đi đến một tính chất nữa cũng thuộc phần hình thức của truyện ngắn, đó là các sự kiện được mô tả cần phải cô động trong chi tiết và liên quan chặt chẽ với nhau.<br />
<br />
Các nhà văn có cách diễn tả đặc biệt về tính chất "chi tiết cô đọng và liên quan nhau" của truyện ngắn.<br />
<br />
Nhà văn Mặc Đỗ cho rằng "truyện ngắn là một truyện dài đúc lại chung quanh một tình tiết, một động tác chính. Truyện ngắn gần với kịch". Khi nhắc đến kịch, Mặc Đỗ muốn nhắc đến kịch Hy Lạp hay ít ra cũng là kịch ở Âu Châu trước thế kỷ XVIII với những luật lệ về đồng nhất động tác, thời gian và không gian, nghĩa là truyện ngắn không được dài dòng, miên man mà chỉ xoáy trục quanh một nét chính.<br />
<br />
Nhà văn Nguyễn Nghiệp Nhượng, phát biểu có vẻ Tây Phương hơn nhưng cụ thể hơn: "Truyện ngắn giống như một sự soi sáng tập trung".<br />
<br />
Nhà văn Nguyễn Đông Ngạc cũng một ý đó: "Vì là truyện ngắn nên tình tiết ý tưởng phải thật chọn lọc và có tính chất quyết định hơn (thơ, truyện dài). Truyện ngắn gần giống như thơ Đường về nội dung". Nhắc đến thơ Đường, Nguyễn Đông Ngạc muốn nói về tính chất cô động ít lời, chi tiết được chọn lọc để phục vụ cho "đề" của loại này. <br />
<br />
Những nhà văn tên tuổi khác nói cách này, cách kia nhưng đại khái cũng tương tợ. Âu Mỹ cũng không nói gì mới hơn. Ta có thể đi đến một định nghĩa dễ hiểu " Truyện ngắn là một sáng tác nghệ thuật có tính cách cô đọng, kết hợp giữa cốt truyện, nhân vật, diễn tiến, để diễn tả hoàn chỉnh một điều cần diễn tả, không dư cũng không thiếu". Thiếu, truyện trở thành lỏng chỏng, mất cân bằng và tối tăm; dư, truyện sẽ nhạt, dài dòng, rườm rà nhiều lời ít ý, làm nản chí độc giả.<br />
<br />
Nhà văn Doãn Quốc Sỹ gọi định luật không được dư thừa của truyện ngắn là tính chất không có chi tiết tràn bờ, không có chi tiết tràn bờ cũng chỉ là một cách nói khác về tính nhất quán của truyện ngắn.<br />
<br />
Nữ văn sĩ Nadine Gordiner của Nam Phi nhắc đến tính cách nhất thống vấn đề của truyện ngắn khi bà nói trong bài tựa tuyển tập truyện ngắn của mình : "truyện ngắn được tạo thành bởi một vấn đề gì nhà văn có thể nắm, bắt được hoàn toàn ngay tức khắc trong trí tưởng tượng của mình" trong khi đó đối với truyện dài điều này phải thực hiện từng bước một. Do đó bà cho rằng khi đã có ý tưởng rồi thì không có sự lựa chọn hình thức dài ngắn nữa. Ý tưởng đã quyết định rồi. <br />
<br />
Truyện ngắn hiện ra tức thời. Thường thường truyện ngắn xoay chung quanh một câu chuyện chính, xảy ra trong một thời gian ngắn do một, hai nhân vật chánh. Nếu tác giả chú trọng trên một mặt nào đó, ông ta sẽ trình bày yếu tố đó thật chi tiết và giữ lại thật là tối thiểu những yếu tố khác. Nên nhớ tác giả  hy sinh một số chi tiết thấy không ích lợi cho toàn thể tác phẩm chớ không phải ông không biết những chi tiết chưa được viết ra đó.<br />
<br />
Trong truyện ngắn nhân vật đặt biệt được làm nổi bất bằng hành động, ngôn ngữ, suy tưởng của anh ta và của cả nhân vật phản diện nữa. Phải quan sát thật nhiều về con người, phải thấy được phần điển hình nhân vật mình muốn tả và loại bỏ đi những thứ khác mới có những nhân vật đặc biệt và tác phẩm mới có cơ hội sống theo thời gian. Trong "Một Bông Hồng Cho Emily" của W. Faulkner: Quận Toàn với cách nói chuyện của ông ta với những đặc ngữ, bọn thợ săn chúng tôi "với vỗ vỗ tự tin vào bên trong vế của người thiếu phụ", trong Một Bông Hồng Cho Emily" của W. Faulkner, cô Emily ương ngạnh không thèm tiếp chuyện với bất cứ ai được gởi đến để nói chuyện thuế má với mình. Trong "Tiếng Thầm Quê Mẹ" của Nguyễn văn Sâm, thằng Mỹ ương ngạnh, ngang tàng cướp giật nhưng lời nói cà cử chỉ của nó cho biết bên trong con người của nó.<br />
<br />
Một nhà văn nào đó nói tất cả mọi sản xuất đều có chất phế thải. Công việc của nhà văn cũng vậy, ông ta phải quan sát thật nhiều nhưng cô đọng lại và phế thải một phần lớn. Nếu không biết cô đọng, không biết phế thải nhà văn sẽ trở thành một người ngồi lê đôi mách và một truyện ngắn sẽ thành truyện dài hụt hơi, một truyện dài sẽ thành truyện đầu Ngô mình Sở, đại cà sa, không đâu vô đâu.<br />
<br />
Nhưng trong định nghĩa vừa nêu trên chữ "một sáng tác nghệ thuật" cũng là chữ đặt ra nhiều vấn đề. Có những sáng tác được viết ra đọc lên thấy hứng thú, nao nao, thống khoái, đã điếu, thỉnh thoảng ta thích đọc lại, càng đọc lại càng thấy chiếu sáng, càng khám phá thêm điều mới; những điều tác giả viết làm phong phú tâm hồn ta, thay đổi ta, làm giầu kiến thức ta.<br />
<br />
Có những sáng tác tuy có thể tạo cho ta nụ cười cuối truyện, hay một chút thích thú nào đó -- do câu chuyện mang lại -- nhưng lại thuộc loại đọc xong rồi bỏ, không thể đọc lại vì đọc lại lòng ta sẽ dửng dưng. <br />
<br />
Nghệ thuật của truyện ngắn như vậy nằm ở đâu? Đó là câu trả lời cần nhiều suy nghĩ. Vì chính những người viết, người sưu tuyển truyện ngắn lẫy lừng như Sir Victor Pritchet còn nói rằng sự lựa chọn của mình tùy theo sở thích riêng, có tính cách rất cá nhân và truyện ngắn là một loại nghệ thuật tuyệt đối khó khăn.<br />
