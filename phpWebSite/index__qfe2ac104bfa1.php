Kết thúc quyển sách giới thiệu tiểu  thuyết Mỹ, cuốn "Cavalcade of the American Novel",  ông Edward Wagenknecht cho rằng những nhà phê bình Mỹ khó quyết định đúng  đắn những cuốn sách nào nên  được nói đến và những  cuốn nào nên bỏ qua trong im lặng, để  trôi vào lãng quên của con số quá  lớn sách vỡ xuất bản mỗi năm  không ai có thể đọc hết. Rồi ông  nhận định rằng thông thường,  ngày nay ở Mỹ người điểm  sách đã hoàn toàn dửng dưng với  văn chương như một thứ nghệ thuật  mà chú trọng đến những quyển  sách phản ảnh các bộ mặt của đời  sống Mỹ và cuốn nào càng biểu lộ  được "bộ mặt" đó  thì càng có cơ hội được chú ý đến. Đi xa hơn trong việc tìm nguyên do của  sự chú ý, ông Wagenknecht thấy rằng  những người viết văn càng viết  về những điều không biết xấu  hổ thì càng dễ được chú ý... Điều nhận xét này không những  đúng cho tiểu thuyết nói chung ở  Mỹ mà còn áp dụng được cho  nhiều nước khách chớ không riêng gì Mỹ và ở trong các bộ môn.  Với một xã hội bận rộn và mọi thứ đã trở thành mục tiêu  cho thương mại thì sự phân cách lớn lao giữa tác phẩm được  chú ý và tác phẩm nghệ thuật đương nhiên phải có. Cuốn sách phù hợp  với sở thích của thời điểm chớ không là một tác phẩm có  nghệ thuật văn chương sẽ được chú ý.<br />
<br />
Nói sở thích là nói đến sự  ưa chuộng vì thiếu thốn, vì trọng vọng hay vì ảnh hưởng của môi trường chung quanh. Và khi điều làm  cho người đọc ưa thích mất đi  thì sở thích của giai đoạn cũng  mất. Tác phẩm là sở thích của  giai đoạn họa hoằn lắm mới sống  qua giai đoạn kế tiếp. Sự phụ tình  của thời gian trong trường hợp  này được gọi là sự chọn  lọc của thời gian. Sở thích của  những người ngày nay ở vào  lứa tuổi 50, thuở nhỏ là Long  Hình Quái Khách, là Châu Về Hiệp  Phố, là Cô Bạch Mai (của Nam Đình)  là Gia Long Tẩu Quốc, Võ Đông Sơ  Bạch Thu Hà (Tân Dân Tử) là Thần Hổ,  Ai Hát Giữa Rừng Khuya (Tchya), là Bàn Tay  Máu, Con tàu Máu (Phi Long), là Hồng và Cúc,  Rừng Thẩm Bể Khơi (Ngọc Sơn).<br />
<br />
Một thời ở Sàigòn có cái  sở thích đọc Yêu, Tiền, Loạn  (Chu Tử), Vòng Tay Học Trò (Nguyễn Thị  Hoàng) và bây giờ ở hải ngoại những tác phẩm được bán chạy  là những cuốn được thuật lại đời sống trong trại cải tạo, những ngày chót của Việt Nam Cộng  Hòa, chuyện mấy chú bộ đội ngu ngơ  nhưng ác độc... <br />
<br />
Vì truyện ngắn chỉ đủ chỗ chứa  đựng được ít nội dung vì  vậy chất liệu để diễn tả nội  dung đó cũng rất giới hạn nên  khi chất liệu không còn thích hợp  với thời đại nữa thì truyện ngắn đó dù đã có một thời  được coi là xuất sắc vẫn không thể tồn tại. Ông Clifton Fadiman, một người  làm tuyển tập truyện ngắn Mỹ cho rằng  các tác giả như các tác giả danh tiếng trước đây như Sherwood Anderson,  Erstine Caldwell, Walter de la Mare của truyện ngắn  Mỹ không còn được nhắc đến  nữa và có thể độ 50 năm sau thôi  hai văn tài hiện đại Mỹ là Trevor và John Updike cũng sẽ bị lãng quên.  Truyện ngắn chống chỏi được với  thời gian như The Dead (James Joyce), The Simple Heart,  (Gustave Flaubert) Cái chết của Ivan IIych (Dostoivesky) thiệt là quá ít. Truyện ngắn hay của  của Việt Nam càng bị đào thải mau  hơn vì xã hội Việt Nam thay đổi quá  nhanh. Biết bao nhiêu điều mới đây  là tân thời đã trở thành  hình bóng cũ. Truyện ngắn Anh Phải Sống  của Nhất Linh đã không còn giá trị thưởng thức nữa, các truyện  của Nguyễn Công Hoan (Bước Đường  Cùng) của Lưu Trọng Lư (Nàng Công  Chúa Huế) đã biệt tâm vào sự lãng quên của quần chúng, còn nhắc  đến họa chăng là những người  nghiên cứu lịch sử văn chương.<br />
<br />
Truyện ngắn thắng - hay cầm cự lâu  dài - được sự gạn lọc của thời gian cần phải có điều kiện  nào? Nói cách khác, thế nào là một truyện  ngắn hay đúng nghĩa? Nếu đi từ vấn đề tổng quát  có tính chất mỹ học HAY là gì, HAY thì chắc chắn  sẽ dẫn đến sự bất đồng ý  kiến của nhiều người.<br />
<br />
Nhưng khởi  từ một khái niệm cụ thể thế  nào là một truyện ngắn hay để đi  đến những tiêu chuẫn cụ thể,  sự bất đồng sẽ ít đi. Điều khó khăn là những tiêu chuẩn được đưa  ra đó không phải ai ai cũng chấp nhận.  Xác định những  yếu tính của một  truyện ngắn hay do vậy phần nào mang tính cách chủ quan dựa trên những suy ngẫm và kinh nghiệm cá nhân. Khuôn vàng  thước ngọc để mọi người  đặt truyện ngắn lên đấy rồi phán xét, định giá là một điều  không thể nào tìm được sự  đồng tình của nhiều nguời.<br />
<br />
Một nhà thơ trẻ nói với tôi:  "Đứng trước một bài thơ,  truyện ngắn hay, người đọc khó  đồng ý nhưng đứng trước  một bài thơ, truyện ngắn dở, người  đọc dễ dàng đồng ý". Điều  này cũng dễ hiểu. Có quá ít cách  để làm cho điều gì, vật gì trở  nên tốt hơn, hay hơn, được trầm  trồ ngợi khen hơn, nhưng có cả trăm  ngàn cách để làm cho nó dở đi.  Nhưng dựa vào đâu để xác  quyết hay dở? Tiêu chuẩn nào? Nhiều  độc giả như đã có sẵn trong trí  một vài khái niệm - nhưng không rõ  tàng lắm - thế nào là một truyện  ngắn hay, do đó khi đọc truyện nếu thấy phù hợp với những yếu  tính đó, ông ta cho rằng truyện đó  hay, trái lại không thấy những yếu  tố đó, ông cho rằng truyện đó dở.<br />
<br />
Ngược lại cũng có rất nhiều  khái niệm về những khuyết điểm tạo nên truyện ngắn dở. Truyện nào  mắc vào lỗi lầm đó thì bị kết  luận dở. Là người đọc thuần  túy, độc giả không cần phải suy  nghĩ để nắm bắt lấy những khái  niệm hay khuyết điểm mơ hồ làm tiêu  chuẩn đó. Họ không cần chỉ danh những  đặc tính hay/dở đã có sẵn  trong trí (nhiều khi họ không biết) được tạo thành theo thời gian và kiến thức  thủ đắc. Như đã nói, vì tính  cách tương đối của vấn đề  - ở trong bộ môn nhân văn - tất  cả những đặc tính để tạo  thành cái hay dở điều tùy thuộc  khẩu vị thưởng thức (ý thức,  tâm lý, tính tình, học lực...) của  từng người. Các nhà biên tập  truyện ngắn đều đồng ý như vậy.  Clifton Fadinam (The world of the Short stories) là những  thí dụ dễ thấy nhất, biểu lộ trong  sự lựa chọn của họ đã đành  mà còn cả ở sự thú nhận  của họ nữa. <br />
<br />
<div align="center"><b>***</b></div><br />
<br />
Ta đã thấy các nhà  viết truyện ngắn đồng ý một điểm chung là truyện ngắn có tính chất "soi  sáng tập trung" chớ không phải là  một chuỗi chuyện này nọ xảy ra; vậy  thì muốn là truyện ngắn hay điều  tiên quyết là đề tài phải quay quanh một điểm chánh: có thể tỉ mỉ  chi tiết trong các ngõ ngách của điểm  chánh, nhưng không được tỏ ra  quá đáng nhiều mặt, không được  chi ly quá trong các nhánh của truyện để  đồng thời tạo nhiều điểm chánh  quá khác biệt nhau trong một truyện (truyện  Bóng đêm cuối cùng của Phan thi Trọng Tuyến mắc vào lỗi này, làm cho người  đọc đi mông lung). Hãy để tính  chất đa trọng tâm, đa trọng điểm  lại cho truyện dài. Người viết phải  viết như vậy, cô đọng, chủ điểm;  và người đọc cũng ưa thích  vậy, nắm bắt được nội dung ý  nghĩa. Truyện ngắn là đứa con của  truyện dài nên lúc mới tượng  hình nó có tính chất mông lung của  truyện dài, nhưng không phải vì vậy mà nó không  tiến tới một hình thức riêng,  ngoài hình thức ngắn, dài.<br />
<br />
Ở Anh Quốc các truyện ngắn thời  mới phôi thai thường cho hình thức  một truyện dài ngưng nửa chừng,  một truyện dài hụt hơi, tính chất  này cũng thấy ở Mỹ nên Edgar Allen  Poe mới đưa ra những tính chất  phải có của truyện ngắn, đó là  sự cô đọng và sự tròn trịa  của một câu chuyện, một câu chuyện  tự nó đầy đủ mà không dư,  và từ chuẩn điểm đó ông  này cùng với William Hawthorne đã chuyển  biến truyện ngắn Mỹ từ một thứ được viết để lấp đầy  các tạp chí bình dân đã trở  thành một hình thức, một thể loại  văn chương. Sau một trăm năm ra đời, truyện ngắn đã thật sự đi vào  con đường của nó, tách rời hẳn với truyện dài, tạo một thể loại cá biệt. Nhiều nhà văn phát  biểu khôi hài nhưng rất đúng "truyện  ngắn không phải là một truyện dài  viết ngắn hay rút ngắn" vì vậy khi  mang tính cách lê thê nó sẽ không  là một truyện ngắn hay. Truyện ngắn  hay nói cho cùng, phải có sự phong phú  về nội dung, có sự ẩn áo của một bài thơ Đường  tuyệt diệu, càng đọc càng thấm,  càng nghĩ càng khám phá thêm những  ý nghĩa ẩn tàng...<br />
<br />
<div align="center"><b>***</b></div><br />
<br />
Xét cho cùng thì lý do viết về phía  người viết là để thỏa mãn  nhu cầu kể chuyện. Đời sống chúng  ta vốn dĩ là một câu chuyện dài  nếu chúng ta biết tỉa ngọn cắt ngành  thì sẽ biết bao là truyện ngắn. Chúng  ta luôn luôn thấy mình cần kể lại cho người khác nghe chuyện của mình,  và chuyện mình thấy, chuyện mình nghĩ ra. Đó là công tác viết truyện ngắn  bằng miệng. Nhưng rồi phải dùng chữ  viết để truyền bá và bảo tồn cái chuyện của mình. Sang hình thức  này, chuyện có luật lệ, qui tắc của  nó nhưng không thoát khỏi hình thức  ban đầu là một chuyện kể, nghĩa là  có một câu chuyện để nói ra, nói với người khác. <br />
<br />
Nhưng rồi phải dùng chữ viết để truyền bá và  bảo tồn các chuyện của mình. Sang hình  thức này, chuyện có luật lệ, qui  tắc của nó nhưng không thoát khỏi  hình thức ban đầu là một chuyển  kể, nghĩa là có một câu chuyện.  Những tác giả không phải không có lý do khi đặt tựa truyện của mình  bằng những chữ có dính dáng tới  chuyện. Phạm Duy Tốn có "Câu chuyện Một  Tối Tân Hôn", Thế Lữ có "Một  Chuyện Ngoại Tình", "Câu Chuyện Trên Tàu  Thủy" (cùng ở trong tập Bên Đường  Thiên Lôi - 1936) Isak Dinesen có "Câu Chuyện  Của Một Thủy Thủ Trẻ", Nathaniel Hawthorne  có"Câu Chuyện Kể lại Lần Nữa"  (Twice Told Tale), James Joyce có "Trường Hợp Thương Tâm" (Painful Case) (Mà James Joyce trong  truyện nào lại chẳng là truyện kể?).  Kể chuyện là thói quên chung của con  người. Chúng ta luôn luôn có điều  gì để kể và chúng ta thích nghe những điều được kể,  lúc nhỏ truyện cổ tích, lớn hơn  một chút, truyện ma, lớn hơn, truyện  tình, rồi chuyện thế sự nhân  sinh. Nhân loại kể nhau nghe chuyện bằng  lời, bằng chữ khắc vào đá  trước khi biết cách ghi lên giấy.  Ở Trung Quốc, thời TrungCổ có những  nghệ nhân sống bằng nghề kể chuyện.  Ở Ả Rập, còn truyền lại tác  phẩm của một cô gái dùng thuật  kể của mình mà cứu được  biết bao người con gái khỏi chết  oan vì sự tức giận của một ông  vua.<br />
<br />
Nhưng đem những điều kể bằng miệng  diễn lại bằng chữ viết, kể sao ghi  lại như vậy, không có cái nghệ thuật  riêng của chữ nghĩa, của chuyện,  không có sự mô tả kỹ lưỡng  về nhân vật mà chỉ tạo nên những  nhân dáng hình que (stick figures) thì ta sẽ  có "truyện Tàu", truyện "1001 đêm),  hay tiến bộ hơn chút nữa, truyện  kiếm hiệp Kim Dung, truyện tình Quỳnh Dao.  Các loại này vẫn được ưa  thích vì sự kiện, vì cố sự, tình tiết chứa đựng trong đó  chứ không có cái nghệ thuật của chữ nghĩa (Chữ, câu, nhạc điệu...)  không có ý nghĩ thâm thúy của câu  chuyện, của lời văn. Nhiều người  sẽ viện dẫn lý do này nọ để  nói truyện Kim Dung có ý nghĩa nên ngự  trị cả vùng Đông Nam Á, tiểu thuyết  Quỳnh Dao hợp ước vọng của giai tầng trung lưu nên chiếm Hoa lục v.v... nhưng  những điều đó không liên hệ gì hết với nghệ thuật của ngôn  ngữ mà tác phẩm viết cần phải  có nghệ thuật của ngôn ngữ. Người  ta gọi là chữ đắc địa trong một câu, một câu xuất thần trong một bài, một bài kết cấu tân kỳ của tác  giả. Truyện dài dở còn có cơ được nhắc tới, được  dùng làm cảm hứng cho các sáng tác  khác. (Ở Việt Nam là các loại tuồng  rút từ truyện Tàu, truyện "1001 đêm",  truyện chưởng. Ở Đài Loan, Hồng  Kông, là các phim Video chưởng Kim Dung,  tình Quỳnh Dao.) Nhưng chắc chắn truyện  ngắn dở sẽ bị lãng quên, sẽ  bị mất hút vào đám đông vô  vàng truyện đã lấp đầy trang giấy các tạp chí bình dân. Tại sao? Truyện ngắn dở dễ kể lại, dễ tóm lược  và mau chóng trở thành một chuyện  đời, một cố sự, chuyện đầu  bàn cuối xóm mà ai cũng có thể  kể, có thể nói. Truyện ngắn dở  ngoài cốt truyện không còn cái tinh  túy nào khác.<br />
<br />
Cốt chuyện chỉ là xương da - phần  quan trọng khó thấy ở bên trong truyện  ngắn mới quan trọng, mới là cái  phần hồn của truyện. Truyện ngắn hay  vì vậy không thể để lại, hoặc  khó kể vì phần cốt lõi vẫn còn  bàng bạc trong truyện sau khi cốt truyện  được tách ra.<br />
<br />
Truyện "Rừng Mắm" của Bình Nguyên  Lộc nổi tiếng vì câu chuyện, vì cái  ý nghĩa lót đường của các  thế hệ trước mà còn gợi một sự lâng lâng cảm hoài cho người  đọc về những lời "đối-đáp-cho-có-chuyện" mà không-có-gì-để- nói của thằng  Lộc và cô gái mà nó gặp trong rừng.  Truyện "Miên Trường Phía Sau" của  nhà Văn Do Thái Agnon được dịch  đăng ở tạp chí Văn ngoài câu  chuyện ta còn cảm nhận sự bồn chồn,  sự quyết tâm để nắm bắt một  điều cần biết của một học giả.  Truyện viết dở cũng một cốt chuyện  đó, nhưng không cống hiến cho người  đọc được cái không khí bị  thúc bách tìm biết như vậy.<br />
<br />
Truyện "Hầm Rượu" của Edgar Allen  Poe cho thấy về quyết tâm trả thù đến  hững hờ trước cái chết của  kẻ thù, qua những câu nói của nhân  vật ta thấy sự xếp đặt của người  trả thù và sự vô tâm của nạn  nhân. Cái hay của truyện nằm trong nghệ thuật tạo nhân dáng của nhân vật.  Truyện "Cố Sự Ở Đê Uyên Kiều" (An Occurance at Owl Creek Bridge) của Ambrose  Bierce cho thấy cái không khí thiết tha với cuốc sống, tiếc nuối cố bám vào  từng giây phút còn lại cuộc đời  của một tử tội trước giờ  thọ hình. Truyện "Người Đàn  Bà Ngoại Tình" của Albert Camus kể chuyện  một người đàn bà đi du lịch  với chồng, đêm đến người  chồng ngủ, bà ta lẻn ra ngoài ngắm sao,  suy nghĩ mông lung rồi trở vô, ông  chồng vẫn ngủ say. Các nhà nghiên cứu  văn học đều công nhận đây là  truyện ngắn hay. Cái hay nằm trong trạng  thái và sự suy tưởng của người  đàn bà mà chúng ta không thể kể  lại hết ý. Tính chất có-điều-gì-đó-ở-ngoài-câu-chuyện thuộc về nghệ thuật viết chuyện, sẽ  dẫn đến vô vàn vấn đề căn  bản tuy các sách vở văn chương  học đường đã nói đến nhiều (hình thức, cấu tạo, câu văn,  kết ý, xây dựng nhân vật) vẫn  không thể giải thích hết được  các thắc mắc của người muốn  phiêu lưu vào địa hạt văn chương.  Ta phải công nhận một cách tiên thiên  rằng con người luôn luôn bị tù  túng bởi giới hạn của mình trong  hoàn cảnh xã hội và cuộc đời.  Trong thâm tâm ai cũng muốn thoát ra, ngao du, thám hiểm hưởng thụ, hay thực  hiện những điều gì đó mà  với cuộc đời thực tế trước mặt họ không làm được. Truyện  ngắn hay đáp được điều ước vọng muốn bùng vỡ đó của người  đọc, giúp họ thoát ra khỏi đời  hiện tại, tham dự vào cuộc phiêu  lưu tưởng tượng bằng cách  hòa nhập vào đời sống của nhân vật.<br />
<br />
Ngày xa xưa cổ tích thường có  truyện Hoàng tử cưới cô gái nghèo khổ hay ngược lại kiểu Chử  Đồng Tử và Tiên Dung, Tú Uyên  lấy Giáng Kiều. Gần đây thời  Tự Lực Văn Đoàn là các chuyện  tình của các cậu sinh viên Hà Nội với các cô gái quê lúc về nghĩ  hè. Ở miền Nam khoảng sau 1950 là các  cô gái quê nghèo khổ lên tỉnh gặp  người tình công tử con nhà giàu.<br />
<br />
Những đề tài đó giúp người  đọc thoát khỏi cảnh giới thực tế mà mình muốn phá vỡ ra để  có một cuộc đời khác hơn, phù hợp với ước vọng của mình  hơn. Các truyện ngắn kể chuyện kháng chiến, tranh đấu chống thực dân Pháp  xuất hiện ở miền Nam khoảng 1949- 1950  khiến người đọc hừng chí thoát  ly đi chống thực dân thì ít mà  tạo cho họ cái cảm giác chính mình  tham dự vào sự kiện cầm súng  chống kẻ thù thì nhiều.<br />
<br />
Các truyện trong Liêu Trai Chí Dị được  thích một phần vì con người ta được  phiêu lưu tình ái với hồ nữ  xinh đẹp, thư sinh hay chữ, thỏa mãn  ước vọng của phái tính nam nữ.  Đi xa hơn, loại phim Platoon cũng là thử  cố đánh mạnh vào thị hiếu muốn tham dự vào cuộc phiêu lưu tưởng  tượng của khán giả. Sự phiêu lưu đó nhìn dưới khía cạnh  khác được coi như vai trò thưởng thức của văn chương mà người  không đọc sách không thể nào được  hưởng.<br />
<br />
Thỏa mãn khía cạnh thưởng  thức, truyện ngắn chỉ được  ưa thích đọc, say mê đọc bởi  một số đông độc giả nhưng chưa  phải đương nhiên là truyện hay, bởi  vậy mới có sự kiện best-seller book không được coi là tác phẩm văn  chương đúng nghĩa mà được gọi là văn chương của đám đông  - Dương Hà, Dương Trữ La, Lê văn Trương trước đây là thí dụ. Văn chương của  đám đông có khuynh hướng được để ý nhiều hơn khi được đem  giảng dạy tại một số đại học thật lớn ở Mỹ, nhưng vẫn còn  được nhìn bằng cặp mắt trắng bởi đại đa số nhà nghiên cứu,  phê bình. Nhà văn rất dễ bị hấp  dẫn bởi lối viết văn chương của  đám đông và nếu không cưỡng nổi có lúc nhà văn sẽ làm trái  lại những ý hướng ban đầu  khi bước vào nghề nghiệp.<br />
<br />
Ngoài nhu cầu thưởng thức, con người  còn có nhu cầu thỏa mãn sự tìm  hiểu để biết về chính đời  sống của con người. Truyện ngắn phải đem đến cho người đọc một  kiến thức nào đó về cuộc đời,  làm cho tinh nhuệ, bén nhậy cái ý thức  về cuộc sống. Truyện phải giải thích  cho họ một khía cạnh nào đó về  cuộc đời ở mặt hành động,  xử thế, tâm lý, phản ứng, thái độ. Các mặt này có khi được tác  giả diễn tả riêng rẽ nhưng thường là pha trộn nhau và đem đến cho người  đọc một sự thống khoái rằng  mình thấy được, biết được  một điều lạ.<br />
<br />
Truyện Sợi Tóc của Thạch Lam cho thấy  con người bị đu đưa giữa hai  hành động xấu tốt, thiện ác, khoảng  cách giữa một hành động xấu  với một hành động bình thường  rất nhỏ.<br />
<br />
Truyện Tiếng Thầm Quê Mẹ của Nguyễn  Văn Sâm cho ta thấy lời kêu gọi  văng vẳng sâu kín trong lòng của một  thằng con lai về cái quê hương của  mẹ nó, về những người đồng số  phận với mẹ nó.<br />
<br />
Các chuyện về xứ tuyết của Jack  London cho thấy thái độ của người  dân Esquimo trước cái chết của  tuổi già, trước những điều  lạ mà họ không thể tưởng tượng  được. Truyện Một Đóa Hồng  Cho Emily của W. Faulkner đưa cho ta thấy tâm  lý của một người đàn bà  kiêu kỳ, không còn phù hợp với  cuộc đời trước mặt nữa.<br />
<br />
Điều khao khác hiểu biết của người  đọc sách thì vô cùng và phong phú  ở thể loại. Có thứ cụ thể  (sự tàn ác của cộng sản, đời  sống ở các vùng xa lạ với ta,  nếp sống xưa của người dân miền  Nam, đời sống ờ trại tỵ nạn,  trong bệnh viện...) có thứ trừu tượng  (tánh khí của phụ nữ, thái độ  của đàn ông trước một hoàn cảnh, lòng ái quốc, ý chí hy sinh, lòng  thù hận, sự bao dung, nỗi chán chường, trạng thái bẽ bàng của người tỵ nạn, nỗi cô  đơn của người già...) có thứ  thuộc về một trạng thái tâm lý  nghĩa là một tâm trạng ngắn về một  thái độ (tâm trạng của một người  thầy giáo mất nghề ở Mỹ, tâm  trạng người gặp lại người  tình cũ).<br />
<br />
Khởi thủy của truyện ngắn, người  đọc thích hiểu biết về điều cụ  thể nên truyện ngắn thường là  mô tả con người thiên nhiên và phản ứng của con người trước  một hoàn cảnh. Đó là những hoạt  động thể chất và những xung đột  ở bên ngoài con người.<br />
<br />
Thế kỷ  XIX với sự lớn mạnh của khoa  học về tâm lý và phân tâm, người  viết đi vào những vấn đề trừu  tượng rồi đi vào những sự  phân tích bên trong con người, những  phút giây, những xung đột trong nội  tâm, trình bày cho thấy cái tâm trí,  tâm hồn của nhân vật mà nhà văn  Thế Lữ gọi là giải phẫu tâm  lý.<br />
<br />
Các truyên ngắn loại này xuất  hiện càng lúc càng nhiều tạo nên  trường phái cổ điển. Trường  phái mới này dẫn đầu với Leo Tolstoi, Stephen Crane, James Joyce, John Steinbeck, Edith Wharton,  Joyce Carol Oates, đã tạo nên một nhu cầu  mới trong sự thưởng thức truyện  ngắn và tạo ra một cách viết truyện ngắn mà người đọc nếu đọc  mau, đọc nhẩy cố nắm bắt riêng câu chuyện không thôi sẽ mất đi những  đoạn có ý nghĩa. Sự tranh chấp này cũng gay gắt như sự tranh chấp thơ  mới - thơ cũ trước đây, sự  thắng bại thấy rõ ràng trongtương  lai, nhưng còn cần một thời gian nữa  trường phái cổ điển mới chịu  nhường bước.<br />
<br />
Đáp ứng hai mặt đòi hỏi thưởng  thức và nhu cầu thưởng thức với nhu cầu tìm hiểu của con người,  truyện ngắn cùng lúc diễn tả một  điều gì đặc biệt cụ thể, có  tính cách cá biệt có một không hai  của cốt truyện đồng thời mô  tả một điều có tính cách tổng  quát, trừu tượng về cuộc đời,  về nhân sinh.<br />
<br />
Truyện ngắn không tự mâu thuẫn khi  vừa có tính riêng biệt vừa có  tính tổng quát. Sự đặt thù khiến  người đọc thích thú theo dõi câu chuyện, để nhớ và có cảm tưởng  mình thủ đắc thêm một điều gì  đó mới lạ, sự chung chung đưa  đến sự đồng ý của độc  giả về diễn biến của sự tình,  cho họ khái niệm rằng chuyện nó phải  xảy ra như vậy...<br />
<br />
Một tác giả có tài có thể sản  xuất hàng loạt truyện ngắn hay bằng  cách hòa hợp một cách tinh tế giữa  hai yếu tố đối nghịch nhau đặc biệt  và tổng quát nói trên, Bret Harte của  thời tìm vàng Viễn Tây là một  thí dụ hùng hồn. Bret Harte nổi tiếng bằng một truyện ngắn "The Luck of Roaring  Camp" được cả nước Mỹ  biết tiếng. Truyện của ông in bằng những  ấn bản đặc biệt có hình vẽ đóng  gáy mạ vàng cầu kỳ để trong phòng  khách của hầu hết các gia đình Mỹ  thường hay đọc sách, được  in lại ở Anh, được dịch ra tiếng  các nước Âu Châu. Những chủ  rạp hát hối thúc ông viết thành tuồng các truyện phiêu lưu miền Viễn  Tây lúc mới lập quốc, ông được  mời đi khắp nơi diễn thuyết về  đời sống California... Các truyện nổi tiếng là The Luck of Roaring Camp, The Outscasts of Poke  Flat, The Tennessee's Partner đều có phần đặc  biệt riêng, điểm đặc thù này  khó gặp được ở tác giả  khác; tả thực cái khắc khổ và ngay cả điều xấu xa, bẩn thỉu, đê  tiện của đời sống của những người tìm vàng; mô tả chi tiết  sống động ngay cả với những nhân  vật phụ, làm người đọc bị  mê hoặc. Người đọc Bret Harte thấy  như mình phiêu lưu vào vùng tác giả  kể bằng các chi tiết cụ thể với  các nhân vật của thời đại khai  hoang, giờ không còn nữa (tính đặc  biệt, cụ thể). Người đọc đồng  thời cũng thấy ở tác phẩm của  Bret Harte vấn đề tổng quát muôn thuở  được trình bày một cách tiềm  ẩn nhưng làm ta xúc động, thấm thía,  đó là một phối hợp tuyệt diệu  của trách nhiệm con người trong một  cộng đồng nho nhỏ, đặc biệt. <br />
<br />
Ngoài  tính chất đáp ứng nhu cầu thoát  ly và tìm hiểu, truyện ngắn hay còn cần  yếu tố kỹ thuật. Điều này quá  dài dòng. Đại khái ngày nay khái  niệm truyện không có kết thúc, chỉ  là một mẫu rời của cuộc sống;  nó như chính cuộc đời - không hoàn tất - đang được ưa chuộng,  khiến cho quan niệm cổ điển truyện được  viết theo nhịp ba mở đầu - khai triển  - kết thúc hình như đang ở trong giai  đoạn trở thành bà già còm cõi,  cỗ lỗ. <br />
<br />
<div align="center"><b>***</b></div><br />
<br />
Truyện ngắn hay tạo bởi nhiều yếu  tố đặc biệt khiến cho có sự  kiện nghịch lý là vô vàn nhà văn  nổi tiếng ở địa hạt truyện dài  lại thất bại ở địa hạt truyện  ngắn. Có nhà văn cả đời viết  hàng trăm truyện như tiếc thay gom lại  truyện hay ta không in đủ một tập cho  có bề thế (Bình Nguyên Lộc) có người viết báo này báo kia mang tiếng là nhà  văn nhưng viết mãi chưa được  cái truyện ngắn hay.... Nếu nắm bắt được những yếu tính của truyện  ngắn, nhà văn thất bại trong truyền  dài lại thành công ở mặt truyện  ngắn (Mai Thảo, Kipling, Cheknov, D.H.Lawrence). <br />
<br />
Nhưng tại sao lại truyện ngắn chớ?  Văn chương còn biết bao nhiêu loại  khác; chuyện dài, thơ, kịch, tùy bút,  ký, biên khảo, tạp ghi... Vâng, trong văn  chương ở Mỹ hiện tại thì truyện  ngắn không được ưa chuộng lắm,  tập san SSI (Short Story International) mỗi năm ra  sáu số để giới thiệu các truyện ngắn hay của thế giới cho độc giả  Mỹ mà sống èo uột rồi hình như  đã đình bản. Nhưng đối với Việt Nam thì truyện  ngắn là cửa ngõ rất quan trọng; hầu hết nhà văn đều bắt đầu  bằng con đường này qua các tạp  chí văn học chuyên đăng truyện ngắn,  thơ và hình như không khuyến khích  những thể loại khác.<br />
<br />
Nhóm chủ trương tập sang SSI nói trên  khi kể lý do chủ trương có đưa  ra một câu quan trọng tôi xin dùng để  kết luận bài này:" Truyện ngắn quốc  tế là phương tiện để dân tộc  các xứ hiểu nhau hơn nhờ cái  huyền lực (power and magic) của truyện ngắn  do các nhà văn hiện đại viết ra".<br />
<br />
Việt Nam tự do muốn được dân  tộc các nước hiểu mình hơn cần phải có nhiều truyện ngắn hay, không  phải kiểu "Con Gà Trống" / Tạo  Kim Hai (*).<br />
<br />
Kết thúc bài nầy, tôi muốn nói rằng truyện ngắn như một thiếu nữ, khó phân tích cái đẹp của họ, có thể khó hiểu nữa là khác, nhưng chắc chắn ai cũng biết thế nào là một phụ nữ xấu, vô duyên. Và xin đừng ai đưa một người xấu  lên để nói đấy là người đẹp của dân Việt chúng ta như trường hợp "Con Gà Trống" nói ở trên. <br />
<br />
NVS<br />
<br />
(*) </i>Tao Kim  Hai -- The *bleep*, được  chọn là truyện ngắn  hay của Annam đăng  trong  Tuyển  tập  các  truyện ngắn  hay  thế  giới  -- Crow Puplisher, 1947, trang 845.</i><br />
