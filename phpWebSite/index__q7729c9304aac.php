<h3>Được Thư Bạn Báo Tin Mẹ Mất</h3>



<B>NGUYỄN VĂN SÂM</B><br />
<br />
Bài thơ thay lời tựa <i>Câu hò Vân Tiên</i> (Gió Việt, Texas, 1984)<br />
<br />
Thư anh báo tin mẹ từ trần<br />
Ẩn trong đó muôn ngàn đau đớn<br />
     với long lanh lệ ngấn<br />
Muôn nỗi héo hon.<br />
<br />
Tình nào cao hơn mẹ thương con<br />
Lòng nào đau hơn con mất mẹ<br />
<br />
Anh không quỳ được bên quan tài <br />
Lạy người xẻ thịt banh da nuôi anh<br />
     nên hình nên vóc<br />
Anh không được đi linh cữu<br />
Khóc tiễn đưa vào đất lạnh<br />
Ðấng sanh thành nặng nhọc vì con<br />
Anh không được đứng nhìn thi thể mẹ<br />
     mỏi mòn thân cò lặn lội bờ ao<br />
<br />
Anh nơi đây trắng đêm nhìn những ánh sao<br />
Ðón từng bức thơ tin bịnh thuyên bịnh giảm<br />
Chờ từng tin tức lúc khỏe lúc mê<br />
Bồi hồi <br />
Cắt dạ<br />
<br />
Vì sao mình cách mẹ<br />
Tại ai mình chẳng thấy mộ cha<br />
Lúc mẹ lâm chung<br />
Con cách nửa vòng trái đất vắt vẻo<br />
    trên dàn cao sơn nhà cho dân tộc lạ<br />
Lúc mẹ vật mình<br />
Con cắt cỏ tưới bông lau nhà chùi cửa <br />
    cho những người bạn mới phương tây<br />
Cuộc thế vần xoay<br />
Con không được vấn an từ mẫu<br />
Ðất nước chuyển vần<br />
Con bạc mái tóc vong gia<br />
 <br />
Ðêm hằng đêm con thề mình lúc nào đó<br />
     sẽ về quỳ bên gối mẹ<br />
Khóc nhìn khi thấy lại mẹ già<br />
     tuổi xế bóng dâu<br />
Lẩn quẩn bên từ thân tóc mây tuổi hạc<br />
Trả phần nào chữ hiếu muộn màng<br />
<br />
Rồi ngày tháng lang thang<br />
Chỉ năm ba dòng chữ nát<br />
Mấy chục vần thơ xuông<br />
Ðôi ba bài phiếm luận<br />
Một ít bạn bè<br />
Giặc có chết đâu bằng những nét bút căm hờn<br />
     tím mật bầm gan?<br />
Thiên hạ có tỉnh đâu bằng những trang giấy<br />
     tâm tình moi tim móc mật?<br />
Mẹ ơi, mẹ mất rồi con trả giá quá cao<br />
     mà chí trai chưa trọn<br />
<br />
Nhưng không sao!<br />
Vì con biết mẹ thương con<br />
Nơi kia miền miên viễn xa xôi <br />
Chắc mẹ mỉm cười <br />
Mãn nguyện<br />
Con của mẹ vẫn hẹn ngày về<br />
Thăm mộ cha <br />
Lạy mộ mẹ<br />
Trả chút tình<br />
Khi màu máu đỏ phương đông được thay bằng<br />
     màu xanh tươi thắm<br />
