<h3>Việt Sử Diễn Nghĩa Tứ Tự Ca</h3>



<h3>Nguyễn Văn Sâm và Nguyễn Hữu Vinh phiên âm</h3>
<br />
Ðây là bài ca viết về một quảng dài lịch sử hơn mấy nghìn năm, từ thời vua Ðế Minh là cháu Viêm Ðế Thần Nông thứ ba cho đến khoảng thời gian đức Thế Tổ của triều đình nhà ta lên ngôi. Nay chọn những chuyện lớn viết thành diễn ca cho đàn bà con trẻ biết được đôi điều, càng nhiều càng tốt, để khỏi làm trò cười cho thiên hạ vì không biết chuyện tổ tiên. Dù rằng đã gắng công cố sức sửa sai, thêm bớt nhưng sợ vẫn còn nhiều sai lầm, sơ sót. Mong người đọc lượng thứ cho.<br />
<br />
Kính trình lên để xem xét.<br />
<br />
<b>Thái Tử Thiếu Bảo Hiệp Tá Ðại Học Sĩ quản lĩnh Học bộ Thượng Thư kiêm Lễ bộ Sự Vụ Quốc Sử Quán Tổng Tài kiêm Quốc Tử Giám sung Cơ Mật Viện đại thần Khánh Mỹ Tử Tín Trai Hồ Tướng công.</b><br />
<br />
<b>PHÊ:</B><br />
<br />
<i>Lời văn đơn giản nhưng đầy đủ chi tiết, đây là một việc làm có công lớn đối với lịch sử nước Việt của bậc vương giả.<br />
<br />
Tháng giêng năm Khải Ðịnh thứ sáu.</i><br />
<br />
<h3>Việt Sử Diễn Nghĩa Tứ Tự Ca</h3>
<br />
Hồng Nhung, tự Tiêu Khanh, Tuy Lý Quận Công nhậm chức Hữu Tham Tri bộ Lễ, sung chức Tả Tôn Khanh của Tôn Nhân Phủ.<br />
Hồng Thiết, tự Lục Khanh, con thứ 18 của Tuy Lý Vương, Công Bộ Thị Lang, kiêm chức Nghị viên của hội Vệ Sinh.<br />
<br />
Cùng diễn dịch.<br />
<br />
<br />
