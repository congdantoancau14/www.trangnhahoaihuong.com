<h3>Ai Cũng Biết Thương Yêu</h3>


<b>Everybody Loves Something - Pema Chödrön</b><br />
<br />
<a href="http://www.trangnhahoaihuong.com/files/AiCungBietThuongYeu.pdf">Đọc bằng bản PDF</a><br />
<br />
<i>Bodhicitta</i>, bồ đề tâm, trong đạo Phật cũng còn có nghĩa là một tâm hoàn toàn rộng mở. "Citta" có nghĩa là tâm, và "bodhi" có nghĩa là giác ngộ.<br />
<br />
Con đường phát triển bồ đề tâm là một hành trình cá nhân của mỗi chúng ta. Con đường ấy cũng chính là cuộc đời mà ta đang có đây, một hành trình trên con đường giác ngộ. Nhưng giác ngộ không phải là những gì ta đạt được sau khi đã nghe những lời hướng dẫn, và rồi thực hành cho đúng. Thật ra, trong vấn đề giác ngộ ta không thể nào "thực hành đúng" được hết!<br />
<br />
Trên hành trình ấy, ta đi về một hướng mà mình không biết rõ, và nơi đó ta cũng không thể nào xác định chắc chắn được. Chúng ta chỉ biết tập cho mình có một cái nhìn mới, biết cảm nhận thực tại một cách cởi mở và uyển chuyển hơn. Phát triển tâm bồ đề là một phương cách giúp ta thực hiện được điều ấy. Và chúng ta có thể bắt đầu bằng cách tiếp xúc trực tiếp với những gì đang có mặt, bằng cách nhận diện những cảm xúc của mình.<br />
<br />
Bồ đề tâm thường có mặt những khi ta cảm thấy an tĩnh và hạnh phúc, khi ta biết thương yêu, dù bất cứ dưới một hình thái nào. Trong mỗi giây phút an lạc là bồ đề tâm có mặt. Và nếu ta biết nhận diện và trân quý những giây phút ấy, cho dù nó có ngắn ngủi hoặc mỏng manh đến đâu, tâm thương yêu cũng sẽ từ từ nới rộng ra theo thời gian. Khả năng thương yêu của ta có một năng lượng rất lớn, nếu biết nuôi dưỡng và tưới tẩm, nó sẽ lớn rộng ra đến vô cùng tận. <br />
<br />
Và tâm bồ đề không phải chỉ hiện hữu khi ta cảm thấy an tĩnh mà thôi, thật ra nó cũng có mặt trong những lúc ta cảm thấy tức giận, ghen ghét, ganh tỵ hoặc trong những bất mãn sâu xa. Ngay giữa những cảm xúc tiêu cực và đau đớn nhất, ta cũng vẫn có thể tiếp xúc được với bồ đề tâm của mình, nếu ta biết tiếp nhận chúng với một con tim rộng mở, và ý thức rằng đó là một khổ đau chung. Chúng ta đều cùng chia sẻ với nhau một nỗi khó khăn ấy, khổ đau này không phải là của riêng ai. Ngay giữa một hoàn cảnh khốn khó nhất, ta vẫn có thể nghĩ đến những người đang có cùng một cảnh ngộ như mình, và cầu mong cho tất cả được an vui, được thoát ra khỏi khổ đau. Và mỗi khi ta tiếp xúc lại với cảm xúc ấy của mình, những bức tường chia cách giữa ta và người chung quanh sẽ tự động tan biến mất.<br />
<br />
Trên đảo Cape Breton, nơi tôi ở tại Nova Scotia, vào mùa đông những mặt hồ đều bị đông cứng. Nó cứng chắc đến nỗi người ta có thể lái xe hơi hay xe tải chạy lên ngay trên đó. Nhà phát minh ra điện thoại là ông Alexander Graham Bell khi xưa cũng đã cất cánh phi cơ của ông trên mặt hồ ấy. Nó đông cứng đến như vậy. Và tôi liên tưởng đến những thói quen, tập quán của chúng ta, dường như chúng cũng đông đặc giống như mặt nước đá ấy. Nhưng khi mùa xuân đến, những tảng băng đá đó sẽ tan chảy. Tính chất của nước muôn đời vẫn vậy, chưa bao giờ bị hư hao hoặc mất đi, cho dù là đang ở giữa một mùa đông dài vô tận. Nó chỉ<br />
thay đổi hình tướng mà thôi. Và khi tảng băng tan ra, tính chất mầu nhiệm nuôi dưỡng sự sống của nước lại có mặt.<br />
<br />
Bản chất bao dung và rộng mở của một tâm bồ đề cũng tương tự như thế. Nó bao giờ cũng có mặt nơi này, cho dù lúc ấy ta có cảm tưởng như tình thương của mình hoàn toàn bị khô cằn hoặc chai đá, dường như mình có thể đáp được cả một chiếc phi cơ lên trên ấy!<br />
<br />
Những khi tôi cảm thấy tâm hồn mình như đang ở giữa một mùa đông dài tăm tối, và dường như không gì có thể làm cho nó tan chảy được, tôi chợt nhớ lại hình ảnh này và biết rằng, cho dù tảng băng có đông cứng đến đâu, dòng nước thương yêu vẫn không hề bị khô cạn hay mất đi. Nó lúc nào cũng hiện hữu. Và trong những giây phút ấy, tôi ý thức được tâm bồ đề của mình vẫn đang có mặt, dầu là trong một dạng đông cứng và bất động. Tôi biết rằng, mình có thể làm tan chảy trạng thái đông đặc ấy bằng hơi ấm của tâm từ. Và một phương cách hay nhất là ta hãy tưởng hoặc nhớ đến một người nào mà mình cảm thấy thương mến, thân thiết, hoặc biết ơn. Có nghĩa là ta khơi dậy năng lượng ấm áp đang có mặt sẵn trong chính ta. Nếu như ta không nghĩ ra được một người nào thì ta có thể nghĩ đến một hoàn cảnh nào đó, hoặc một hoa lá nào mà ta ưa thích chẳng hạn. Đạo sư Trungpa Rinpoche thường hay nói, "Tất cả mọi người, ai cũng phải ưa thích một cái gì đó. Cho dù đó có thể chỉ là một ổ bánh mì." Ý ông muốn nói, ta hãy tiếp xúc lại với niềm vui sẵn có trong ta, và nuôi dưỡng nó.<br />
<br />
Hãy nghĩ đến một người hay một hoàn cảnh nào có thể tự động khơi dậy tâm từ trong ta. Tâm từ là ý muốn đem niềm vui đến cho người khác và giúp cho họ được vơi bớt khổ đau. Đó không phải là một lòng thương hại hoặc một thứ tình cảm máy móc, nhưng được phát xuất từ một cảm nhận rằng, tất cả chúng ta đều cùng chung một hoàn cảnh như nhau. Tâm từ là một mối quan hệ bình đẳng. Vì vậy, những khi nào ta cảm thấy như mình bị đông cứng, bạn hãy tiếp xúc lại với tình thương ấy đang có mặt sẵn trong ta - cảm xúc đối với người nghèo khó, đớn đau vì bệnh tật, với những người thân, hoặc với bất cứ ai ở nơi nào - hãy để cho nó làm tan chảy những tảng băng đông đá, và mở rộng con tim mình ra. Tình thương cũng giống như là những yếu điểm trên một bức tường thành kiên cố của cái Ngã của mình. Và chúng ta nên tấn công vào những chỗ hở ấy.<br />
<br />
Nếu như chúng ta chỉ tiếp xúc được với tâm từ trong một giây phút ngắn ngủi thôi, nó cũng sẽ khiến cho khổ đau của ta được mềm ra, và khả năng hạnh phúc của mình sẽ được tăng trưởng thêm một chút. Và trong ngay giây phút ấy, ta tiếp xúc được lại với bồ đề tâm của mình.<br />
<br />
Khi tôi còn nhỏ có những truyện tranh hình về một nhân vật tên là <i>Popeye</i>. Bình thường thì ông ta rất là yếu ớt, và có nhiều khi ông lại bị người khác tìm cách ăn hiếp, hoặc đe doạ. Những lúc ấy ông ta lấy hộp rau <i>spinach</i> ra, và nuốt trọn hết. Ông chỉ cần mở nắp hộp ra và đổ hết vào miệng, và rồi - đùng một cái! Ông trở nên một người có đầy đủ tự tin và một sức mạnh vô địch để đối phó với bất cứ một đối thủ nào. <br />
<br />
Và khi chúng ta dùng những cảm xúc thương yêu của mình để tiếp xúc lại với bồ đề tâm thì việc ấy cũng xảy ra với chính ta! Tâm bồ đề cũng giống như là rau spinach của tâm linh vậy. Nhưng xin các bạn đừng nói lại với ai là tôi đã ví dụ như vậy nhé!<br />
