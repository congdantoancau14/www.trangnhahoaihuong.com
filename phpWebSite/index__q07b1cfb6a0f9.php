(Read: 56903)

</td></tr>


<tr><td><img src="http://internationalpsychoanalysis.net/wp-content/uploads/2008/09/levi-strauss-claude.jpg" align="left" hspace="5">
<div align="center"><br />
<b>TRẦN NGỌC NINH</b><br />
(với sự cộng tác của Trần Uyên Thi)</div><br />
<div align="right"><i>Bài này là của một người học-trò chưa bao giờ được gặp mặt Thày, cũng chưa từng được nghe tiếng nói của Thày cho đến sau khi Thày đã rời khỏi cõi đời đầy chấp-kiến và vọng-ngôn này. Những dòng dưới đây là để kính cẩn dâng lên hương-hồn một vị Thày đã mở mắt cho tôi vào Tình Người trong một địa hạt mà người Việt-Nam thường không nhìn đến.<br />
Trần Ngọc Ninh</i></div><br />
<br />
