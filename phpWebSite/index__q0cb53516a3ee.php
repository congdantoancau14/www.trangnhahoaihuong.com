<h3><h3>Thiền sư TỪ ĐẠO HẠNH và văn khắc chuông chùa Thiên Phúc</h3></h3>



<b>Nguyễn Hữu Vinh dịch và giới thiệu, Thích Thiện Niệm đính chính</b>. <br />
<br />
    Thiền sư Đạo Hạnh là một danh sư đời Lý, có công lớn đối với triều đình. Công đức của ngài được ghi lại nhiều trong Thiền Uyển Tập Anh (3), Lĩnh Nam Chích Quái (4), Đại Việt Sử Lược (6), Ðại Việt Sử Ký Toàn Thư (7), An Nam Chí Lược (12)...<br />
<br />
Theo An Nam Chí Lược, một cuốn sử xưa, quyển thứ 15 viết rằng: <i>"Thiền sư Từ Đạo Hạnh là một nho sinh, thích thổi sáo, ngày cùng bạn đi chơi khắp nơi, đêm đọc sách suốt sáng. Một hôm vào chơi núi Phật Tích, thấy một hòn đá có dấu chân bên phải, ấn chân vào so thử, in như hệt. Về nhà từ biệt cha mẹ vào núi cất am tu hành. Vua Lý chưa có con nối dõi, khiến các thầy chùa danh tiếng cầu đảo. Có một ông sư, không đến làm lễ cầu tự cho vua mà còn dùng phép trám yểm. Vua nghe được bèn hạ ngục tất cả các thầy chùa trong vùng. Nhờ có một hoàng tử, hết lòng cứu giúp mới khỏi. Hoàng tử nói với sư rằng:</i> "Ta cũng không có con, xin sư vì ta mà cầu đảo".<i> Sư nói với hoàng tử bảo với phu nhân vào phòng tắm rửa, sư đi ngang cửa phòng, phu nhân liền có thai. Đến ngày hạ sinh, hoàng tử cho mời sư đến, thì sư đã mất trong núi. Phu nhân sinh được một trai, mặt mũi khôi ngô. Vua Lý lập làm Thái tử…"</i>. Chuyện này khá trùng hợp với chính sử ghi trong sách Đại Việt Sử Lược, thì vị hoàng tử này là Sùng Hiền Hầu, em vua Lý Nhân Tông. Sau vua Lý Nhân Tông vì không có con, nên nhường ngôi cho con của Hầu,, tên là Dương Hoán, sau này là Lý Thần Tông. <br />
<br />
