   Diệu lý tuy chỉ có một mà vọng cảnh [8] thì thật nhiều. Tuy là một nhưng do thiên biến vạn hoá tạo thành. Dù thiên biến vạn hoá tạo thành cũng chỉ là duy nhất mà thôi, không hình tượng mà có thể lường được, không lời nói mà có thể cảm được, không hình tượng mà hiện khắp cõi đại thiên [9], không lời nói mà nghe vang khắp cõi Phật [10]. Nhỏ bé mà không cùng, hổn độn mà không hoá thành đen, ở đời trần bụi mà  trang nghiêm như Hoa Tạng thế giới [11], ở kiếp ô trược mà long lanh như ngọc thạch. Đó là sự may mắn của chúng sinh, chứ chẳng phải ý riêng gì của chư Phật. Kẻ giác ngộ thì thẳng đường lên Niết Bàn, còn kẻ mê lầm thì sinh diệt theo Sáu con đường [12]. Rồi thì cứ lo lắng, giả tướng thì nhiều. Việc thánh hiền sánh như kiến tìm mùi tanh. Chuyện thần lực cũng như gió đè cỏ mọc. Cứu mê tăm tối, bận rộn lăn lóc với những công việc cấp bách, lại phải vươn mang vào tà ma, bệnh tật. Đem lời cổ nhân ra dạy bảo cũng khó làm được. Nay dùng chuông làm vật cảnh tỉnh, mới có thể có hiệu quả dần dần. Việc giáo hoá thì phải tuỳ căn cơ mà tìm phương cách. Thấy giáo lý "Nhất Thừa" [13] là hơn cả, mà chuông là vật quan hệ nhất.<br />
<br />
   Chuông, ngoài Tròn [14], Chắc [15] trong Rỗng [16], Không [17]. Thường sử dụng, quá quen nên hay quên nên gọi là Tròn. Khó bị hư nên gọi là Chắc. Đem vật thọc vào, đổ chứa vào mà không trở ngại gì nên gọi là Rỗng. Ngân nga vang vọng nên gọi là Không. Nếu không phải thì sao Phật cho gõ một tiếng mà sấm trời im bặt, mọi âm vang trên mặt đất đều lặng câm. Đó là lúc trong Tam Giới [18] tỏ ngộ. May mắn biết rằng chúng sinh trong Tam Đồ mãi chịu Khổ. Biết như vậy mà không đem sức mình ra để cứu thiên hạ hay sao? Từ đó về sau, mỗi khi gặp lễ, đèn treo, chỗ sắp, nghe tiếng chuông Phật tử sắp thành hàng. Bước lên bệ gióng chuông thuyết pháp bội phần trang nghiêm. Làm được như vậy, có ai hơn được!<br />
<br />
   Nay có thầy Đạo Hạnh, từ bé cho đến lớn, cốt cách lạ thường, Tụng học kinh Liên [19] sang sảng. Xuất gia hành đạo, thấm nhuần ý Phật từ bi. Xây tháp [20] trang nghiêm. Học kinh kệ thấm nhuần đạo lý. Gặp lúc trời hạn, vung tay một cái trời mưa xuống dầm dề. Học thói người xưa nhịn ăn, ngồi nhiều năm mà vẻ mặt không thấy đói. Dân gặp lúc bịnh dịch, phẩy nước lạnh thì bịnh lành ngay. Việc chưa xảy ra mà đoán biết trước như có phù phép. Kinh dạy rằng Phật có "Tám Lời" [21], nếu không có thầy thì làm sao Tám Lời âm vang tiếp tục. Phật đặt ra "Thi La" [22], nếu không có thầy thì làm sao "Thi La" bền vững. Nếu không có thầy thì làm sao thắp được hương trong vườn phúc của Đế Thích [23]. Dược Vương [24] đốt thịt chữa bệnh, nếu không có thầy thì ai chịu đựng nỗi. Quan Âm cứu nạn, nếu không có thầy thì ai biết đến công đức của ngài. Cao tăng tỏ việc linh dị, nếu không có thầy ai nối gót thần linh?<br />
<br />
   Nay chuyện hành đạo đã xong, muốn tìm nơi ẩn náu. Ra phía tây kinh thành, nơi tĩnh mịch xa, chốn ồn ào huyên náo, đi qua đường lối hiểm nghèo nhưng lòng thanh tịnh. Qua khỏi con sông, gặp núi xanh, leo đường dốc đi lên, đất đá rơi xuống lăn lóc, nắm dây trèo lên nơi cao. Núi này cao ngút bao bọc như núi Lăng Già [25], có trăng thu tròn đẹp, có dốc đá kỳ vĩ, có vòm đá, động đá thờ Phật, có mây ngũ sắc kết tủa như châu ngọc buông rèm, rực rỡ tơ vương đan hình vào nhau như màng nhện. Dưới có vết tích của Phật, giữa có đài nghê tráng lệ. Dấu Phật có ngọc trắng dưới đáy, có rồng xanh bao bọc bên ngoài. Ðài nghê có tê giác đứng trấn bên cạnh. Có đèn treo kết chuỗi thành hàng. Ðây đâu phải chỉ giống phòng phương trượng, mà chính là ngọn Thứu Phong [26]. Ngày xưa các bậc ẩn sĩ góp sức, góp của làm nên, đâu có khác gì thần linh tạo thành? Thầy đến ở chưa tới mười ngày mà đã có điều linh ứng. Cọp tới chầu hầu, rồng kia thuần tính. Ðêm vắng tụng kinh Liên, trời cao vòi vọi vang nghe tiếng trống. Thầy ở suốt sáu năm, ân huệ vun đầy. Các hoàng tử xe ngựa tới lui tấp nập. Mọi người trong nước đến dâng hoa đảnh lễ. Vua cho người lại ban chiếu chỉ, làm tiệc chay cúng dường. Ban cho áo mão cà sa, cung nghinh như bậc thượng khách. Lên xe Phật để cầu Tứ quả [27]. Lễ chay xong rồi, thầy chống gậy đi trở xuống chân núi. Tất cả các đệ tử mọi người cùng nói rằng: “Vách đá dựng đứng, đường đi nguy hiểm. Bước chân như thần của thầy thì đi dễ, chứ khách phàm thì làm sao bước đi được. Xem chỗ đất này cũng là nơi thắng cảnh. Ðồi núi chập chùng đâu khác gì núi Bồ Ðà. Nước trong vắt thua gì biển Hương Hải. Gọi thợ giỏi, chọn nơi chính giữa, xây lầu ngọc sáng chói bốn phương. Giữa đặt tượng Phật hào quang sáng rạng. Mọi người cùng tỏ lời nói này. Cây cỏ rì rào cùng loan tin đi. Trong chốc lát, thiện nam tín nữ tề tựu đông đúc. Chỉ trong một ngày mà quang cảnh trở nên khác lạ. Người đốn cây quý, kẻ xây lò gạch. Thước mực giăng đầy. Búa rìu chan chát. Chốc lát, sân mới nguy nga, gác lầu sừng sững. Trồng tùng xanh cho mát mẻ lối đi. Gầy hoa cảnh cho vườn thêm ngát.<br />
<br />
   Thầy nói rằng: "Chùa thì trang nghiêm, Phật tử thì đông đúc. Gặp lúc lễ lượt thuyết pháp thì phải treo chuông cảnh tỉnh. Phật pháp là chuyện của ta, nhưng chuông thì phải nhờ người". Nói rồi, chống pháp trượng ra đi, thoăn thoắt trên khắp nẻo đường, như lân vờn thú nhảy, như phượng múa rồng bay. Người ta tranh nhau đi theo, chưa tới hai mươi ngày đã quyên được (đồng đỏ) đem về chất một đống cao. Rồi đem đến chùa Hưng Phúc. Gửi thư về tâu cho vua rõ, ngài đã cho phép dựng chùa. Nhào đất làm khuông, đốt lửa luyện đồng Ngày đúc, thầy dù chẳng nói gì, nhưng người người vui vẻ huyên náo. Cám ơn Thái Hậu [28] nhiệt tình cho người đem tặng lễ vật. Rồi thì hết cả nhà giàu đều kéo xe tới, trai trẻ cũng lũ lượt tới giúp đến nối buôn làng vắng vẻ. Người đến đông như đi phiên chợ đông vậy. Chẳng mấy chốc, thợ rèn gắng sức, thợ đúc lo lắng chuẩn bị, thổi ống bệ tiếng nghe vang dội, lửa đỏ cháy rực, chiếu sáng lên tới dãy ngân hà. Chuông đúc xong thấy rõ lạ thường, có nhiều điểm tốt lành. Không lâu sau đó, mời mọi người buộc thừng khiêng lên. Mới chùi mà sáng bóng tợ hoa tuyết. Vừa gõ thì tiếng ngân vang như sấm, vang dậy khắp nơi. Mọi người đều mừng rỡ thích thú. Thầy sắp trở về lầu Đại Bi trên núi Bồ Đà. Dùng dây vàng buộc treo, dùng chày kình đánh chuông, ngày đêm hành đạo. Trước, báo ân dày của Vua [29], cầu mong ngai vàng bền vững. Nhờ pháp khí (chuông) mà dân gian thanh bình, đất nước bình yên, con dân no ấm. Nguyện rằng đem đạo nhiệm mầu, thấu triệt thuần chân làm phúc lớn che chở cho mọi người, để khuông phò nghiệp lớn. Sau, mong cho mọi. người lớn bé cùng nương theo mà hướng đến cõi thiện, cùng theo Phật pháp. Hôm nay có được phúc lành để sau chứng ngộ.<br />
<br />
   Thầy nói với tôi rằng: "Chuông đã đúc xong, vì mọi người có duyên tu tập, còn ta chẳng có công đức gì. Hãy ghi lại tên tuổi của những người đã cúng dường để lưu truyền lại mai sau". Huệ Hưng ít học, cầm bút viết bài minh này.<br />
