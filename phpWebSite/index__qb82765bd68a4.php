<h3>Hãy luôn luôn nói với ba</h3>



<b>Jamie Buckingham (1932-1992)</b><br />
Hoài Hương chuyển ngữ<br />
<br />
<i>“Cuộc đời quá ngắn ngủi, tại sao chúng ta không biểu lộ những tình cảm chân thật trong lòng?”</i><br />
<br />
Gia đình tôi vốn có chừng mực trong quan hệ cư xử.  Chúng tôi ít khi thổ lộ tâm tình với nhau, ít khi ôm lấy nhau, và hầu như chẳng khi nào hôn nhau.  Bọn đàn ông trong gia đình chúng tôi chỉ bắt tay nhau là cùng.  Ba tôi dạy chúng tôi khi bắt tay thì phải xiết thật chặt và nhìn thẳng vào mắt người đối diện.<br />
<br />
Nhưng khi về già, ba tôi trở nên cởi mở hơn.  Ông không còn mắc cỡ khi người khác bắt gặp ông đang khóc.  Ông bắt đầu nắm lấy tay mẹ tôi và hôn bà ngay trước mặt chúng tôi, điều mà chúng tôi chưa từng thấy ông làm khi còn trẻ.  Đôi khi ba tôi còn choàng tay ôm lấy những người đàn bà không phải là  người vợ yêu quý của ông.  Có lẽ người ta cho rằng ông [càng già càng] lẩm cẩm, nhưng tôi thì nghĩ rằng ông chín chắn.  Ba tôi có lần tâm sự với tôi rằng càng về già, ông càng nghiệm ra rằng cởi bỏ những sự gò bó về lễ giáo không có nghĩa là  không đứng đắn.  Cuộc đời quá ngắn ngủi, tại sao chúng ta không biểu lộ những tình cảm chân thật trong lòng?<br />
<br />
Nhìn thấy ba tôi trở nên khoáng đạt hơn trong cử chỉ của ông, tôi cũng muốn bày tỏ tình thương của tôi đối với ba tôi bằng những phương thức có ý nghĩa hơn.  Ấy vậy mà mỗi khi từ biệt ba tôi, thay vì cúi xuống hôn ông, tôi lại chìa tay ra.  Tôi rất muốn nói với ba tôi mấy chữ “Con thương ba”, nhưng có cái gì ở trong cổ họng làm tôi tắt nghẹn, không thốt nên lời.  Tôi không có đủ can đảm!<br />
<br />
Cuối cùng, tôi không chịu đựng được nữa.  Cái khái niệm phức tạp và méo mó của tôi về “đàn ông tính” khiến tôi bị giày vò không ngớt.  Một buổi chiều Thứ Bảy nọ, tôi quyết định lái xe hàng mấy trăm dặm đường về thăm ba mẹ tôi.  Bước vào thư phòng của ba tôi, tôi bắt gặp ông đang ngồi trên chiếc xe lăn, hí hoáy với cuốn sổ chi tiêu của ông.<br />
<br />
“Thưa ba - tôi lên tiếng - con về đây với một mục đích duy nhất: con có mấy lời này muốn nói với ba, sau đó con có chuyện này cần làm.”<br />
<br />
Tự nhiên, tôi cảm thấy xấu hổ.  Tôi đã 46 tuổi đầu, chứ đâu phải là một đứa con nít!  Nhưng nghĩ lại mấy trăm dặm đường mà tôi đã trải qua, tôi quyết định không lùi bước.  <br />
<br />
“Con thương ba lắm!” Tôi nghẹn ngào nói.<br />
<br />
Ba tôi đặt cây viết xuống bàn, đan hai tay để lên bụng, dịu dàng hỏi tôi:<br />
<br />
“Con lái xe mấy trăm dặm đường về đây để nói với ba điều này sao?  Con không cần thiết phải làm như vậy, nhưng dù sao ba cũng rất lấy làm an ủi.”<br />
<br />
“Bao nhiêu năm nay rồi, con đã muốn nói mấy lời này với ba, nhưng sao nói ra miệng thật là khó.  Con thấy viết thư dễ hơn nhiều.” - tôi đáp.<br />
<br />
Ba tôi trở nên đăm chiêu, rồi ông từ từ gật đầu.<br />
<br />
“Còn một điều này nữa, thưa ba,” tôi nói.<br />
<br />
Ba tôi vẫn không ngẩng lên nhìn tôi, ông tiếp tục gật gù.  Tôi cúi xuống hôn ông, trước hết lên má bên trái, rồi đến má bên phải, rồi sau cùng lên vầng trán của ông.  <br />
<br />
Ba tôi với hai cánh tay rắn chắc của ông nắm chặt cánh tay tôi, kéo tôi cúi xuống, rồi choàng tay ôm lấy cổ tôi.  Hai cha con đứng lặng yên hồi lâu trong tư thế vụng về đó.  Một lúc sau, ông buông tôi ra, và tôi đứng thẳng người lên.  Mắt ba tôi ngấn lệ, môi ông run run:<br />
<br />
“Ông nội con qua đời khi ba còn là một thanh niên.  Sau đó không lâu, ba vào Đại học, rồi đi dạy học, rồi sang Pháp.  Sau Chiến Tranh Thế Giới Thứ Nhất, ba trở về nước, nhưng chỉ thỉnh thoảng mới về thăm bà nội.  Lúc bà nội đã lớn tuổi, ba có mời bà về chung sống với gia đình mình.”<br />
<br />
Ông dừng lại, mỉm cười:<br />
<br />
“Con có biết bà nội nói sao không?  Bà nói: “Không, mẹ muốn ở nhà của mẹ, nhưng mẹ rất cám ơn con đã có ý mời mẹ sang ở chung.  Và mặc dầu mẹ sẽ không bao giờ làm như vậy, mẹ mong rằng con sẽ cứ tiếp tục mời mẹ, cho đến ngày mẹ không còn trên cõi đời này.”<br />
<br />
Ba tôi ngẩng lên nhìn tôi:<br />
<br />
“Ba biết con thương ba, nhưng ba mong rằng con hãy luôn luôn nói với ba điều đó, cho đến ngày ba không còn trên cõi đời này.”<br />
<br />
Tôi có cảm giác như vừa quẳng đi một hòn đá nặng trĩu đè lên trái tim tôi bấy lâu nay.  Tôi lái xe về nhà mà thấy lòng tràn ngập một cảm giác nhẹ nhàng, phấn chấn.  Cuối cùng, tôi cũng đã được tự do.<br />
<br />
Virginia, 10/2001<br />
HH chuyển ngữ<br />
