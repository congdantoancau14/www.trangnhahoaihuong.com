<b><h3>Chùa Hà Trung và sư Tạ Nguyên Thiều</h3></b><br />



<b>Nguyễn Hữu Vinh biên soạn</b><br />
 <br />
      Huế không thiếu những ngôi chùa nổi tiếng, không phải vì chùa tọa lạc ở nơi  phong cảnh nên thơ, mà vì các chùa đã đóng vai trò quan trọng trong công việc hoằng pháp giáo lý Phật giáo trong suốt thời gian dài trong quá khứ. Quần thể chùa chiền ở Huế đa số đều tập trung vào các vùng lân cận thành phố, phân bố rãi rác về phía Tây Nam của kinh thành. Ðây là dải đất ven bờ sông Hương,  phong cảnh thiên nhiên hữu tình, sông núi hiền hòa nên sự có mặt của các ngôi chùa này là điều dễ hiểu. Nhưng có một ngôi chùa rất xưa, không nằm trong dải đất ven bờ sông Hương, núi Ngự hữu tình này và đã bị lãng quên trong suốt thời gian dài. Ðó là chùa Hà Trung. <br />
     Từ chùa Thiên Mụ ven theo tả ngạn sông Hương lần đi về thành phố, tạt ngang chùa Báo Quốc, xong hướng về hướng Nam dọc theo quốc lộ 1,  đi khoảng 30 km, dần dần sẽ đến vùng gió cát vi vu thơm mùi nước mặn biển cả. Ðó là vùng kề cận đầm Hà Trung phá Tam Giang. Ngôi chùa nằm trong vùng đầm phá nhiều gió mặn, cát trắng, thuộc làng Hà Trung, xã Việt Hà, huyện Phú Vang, tỉnh Thừa Thiên. Qua biết bao vật đổi sao dời, chùa gần như đã bị lãng quên trong năm tháng chiến tranh, đã bị đổ nát theo thời gian mưa gió. Dù qua những cố gắng trùng tu cách đây không lâu, nhưng vẫn còn cần nhiều nỗ lực hơn nữa mới mong khôi phục dáng nét huy hoàng của thời vàng son xưa cũ.  <br />
    Ngôi chùa này là một trong những ngôi chùa rất xưa ở Huế, đóng một vai trò quan trọng trong lịch sử truyền bá Phật giáo Ðại Thừa ở xứ đàng trong. Chùa tọa lạc ở một địa thế đặc biệt, vì chùa được xây dựng trên con đường giao thương bằng đường thủy giữa Hội An và Huế, cách xa vùng chùa chiền danh tiếng chung quanh thành phố. Chùa có một quá khứ hiển hách là vì chùa có một nhà sư đặc biệt trụ trì. Ðó là sư Tạ Nguyên Thiều (謝元韶). Sư này là ai, gốc gác ở đâu? Sách Đại Nam Nhất Thông Chí (1) quyển Thừa Thiên, phần tăng lữ viết: “…Tạ Nguyên Thiều tên Thụy là Hoán Bích, người gốc Triều Châu tỉnh Quảng Đông, nhà Thanh, xuất gia lúc 19 tuổi. Qua Đại Việt thời Thái Tông Hoàng Đế (tức chúa Hiền Nguyễn Phúc Tần (1648-1687)), đến Qui Ninh (Nay Quy Nhơn) xây chùa Di Đà, hoằng dương Phật pháp. Sau đó ra Thuận Hoá, xây chùa Quốc Ân. Tạ Nguyên Thiều vâng lệnh Anh Tông Hoàng Đế (1687-1691) sang Quảng Đông mời cao tăng Thạch Liêm Hoà Thượng”. <br />
      Ngược dòng thời gian, bước vào giữa thế kỷ 17. Ở Trung Quốc, nhà Thanh đánh đuổi nhà Minh. Vua Thanh Thái Tổ diệt nhà Minh và lên ngôi năm 1644. Từ đó, những phong trào phò Minh diệt Thanh xảy ra khắp nơi. Đấy là vào thời dân Tàu thờ nhà Minh tràn qua lánh nạn nhà Thanh ở Đại Việt ta, sinh ra lượt sóng di dân từ miền nam Trung Quốc sang. Cũng vào thời đó, chính là lúc Trịnh Nguyễn phân tranh. Ở đàng trong các chúa Nguyễn tìm cách củng cố đế nghiệp để chống chọi với chúa Trịnh ở phương bắc. Các chúa Nguyễn ngoài việc lo chống cự với chúa Trịnh, nhưng đồng thời cũng lo bành trướng thế lực vào phương nam. Thế nên các chúa Nguyễn đã khôn khéo trong việc sử dụng nguồn nhân lực và tài lực của người di dân gốc Minh này. Sư Tạ Nguyên Thiều cũng là một trong những người di dân đó. Ban đầu sư theo các tàu buôn vào cửa Quy Nhơn, ở lại lập nghiệp và hoằng pháp Phật giáo. Một khoảng thời gian sau mới ra Thuận Hóa hoằng pháp và xây dựng nhiều chùa chiền ở đó. Cũng trong thời gian này, khi dòng người Minh Hương tràn sang, Phật giáo Ðại Thừa cũng dần dần bắt mầm, nẩy nở, ảnh hưởng lớn đến đời sống của dân ta, nhất là trong giới vua chúa. Chúa Ngãi Nguyễn Phúc Trăn (Thái) (1687-1691) đã  hạ lệnh cho Tạ Nguyên Thiều qua Quảng Đông mời sư Thích Đại Sán, sư Thích Đại Sán hiện nay còn được thờ phụng tại chùa Thiên Mụ, Huế, sang Đại Việt hoằng pháp. Bia của chúa Nguyễn Phúc Chu (1691-1725) dựng tại chùa Quốc Ân, Huế, đời Lê Dụ Tông thứ 10 có viết: “Hoán Bích Thiền Sư Tạ Nguyên Thiều ở chùa Hà Trung (Thừa Thiên) vâng lệnh chúa Nghĩa sang Quảng Đông mời Đại Sán Hoà Thượng”.  Dù chuyện sư Tạ Nguyên Thiều sang Quảng Ðông mời sư Thích Đại Sán qua Ðại Việt không thành, song đây là chính cơ duyên để sau này khi chúa Nguyễn Phúc Chu lên ngôi, cho người sang mời lại và  sư Ðại Sán đã nhận lời. Chuyến đi này đã được ghi  lại trong sách của sư Thích Ðại Sán, còn lưu truyền lại đến ngày nay là Hải Ngoại Kỷ Sự (海外紀事)(2). Vào thời Hiển Tông Hoàng Đế (chúa Nguyễn Phúc Chu), sư Tạ Nguyên Thiều được chúa cho ra trụ trì ở chùa Hà Trung cho tới lúc mất. Sau khi mất, sư được Hiển Tông Hoàng Đế tặng tên Thụy là Hạnh Đoan Thiền Sư (1).<br />
     Vết chân của sư Tạ Nguyên Thiều trên đất nước miền trung Việt Nam từ Quy Nhơn cho tới Huế, đã xây dựng nhiều ngôi chùa nổi tiếng. Những ngôi chùa này vẫn còn hiện hữu cho tới bây giờ, như chùa Quốc Ân, Di Ðà, v.v. Sự nghiệp của sư cũng lớn lao thể hiện qua việc được chúa Nghĩa Nguyễn Phúc Trăn tin dùng và phái qua Quảng Ðông mời sư Thích Ðại Sán. Với công lao lớn như thế, nhưng không hiểu vì lý do gì mà đến bây giờ tên tuổi của sư ít được ai biết đến, bị quên lãng dần theo với thời gian năm tháng.  Trong khi Thích Ðại Sán chỉ qua Ðại Việt theo lời mời của chúa Nguyễn Phúc Chu đến hoằng pháp ở Thuận Hóa một thời gian ngắn, may mắn được chúa Nguyễn Phúc Chu tôn làm thầy để quy y Bồ Tát Giới lại được hưởng hương khói ngàn năm ở chùa Thiên Mụ. Sách Đại Nam Nhất Thống Chí, sách được tu bổ sau các sách Đại Nam Thực Lục, cũng chỉ ghi lại công lao hoằng pháp của sư Tạ Nguyên Thiều (Hạnh Đoan Thiền Sư) mà thôi.<br />
     Chùa Hà Trung ở trong vùng đầm phá, giữa trời mây nước đồng ruộng bao la, phong cảnh thiên nhiên hữu tình. Bước vào chùa phải đi ngang ao sen nhỏ, quanh vườn đủ loại cây cảnh. Cảnh vật không khác gì nhiều so với cảnh vật điển hình của một ngôi chùa ở Huế. Chùa còn lưu giữ một tượng Phật bà Quan Thế Âm bằng đá khá cao khoảng hơn 2m, chạm trổ tinh xảo, phảng phất hình nét chạm trổ của thợ chạm Trung Hoa. Chùa cũng còn có một chuông đồng rất xưa quý giá. Ðây là hai bảo vật, chứng tích của sự di dân của dân Minh Hương còn để lại. Chùa Hà Trung không biết được xây từ đời nào. Chùa đã hiện hữu rất lâu ở đây. Trong cuốn Hải Ngoại Kỷ Sự của sư Thích Ðại Sán có ghi lại ba bài thơ tả cảnh chùa Hà Trung rất hay , khi sư đang trên đuờng từ Thuận Hóa vào Hội An, từ đó theo các thuyền buôn để trở về lại Quảng Ðông vào năm 1695. <br />
