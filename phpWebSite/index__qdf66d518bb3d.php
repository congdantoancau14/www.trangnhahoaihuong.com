<h3>THƠ ĐƯỜNG với Nguyễn Hữu Vinh - bài 2</h3>



<h3>Thái Kim Lan ghi và bình</h3>
<br />
TỐNG LINH TRIỆT<br />
<br />
Thương thương Trúc Lâm tự<br />
Yểu yểu chung thanh vãn<br />
Hà lập đái tà dương<br />
Thanh sơn độc quy viễn<br />
<br />
<i>Lưu Trường Khanh</i><br />
<br />
Bóng chiều xanh nhạt vùng chùa Trúc Lâm<br />
Xa nghe tiếng chuông chiều rời rạc vọng lại<br />
Chiếc nón lá sen phản ánh bóng nắng chiều<br />
Một mình bác đi về giữa núi biếc<br />
<i>Nguyễn Hữu Vinh dịch nghĩa </i><br />
<br />
<b>Lời ghi của người dịch:</b><br />
<br />
Tiễn đưa bạn trong bóng chiều tịch mịch, thời gian đọng lại như tâm tình bạn đậm đà không tan loãng được. Một tiếng chuông chùa xa vọng lại đánh thức dậy sự thật buồn tênh. Bạn đã đi rồi, ta còn quyến luyến đưa mắt đưa tiễn theo bóng nắng chiều rọi trên chiếc nón xa trong núi xanh.<br />
<br />
Tiễn bạn Linh Triệt<br />
<br />
Trúc Lâm chiều tím nhạt<br />
Rời rạc tiếng chuông chùa<br />
Nón lá còn vương nắng<br />
Bạn về trong núi xa.<br />
<i>Nguyễn Hữu Vinh dịch thơ</i><br />
<br />
<b>Thái Kim Lan bình:</b><br />
<br />
Vừa từ Việt nam trở lại Đức, đến nhà chưa nóng chỗ ngồi, vội tạt qua quán trà Thơ Đường hơn cả tháng không tới lui. Chưa kịp kêu “ui chao ơi khát trà!“ ồn ào như thường lệ, thì đã thấy ông chủ quán lù lù ngồi sẵn đó từ bao giờ với chén trà đượm mùi Thiền “Tống Linh Triệt“ và tiếng ngân nga của chuông chùa Trúc Lâm, lắng đọng. <br />
Trên vai áo bụi đường chưa rũ sạch của kẻ hành nhân còn quáng nắng quê hương, mình tự hỏi mình, ta đã VỀ (quy) hay ta đang ĐI (viễn) ? <br />
Thấp thoáng nghe trong tiếng chuông có lẫn tiếng hát rong nghêu ngao của tên “du tử một thời“ vang vọng “trong khi ta về lại nhớ ta đi" thân thuộc gần gũi từ cõi xa mô đó của Huế xưa (1). Chiếc ghế đang ngồi bỗng lênh đênh như một chiếc thuyền nan trôi giạt trên giòng sông Hương vào một buổi chiều mông lung sắc tím. Ai đã một lần về Hương Giang của Huế thường không thể quên được vùng ảo hoá “tím cả chiều hoang biền biệt“ giữa núi vàsông như một loại hương thơm bí ẩn kỳ diệu làm ngây ngất tâm hồn. Sáng, trưa, chiều ai đi qua cầu Trướng Tiền đã trót một lần ném mắt nhìn sông đều cảm thấy từ đó vướng vất trong lòng ảnh tượng của vùng màu "thương tử" (màu tím xanh) mênh mang. Huế buổi chiều nhìn về phiá núi ẩn hiện màu xanh lam, khi có mây vờn ánh tà dương bay qua là lúc không gian thoáng ngợp một màu tím xanh “thương tử“, khi nắng chùng xuống lưng đồi ấy là lúc cả vùng sông nước thăm thẳm chết đuối trong một màu tím "than" hết đường cứu vớt...Rồi năm, rồi tháng, màu tím Huế cứ như một loại hương độc nhẹ nhàng lây lất ngấm dần trong tâm khảm người Huế, trở nên một thứ bệnh âm thầm dai dẳng khi có khi không, một thứ bệnh kinh niên chỉ có nơi người Huế. Chưa có người xứ nào trên đất nước Việt Nam đi xa mà lại nhớ cảnh nhớ người như người Huế, có lẽ cũng chỉ vì cái màu “tím Huế“ vừa mộng mơ vừa u uất đã tẩm sâu trong từng  kinh mạch...<br />
<br />
“Ơ kìa ông chủ quán, trà đang chảy tràn ra khỏi chén mà sao ông không dừng ?“ (2)<br />
<br />
Có phải ông cũng đang bị “vương“ (3) màu tím Huế cho nên mới bạo gan đổi chữ “thương thương Trúc Lâm tự“ của Lưu Trường Khanh ra “Trúc Lâm chiều tím nhạt“ không ? Lần trước ông đã đổi “Lạc Thành“ và khúc “Chiết Liễu“ của Lý Bạch ra Thành Nội Huế và khúc Thiên Thai, ai cũng niệm tình “cố viên“ mà tha thứ. Nhưng lần này e khó thoát. Nhà phê bình văn học Đặng Tiến đang chờ ông trước tam tòa cùng với các vị thi bá nêu tội “dịch bậy bạ“ của ông nơi tề ! Coi chừng bị tru di ! Hãy mau mau hồi đầu lai tỉnh, đổi lại “Trúc Lâm màu tím nhạt“ thành màu lam u mặc đượm mùi Thiền vị cho đúng đắn với chữ nghĩa cho rồi !<br />
<br />
Mà quả thật như thế. Cả bài thơ chỉ bàng bạc một vị Thiền từ câu đầu đến câu cuối. Những nét chấm phá mơ hồ sương khói “thương thương“, “yểu yểu“ gây ấn tượng nhẹ nhàng “có mà không“ của cảnh trời biệt ly, tạo nên “màu“ thời gian (nắng chiều) và “tiếng“ không gian (chuông chùa Trúc Lâm) cho hai câu theo sau. Trong hai câu kế tiếp có thể nói thi nhân đã dụng từ đến mức thượng thừa để tả... nói là tả nhưng thật ra là vẽ... nhưng không phải là vẽ cảnh mà là vẽ trong lòng người đọc “nỗi niềm đi xa“  “độc qui viễn“. Ở đây có AI đi AI về ? Hình như chẳng có ai!  Chỉ có một nỗi “ĐI – VỀ” trong núi rừng xanh ngát của một giọt nắng trên vành lá sen đang chuyển động. Giọt nắng có biết buồn ly biệt ? Nếu có,ủ ê chỉ có MỘT nỗi sầu được xẻ làm hai, cho nên chẳng có ai buồn hơn ai trong ”Tống Linh Triệt", bởi vì ở đây chẳng tìm ra được một cái NGÃ để buồn, mọi chuyển động QUI –VIỄN đều là những giọt nắng nhấp nhô trong cảnh núi rừng hoàng hôn, mà mỗi rung cảm đều là những rung động chung cho cả người đi lẫn kẻ về.<br />
Nghệ thuật kỳ tình của Lưu Trường Khanh có thể nói nằm vỏn vẹn trong hai hình ảnh: nắng trên nón và độc qui viễn. Nhà thơ không tả người mà chỉ tả cảnh, nhưng ta biết đó là người. Nhưng lại không phải là con người cá nhân riêng biệt theo khái niệm tây phương mà là một tiểu ngã trong đại ngã vũ trụ vô cùng.<br />
Khi đọc câu “Nón lá còn vương nắng" (“Hà lập đái tà dương”) bất giác người đọc nhớ đến Descartes trong “Meditatio II”(4) khi ông lý luận về sự hiện hữu của TÂM (mind, l esprit) phân biệt với ấn tượng giác quan. Cái gì làm cho ta đi đến kết luận có người đang đi qua dưới đường, khi ta chỉ thấy qua khung cửa sổ chiếc mũ và tà áo đang chuyển động mà không thấy toàn diện con người ? Descartes bảo không phải do thị giác của chúng ta, bởi vì thị giác chỉ thấy mũ và áo là hai ấn tượng rời rạc, mà chính do ”khả năng phán đoán”, chính do TÂM khởi, suy ra từ ấn tượng mũ áo đến toàn diện con người, để “biết” có người đang đi.<br />
Có phải các nhà thơ Đường đã nắm được yếu quyết chữ TÂM của Huệ Năng và Descartes ? “Không phải gió động, cũng không phải tấm vải động, mà chính TÂM ta động” (5) , nên chỉ cần một giọt nắng trên vành mũ lá sen cũng đủ cho ta biết có người đang đi trong núi rừng, càng lúc càng xa, đơn độc, một mình trong cõi đi – về, và cả một chuỗi vui buồn từ đó theo nhau…<br />
Trông cảnh không thấy người mà tràn đầy tình người.<br />
Nhưng cũng  chính ở điễm này chữ TÂM của Huệ Năng và của các nhà thơ Đường tách rời quan điểm của Descartes với khái niệm về một cái ngã cá nhân chủ thể đối nghịch với tha nhân. Chữ TÂM trong ”Hà lạp đái tà dương, Thanh sơn độc qui viễn” gói trọn cả “người đi kẻ về” trong một nhất thể rung cảm của thi nhân.<br />
Chính cơ cấu ngôn từ của hai câu thơ cuối cũng nói lên được đặc tính nhân sinh quan “vô ngã” của tư tưởng Thiền và văn học Á đông : trong giọt nắng lung linh có bóng người như một ý niệm vô ngã, trong “độc qui viễn” không có một chủ thể như một cái tôi tuyệt đối, mà chỉ có sự “ĐI –VỀ”  đơn độc trong cát bụi vô cùng<br />
Nghệ thuật thi ca của họ Lưu tài tình đã biến cái nhìn Thiền học thành thơ và đã đưa chất thơ thấm nhập vào không gian bao la rộng lớn của tư tưởng Thiền. <br />
Toàn thể bài thơ là một bức tranh Thiền đạt đạo trong nguyên tắc giảm thiểu tối đa màu sắc, ánh sáng và âm thanh đưa người đọc trở về những cảm xúc nguyên thủy nhất : màu lam u mặc của khói sương và núi rừng xa thẳm làm nền cho “giọt nắng”, điểm sáng linh động duy nhất của toàn thể bài thơ đi đôi với âm thanh thô kệch “độc quy viễn” tạo nên một tương phản đen trắng gây biến động trong TÂM người đọc và với tiếng chuông ngân nga, ngưởi đọc có cảm tưởng tâm mình đang chuyển cùng với giọt nắng vô ngã để thong dong Đi –VỀ trong vũ trụ bao la.       <br />
Cho nên, này ông chủ quán bán trà thượng hảo hạng ! Nếu đưa chữ “bác” hay “bạn” vào trong câu cuối “Bạn về trong núi xa” để lập văn theo kiểu tây phương thi e rằng người đã phá vỡ vũ trụ quan thi tứ “vô danh thiên địa chi thủy” (6) tuyệt vời của Lưu Trường Khanh! <br />
Tội nớ thiệt đáng phạt mấy trượng !<br />
<br />
