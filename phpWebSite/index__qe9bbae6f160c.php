<h3>Nguyễn Văn Sâm và Khói Sóng Trên Sông</h3>



<b>NGUYỄN XUÂN HOÀNG</B><br />
<br />
Văn chương Nam Kỳ Lục Tỉnh vẫn luôn luôn lôi cuốn tôi. Truyện của Hồ Biểu Chánh, Sơn Nam, Kiệt Tấn, Bình Nguyên Lộc, Lê Xuyên, Nguyễn Thị Thụy Vũ, Vương Hồng Sển, Huỳnh Phan Anh, ... và trong những năm tháng sống xa quê hương, được đọc Cao Đông Khánh, Hồ Trường An, Nguyễn Văn Ba, Võ Kỳ Điền, Trần Long Hồ, Bùi Thanh Liêm, Nguyễn Tấn Hưng, Lương Thư Trung, Nguyễn Thị Long An... với tôi là một hạnh phúc. <br />
<br />
Đó là những tác giả mang đến cho người đọc không khí của miền đất "hảo hớn", bầu trời của "bao dung và cởi mở", hơi thở nồng nàn của ruộng đồng, sự thơm tho của cây trái, cái dào dạt mênh mang của dòng sông Cửu Long... <br />
<br />
Đó là chưa kể Tô Thùy Yên, mà tiếng thơ của ông đã bay trùm lên khắp miền đất nước như một cái bóng lớn trong thế giới thi ca Việt Nam... Có thể tôi còn thiếu sót một số tên tuổi khác trong những tác giả Nam Kỳ Lục Tỉnh, nhưng một tác giả tôi không thể quên, đó là Nguyễn Văn Sâm, người bạn từ năm 1969 đã viết Văn Chương Tranh Đấu Miền Nam (1971), Văn Học Nam Hà (1972), Văn Chương Nam Bộ; và những năm tháng tại Mỹ ông đã viết Câu Hò Vân Tiên (Texas, 1985), Ngày Tháng Bồng Bềnh (Texas, 1987). Mười ba năm sau khi in tập truyện Ngày Tháng Bồng Bềnh, Nguyễn Văn Sâm vùa gửi đến người đọc những sáng tác mới của ông: Khói Sóng Trên Sông. Trong một email, ông hỏi tôi "tao sẽ in tập truyện mới. Nhà xuất bản Văn đứng tên được không?" "Tại sao không?" Tôi đã trả lời ông như vậy. Chúng tôi quen nhau đã lâu. Cùng học chung trường Petrus Ký, cùng đi quân trường Quang Trung, từng cà phê cà pháo ở những quán nước Sài Gòn. Sâm là một người chân chất, và thẳng thắn -như đa số người miền Nam. Ông quả là một người bạn tốt. Tuy vậy, về chuyện chữ nghĩa văn chương, ít ra là thời bấy giờ, những năm sáu mươi-bảy mươi ở Sài Gòn, ông và chúng tôi không cùng chung một quan điểm. Nguyễn Văn Sâm lúc đó viết biên khảo hơn là sáng tác. Có vẻ công việc dạy học đã đặt ông vào cái thế một công đôi chuyện. <br />
<br />
Hồi đó, bọn chúng tôi -Huỳnh Phan Anh, Nguyễn Đình Toàn, Nguyễn Quốc Trụ, Nguyễn Nhật Duật, Đặng Phùng Quân - vẫn thường lê la ở quán Cái Chùa mỗi sáng, nói đủ thứ chuyện giữa những ly cà phê trước khi đến sở làm. Trong khi chúng tôi, nói theo Huỳnh Phan Anh, 'đi tìm tiểu thuyết mới ở Việt Nam, dòng tiểu thuyết ly khai với truyền thống cũ, thuộc Tự Lực Văn Đoàn, hoặc nói rộng hơn, ly khai với tiểu thuyết giai đoạn tiền chiến" thì Nguyễn Văn Sâm hết Văn chương miền Nam, tới văn chương Nam bộ, hết Vũ Anh Khanh, Thẩm Thệ Hà, tới Dương Tử Giang,… Ông cứ đi ngược lại với bọn tôi. <br />
<br />
Khi cuộc chiến kết thúc, chúng tôi mỗi người một ngã. Kẻ ở, người đi. Văn chương chữ nghĩa trong một thời đại hoài nghi trở thành trò chơi của tội lỗi. Sách vở từ trong tủ kính rủ nhau bước xuống chợ trời. Như những hạt bụi bị trận cuồng phong thổi tung, chúng tôi bay đi mười phương tám hướng. Và sau cùng như những hạt bụi, chúng tôi lại gặp nhau. <br />
<br />
Houston, nơi tôi đã đôi lần đến. Nhiều người bạn cũ đã gặp. Nhiều người bạn mới vừa quen. Cách đây mấy năm là Tường Vy &amp; Cao Hữu Tích. Gần đây là Phương Hoa &amp; Đăng Khánh. Bữa cơm gia đình nhà Duy Trác thân tình và đầy những nụ cười. Bữa cơm nhà anh chi Minh &amp; Điệp Mỹ Linh tôi đã chạy đến theo cây kim đồng hồ. Gặp lại Đặng Phùng Quân, Hàn Song Tường, Ngu Yên, Trương Trọng Trác, Vũ Thanh Thủy &amp; Dương Phục, vợ chồng Phạm Quang Tân, Nguyễn Vĩnh Châu. Và phải chờ đến trưa ngày hôm sau mới gặp lại người bạn già Nam Kỳ-Lục Tỉnh Nguyễn Văn Sâm. <br />
<br />
"Mày nói cho tao mấy lời trong buổi ra mắt sách của tao." Nguyễn Văn Sâm đã dặn như thế cả tháng trời trước khi tôi đến Houston. "Nói thì nói." Tôi trả lời như vậy, nhưng thực sự lòng chưa biết sẽ nói gì. Tôi được Sâm cho đọc bản thảo trước. "Viết cho cái tựa đi, cha nội." Sâm nói như ra lệnh. Sắp tới ngày ra mắt sách, tôi vẫn chưa gửi qua cho Sâm cái tựa. Còn hơn một tuần tôi email bài viết. Sâm trả lời "không convert được." Phải nhờ đến Nguyễn Vĩnh Châu. Và đâu cũng vào đấy. "Cái thằng, coi bộ vậy mà cũng công tử Bạc Liêu chớ!" Tôi đã nghĩ về Nguyễn Văn Sâm như vậy. <br />
<br />
Tôi thú thật là đến Houston mấy lần mà chẳng biết gì về thành phố này. Từ phi trường về đến nhà Tường Vy, hoặc nhà Phương Hoa, hoặc khách sạn. Và một tiệm ăn nào đó. Là hết. Houston sau cùng chỉ là những trang sách. Lần trước cách đây mấy năm nghe một chương trình nhạc và vinh danh một số người. Lần sau nghe nhạc Đăng Khánh với Tuấn Ngọc, Thanh Hà, Thái Thảo. Lần này, đến với Nguyễn Văn Sâm được gặp những người quen cũ: Doãn Quốc Sỹ, Vũ Ngự Chiêu, Cao Đông Khánh, Lê Quỳnh Mai [cũng hơn mười năm rồi, khi ngày đầu tiên đến Montreal giới thiệu số ra mắt tạp chí Thế Kỷ 21 và cuốn truyện dài Sa Mạc] , gặp giáo sư Đàm Trung Pháp, và những người đã từng đóng góp bài vở cho Văn: Quan Dương, Phạm Ngũ Yên, Thu Thuyền, Kiều Mộng Hà, Phạm Quang Tân, Nguyễn Anh Tuấn...  <br />
Phải nói là bài của giáo sư Đàm Trung Pháp giới thiệu và phân tích về Nguyễn Văn Sâm rất hay. Ông cho thấy một Nguyễn Văn Sâm là nhà văn sử dụng nhuần nhuyễn về ngôn ngữ Đồng bằng sông Cửu Long. Ông cho rằng tập truyện Khói Sóng Trên Sông của Nguyễn Văn Sâm "là một rừng thành ngữ bình dân, nghe lên thì khoái tai, mà đọc lên thì khoái mắt." <br />
<br />
Tôi chia xẻ ý kiến của giáo sư Pháp: Toàn tập truyện của ông Nguyễn tràn đầy lời ăn tiếng nói dân gian của sông Tiền sông Hậu. Truyện của ông nặng chất ký mà nhẹ chất tiểu thuyết. Có thể nói Khói Sóng Trên Sông là bức tranh vẽ lại sự hình thành của đô thị Sài Gòn. Không phải một Sài Gòn bề mặt với những con đường "cây dài bóng mát", những quán cà phê đợt sóng mới, những vũ trường sang trọng trai thanh gái lịch và người hùng. Nguyễn Văn Sâm đã nhìn Sài Gòn từ cái phía trái của nó. Bóng tối và sự khốn khó. Sài Gòn của mồ hôi và nước mắt. Đó là Xóm Sáu Lèo, là đình Tân Kiểng, là khu Mã Lạng, là Xóm Chiếu, là Chánh Hưng, là Chợ Cầu Kho, là Bến Tắm Ngựa,... <br />
<br />
Nguyễn Văn Sâm là một người kể chuyện hơi rề rà nhưng có duyên. Ông không vội vàng và người đọc ông cũng không có ý muốn ông phải gia tăng tốc độ. Ông cứ nhẩn nhơ nói, như một người đọc thơ Lục Vân Tiên, và người nghe có thể vừa nghe vừa uống rượu hoặc nhấp chén trà tàu. <br />
<br />
Trong thế giới văn chương miệt vườn, Nguyễn Văn Sâm là người nắm khá vững ngôn ngữ Nam Kỳ-Lục Tỉnh nhất. Cũng dễ hiểu tại sao ông không sáng tác cùng thời với chúng tôi. Chính là những bài biên khảo về văn chương Nam bộ đã giúp ông sau đó - thay vì nghiên cứu - đã viết thẳng bằng trái tim. <br />
<br />
Sài Gòn của Nguyễn Văn Sâm đích thực là Sài Gòn của những con người nào được nó nuôi dưỡng, dạy dỗ, và làm cho nó lớn lên. <br />
<br />
<I>Khói Sóng Trên Sông</I> là một tác phẩm văn chương của một người cầm bút thực sự. <br />
<br />
