<h3>Màu Thời Gian</h3>



<b>NGUYỄN VĂN SÂM</b><br />
<br />
Sau thời gian địa ngục đằng đẵng, tôi trở về với cái xách tay rách và tờ giấy trả về nguyên quán in trên giấy đen cáu bẩn. Tấm giấy quỷ quái nhiều người mòn mỏi đợi chờ đến biến tánh và biến thể. Bầu trời xanh trong vắt như pha lê trên đầu. Chim rừng líu lo ca hát tiễn đưa người vừa trả xong món nợ lạ lùng nhất thời đại. Món nợ chồng lên đầu dân tộc bất ngờ như trận mưa xối xả tưới ào xuống thành phố không một dấu hiệu báo trước. Mấy năm vô lý trong trại mỗi ngày qua như một thế kỷ đè nặng lên tâm hồn khô cằn vì căm hờn tủi nhục rồi cũng qua. Tôi thở dài. Thoát nợ. Trong sự rộn rã của một con chim chùn chân đã lâu khi thấy bàn tay nào đó sắp mở cửa lồng, tôi đè nén sự xúc động bằng cách chậm rãi xếp những đồ nhật dụng đã tẩn mẩn tỷ mỷ chế tạo trong những ngày nghỉ ngơi suốt khoảng thời gian đày ải, mắt cố tìm một vài người bạn xấu số hơn để nói lời từ biệt hoặc giả lén nhận chuyển giùm tin tức cho gia đình. Họ đã đi lao động hết trơn...Tôi muốn chửi thề. Tụi nầy mánh thiệt. Cho về mà không báo trước để chuẩn bị, giấu như mèo giấu cứt. Thế là có lẽ tôi sẽ rời nơi nầy, nơi chôn một phần tuổi thanh xuân của mình - mà không gặp được những người bạn đã cùng mình chia lao xẻ khổ.<br />
