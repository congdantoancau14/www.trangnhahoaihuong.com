Cánh cửa thời gian đã nhốt tôi lại, đã tàn ác chém chặt gọt đẽo hình hài tôi, đã quăng ra đời một xác héo úa khô cằn, khác hẳn con người sống động tươi mát nó đã ngoạm lúc trước. Nhiệm vụ hoàn hảo đến nỗi chính người thân thiết của tôi cũng không nhận ra. Bi hài ở chỗ đó. Cầu mong màu thời gian xanh xanh mãi mãi với nàng. Riêng tôi màu tím ngắt chắc sẽ theo đuổi lâu dài sau mấy năm đọa đày từ ấy. Bài thơ tình của một tác giả ưa thích nhảy vào trong trong tôi, biến thể một cách đáng thương và phù hợp.<br />
