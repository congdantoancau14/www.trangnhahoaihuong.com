<tr><td><h3>Sắp ra mắt <i>Lộc Minh Đình Thi Thảo</i></h3></td></tr>


<tr><td>

Posted by: HoaiHuong on 08/06/2006 04:45 AM 


</td></tr>


<tr><td><br />
<i>Lộc Minh Đình Thi Thảo</i> là một tập thơ chữ Hán, gồm 197 bài, do thi ông nổi danh của sông Hương núi Ngự, Ưng Bình Thúc Giạ Thị, sáng tác.  Dịch giả Nguyễn Hữu Vinh, bằng một sự rung cảm bén nhạy với tâm hồn của nhà thơ, và với lòng yêu văn hóa Việt Nam tha thiết, đã bỏ ngót hơn 4 năm trời dày công phiên dịch và chú giải tập thơ này.<br />
<br />
Trangnhahoaihuong.com, được sự uỷ thác của dịch giả Nguyễn Hữu Vinh và nhà thơ Tôn Nữ Hỷ Khương - ái nữ của cố thi gia Ưng Bình Thúc Giạ Thị, xin trân trọng giới thiệu tới độc giả khắp nơi thi tập có giá trị này. <i>Lộc Minh Đình Thi Thảo</i> sẽ ra mắt độc giả trên mạng Internet lần đầu tiên, với đầy đủ nguyên bản chữ Hán, bút tích của tác giả, bản đánh máy dưới dạng Unicode, bản dịch, và chú giải, trong nay mai.  Xin đón đọc.<br />
<br />
Dịch giả Nguyễn Hữu Vinh và nhà thơ Tôn Nữ Hỷ Khương giữ bản quyền.  Mọi trích dẫn, trích dịch, xin ghi xuất xứ rõ ràng.  Tuyệt đối xin đừng sử dụng những tài liệu này vào những mục đích thương mại.<br />
<br />
Trangnhahoaihuong.com</td></tr>


