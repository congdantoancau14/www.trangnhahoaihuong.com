<br />
<i>Tình như một bức phong còn kín<br />
Gió nơi đâu, gượng mở xem</i><br />
(Nguyễn Trãi)<br />
<br />
Năm nào cũng vậy, khi những giọt tuyết cuối cùng vừa tan, khi khí xuân còn chưa thành hình hẳn mà chỉ mới phảng phất trên những cành cây trước sân, khi trong đất nghe như có tiếng cựa mình của những cội cây đang ở độ sung mãn nhất, chỉ còn chờ đủ ngày là bung ra hàng loạt những nụ tươi non đầu đời, tôi lại giở bài ĐÀO HOA THI của Nguyễn Trãi ra đọc. Tính đến nay là năm thứ mười. Chín lần kia, tôi đọc bài thơ như một <i>bản nhạc không lời</i>, làm như tôi sợ nếu tôi bắt đầu suy tư về phần <i>nghĩa</i> thì tôi sẽ đánh mất bài thơ vĩnh viễn như làm tuột khỏi tay cái tách trà mà tôi yêu quí nhất vậy. Với tôi, Đào Hoa Thi đã đủ đẹp ở phần nhạc tính của nó, cái phần nằm ở dưới ngôn từ và ở trong tâm thức của nhà thơ, cái phần làm cho bài thơ khỏi rơi vào sự miêu tả một cái gì cụ thể, hay kể lể tâm sự một điều gì, mà chỉ là những nét chấm phá mơ hồ, bay bổng, nhẹ tênh, gợi lên những cái ngoài tầm mắt, ngoài suy tư, ngoài ý niệm, mênh mông và vô cùng.<br />
<br />
Nhưng năm nay, cưỡng không nổi sự tò mò về một số từ cổ mà ngay chính các học giả cũng còn chưa thống nhất cách đọc và hiểu, tôi bắt đầu giở trên kệ xuống những cuốn sách đã bị bỏ quên từ mấy năm nay. Thật ra, sách viết về <i>Quốc Âm Thi Tập</i> (QÂTT) của Nguyễn Trãi không có là bao nhiêu. Bản Nôm thì tôi có bản Phúc Khê (mùa thu năm Tự Đức Mậu Thìn 18681) do Giáo sư Lê Văn Đặng gửi cho, đem so với bản in trong <i>Nguyễn Trãi Toàn Tập Tân Biên</i> (do Mai Quốc Liên chủ biên, NXB Văn Học, 2001, gọi tắt là bản MQL) thì không thấy có chữ nào khác. Bản này Giáo sư Đặng scan lại từ một quyển sách tiếng Pháp ở thư viện Suzzallo (University of Washington, WA), nhưng tiếc là vì đã quá lâu, Giáo sư chưa nhớ ra tên sách. Về phần phiên âm thì có bản Đào Duy Anh, Nguyễn Đình Hòa &amp; Lê Văn Đặng, Mai Quốc Liên. Bản MQL có khảo dị phần phiên âm của Trần Văn Giáp, Vũ Văn Kính. Còn thì tôi phải lục lọi trong những tác phẩm cổ và tự/từ điển cổ. Nhưng, sau khi đã đối chiếu các bản phiên âm khác nhau và tìm tòi suy nghĩ thêm mất mấy ngày, tôi vẫn không thấy ra được điều gì mới ngoài những điều đã biết trước đây…<br />
<br />
<i>(Ghi chú 1: Đây là chỗ đáng thương của nền văn học cổ Việt Nam. Nhiều tác phẩm được viết từ TK XIII, XV mà hiện nay giới<br />
nghiên cứu chỉ có trong tay bản chép tay hay bản khắc gỗ của TK XVII, XVIII, vì bản chính đã bị lửa chiến tranh thiêu đốt, hoặc bị thất lạc, hoặc bị tiêu hủy. Riêng với QATT, những gì Nguyễn Trãi viết ra đã tuyệt tích. Hai mươi lăm năm sau ngày ông bị tru di tam tộc, vua Lê Thánh Tông mới minh oan cho ông và sai Trần Khắc Kiệm sưu tầm di cảo thơ văn của ông, in vào bộ Ức Trai Thi Tập vào năm 1480 (công việc sưu tập này mất mười năm). Nhưng sách đó sau cũng bị thất lạc nốt, chỉ còn lại một ít thơ văn rải rác trong các bộ sách khác, như Toàn Việt Thi Lục của Lê Quý Đôn và Hoàng Việt Thi Văn Tuyển của Bùi Huy Bích. Mãi đến đời nhà Nguyễn, tức là hơn 400 năm sau, Dương Bá Cung, người cùng làng với Nguyễn Trãi, mới đi từ Bắc vào Nam thu thập, dò hỏi, biên chép và cho in thành bản Phúc Khê 1868. Đây là bản mà hiện nay chúng ta có được.)</i><br />
<br />
…Cho đến khi tôi có được bản phiên âm và chú giải của Giáo sư Lê Hữu Mục, một món quà bất ngờ mà Giáo sư Trần Ngọc Ninh đã ưu ái gửi cho tôi khi biết tôi đang đọc lại Đào Hoa Thi.<br />
<br />
Tôi hồi hộp mở cái nơ màu gold mà Gs Ninh đã thắt vào bản phiên âm của Gs Mục, một cử chỉ biểu lộ lòng trân trọng của Cụ đối với tác phẩm của Nguyễn Trãi. Đó là một bản thảo viết tay đã lâu, giấy đã ngả vàng, chữ viết ngay hàng thẳng lối, đậm nét và rõ ràng. Tôi được biết Gs<br />
Mục đã bỏ ra hơn ba mươi năm ròng đọc QÂTT và đã phiên âm, chú giải toàn bộ tác phẩm này, với khoảng 400 trang viết tay, nhưng bản thảo đó chưa hề được in thành sách.<br />
<br />
Tôi đọc một hơi những những trang giấy có bút tích của Gs Mục, và cảm giác khi đọc xong là một nỗi hân hoan vui sướng vừa được qua một cuộc phiêu lưu chữ nghĩa kì thú và thi vị. Dưới đây, tôi xin được khảo dị những bản phiên âm khác nhau, đặc biệt là bản LHM, mà mặc dầu tác giả hết sức mong mỏi, đến nay vẫn chưa được trình làng, trước là để quí độc giả thưởng lãm một bài thơ hay của một tâm hồn lớn như Nguyễn Trãi, sau là để giới thiệu với học giới bản phiên âm của một nhà Nôm học có uy tín về các tác phẩm của Ức Trai, trong khi chờ đợi toàn bộ<br />
công trình của ông có đủ duyên để ra đời.<br />
<br />
Đào Hoa Thi gồm sáu đoạn, làm theo lối “thủ vĩ liên hoàn”, nghĩa là lấy mấy chữ cuối của đoạn trên đem lặp lại ở đoạn dưới. Sáu đoạn đều viết theo thể thất ngôn tứ tuyệt, nhưng đều sử dụng những vần chính khác nhau. Đoạn đầu dùng vần trắc, bốn đoạn giữa dùng vần bằng, và<br />
lại kết thúc với vần trắc ở đoạn cuối, như một bản nhạc rondo. Toàn bài thơ như một điệu luân vũ — mỗi điệu vũ là sự tiếp nối của điệu vũ trước. Trong QÂTT, sáu đoạn này được đánh số bài từ 227 đến 232.<br />
<br />
<br />
<b>ĐÀO HOA THI</b><br />
227. Một đóa đào hoa khéo tốt tươi<br />
Cách xuân mởn mởn <b>thấy</b> xuân cười<br />
Ðông phong ắt có tình hay nữa<br />
Kiến tiện mùi hương dễ động người<br />
<br />
228. Ðộng người, hoa khéo <b>tỏ</b> tinh thần<br />
<b>Ít</b> bởi vì hoa, <b>ít</b> bởi xuân<br />
Dỉ sứ chim xanh đành choạc lối<br />
Bù chì đã có khí hồng quân<br />
<br />
229. Khí hồng quân hỡi, xá chời qua<br />
Chớ <b>phụ</b> xuân này, chớ <b>phụ</b> hoa<br />
Hoa có ý thì xuân có ý<br />
Ðâu đâu cũng một khí dương hòa<br />
<br />
230. Khí dương hòa há có tây ai<br />
Nừng một hoa này nhẫn mọi loài<br />
Toan kể chỉn còn ba tháng nữa<br />
Cập xuân mựa để má đào phai<br />
<br />
231. Má đào phai hết bởi xuân qua<br />
Nếu lại đơm thì <b>liền</b> luống hoa<br />
Yến thửa Dao Trì đà có hẹn<br />
Chớ cho Phương Sóc đến lân la<br />
<br />
232. Phương Sóc lân la đã hở cơ<br />
Ba phen trộm được, há tình cờ<br />
Có ai ướm hỏi Tây Vương Mẫu<br />
Tin khá tin thì ngờ khá ngờ<br />
<br />
Xin được thưa ngay rằng bản phiên âm trên đây là dựa vào bản LHM, trừ những từ tô đậm, là những từ mà tôi xin được mạn phép đọc khác, mặc dầu chỉ là một kẻ hậu học và luôn coi Gs Mục là một bậc thầy trong Nôm học. Vả lại, nói cho cùng, những chỗ đọc khác này<br />
cũng không có gì gọi là “to tát” cho lắm, mà chỉ là ý kiến cá nhân. <br />
<br />
Bản LHM đọc như sau:<br />
<br />
Bài 227, câu 2: Cách xuân mởn mởn <b>thể</b> xuân cười (LHM)<br />
Bài 228, câu 1: Động người, hoa khéo <b>hởn</b> tinh thần (LHM)<br />
Bài 228, câu 2: <b>Ắt</b> bởi vì hoa, <b>ắt</b> bởi xuân (LHM)<br />
Bài 229, câu 2. Chớ <b>phũ</b> xuân này, chớ <b>phũ</b> hoa (LHM)<br />
Bài 231, câu 2. Nếu lại đơm thì, <b>lên</b> luống hoa (LHM)<br />
<br />
Và còn đôi ba chỗ cách đọc tuy giống nhưng cách hiểu hơi khác. Chi tiết xin được trình bày rõ dưới đây...<br />
