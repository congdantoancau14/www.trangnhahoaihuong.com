<h3>tôi đưa em sang sông</h3>



<b>Sáng tác: Nhật Ngân<br />
Hoà âm: Hồ Đăng Tín<br />
Trình tấu: Hoài Hương</b><br />
<br />
<a href="/DocTau/tdess_HH_ph.mp3" target= _blank>Nghe độc tấu</a><br />
<br />
<br />
Tôi đưa em sang sông<br />
Chiều xưa mưa rơi âm thầm <br />
Để thấm ướt chiếc áo xanh <br />
Và đẫm ướt mái tóc em <br />
Nếu xưa trời không mưa,<br />
Đường vắng đâu cần tôi đưa?<br />
Chẳng lẽ chung một lối về, <br />
Mà nỡ quay mặt bước đi?<br />
<br />
Tôi đưa em sang sông <br />
Bàn tay nâng niu ân cần <br />
Sợ bén đất lấm gót chân<br />
Sợ bén gió buốt trái tim <br />
Nếu tôi đừng đưa em<br />
Thì chắc đôi mình không quen <br />
Đừng bước chung một lối mòn <br />
Có đâu chiều nay tôi buồn?<br />
<br />
Rồi thời gian lặng lẽ trôi <br />
Đời tôi là chiến binh <br />
Đi khắp phương trời <br />
Mà đời em là ước mơ <br />
Đẹp muôn ngàn ý thơ<br />
Như ngóng trông chờ <br />
<br />
Hôm nao em sang ngang<br />
Bằng xe hoa thay con thuyền <br />
Giờ phút cuối đến tiễn em<br />
Nhìn xác pháo vướng gót chân <br />
Gót chân ngày xa xưa <br />
Sợ lấm trong bùn khi mưa <br />
Giờ đã thay một lối về<br />
Quên cả người trong gió mưa!<br />
<br />
Vài thông tin về nhạc phẩm này, trích từ trang web của La Tung Sơn:<br />
<br />
<i>...Nhật Ngân hoàn thành nhạc phẩm đầu tay khi ông mới vừa 18 tuổi vào năm 1960. Đó là một ca khúc tình cảm mang tên Tôi Đưa Em Sang Sông. <br />
<br />
Mặc dù chưa có phương tiện phổ biến rộng rãi trong thời gian đầu, nhưng Tôi Đưa Em Sang Sông đã trở thành một ca khúc được giới học sinh, sinh viên Đà Nẵng rất ưa thích, chép tay chuyền cho nhau hát. Sau đó, Nhật Ngân gửi ca khúc này vào Sài Gòn nhờ nhạc sĩ Y Vân phổ biến dùm, với sự sửa đổi một vài chữ trong bản nhạc cho hợp với đường lối của Bộ Thông Tin, lúc đó không cho phép phổ biến những nhạc phẩm ủy mị, ướt át. Câu "Rồi thời gian lặng lẽ trôi, đời tôi là cánh mây, trôi bốn phương trời, Và đời em là cánh hoa, thì  bao người ước mơ, đưa đón trông chờ" được nhạc sĩ Y Vân đổi thành "Rồi thời gian lặng lẽ trôi, đời tôi là chiến binh, đi khắp phương trời. Và đời em là ước mơ, đẹp muôn ngàn ý thơ, như ngóng  trông chờ" cho phù hợp với hoàn cảnh chiến tranh của đất nước. Câu kết của bản chính là "Nàng đã thay một lối về, thay cả bàn tay đón đưa" cũng đã được Y Vân đổi thành "Nàng đã thay một lối về, quên cả người trong gió mưa." Sự thay đổi lời ca này đã khiến cho tác giả cảm thấy "hẫng" đi một chút, như lời ông nói, vì không đúng với tâm trạng của mình, khi, đến lúc đó, chưa hề trải qua đời sống trong quân ngũ. Hơn nữa, vì tác giả là một người chưa có tên tuổi nên cần nhờ tới một nhạc sĩ nổi tiếng đứng chung tên với Tôi Đưa Em Sang Sông để dễ dàng đến với quần chúng hơn. <br />
<br />
Khi được phát hành, Tôi Đưa Em Sang Sông được đề tên bởi hai người là Trần Nhật Ngân và Y Vũ. </i><br />
