<h3>Đại Trượng Phu</h3>



<b>Thiền sư Nhất Hạnh</b><br />
<br />
Cửa tùng đôi cánh khép<br />
Một mũi tên sáng loáng lìa dây cung<br />
Lao vút tới<br />
Mặt trời nổ tung<br />
Đầy sân hoa cam rụng<br />
Phảng phất<br />
Bóng vô cùng<br />
<br />
<i>Source: http://www.langmai.org</i><br />




<h3>Bên Mé Rừng Đã Nở Rộ Hoa Mai</h3>



<b>Thiền sư Nhất Hạnh</b><br />
<br />
Thầy đi tìm con<br />
Từ lúc non sông còn tăm tối<br />
Thầy đi tìm con<br />
Khi mọi loài còn chờ đợi ánh dương lên<br />
Thầy đi tìm con<br />
Khi con còn đắm chìm trong một giấc ngủ triền miên<br />
Dù tiếng tù và đã vọng lên từng hồi giục giã<br />
Không rời non xưa<br />
Thầy đưa mắt về phương trời lạ và nhận ra được trên vạn nẻo đường từng dấu chân của con<br />
Con đi đâu?<br />
<br />
Có khi sương mù đã về giăng mắc chốn cô thôn<br />
Mà trên bước phiêu linh con vẫn còn miệt mài nơi viễn xứ<br />
Thầy đã gọi tên con trong từng hơi thở<br />
Tin rằng dù con đang còn lạc loài đi về bên nớ<br />
Con cũng sẽ cuối cùng tìm ra được lối trở về bên ni<br />
Có khi Thầy xuất hiện ngay giữa đường con đi<br />
Nhưng mắt con vẫn nhìn Thầy như nhìn một người xa lạ<br />
Không thấy được mối túc duyên<br />
Không nhớ được lời nguyền xưa vàng đá<br />
Con đã không nhận ra được Thầy<br />
Vì tâm con còn vướng bận những hình bóng xa xôi<br />
<br />
Trong kiếp xưa con đã từng nhiều lần nắm tay Thầy rong chơi<br />
Thầy trò ta đã ngồi thật lâu cạnh những gốc thông già trăm tuổi<br />
Đã từng đứng yên cùng lắng nghe tiếng gió thì thào mời gọi và ngắm nhìn những cụm mây trắng bay<br />
Con đã từng nhặt đưa Thầy những chiếc lá ngô đồng đầu thu đỏ thắm<br />
Thầy đã từng đưa con vượt qua những khu rừng tuyết phủ giá băng<br />
Nhưng đi đâu Thầy trò ta cũng luôn luôn trở về nơi non xưa chốn cũ, để được gần gũi sao trăng<br />
Để được mỗi khuya gióng tiếng chuông đại hồng cho mọi loài tỉnh thức<br />
Thầy trò ta đã từng ngồi yên trên An Tử Sơn cùng đại sĩ Trúc Lâm bên những cây đại già nở hoa thơm ngát<br />
Đã từng đưa tàu ra khơi vớt người thuyền nhân phiêu dạt<br />
Đã từng cùng nhau đánh tranh dựng chiếc thảo am bên sông và giăng lưới vớt Trạc Tuyền khi Tiền Đường đang đùng đùng dậy sóng<br />
Thầy trò ta đã mở lối bước lên trời ngoại phương lồng lộng<br />
