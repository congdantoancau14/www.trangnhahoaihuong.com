‎(Mọi nước dứt chiến chinh)‎<br />
<br />
Một bài kệ nhỏ, vỏn vẹn chỉ có bốn câu, đã gói ghém, với những hình ảnh tuyệt đẹp, từ cung ‎điện đến đời sống dân gian, từ vận nước đến cái thế lớn trong thiên hạ, và từ đầu đến cuối ‎thoát ra một hương sắc Thiền nhẹ nhàng thanh nhã, luyện cái thiên nhiên vào cái trừu tượng ‎rồi chuyển cái trừu tượng vào cái thực tế, và đồng thời, đem cái tư tưởng chính trị Việt Nam ‎diễn ra, sáng như trăng rằm, trong như ngọc bích, thực là kỳ tuyệt. Mở sử ra đọc lại, thấy ‎những lời của Trần Hưng Ðạo dặn dò vua trước khi chết, cũng là cái tinh thần ấy, nhưng ‎chân phương là chừng nào, khẩn thiết là chùng nào ; thực là lời của vị võ thần giữ nước, ‎nhìn thấy một chiến lược toàn diện và hiểu rằng nồng cốt của nước là dân. Xem đến Bình ‎Ngô Ðại Cáo của Lê Lợi - Nguyễn Trãi: vẫn là cái tư tưởng chính trị căn bản xưa, nhưng ‎phát triển ra lâm ly dũng mãnh, lúc như gió rít trong ngàn cây, lúc như sóng thần từ lưng trời ‎đổ xuống, từ đầu đến cuối chỉ vì nước vì dân, coi dân là nước và nước là dân, rồi cuối cùng ‎cũng chứng tỏ sự vô vi trong uy vũ để mua lấy một nền hoà bình vinh quang vĩnh cửu. Tư ‎tưởng chính trị Việt Nam có một truyền thống, cho đến lúc ấy chưa bao giờ bị thực sự gián ‎đoạn. Nhưng vài trăm năm sau đó thì rừng mây bắt đầu bị xẻ ra. Rồi vài chục năm gần đây, ‎người trong nước đã khởi sự rút mây. Tư tưởng chính trị Việt Nam bị ô nhiễm đến độ rằng ‎những bậc thức giả trong nước cũng không nhìn thấy nữa.‎<br />
<br />
Nay là lúc chúng ta phải gạn đục khơi trong lại. Dòng tư tưởng của Việt Nam ở ngưỡng cửa ‎của thế kỷ thứ hai mươi mốt tất nhiên không thể vẫn là bốn câu thơ của sư Pháp Thuận. ‎Lịch sử Việt Nam cũng không dừng lại ở thời Lê Ðại Hành. Qua mỗi lần chuyển mình của ‎lịch sử, tư-tưởng Việt Nam đã thay đổi và còn phải luôn luôn thay đổi. Nhưng chúng ta ‎quyết không để cho một bọn ngụy trí thức, trong sự ngu tối và cuồng-loạn vọng-ngoại, xoá ‎bỏ đi bốn ngàn năm lịch sử tư tưởng của Việt Nam để thay thế bằng cái quái thai đầu Ðức ‎mình Nga gọi là chủ nghĩa Mác Xít Lê Nin Nít.‎<br />
<br />
Trần Ngọc Ninh<br />
