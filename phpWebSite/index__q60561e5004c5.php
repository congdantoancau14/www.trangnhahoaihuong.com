<h3>Tư tưởng và Tư tưởng Chính trị Việt Nam</h3>



<b>TRẦN NGỌC NINH</B><br />
<br />
<I>‎“… Nước là dân và toàn dân phải như dây quấn thì mới tạo được hoà bình ở trời Nam: làm ‎lịch sử là kiến tạo hoà bình vĩnh cửu, chứ không phải là gieo rắc thù hận và những mầm ‎mống của đấu tranh không cùng …”‎</I><br />
<br />
<br />
Kể từ khi lập quốc cho đến ngày nay có một dòng lịch sử Việt Nam trong đó đã cấu thành ‎nên một quốc dân Việt Nam, thì hiển nhiên rằng phải có một tư tưởng Việt Nam.‎<br />
<br />
Tư tưởng Việt Nam là cái động lực lớn để giữ nước và yên dân. Tư tưởng Việt Nam là cái ‎sức mạnh chính yếu đã tạo ra sự đặc thù của con người và văn minh Việt Nam trên trái đất ‎của loài người. Tư tưởng Việt Nam là tư tưởng lãnh đạo lịch sử Việt Nam. Những ngọn ‎sóng của lịch sử thế giới nhiều khi đã tràn ngập cả cõi sống Việt Nam. ‎<br />
<br />
Tư tưởng Việt Nam đã có những thời bị dìm xuống tận đáy sâu thẳm của những vực không ‎bờ tưởng rằng vĩnh cửu không còn một cái bóng, một tiếng vang, trong trí nhớ của người ta. ‎Nói đến tư tưởng Việt Nam trong những thời quốc vận suy mạt này, những người tự thổi ‎lên là kẻ sĩ hay trí thức chỉ biết nhìn nhau ngơ ngác, tưởng là nói chuyện quỷ thần. Có hay là ‎không có? Hình bóng ra sao? Ðạo Nho chăng? Hay là Ðạo Lão? Ðạo Phật? Ðạo Chúa? Tư ‎tưởng của Lư Thoa à? Chủ nghĩa của Các Mác chăng? Thưa là hoạt kê và cũng thực là bi đát. ‎Y như đứa trẻ mồ côi bị loài sói nuôi thì gọi sói là mẹ và coi sự đấu tranh sinh tồn của loài ‎sói là lẽ sống của chính mình. Sự mất bản thể và tha hoá có thể kéo dài cả thế kỷ, cả mười ‎thế kỷ tối tăm.‎<br />
<br />
Nhưng rồi tư tưởng Việt Nam lại nổi lên, với những nguồn sinh lực mới, giàu hơn, mạnh ‎hơn, đẹp hơn, thực hơn, và trăm phần tươi sáng hơn. Nó châm lên những bó đuốc mới để ‎phá tan đêm tối mà đón ánh mặt trời buổi ban mai. Nó khơi lại trong mỗi trái tim cái tàn lửa ‎cũ cho bùng lên thành cục than hồng của lòng yêu nước vạn năng. Nó làm cho giang sơn đất ‎nước rực lên một mầu vinh quang và sình bùn cũng chứa đựng những hứa hẹn không cùng.‎<br />
<br />
Nhưng các đế quốc lớn trong thiên hạ vẫn không ngớt thèm muốn cái nơi góc bể chân trời ‎mà tiền nhân chúng ta đã biến thành gấm vóc thi ca và gọi bằng cái tên yêu dấu là nước ta, ‎quê ta. Dầu là từ Bắc phương gần, Bắc phương xa, - nơi lòng người giá lạnh như băng tuyết ‎nghìn thu, hay từ phương tây bên bờ của đại dương mà mặt trời lặn xuống, kẻ xâm lăng, với ‎sự phản bội của những Trần Ích Tắc, Lê Chiêu Thống, Ðồng Khánh, Hồ Chí Minh, sợ cái tư ‎tưởng quật cường bất khuất của người Việt Nam yêu nước, đã bao lần đốt lửa để nấu chảy ‎trống đồng, thiêu hủy sách vở và đem xe, tàu đến để chở cái rừng tư tưởng Việt Nam về nơi ‎chính quốc mà chôn trong những phòng cấm của những tàng kinh các quốc gia của họ. ‎Nhưng cái hoá thân có hình hài sắc tướng với những chữ nghĩa trên trang giấy có thể bị đốt, ‎bị khoá, mà pháp thân của tư tưởng Việt Nam, không sống gửi vào vật chất, vẫn tự tại và tự ‎tồn, để chờ ngày quật khởi.‎<br />
<br />
Trên khắp nước Việt Nam, không có một tấc đất nào không có máu thịt của ta trong những ‎kiếp trước. Không có một lá cây ngọn cỏ nào mà mỗi tế bào không có một phần của ta ngày ‎xưa. Tất cả cái phong cảnh của đồng ruộng núi sông trong nước là do khối óc và bàn tay của ‎tiền nhân xây đắp. Ðó là cái vùng trời và những con đường của văn hoá dân tộc. Và mỗi cái ‎thoáng nghĩ trong đầu óc của một người hiện ra trong một lời nói, một nụ cười hay một cái ‎nhúc nhích của một sợi cơ trong một bàn tay, hoặc phải nén xuống trong cõi lòng không đáy ‎của những ngàn năm đàn áp, cũng chứa đựng tất cả cái tư tưởng Việt Nam.‎<br />
<br />
Vào đầu thế kỷ thứ 17 ở bên trời Âu, có nhà đại khoa học, đại văn hào là Blaise Pascal đã để ‎lại cho hậu thế những mảnh vụn của một cuốn sách mà người ta chắp nhặt lại, đặt cho một ‎cái đầu đề là Tư Tưởng (Pensées). Ðại để đi ngược lại với người đời thường nghĩ rằng hiểu ‎nhau rồi mới yêu nhau được, Pascal nói rằng có yêu Chúa thì mới hiểu được Chúa, và không ‎ngần ngại đi đến cuộc đánh cá lớn nhất trong lịch sử triết học Tây phương, là cứ đi lễ đi rồi ‎mới có thể mong được ban ân. Hành tiên, trí hậu.‎<br />
‎ ‎<br />
