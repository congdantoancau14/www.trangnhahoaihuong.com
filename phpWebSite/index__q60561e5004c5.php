Tư tưởng Việt Nam cũng như Chúa của Pascal. Có đó, mà không có đó. Có đó cho người đã ‎yêu, đã thấy. Khi ấy thì có khắp mọi nơi, từ cái cực vi đến cái cực đại, từ trong một mô đất ‎bên bờ ruộng đến những con sông dài chở củi, lúa và tình người ; từ tiếng sáo diều trên cánh ‎đồng quê đến những lời hát vô tận của gái trai trong cuộc sống văn hiến, từ một hột cơm, ‎một cọng rau đến sự nghiệp bất diệt của một Nguyễn Trãi. Nhưng rõ ràng hiển nhiên là thế, ‎mà vẫn không có với những kẻ lạc loài.‎<br />
<br />
