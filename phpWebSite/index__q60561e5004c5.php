Vô vi cư điện các. `Không làm` trong chốn quyền quý. Ðây là lời dạy vua quan trong sự cai ‎trị. Vô vi là không làm. Không phải sự vô vi của Lão Tử, cưỡi con lừa già ra khỏi cổng thành ‎để làm một Thái Thượng Lão Quân, ngồi nấu thuốc trường sinh bất lão. Mà là sự vô vi của ‎Ðạo Phật. Sư Pháp Thuận là người Thiền Môn, không là một đạo sĩ. Trong Ðạo Phật, vô vi ‎là sự không làm những cái không phải là Bát Chánh Ðạo, quan trọng hơn hết thẩy là sự ‎không làm hại, ahimsa, mà sau này Mahatma Gandhi coi là sự dũng cảm tối hậu và phương ‎châm chính trị tối cao. Trong Ðời, vô vi là không can thiệp, không bắt ép, không bó buộc, ‎không phá rối truyền thống, pháp luật, và tín ngưỡng mà nhân dân đã thuận theo trong tự do, ‎và cuối cùng, không mượn những cớ giả dối để đem quân đi chiếm đóng một nước khác. Ðó ‎là những lời dạy của chính Phật Như Lai, về dân nước Vajji. Vô vi là cái cực đối lập với ‎chuyên chế. Chính trị vô vi tôn trọng dân quyền và nhân quyền. Chính trị vô vi có một điều ‎kiện căn bản: nhân dân phải như dây quấn. Khi tất cả mọi giới đã ràng buộc lấy nhau trong ‎cái thế liên kết, liên đới, liên thuộc, thì hoà bình trong xã hội tự nhiên được thực hiện, mọi ‎sự cưỡng bách từ trên xuống trở thành vô nghĩa. Một xã hội yên vui không cần phải có một ‎Ðảng lãnh đạo và cũng chẳng phải mướn một nhà nước quản lý. Những cái đó là những phát ‎minh thời đại của những đỉnh cao trí tuệ, nhìn vào một cái sơ đồ của xã hội Âu Tây bệnh ‎hoạn. rồi cho rằng lịch sử của loài người chỉ là lịch sử đấu tranh giai cấp, và mọi xã hội đều ‎được cấu tạo với hai lớp người, kẻ bóc lột và người bị bóc lột. Hãy so sánh cái xã hội thô sơ ‎ấy với tư tưởng Việt Nam ở cuối thế kỷ thứ mười, trong câu kệ của Thiền Sư Pháp Thuận : ‎Vận nước như dây quấn : cơ cấu xã hội phức tạp là thế, chặt chẽ là thế, nhưng vẫn có tự do ‎vì một dây mây cá nhân vẫn có thể trồi từ lớp này lên lớp khác mà không cần phải có một kế ‎hoạch nào của nhà nước chỉ huy cả.‎<br />
