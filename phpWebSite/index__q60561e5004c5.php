Ðây là sách lược chính trị để mở nước, sau mười thế kỷ Bắc thuộc. Triều đại nhà Ngô, mặc ‎dầu đã chiến thắng quân Nam Chiếu một cách lẫy lừng trên sông Bạch Ðằng, nhưng còn ‎lung lay và chưa có chính sự. Loạn mười hai sứ quân được dẹp bởi Ðinh Bộ Lĩnh, người ‎anh hùng thôn dã, nhưng nhà Ðinh còn phải nấu vạc dầu và nuôi cọp dữ để giữ vững ngôi ‎vua mà vẫn còn bị tiêu diệt bởi mũi dao của kẻ thích khách. Lê Ðại Hành lên ngôi trong sự ‎đàm tiếu của bọn anh em tay chân của Ðinh Bộ Lĩnh, phương Bắc thì nhà Tống đem quân ‎xuống để mưu đồ tái chiếm vùng đất thuộc cũ, miền Nam thì Chiêm Ba bắt sứ và khinh khi ‎nền độc lập còn thơ ấu của nước Việt Nam. Dầu đã là Thập Ðạo Tướng Quân Lê Hoàn, vua ‎Lê Ðại Hành cũng không khỏi có những bối rối lo âu. Sự mầu nhiệm kỳ diệu là vua Lê Ðại ‎Hành, một quân nhân vừa ra khỏi đêm tối của thời trung cổ bán khai, đã quay sang một nhà ‎sư học sĩ để hỏi việc nước. Và chúng ta được thấy sự khai sinh của tư tưởng chính trị Việt ‎Nam trong văn chương chữ nghĩa.‎<br />
<br />
Quốc tộ như đằng lạc, vận nước như dây quấn. Những dây mây trong rừng, dây sắn dưới ‎ruộng, quấn quít chằng chịt vào nhau như dây đan, như dệt, dựa vào nhau mà đứng vững ‎trong gió bão, như trường thành. Ðó là cái hình ảnh của xã hội. Các nghề nghiệp lồng vào ‎nhau, các giai tầng tựa vào nhau. Sự liên đới và đại đoàn kết của toàn dân là nền tảng của sự ‎vững bền của vận nước. Người dân Việt Nam hiểu rõ điều ấy từ ngàn xưa. Tục ngữ ca dao ‎nối tiếp vào bốn câu kệ của Thiền Sư Pháp Thuận mà giải thích thêm. `Vì cây dây quấn`, ‎người ta nói. Những sợi mây xoắn vào nhau, móc vào nhau, khoác chặt lấy nhau là vì sự ‎sống còn và vững mạnh của cả cây mây. Cũng như toàn thể dân trong nước, sát cánh nhau ‎trong sự đấu tranh chung, là để giữ nước và xây dựng nước. Vì nước, tất cả các dây người ‎cũng quấn; tay khoác tay, sự hợp quần phải chặt chẽ, trận tuyến phải dầy đặc. Cây là gốc ‎của dây. Nếu người lãnh đạo hiểu được rằng `vận nước như dây quấn` thì người dân sẽ đáp ‎ứng lại rằng toàn dân đã sẵn sàng, không trừ một giới nào. Dân là đằng lạc, quốc tộ là do ‎dân.‎<br />
<br />
Trong cái đằng lạc ấy, không phải là sự hỗn độn, không có sự tranh chấp. Dây già, dây non, ‎dây cao, dây thấp, thậm chí đến cả dây chết, dây sống cũng vẫn ôm nhau, quyện nhau, ‎không rời, không nhả, chia sẻ với nhau những nỗi khó khăn khổ cực của đời sống giữa rừng ‎già. Thế nhưng `rút dây động rừng `chỉ cần cho kẻ lạ thấy được một cái đầu mối nào đó để ‎rút ra một sợi mây thì cả rừng mây sẽ bị động và dầu là một cơ cấu thiên niên vạn đại cũng ‎có thể sụp đổ. Ðến thế kỷ thứ hai mươi này, người ta sẽ gọi đó là `cách mệnh`. Cách mệnh là ‎rút ra một sợi dây của đằng lạc và gieo cái ý thức rằng sợi dây cao đè sợi dây thấp, sợi dây ‎già buộc sợi dây non, và phải rút đi một sợi dây thì thiên hạ mới thái bình. Ðó không phải là ‎tư tưởng chính trị Việt Nam. Ðó là tư tưởng loạn nước loạn dân. Nhóm lên ngọn lửa đấu ‎tranh giai cấp là chính thức hoá nội loạn. Ðó là một tư tưởng ngoại xâm.‎<br />
