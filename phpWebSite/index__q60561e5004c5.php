Ngay cả trong những sách vở còn lọt qua mạng lưới của đế quốc và chó săn cũng còn để lại ‎chút ít di tích của tư tưởng đích thực Việt Nam. Cho những ai biết đọc, cho những ai đọc ‎với tình người Việt Nam, với tình nước Việt Nam. Trong thực tế thì cũng chẳng còn bao ‎nhiêu. Một vài mảnh giấy đã nhám lửa, vùi trong những đống tro tàn của những hoả đài văn ‎hoá. Nhưng quý làm sao ! Đẹp làm sao ! Và thâm trầm biết là chừng nào qua những huy ‎hoàng và đắng cay của lịch sử !‎<br />
<br />
Tư tưởng chính trị nằm ở trong tư tưởng là cái ánh của tư tưởng để soi đường cho chính trị, ‎là cái kim chỉ nam để cứu nước, giữ nước và yên dân. Tất nhiên rằng đế quốc và phản quốc ‎ở bất cứ thời nào, cũng phải truy lùng và tiêu hủy tư tưởng chính trị của người dân yêu ‎nước, trước tất cả những gì khác, hữu hình hay vô hình. Binh Thư Yếu Lược của Trần Hưng ‎Ðạo đã tuyệt diệt, nhưng An Nam Chí Lược của Trần Ích Tắc vẫn còn cho tới ngày nay, là ‎vì thế.‎<br />
<br />
Trong tâm khảm của chúng ta, không một người nào không tôn thờ cuốn sách mà không ‎một ai được trông thấy, cuốn Binh Thư đã đuổi giặc Nguyên ra ngoài bờ cõi. Và tuy cũng ‎còn có những sử gia vì sự bắt buộc của nghề nghiệp phải đọc cuốn sử vong bản về đất An ‎Nam, nhưng cũng không có một ai không khinh bỉ và thương hại cái văn tài trác tuyệt đã ‎lầm đường mà thành nô dịch cho đế quốc.‎<br />
<br />
Tư tưởng chính trị bị đốt, bị chôn nhưng vẫn sống trong lòng người dân, ở đó nó âm ỉ cháy ‎mãi, nuôi dưỡng bởi cỏ hoa của đất nước, để vạn kiếp bí truyền cho con cháu đời sau. Và ‎khi nào cần thiết thì Binh Thư lại xuất hiện, Binh Thư không sách, Binh Thư không chữ, vì ‎đó mới là Binh Thư thực của tư tưởng Việt Nam: Binh Thư Yếu Lược là thời trời, là lợi đất, ‎là hoà người Việt Nam. Binh Thư sách đã bị ngọn lửa hung tàn của nhà Minh đốt cháy, ‎nhưng cuốn sách ấy còn dùng làm gì sau khi nó đã vẻ vang chiến thắng quân Nguyên ? Còn ‎lại là cái tin tưởng và cái tinh thần mà Lê Lợi và Nguyễn Trãi cùng với toàn dân đã thừa ‎hưởng của Binh Thư, với những chiến lược mới phải được sáng tạo ra để đánh đuổi một kẻ ‎thù mới, và lập nên nền đại định Bình Ngô.‎<br />
<br />
Thế nhưng có còn một chút di tích gì của tư tưởng chính trị Việt Nam trong kinh sách ‎không ?‎<br />
<br />
Một ngàn năm trước đây, vào khoảng thập niên từ 980 đến 990, không phải 70 năm của sự ‎thành lập Liên Xô, không phải 200 năm của sự ban hành hiến pháp Hoa Kỳ, cũng không ‎phải thiếu đầy 200 năm kỷ niệm cuộc cách mệnh Pháp, một ngàn năm trước đây, trong nền ‎độc lập mới còn chập chững của nước Ðại Việt ta, vua Lê Ðại Hành (ở ngôi từ 980 đến ‎‎1005) đã hỏi pháp sư Ðỗ Pháp Thuận (mất năm 991) về vận nước. Sư Pháp Thuận nói kệ để ‎trả lời vua; kệ rằng: ‎<br />
