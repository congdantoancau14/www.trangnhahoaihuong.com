<h3>Bên Mé Rừng Đã Nở Rộ Hoa Mai</h3>


<b>THIỀN SƯ NHẤT HẠNH</B> <br />
<br />
Thầy đi tìm con<br />
Từ lúc non sông còn tăm tối<br />
Thầy đi tìm con<br />
Khi mọi loài còn chờ đợi ánh dương lên<br />
Thầy đi tìm con<br />
Khi con còn đắm chìm trong một giấc ngủ triền miên<br />
Dù tiếng tù và đã vọng lên từng hồi giục giã<br />
Không rời non xưa<br />
Thầy đưa mắt về phương trời lạ và nhận ra được trên vạn nẻo đường từng dấu chân của con<br />
Con đi đâu?<br />
<br />
Có khi sương mù đã về giăng mắc chốn cô thôn<br />
Mà trên bước phiêu linh con vẫn còn miệt mài nơi viễn xứ<br />
Thầy đã gọi tên con trong từng hơi thở<br />
Tin rằng dù con đang còn lạc loài đi về bên nớ<br />
Con cũng sẽ cuối cùng tìm ra được lối trở về bên ni<br />
Có khi Thầy xuất hiện ngay giữa đường con đi<br />
Nhưng mắt con vẫn nhìn Thầy như nhìn một người xa lạ<br />
Không thấy được mối túc duyên<br />
Không nhớ được lời nguyền xưa vàng đá<br />
Con đã không nhận ra được Thầy<br />
Vì tâm con còn vướng bận những hình bóng xa xôi<br />
<br />
Trong kiếp xưa con đã từng nhiều lần nắm tay Thầy rong chơi<br />
Thầy trò ta đã ngồi thật lâu cạnh những gốc thông già trăm tuổi<br />
Đã từng đứng yên cùng lắng nghe tiếng gió thì thào mời gọi và ngắm nhìn những cụm mây trắng bay<br />
Con đã từng nhặt đưa Thầy những chiếc lá ngô đồng đầu thu đỏ thắm<br />
Thầy đã từng đưa con vượt qua những khu rừng tuyết phủ giá băng<br />
Nhưng đi đâu Thầy trò ta cũng luôn luôn trở về nơi non xưa chốn cũ, để được gần gũi sao trăng<br />
Để được mỗi khuya gióng tiếng chuông đại hồng cho mọi loài tỉnh thức<br />
Thầy trò ta đã từng ngồi yên trên An Tử Sơn cùng đại sĩ Trúc Lâm bên những cây đại già nở hoa thơm ngát<br />
Đã từng đưa tàu ra khơi vớt người thuyền nhân phiêu dạt<br />
Đã từng cùng nhau đánh tranh dựng chiếc thảo am bên sông và giăng lưới vớt Trạc Tuyền khi Tiền Đường đang đùng đùng dậy sóng<br />
Thầy trò ta đã mở lối bước lên trời ngoại phương lồng lộng<br />
Sau bao tháng ngày công phu chọc thủng lưới thời gian<br />
Đã từng cất giữ được ánh sáng của những vì sao băng<br />
Làm đuốc soi đường cho những ai muốn trở về sau những tháng ngày rong ruổi<br />
<br />
Nhưng cũng có khi hạt giống lãng tử trong con bừng sống dậy<br />
Con đã rời bỏ Thầy, rời bỏ huynh đệ một mình thất thểu ra đi…<br />
Thầy nhìn con xót thương<br />
Tuy biết rằng đây không thực sự là một cuộc phân kỳ<br />
Bởi vì con đang có Thầy nơi từng tế bào trong cơ thể<br />
Biết con còn phải thêm một lần đóng vai người cùng tử<br />
Nên Thầy đã nguyện sẽ có mặt đó cho con mỗi lần con gặp bước gian nguy<br />
<br />
Có khi con nằm thiếp đi trên cát nóng sa mạc chốn biên thùy<br />
Thầy đã hoá thân làm đám bạch vân đem cho con bóng mát<br />
Đến giữa khuya đám mây đọng lại thành sương, cam lộ rơi từng hạt để con uống lấy trong cơn mê<br />
Có khi con ngồi dưới vực sâu tăm tối, hoàn toàn cách biệt trời quê<br />
Thầy đã hoá thân thành chiếc thang dài và nhẹ nhàng bắc xuống<br />
Cho con leo lên vùng chan hoà áng sáng<br />
Để tìm lại được màu trời xanh và tiếng suối tiếng chim<br />
Có lúc Thầy nhận ra con ở Birmingham<br />
Ở quận Do Linh hay miền Tân Anh Cát Lợi<br />
Có lúc Thầy gặp con ở Hàng Châu, Hạ Môn hay Thượng Hải<br />
Có lúc Thầy tìm được con ở St Peterburg, hoặc ở Tây Bá Linh<br />
Có khi mới lên năm mà thấy con, Thầy cũng nhận được chân hình<br />
Thấy được hạt giống bồ đề nơi con, mang trong trái tim còn niên thiếu<br />
Thấy con, Thầy đã luôn luôn đưa tay làm dấu hiệu<br />
Dù nơi gặp con là ở miền Kinh Bắc vùng Bến Nghé hay ở cửa biển Thuận An<br />
Có khi con là trái trăng vàng ửng chín lơ lửng treo trên đỉnh Kim Sơn<br />
Hay là con chim con chiêm chiếp kêu đêm đông bay qua rừng Đại Lão<br />
Rất nhiều khi Thầy thấy được con nhưng con không thấy được Thầy, dù trên nẻo đường con đi sương chiều đã thấm vào ướt áo<br />
Vậy mà cuối cùng con cũng đã trở về<br />
Con trở về ngồi dưới chân Thầy nơi chốn non xưa<br />
Để rồi tiếng chim kêu tiếng vượn hú lại cùng hòa với tiếng công phu sớm trưa<br />
Con đã về bên Thầy, thực sự muốn chấm dứt cuộc đời lãng tử<br />
<br />
Sáng nay chim chóc ca mừng vầng ô lên rạng rỡ<br />
Con có hay<br />
Trên bầu trời xanh mây trắng vẫn còn bay?<br />
Con ở đâu? Cảnh núi xưa còn đó nơi hiện pháp chốn này<br />
Dù đợt sóng bạc đầu vẫn còn đang muốn vươn mình đi về phương lạ<br />
Nhìn lại đi, Thầy đang ở trong con, và trong từng nụ hoa, chiếc lá<br />
Nếu gọi tên Thầy, con sẽ tự khắc thấy Thầy ngay<br />
Con đi đâu? Cây mộc già đã nở hoa, thơm nức sáng nay<br />
Thầy trò ta thật chưa bao giờ từng cách biệt<br />
Xuân đã về, các cội thông đã ra chồi óng biếc <br />
Và bên mé rừng đã nở rộ hoa mai<br />
