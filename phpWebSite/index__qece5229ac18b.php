"Qua 197 bài thơ chữ Hán, thi ông Ưng Bình Thúc Giạ Thị đưa người đọc về thế giới phong lưu của hàng ‎quan lại mặc khách ngày xưa. Người đọc cảm thấy buồn vui lẫn lộn, tình cảm dạt dào và có được những ‎cảm giác nhớ nhung chất ngất, bên tai còn nghe văng vẳng đâu đây những tiếng cười vui với những nhịp ‎trống, lời ca, tiếng hát, câu hò của khách thơ, của ca nữ trong những dịp vui ca Huế, ca Trù hay trong những ‎lúc dạo chơi với núi non, trăng thanh, gió mát, hoa tươi, cỏ đẹp, núi biếc, sông mờ, thuyền chèo… ở miền ‎trung nước Việt trong những năm khoảng giữa thế kỷ XX. Với những vần thơ cô đọng nhưng dễ rung cảm con ‎tim, người đọc dễ cảm nhận được ý nghĩa của tình người qua những vần thơ chữ Hán trong tập Lộc Minh Đình ‎Thi Thảo."‎<br />
<b>Nguyễn Hữu Vinh</b>, Taiwan, 2002‎<br />
<br />
"Chúng ta đã biết câu hò “Trước bến Văn Lâu” của Cụ Ưng Bình đã đi vào lòng người Việt. Chúng ta sẽ ngạc ‎nhiên khi thấy thơ chữ Hán của cụ cũng rất tình cảm và dễ làm nao nao lòng người. Bản dịch theo thể Đường ‎luật của Hữu Vinh giúp người đọc đi gần nguyên tác và cho ta có cơ hội hiểu thêm thi tứ của một bậc thi hào ‎đất Thần Kinh.‎"<br />
