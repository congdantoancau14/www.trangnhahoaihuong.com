<b><div align="center">Giới thiệu sách mới: Lộc Minh Đình Thi Thảo của Ưng Bình Thúc Giạ Thị, do Nguyễn Hữu Vinh dịch</div></b><br /><br />


<i><img src="http://www.viethoc.org/eholdings/images/LMDTT_bia_goc.jpg"  align="left">
<br />
Xin trân trọng giới thiệu đến quý thân hữu khắp nơi một tập thơ độc đáo gồm 197 bài thơ chữ Hán của Thi Ông lừng danh đất Thần Kinh - <b><a href="/images/TieuSu_UB.gif" target = _blank>Ưng Bình Thúc Giạ Thị</b></a> (1877-1961) - qua bản dịch của <b><a href="/images/TieuSu_NHV.gif" target = _blank>Nguyễn Hữu Vinh</a></b> (Đài Loan).<br />
<br />
Sách in mỹ thuật, gồm nguyên bản chữ Hán với thủ bút của tác giả, bản dịch nghĩa, dịch thơ và chú giải; dày 570 trang. <br />
<br />
Do <a href="http://www.viethoc.org" target = _blank>Viện Việt-Học</a> xuất bản.</i><br /><br />


