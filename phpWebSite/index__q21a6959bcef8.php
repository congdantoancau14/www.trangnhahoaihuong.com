<h3><h3>Những cành mai xa xứ</h3></h3>


<b>Nguyễn Hữu Vinh, mùa đông 2005, thành phố Tân Trúc, Ðài Loan</b><br />
<br />
    Trong cuộc đời phiêu lãng của mình, tôi đã ấp ủ nhiều kỹ niệm về loài hoa mai. Dù bây giờ quê hương ở đó…<i>muốn về về cũng được, sông Hương còn đó có ai giành</i>…(1), nhưng…mỗi năm trong những lúc trời xuân sắp trở lại, thì cứ văng vẳng nghe trong lòng tiếng cười vui của cha mẹ, anh em, quây quần dưới ngôi nhà vườn đầy nụ xanh non, có cội mai già mảnh khảnh, lốm đốm điểm những nụ mai vàng vừa hé.  Hình ảnh cô bạn gái nhỏ áo trắng năm xưa cũng hiện về trước mắt, đạp chiếc xe đạp đến chơi dựng kề dưới gốc cây mai trước hiên nhà.  Cũng vậy, chiếc thiệp chúc tết của nàng năm xưa nay vẫn còn trong cặp, cành hoa mai trên thiệp lụa đã phai màu cũng còn cười bên hàng chữ…năm năm rồi cũng sẽ không lâu đâu…!  Mỗi lần nhìn lại cánh thiệp xuân in hình đóa mai vàng đó, trong lòng lại cảm xúc đến rưng rưng. Không có gì mang đến cho tôi ý niệm mùa xuân trọn vẹn hơn khi nâng trên tay một đóa mai vàng. Đành rằng mỗi loài hoa có một vẻ đẹp, một màu sắc và ý nghĩa riêng, nhưng sao giữa thế giới hoa xuân muôn hồng nghìn tía, tôi vẫn yêu hoa mai, nhất là loài mai vàng. Có lẽ hình ảnh đóa mai vàng đã hằn sâu vào ký ức tôi, vượt ra ngoài khuôn khổ cách đánh giá về cái đẹp thường tình để nghiễm nhiên trở thành biểu tượng của những gì thương yêu, thanh cao, giản dị và thân thiết. Tự bao giờ, hình ảnh đóa mai vàng đã hóa thân thành hình bóng quê hương đối với người xa xứ. Ðếm tay xem lại mình cũng đã lâu lắm rồi, dễ chừng đã hơn 30 năm chưa được nhìn lại cánh mai vàng năm cánh của quê hương.  Nhớ có một  lần, trời cũng heo may và sắp vào xuân, hương gió cũng dễ gợi cho lòng người những nỗi nhớ bâng quơ, lần đó đi ngang khu đồi trồng hoa mênh mông, bên rặng núi Dương Minh ở Taipei, một khu rừng hoa mà hễ đến tháng ba là trăm ngàn hương sắc hoa hé cười đón gió. Tôi càng hồi hộp, bồi hồi và náo nức bao nhiêu khi nhìn thấy hai chữ Mai Lâm (Rừng mai) trước cổng, những tưởng là sẽ được ngắm các nàng mai vàng thân thuộc, thì càng thấy thất vọng bấy nhiêu vì trước mắt là một rừng mai trắng. Tôi lẩm bẩm với mình: “đây cũng là hoa mai ư? Ô! ừ! nó cũng là một loại hoa mai trong hàng chục loại hoa mai”. Nhưng tôi thấy những gốc mai trắng này vô vị không có hồn như cái hồn tôi mong đợi,  không có cái hình dáng của loài hoa mà tôi hằng ấp ủ trong lòng. Mặc dù đó chỉ là loài mai trắng vô vị, nhưng không hiểu tại sao, những cội mai trắng này hình như ngóng đợi để đưa hồn người xa xứ trở về với cội mai vàng năm cũ. À thì ra, cái hồn và bóng mà tôi mong ước không nguôi ấy là chính là cành mai vàng năm cánh của xứ Huế.<br />
     Dòng đời bất tận, công việc bộn bề, mệt nhoài, chợt thảng thốt nhận ra mùa xuân đã qua mau như định luật vô thường xưa nay vẫn vậy. Rồi tự trách mình sao vội quên hai câu thơ của Thiền sư Mãn Giác: <br />
<br />
<i>Chớ bảo xuân tàn hoa rụng hết <br />
Đêm qua sân trước  một nhành mai</i> (2)<br />
                                            (Ngô Tất Tố dịch)<br />
<br />
Thì ra, đóa mai vàng của mình vẫn luôn hiện hữu ngay cả khi xuân tàn.  Không phải đợi đến mùa xuân, ta vẫn luôn có trong tâm mình một cành mai rực rỡ. Sự xuất hiện cành mai vàng thân thiết trong tâm tưởng tôi bao giờ cũng liền với cái tình đối với mảnh đất thân yêu,  ngay cả hình bóng cành mai thiền của Thiền sư Mãn Giác cũng làm lòng tôi dấy lên nhanh chóng mối tình quê dạt dào, tưởng nhớ ngay đến nơi quê hương ngàn trùng đó với những hình ảnh ngày đầu năm đi lễ Phật ở chùa Linh Mụ. Vì thế, ta không thể không cảm thông nỗi nhớ quê đau đáu, xót thương, mòn mỏi,  bơ vơ nơi đất khách của Lê Cảnh Tuân (3)  trong cảnh lưu đày:<br />
<br />
<i>Quán trọ khách còn đó<br />
Xuân nay lại tới nơi<br />
Ngày về thăm chốn cũ<br />
Mai đã cỗi già rồi </i><br />
   (Nguyễn Hữu Vinh dịch)<br />
<br />
    Cũng như thế, Lý Bạch trong lúc bị biếm đày đi xa, ngang qua lầu Hoàng Hạc, vi vu nghe trong gió tiếng sáo, nỗi buồn nhớ quê thấm thía làm buốt cóng con tim, dù đang giữa mùa hè mà tưởng chừng thấm lạnh như trong mùa đông buốt giá đầy hoa mai rơi rụng.<br />
<br />
<i>Cũng làm khách biếm tận Trường Sa<br />
Mắt dõi Trường An chẳng thấy nhà<br />
Vi vút lầu Hoàng nghe tiếng địch<br />
Trời hè mai rụng rớt đầy hoa</i> (4)<br />
                  (Nguyễn Hữu Vinh dịch)<br />
<br />
      Giữa buổi giao mùa tháng chạp của thành phố Taipei, chờ đợi để đón đưa một người bạn cũ đến từ phương Tây xa lắc đến thăm là một niềm vui lớn...<i>Tha hương ngộ cố tri</i>...thì còn gì sung sướng hơn nữa.  Nhưng tại sao vẫn có một điều gì cảm thấy thiếu sót, bâng khuâng, ngậm ngùi, nao nao trong dạ. Ngẫm đi suy lại mới biết, đó là nỗi lòng quê đang khuấy động con tim. Có lẽ, ai người xa quê đều có nhiều thiếu thốn, thiếu bàn tay mẹ đặt run run trên trán mình mỗi khi đau ốm, thiếu ánh mắt nghiêm khắc nhưng yêu thương của cha,  thiếu món canh mẹ nấu rau mồng tơi xanh-rờn-cô-hàng-xóm, thiếu trách ruốc kho sả mặn chát lưỡi trong những ngày mưa lụt. Song có một điều dư thừa, dư thừa đến vô tận, lúc nào cũng thấy, lúc nào cũng có,  đó là nỗi lòng quê dằng dặc trong tim.  Ước gì người bạn phương xa ấy, từ quê mình đến đây! Chẳng trách sao được, biết bao cô gái lấy chồng xứ ngoại cứ bị ám ảnh bởi một cành mai ma quái và ác nghiệt:<br />
<br />
<i>Bác từ quê  mình tới<br />
Hẳn rõ chuyện quê xưa<br />
Ngày đi bên song cửa<br />
Mai vàng đã nở chưa</i> (5)<br />
    (Nguyễn Hữu Vinh dịch)<br />
<br />
     Thử lặng yên ngắm nhìn một cành mai trắng ở quê người, để cho hồn mình phiêu dạt, bay về với đóa mai vàng lung linh sương lạnh đầu xuân nơi quê hương - một khoảnh khắc tĩnh lặng, bình yên - chỉ là một khoảnh khắc thôi, nhưng cũng đủ để thấy cả một mùa xuân thân yêu đang tràn về thắm thiết và thôi thúc! <br />
<br />
<i>Cô đơn làm khách trọ quê xa <br />
Tết, lễ lòng thêm quặn nỗi nhà <br />
Leo núi anh em đi chạp mộ <br />
Thắp hương chỉ thiếu một mình ta</i> (6)<br />
                          (Nguyễn Hữu Vinh phỏng dịch)<br />
