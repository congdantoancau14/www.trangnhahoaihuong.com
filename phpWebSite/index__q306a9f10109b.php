<h3><h3>Tựa</h3></h3>


<b>Tôn Nữ Hỷ Khương</b><br />
<br />
Hai chữ <b>cơ duyên</b> trong đạo Phật thật vô cùng kỳ diệu. Tôi đã may mắn có được những cơ duyên đưa đẩy phát sinh những công việc thành tựu tốt đẹp mà tôi  vẫn nghĩ nhờ ơn chư Phật  độ trì mới gặp được duyên lành.<br />
<br />
Mùa xuân năm 1994, tình cờ tôi gặp <b>Nguyễn Hữu Vinh</b> tại nhà hai em Thu, Châu là bà con với tôi. Vinh là bạn của Thu, cũng người Huế, thỉnh thoảng Vinh về thăm quê và lúc nào cũng ghé chơi nhà Thu, các bạn văn nghệ thường gặp nhau trong dịp này.<br />
<br />
Một hôm Vinh ghé thăm tôi, ngồi chơi  ở phòng khách với mấy người bạn, trong lúc trao đổi chuyện trò về vấn đề thi ca xứ Huế rất hào hứng, Vinh chợt nhìn thấy trên kệ tủ một cái dĩa sứ có nét thư họa của họa sĩ Vũ Hối viết bốn câu thơ của Hỷ Khương:<br />
<br />
<i>Vẫn biết cuộc đời là mộng ảo,<br />
Phù sinh một kiếp thoáng qua mau.<br />
Tóc xanh đang độ thời thơ ấu,<br />
Thoảng chốc thì ra đã bạc đầu.</i><br />
<br />
Vinh tỏ ý thích và muốn xin tôi đem về Đài Loan giữ kỷ niệm.  Tôi vui vẻ tặng Vinh , rồi qua câu chuyện ấm nồng của buổi họp mặt  tình cờ, tôi thấy Vinh có năng khiếu về văn chương, mà lại có vẻ say mê nữa. Có lẽ động đến tình tri âm, tôi vội viết tặng Vinh cuốn <b>Thơ Ca</b> Tuyển Ưng Bình Thúc Giạ Thị do nhà xuất bản Thuận Hóa ấn hành năm 1992, Vinh rất vui mừng và cám ơn rối rít . Một tuần sau, khi trở về Đài Loan, tôi nhận được thư Vinh gửi thăm, trong đó có đoạn: "Sách chị cho, em gối đầu giường".<br />
		<br />
Đọc sách,  Vinh thấy có phần thơ chữ Hán: <b>"Lộc Minh Đình Thi Thảo"</b>. Lại có mấy bài dịch thơ của học giả Giản Chi, nhà thơ Thanh Tùng và nhà văn, nhà nghiên cứu Thanh Vân... Vinh yêu cầu tôi cho Vinh được xem bản thảo, tôi sốt sắng photocopy gửi qua cho Vinh . Thế là Vinh bắt đầu đọc , càng đọc càng say mê. Đồng thời có một sự khích lệ rất mạnh mẽ đối với Vinh là khi Vinh đưa tập thơ Lộc Minh cho vài vị giáo sư ở Đài Loan xem thì họ có nhận xét : “Tác giả là một người rất tài hoa, lại thâm nho và thật uyên bác”. Điều này làm cho Vinh càng thêm phấn khởi để càng đi sâu vào công việc dịch thuật với niềm hăng say thích thú.<br />
		<br />
Một hôm Vinh nhỏ nhẹ nói với tôi: "Chị Hỷ Khương nói cho em hiểu rõ thêm về luật thơ Đường, câu nào phải đối với câu nào, vần nào liên vận với nhau v.v..." Tôi nói sơ qua rồi hai chị em thảo luận một hồi rất là  thú vị. Thực tình tôi rất phục tính kiên trì và trí thông minh của Vinh.<br />
<br />
Nguyễn Hữu Vinh là một sinh viên hạng giỏi.  Năm 1973 được học bổng của chính phủ Đài Loan cấp theo học ngành Electrical  Engineering, tốt nghiệp Master of Science năm 1980. Vừa làm việc vừa tiếp tục học , và hiện nay Vinh là chuyên gia về Computer Enginneering. Vinh lập gia đình với một thiếu nữ Trung Quốc, có hai con, một trai, một gái, hiện cư trú tại  Đài Loan.<br />
<br />
Vinh bắt đầu làm công việc dịch thơ từ giữa năm 1994 cho đến cuối năm 1998 thì hoàn thành, sau đó dần dần sửa chữa, chăm sóc lại kỹ hơn. Vinh dịch "Lộc Minh Đình Thi Thảo" song song với công việc làm hằng ngày hết sức bận rộn. Những lúc kẹt xe giữa đường Vinh cũng nghĩ đến và nhớ mấy vần thơ... Có khi đang đi trên xe, Vinh điện thoại về Việt Nam  nói chuyện với tôi, vui cười, cởi mở khi nhắc lại một câu thơ đắc ý... Rõ ràng Vinh đã làm với tất cả tấm chân tình, niềm say mê đặc biệt, và có thể nói sâu xa hơn: Vinh cũng muốn làm “ một cái gì“ gọi là đóng góp cho nền văn học nước nhà nói chung và đất Huế nói riêng của một người con xa xứ luôn hướng về quê mẹ yêu thương với muôn vàn nỗi "nhớ mong da diết"! Và cuối cùng Vinh cũng nghĩ như tôi: nếu  không có hai chữ "cơ duyên" thì không "thành sự”  được.<br />
<br />
Hôm nay, thay mặt gia đình, tôi chân thành gởi lời cảm ơn nồng nhiệt đến Vinh, ngưòi bạn trẻ mà tôi hằng mến phục. Trong sự việc này, tôi cũng không thể nào quên gởi lời trân trọng và tri  ân sâu sắc đến quý vị <b>từ trước</b>, tới <b>bây giờ</b> và cho đến cả <b>mai sau</b> đã ưu ái dành cho <b>Lộc Minh Đình Thi Thảo</b> một cảm tình đặc biệt, mất nhiều thì giờ, công sức, nghiên cứu, dịch thuật, truyền bá và đánh giá sự nghiệp thi ca của phụ thân tôi là <b>Ưng Bình Thúc Giạ Thị</b>.<br />
<br />
Một lần nữa, xin muôn vàn cảm tạ.<br />
<br />
Miền Nam, mùa Thu Kỷ Mão 1999<br />
								 <br />
