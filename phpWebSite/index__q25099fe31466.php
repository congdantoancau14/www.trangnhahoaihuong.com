<h3>Bộ chữ (font)</h3>



Tất cả các chữ Hán Nôm trên trang web này đều ở dạng Unicode (UTF-8). Để hiển thị các chữ Hán Nôm trên máy của quý vị, xin cài đặt hai bộ font chữ Nôm HAN NOM A và HAN NOM B. Xin xem <a href = "http://www.viethoc.org/hannom/tdnom_chidan.php">hướng dẫn</a> tại trang web của Viện Việt Học.<br />




