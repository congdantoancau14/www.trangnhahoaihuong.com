  <li><a href="http://www.babelstone.co.uk/Software/BabelMap.html">BabelMap</a> - Nếu không tìm thấy một chữ Hán/Nôm nào đó trong bàn gõ HanNomIME, dùng BabelMap. BabelMap cho phép chêm (insert) tất cả các chữ Hán Nôm dạng Unicode có mặt trong tất cả các bộ fonts cài đặt trong máy của quý vị vào MS Word.</li>
  <li><a href="http://www.viethoc.org/hannom/tdtc_off.php">Thiều Chửu Hán Việt Tự Điển.</a> Bản Java Offline. Một quyển tự điển Hán Việt điện tử, cho phép tra nghĩa và đánh máy chữ Hán rất tiện dụng.</li>
  <li><a href="/phpWebSite/index.php?module=pagemaster&amp;PAGE_user_op=view_page&amp;PAGE_id=309">Cách tạo font chữ Nôm dùng riêng trong máy.</a>: Đôi khi, quý vị có thể gặp một số chữ Nôm không có trong các bộ font cài đặt trong máy của quý vị. Quý vị có thể tạo cho mình một bộ font để dùng riêng. (Tất nhiên, nếu muốn máy của người khác cũng đọc được chữ Nôm đó, quý vị phải gởi cho người dùng bộ font đó để cài vào máy.) <br />
