<h3>Văn tế Thầy: Vô Uý, Vô Ưu, Vô Cầu</h3>



<i>Đọc trước vong linh Thầy Nguyễn Khắc Kham<br />
Ngày 15/03/2007</i><br />
<br />
Thưa Thầy:<br />
Chúng con linh cảm chúng ta sẽ có ngày chia tay<br />
Thật gần!<br />
Khi nhìn Thầy yếu đuối ở tuổi một trăm<br />
Ngồi thụt sâu vào trong ghế dựa<br />
Mắt mơ hồ nhìn vào đám môn sinh<br />
Thầy không còn nhận ra được những người thân quen lâu ngày mới gặp<br />
Trí nhớ về đời thường theo thời gian đã trở nên suy tệ…<br />
Nhưng<br />
Trí nhớ về những chuyện làm văn hóa văn chương vẫn chất ngất trong đầu<br />
Thầy dạy:<br />
Nên viết quyển Văn Học Sử Việt Nam, nhấn mạnh trên thời Chữ Quốc Ngữ, chú trọng những tác phẩm Nôm: lớp trẻ đang rất cần.<br />
Thầy dạy:<br />
Nên soạn lại quyển Tự Điển Tiếng Việt để phù hợp với thời đại mới, thí dụ mới và chữ mới.<br />
Thầy dạy:<br />
Nên gấp rút hoàn thành quyển Tự Điển Chữ Nôm để giữ gìn sắc màu văn hóa Việt.<br />
Thầy dạy:<br />
Nên nghiên cứu những tài liệu xưa để nâng cao kiến thức ngày nay vì kiến thức không bao giờ giới hạn.<br />
‘Tôi già rồi, không ngại thời gian thách thức, chỉ ngại không thấy được công trình hoàn tất của các anh.’ <br />
Chúng con bội phục cái tâm Vô Úy của Thầy:<br />
Ung dung tự tại trước cuộc sống vô thường, chẳng sợ rằng mình sẽ đi xa…..<br />
Chỉ sợ sự rao truyền văn hóa của mình không còn cơ hội.<br />
Một ngày cách đây hai tháng:<br />
Thầy còn cười rất vui khi thấy học trò đến thăm.<br />
Thú vị nhắc lại những chuyện đời xưa cũ.<br />
Thầy còn ngồi ăn với chúng con, một chút cháo, một chút phở, <br />
Dầu rất ít….<br />
Bây giờ Thầy đã giũ áo ra đi<br />
Biền biệt cánh hồng bay bổng.<br />
Bỏ lại nhân gian với bộn bề phiền muộn, âu lo, tranh giành và bất trắc.<br />
Trở về cõi Vô Ưu như khi thầy còn tại thế.<br />
Trong miên viễn thời gian, trong bạt ngàn thế sự <br />
Thầy đã đánh dấu sự có mặt của mình<br />
Bằng tấm lòng Minh Triết<br />
Gia tài của Thầy là những vấn đề lớn của học thuật văn chương.<br />
Chúng con biết:<br />
Có những giọt nước mắt <br />
Rớt xuống hôm nay trong tang lễ của Thầy<br />
Của người thân, môn sinh, bằng hữu <br />
Và cả những ai chưa từng gặp mặt bao giờ.<br />
Nhưng hương linh Thầy phơi phới tới chín từng sao thăm thẳm <br />
Mỉm cười, nhẹ nhàng thanh thản.<br />
Chúng con, <br />
Những người ở lại:<br />
Biết chắc rằng tinh thần Chu Văn An, Đồ Chiểu, Trương Vĩnh Ký… nơi Thầy <br />
Vẫn phưởng phất như còn tại nhân thế hỗn mang.<br />
Cái Tâm Vô Cầu của Thầy sẽ kéo dài vô tận <br />
Vì Thầy là một tấm gương,<br />
Đem đời mình xây dựng nền văn hóa Việt.<br />
<br />
Xin thầy yên nghỉ<br />
Chúng con xin gạt lệ chia tay.<br />
<br />
Nguyễn Văn Sâm<br />
(học trò Chứng chỉ Văn Chương Quốc Âm 1961-1962<br />
và những môn sinh ở xa…Tâm, Tòng)<br />
