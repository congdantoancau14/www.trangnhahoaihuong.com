<h3>Võ Trường Toản Miền Nam</h3>



<i>Kính tặng Thầy, Giáo sư Nguyễn Khắc Kham (1907-2007)</i><br />
<br />
Một trăm năm -- con số đẹp,<br />
Thầy tôi một thế kỷ tuổi đời, <br />
Sức khoẻ còn, trí tuệ sáng ngời lóng lánh tinh anh.<br />
Vẫn trả lời cho học trò rất nhanh thắc mắc,<br />
Hay đi lục tìm tài liệu,<br />
Trong đám rừng chữ nghĩa trong nhà, trên kệ, trong phòng<br />
và đầy cả garage.<br />
Thân già bưng lên bưng xuống,<br />
Từng chồng, từng hộp, từng thùng,<br />
Những kiến thức một đời chắt chiu thâu góp.<br />
Không phàn nàn nửa tiếng đau lưng,<br />
Không than thân già mệt nhọc,<br />
Cũng không nói đến chuyện mất thời giờ hay bỏ lở nửa chừng,<br />
Thác rằng không tìm được,<br />
Hỏi và hỏi. Đáp và đáp.<br />
Tháng tháng năm năm<br />
Thân cò lặn lội.<br />
<br />
Học trò nhiều, nhiều quá, thế hệ nầy chồng chất thế hệ kia,<br />
Từ những năm bên này vùng xôi đậu học hành chẳng đủ sách đủ bàn,<br />
Từ thế hệ Thăng Long, bây giờ biết bao nhiêu người làm lớn,<br />
Tới những người của Đại Học Văn Khoa phôi thai Pháp mới vừa trao trả<br />
Chẳng chút tiện nghi, thiếu cả thầy, trò.<br />
Đến trường Văn Khoa của Miền Nam cất trên nền khám lớn cũ,<br />
Nơi từng giam cầm những Phan Văn Hùm, Tạ Thu Thâu, Nguyễn An Ninh, Hồ Hữu Tường,<br />
Những đại thụ của tư tưởng và hành động Việt Nam.<br />
<br />
Thầy rao giảng kiến thức nhân văn đối chọi lại những sai lầm sắt máu của thời đại nạn ngoại thuộc, xâm lăng, áp bức.<br />
Thầy hiền hòa che khuất những bóng roi gân bò và xiềng xích của quá khứ mất tự do,<br />
đi đâu cũng xin phép và mang theo giấy thuế.<br />
Thầy với những chuyện đi tìm tác giả Trinh Thử rất công phu.<br />
Học trò học hoài mà không sao đủ tài năng bắt chước.<br />
Thầy với bài về Hùng Vương Lạc Vương,<br />
Học trò học hoài mà không sao thuộc.<br />
Kiến thức đầy bồ,<br />
Sách vở đầy kho thầy đọc nghe mê mẫn.<br />
<br />
Nhưng.....<br />
Dạy học là chuyện nhỏ<br />
Trao truyền kiến thức chất chồng học trò rồi không biết mình đắc thụ của ai<br />
Ra đời rùng mình là quên hết<br />
Đạo làm người là điều tôi học được ở thầy.<br />
Một Võ Trường Toản, hậu bán thế kỷ hai mươi của phương Nam <br />
Nhân nghĩa lễ trí tín,<br />
Cẩn thận, tương kính, thương người.<br />
Không bằng kiến thức mà bằng nhịp đập của con tim hòa trong đời sống<br />
<br />
Học trò đến nhà thầy được chăm lo từng chút.<br />
Miếng ăn giấc ngủ. (Ôi cảm động nào bằng!)<br />
Học trò ở xa, thầy gọi điện thoại dặn dò nên làm thế nầy thế nọ.<br />
Cho khỏi dính tiếng thị phi, cho không mắc vòng kiềm tỏa.<br />
Nên mua thuốc A thuốc B.<br />
Trị đau lưng, nhức mỏi...<br />
Tình thương ẩn tàng trong từng lời dặn, nói.<br />
Ân cần,<br />
Nhắc đi nhắc lại.<br />
<br />
Trăm tuổi đầu thầy vẫn như con gà mái xoè đôi cánh rộng ra bảo bọc đàn con,<br />
