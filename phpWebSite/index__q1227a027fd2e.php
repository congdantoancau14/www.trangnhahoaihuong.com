     Mối duyên thơ giữa tôi và thi ông Ưng Bình Thúc Giạ Thị cũng bắt đầu từ đêm Thất tịch (ngày 7 tháng 7 âm lịch) hôm ấy. Tôi bắt đầu đi vào thế giới thơ chữ Hán của thi ông qua tập thơ “Lộc Minh Ðình Thi Thảo” (*). Tôi có duyên may được nhà thơ Tôn Nữ Hỷ Khương, ái nữ của thi ông, tặng cho bản sao photocopy cuốn “Lộc Minh Ðình Thi Thảo” gồm tất cả các bài thơ viết bằng chữ Hán của thi ông. Tôi đã bị lôi cuốn ngay từ đầu, chữ Hán viết bằng tay, đều đặn, đẹp như in. Và cũng từ đêm đó, tôi quyết định chuyển dịch ra thơ chữ Việt, gần 4 năm sau mới hoàn thành, và cũng cho tới bây giờ tôi vẫn bị lôi cuốn mãi hoài bởi những dòng thơ dạt dào, dấy lên những rung động sâu xa trong lòng người. <br />
<br />
     Chúng ta đã thưởng thức Thơ, Ca Huế, Ca Trù, Hò, Tuồng bằng chữ Việt của thi ông, nhưng nói đến sự nghiệp văn chương của thi ông mà không nhắc đến thơ chữ Hán là một điều thiếu sót lớn. Thi ông Ưng Bình Thúc Giạ Thị đã để lại cho kho tàng văn học Việt Nam tất cả 197 bài thơ chữ Hán, nếu kể từng bài thơ thuộc loại tám câu, thì thi ông đã sáng tác hơn 200 bài theo lối thơ Đường luật. Phần nhiều đều là những bài thơ thật tuyệt vời về hình thức lẫn nội dung. <br />
     Cuộc đời Ưng Bình Thúc Giạ Thị là cuộc đời của những bậc đường quan, và cũng là của những kẻ tao nhân mặc khách. Gió mát, trăng thanh, cảnh đẹp, trời thu, tình bạn đều là những yếu tố cần thiết, là nguồn thơ không thể thiếu. Phần nhiều các thi sĩ sống và sáng tác lấy sự cô đơn, sự khổ đau làm lẽ tự nhiên cho nguồn sáng tạo. Thi ông thì trái lại, lấy tình người làm gốc chốt, lấy ngoại cảnh thiên nhiên để cảm hứng, để dệt thành những vần thơ ngọt ngào, thanh thoát và đầy ắp tình người luyến lưu, đậm đà. Thi ông thường hứng tạo những vần thơ đầy ắp tình người trong những lúc cùng bè bạn ngao du, chơi thuyền, leo núi; hay trong những lúc ngâm thơ xướng họa, hay trong những lúc hò hát, hay trong những phút nhớ nhung vì xa cách. Có thể nói rằng trong những yếu tố tạo nên phong thái thơ ca của thi ông thì bạn bè, ca nữ và phong cảnh thiên nhiên đã đóng vai trò quan trọng và không thể thiếu. <br />
     Tập thơ chữ Hán của thi ông hầu như là tập thơ hoạ với thơ của các bạn thơ. Thi ông có rất nhiều bạn bè. Lúc về già thì có Hương Bình Thi Xã, khi còn trẻ thì thường hay hoạ thơ và nhắc nhở đến nhiều lần với mối cảm tình nồng nàn, đậm đà là những người như ông Thúc Thuyên, Đông Chi, Ðông Trì  và Hà Thiếu Trai.  Thi sĩ thì ai cũng lắm tình, nhưng mối tình ruột thịt của thi ông đã đặc biệt đành Thúc Thuyên thì thật là đậm đà, được thể hiện qua tám bài thơ còn để lại trong tập thơ chữ Hán có liên quan đến Thúc Thuyên. Quan Thượng Thư Thúc Thuyên, không ai khác hơn là người em ruột của thi ông, tuổi tác gần kề, cũng yêu thơ và cũng là quan lớn trong triều đình nhà Nguyễn. Đều cùng là những bậc đại quan trong triều, cả hai người đều phải rày đây mai đó, nhậm chức ở những nơi xa. Anh em hiếm lúc đoàn tụ sinh sống bên nhau. Tuy nhiên không phải vì thế mà tình cảm anh em ruột thịt xa mặt cách lòng. Năm Ất Hợi (1935), lúc Thúc Giạ về hưu được hai năm thì Thúc Thuyên mất. Thi ông khóc em thống thiết như sau :  <br />
