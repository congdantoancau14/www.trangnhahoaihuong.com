     Trong 197 bài thơ chữ Hán còn lưu lại, thi ông đã dành gần 15 bài thơ hoạ với ông Hà Ngại. Đây là số tỉ lệ lớn nhất về thơ hoạ của thi ông với bạn bè. Thi ông quen biết với ông họ Hà từ lúc còn làm Tri Phủ huyện Triệu Phong tỉnh Quảng Trị. Tình bạn cứ kéo dài cho tới lúc về hưu và nhất là lúc tuổi gần về trời, thi ông với ông họ Hà có rất nhiều bài thơ hoạ tuyệt tác. <br />
