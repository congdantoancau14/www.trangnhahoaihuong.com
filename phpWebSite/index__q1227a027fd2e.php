     Thúc Giạ nhìn cảnh cũ, lau lách vẫn như xưa, phất phơ theo làn gió nhẹ, rót chén rượu đổ xuống dòng nước chảy dưới ánh nắng chiều đỏ ối để tưởng nhớ người xưa. Trời gió mùa thu xứ Huế đã trở về, cây lá bên bờ sông đã trở vàng, nhớ lúc xưa, ở đây ta cùng em xướng họa, mà nay chỉ còn tiếng gió rì rào, nước mắt Thúc Giạ lả tả rơi. Người bây giờ ở đâu? Những cành hoa xưa còn đó, vẫn nở rộ, vẫn rực rỡ dưới ánh chiều tà, nay chỉ còn yên lặng. Rót chén rượu cúng xuống dòng sông, nghe gió thu trên sông lồng lộng, đâu đây văng vẳng tiếng ca của thuyền chài.   <br />
