<br />
  Trong 197 bài thơ chữ Hán trong tập Lộc Minh Đình thi thảo, thi ông Ưng Bình Thúc Giạ Thị đã để lại cho nền thơ văn của chúng ta nhiều bài thơ trác tuyệt, là những tài liệu quý giá để cho người đời sau còn có dịp nghiên cứu về xã hội, phong tục và tập quán  thời đó, cũng như có dịp hiểu thêm về cuộc đời và sự nghiệp của thi ông. <br />
Thơ chữ Hán của Ưng Bình có những đặc điểm sau đây: <br />
1. Nói chung, thi ông xoay quanh chữ "Tình". Tình đối với núi sông non nước, tình đối với thiên nhiên, tình bạn thơ ca, tình bạn ở quan trường, tình bạn bè thâm giao, tình với cô đào của ca trù và ca Huế. <br />
2. Tình của thi sĩ thường được thể hiện qua những "nỗi buồn", nhưng thi ông buồn một cách rất đặc biệt và đa dạng. Thi ông không buồn như nỗi buồn day dứt, than thở sinh không gặp thời như phần đông các thi gia đời Tống, Đường. Thi ông không buồn tê tái như Đỗ Phủ, không buồn man mác như Lý Bạch, không buồn yếm thế như Lý Thương Ẩn. Trái lại, người làm quan Án Sát mà lúc nào cũng say sưa với cái đẹp của vũ trụ, cái đẹp của thiên nhiên và buồn một cách nhẹ nhàng, thanh tươi. Thi ông buồn vì xa nhà, nhớ quê; buồn vì xa bạn, xa cô đào; buồn vì thiếu người để cùng ngao du sơn thuỷ, buồn vì mưa thu, buồn vì xa người ruột thịt v.v. Do đó thơ chữ Hán của thi ông có sự thu hút mãnh liệt đối với đa số người đọc vì hồn thơ thanh thoát, mộc mạc nhưng tế nhị và sâu sắc. <br />
3. Thơ của thi ông thường hay ghi lại những vết tích lịch sử, địa lý và xã hội cho nên rất gần gũi và dễ gây nhịp cảm với con tim của người đọc cùng xứ sở. Chúng ta có thể cùng được thưởng thức phong cảnh tuyệt vời ở những nơi danh thắng mà trong đó còn có những nhân vật nổi tiếng có liên quan đến lịch sử, văn học và xã hội đương thời.<br />
<br />
  Qua những vần thơ chữ Hán, thi ông sẽ đưa người đọc về thế gới phong lưu của hàng quan lại, thi nhân mặc khách ngày xưa, người đọc sẽ cảm thấy buồn vui lẫn lộn, tình cảm sẽ dạt dào và có được những cảm giác nhớ nhung chất ngất, bên tai còn nghe văng vẳng đâu đây những tiếng cười vui với những nhịp trống, lời ca, tiếng hát, câu hò của khách thơ, của ca nữ trong những dịp vui ca Huế, ca Trù hay trong những lúc dạo chơi với  núi non, trăng thanh, gió mát, hoa tươi, cỏ đẹp, núi biếc, sông mờ, thuyền dạo lênh đênh ở miền trung nước Việt trong những năm khoảng giữa thế kỷ 20. Với những vần thơ cô đọng nhưng dễ gây rung cảm cho con tim, người đọc cảm nhận được ý nghĩa của tình người qua thi ca chữ Hán của thi ông. <br />
