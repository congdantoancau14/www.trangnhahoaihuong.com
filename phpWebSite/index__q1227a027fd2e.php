<h3>Thơ chữ Hán “Lộc Minh Ðình Thi Thảo” của Ưng Bình Thúc Giạ Thị </h3>



      Ðêm tháng bảy âm lịch, trời Taipei vào tiết thu sang. Mưa lách tách trên lá, gió  xì  xào trên cây.  Hơi thu nhẹ thoảng, lòng người cũng vì thế mà chùng xuống, nhớ nhung bâng quơ. Tôi tỉnh lại với thực tại vì chợt nhớ tới mấy câu thơ chữ Hán của Ưng Bình Thúc Giạ Thị, một nhà thơ lừng lẫy của miền sông Hương núi Ngự:<br />
