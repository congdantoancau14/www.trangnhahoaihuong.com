<b>Sự nghiệp, Tư tưởng và Hương hoả của một nhà Đại Trí thức: Claude Lévi-Strauss (1908-2009)</b><br /><br />


<i><img src="http://internationalpsychoanalysis.net/wp-content/uploads/2008/09/levi-strauss-claude.jpg" align="left" hspace="5">
<div align="center"><br />
<b>TRẦN NGỌC NINH</b><br />
(với sự cộng tác của Trần Uyên Thi)</div><br />
<div align="right"><i>Bài này là của một người học-trò chưa bao giờ được gặp mặt Thày, cũng chưa từng được nghe tiếng nói của Thày cho đến sau khi Thày đã rời khỏi cõi đời đầy chấp-kiến và vọng-ngôn này. Những dòng dưới đây là để kính cẩn dâng lên hương-hồn một vị Thày đã mở mắt cho tôi vào Tình Người trong một địa hạt mà người Việt-Nam thường không nhìn đến.<br />
Trần Ngọc Ninh</i></div><br />
<br />
Báo-chí truyền-thông vừa loan tin về sự ra đi của một trong những tư-tưởng-gia vĩ-đại nhất của phương Tây trong thế-kỉ vừa qua.<br />
<br />
Giáo-sư, nhà văn, Hàn-lâm viện-sĩ Claude Lévi-Strauss vừa qua đời một cách lặng-lẽ êm-đềm tại tư-gia ngày 30.10.2009, chỉ vài tuần trước ngày sinh-nhật thứ 101 của Ông.<br />
<br />
Sự-nghiệp và tư-tưởng  của Ông là một hương-hỏa để lại cho đời sau mà chưa một ai trong đời này đã có thể tiên đoán được, tuy tất cả học-giới cảm thấy rằng Ông đã dẫn nhân-loại bước những bước đầu tiên vào một thời-đại mới.</i><br /><br />


