<h3>Nói Với Khoảng Không</h3>



<b>NGUYỄN VĂN SÂM</B><br />
<br />
Nắng đổ lửa mà tôi không có một miếng giẻ rách để che cái  lưng da mèo tam thể lốm đốm những chỗ tìm bầm, rách nát, lăn tăn, xon xót, máu ri rỉ ứa. Cái áo tôi vẫn nằm đó, cách không đầy một thước khi thằng oắt con trong bọn chúng sau khi dân trong xã đã tản mát hết, đứng quanh quất nhìn một hồi rồi buồn tình đưa tay giật mạnh ra khỏi mình tôi, hỉnh mũi, khinh khỉnh liệng xuống đất, nhăn mặt, phủi tay bước mau vô trụ sở không thèm ngó tới cái bản mặt tôi để coi phản ứng như thế nào. Lúc đó tôi vừa bực mình vừa tức cười, thằng ranh con hỉ mũi chưa sách đã bày đặt học cách làm bộ làm tịch ta đây, nhưng bây giờ ngó cái áo, tôi tiêng tiếc, nếu nó không đi ngang, hay nó không hiện hữu trên đời này thì tôi bớt khổ vì nắng sương, vì bầy ruồi quái ác kia. Bầy ruồi mắc dịch mắc toi không biết ở đâu rủ nhau tới đây nhiều quá, chúng cứ thọc mấy cái vòi khốn nạn vô miệng các vết thương, no nê thưởng thức bữa tiệc máu người. Đau nhói tim, buốt thấu tới mây xanh chứ phải chơi sao? Chúng mê man rít như tôi mấy bữa trước còn ở trong phòng giam, được nửa điếu thuốc Vàm cỏ do bạn bè cùng tù thương tình quăng cho, rít lấy rít để sau thời gian đăng đẳng thèm thuồng.<br />
<br />
Như ngài thấy đó, tay chân tôi bị cột chặt như đòn bánh tét, như con heo bị khiêng đi thọc huyết khi làng có đình đám: bốn chân bị cột chụm lại, một cây đòn xỏ ngang. Toòng teng. Rên than eng éc, Nước miếng trắng xóa nhễu nhão. Mặc tình. Người ta vẫn khiêng, công việc vẫn tiếp tục. Vậy nên tôi không than van hay chửi bới gì hết. Cắn răng chịu đựng, im lặng là vàng. Không phải sự im lặng đồng tình, mà là sự im lặng khing bỉ phản đối. Đứng yên quá lâu rồi tôi thèm được nhúc nhích, luôn tiện tống lôi tống khứ bọn ruồi hút máu ác độc này đi, nhưng cây trụ chết bầm dính cứng ngắc dưới đất hợp với mấy sợi dây luộc mắc dịch dai nhách như những ngón tay thép của một người khổng lồ ác độc giữ lại, chỉ cho phép tôi gồng mình chịu đựng, đứng chết trân như trời chồng, không cách nào khác hơn.<br />
<br />
Trở về mấy con ruồi. Cả đàn cả đống, vo ve, xì xào bay lên đậu xuống hí ha hí hửng như mấy thằng công an cười cười nói nói, ậm ọe gỡ gạc bằng miệng bằng tay mấy người đàn bà buôn chui coi bộ sạch nước cản mỗi khi xe ngừng lại trạm trách nhiệm của chúng ở đằng cái nhà trước mặt. Tôi nhăn mặt bực bội vì mấy con ruồi, tôi muốn nổi máu xung thiên lên vì mấy thằng nhóc đó. Cả hai hòa hợp như một ban đại hòa tấu trình bày tính chất vô nhân, nhịp nhàng, xướng họa, đầy đủ bi tráng hăng say, hồ hởi. Tôi chỉ việc nhắm mắt, như con đà điểu trốn chạy thực tế để xua đuổi nhựng hình ảnh đau lòng ra khỏi thị giác, nhưng đối với bầy ruồi kia thì là cả một vấn đề.<br />
<br />
Tôi rùn vai, nhăn mặt, cố nhúc nhích mấy thớ thịt giờ đây cũng bắt đầu làm biếng không muốn hoạt động nữa, hy vọng chúng sợ hãi, nhưng chúng chỉ chớp cánh bay lên một chút, một chút thôi, rồi đáp xuống tiếp tục tận hưởng bữa tiệc ngon lành đã được dọn sẵn. Tôi bị mất tự do mà! Chúng biết tỏng điều đó nên cứ nhởn nha, nhởn nhơ. Rù rì, rủ rỉ, vo vẻ, vo ve. Tôi nghe rõ ràng âm thanh của máu chuyền từ vết thương trên mặt mình, qua mấy cái vòi nhỏ, vô thân thể béo tròn, lầm lầm lì lì tuy nhỏ bằng hạt đậu nhưng tò ra rất chăm chỉ bòn rút sinh lực quí giá cuối cùng của tôi. Đâu cũng vậy, cũng nguyên tắc đó, yếu , mạnh, bóc lột. Trước khi bị cột dính khứng ở đây, tháng trước chứ đâu lâu lắc gì, tôi đã phải hồ hởi phấn khởi cơm bới cơm xách cùng với mấy người người khác dầm mình dưới nước ối đọng hôi thúi, tanh tửi như nước sông Đại Hà múc sình, xắn đất không công cả tháng, về nhà phờ phạc, mụn ghẻ nổi cùng hết mình mẩy rồi.<br />
<br />
Phải ruồi thôi đâu, còn đệ tử của ông nữa. Tôi có thể nói như vậy được không hả. Mặt trời đó. Chói chang trên đỉnh đầu, kiên nhẫn nạo ra từng chút nước nhỏ mọn trong người, trong cổ, trong miệng tôi. Rát muốn xé cần cổ. Mỗi hơi thở như hơi lửa táp cháy đốc giọng, như ai đó cào từ trong phổi tôi cào ra. Tôi thấm ướt cuống họng bằng cách nuốt hơi, hy vọng khí trời thấm mát, nhưng càng nuốt, xương quai hàm hai bên càng bướng bỉnh, nó cứng lại, như lúc bị bịnh quai bị. Tôi thử đủ mọi cách, nào là thở ra bằng miệng, nào là nín thở, nhưng tất cả mọi cách đều vô hiệu. Tôi muốn chết giấc. Thét rồi tôi trân mình chịu đựng, không dám nhúc nhích, không dám nuốt nước miếng, không dám nuốt hơi, cố gắng tiêu thụ một số ít năng lượng để cơ thể có thể chịu đựng lâu dài hơn. Tôi biết mình cuối cùng sẽ thất bại, thảm hại như anh chàng võ sĩ về già thiếu miếng thịt bò trong chuyện của Jack London. Gục đầu dưới nắng cháy da ban ngày hay chết cóng trong sương lạnh buốt tủy ban đêm, tôi chưa biết được. Nhưng tôi biết chắc rằng bản năng sinh tồn sẽ giúp tôi chóng chọi lại sự tàn lụi của thể chất để kéo dài sự sống đến lúc cần thiết. Chắc chắn là tinh thần sẽ thắng cái thân thể yếu đuối này. Như sự đánh gục nguyên tắc căn bản mà chúng thường rao giảng.<br />
<br />
Tất cả tùy thuộc vào tôi. Vào sự quyết sống của mình. Tôi biết tôi làm được. Tôi yếu mệt lắm rồi, nhưng với quyết tâm tôi chắc chắn thần chết cũng phải đứng chờ cho tới khi tôi xong việc. Chắc Ngài ngạc nhiên hỏi: Để làm gì? Ích lợi gì một vài giờ phù phiếm trên cõi đời này khi mình sắp từ giã nó với một ý nghĩa?<br />
<br />
Tôi đợi nàng, bữa nay thứ năm rồi, Ngài biết không? Ờ mà thời gian có nghĩa gì với Ngài đâu, chỉ là cái mốc loài người chúng tôi bày đặt cho tiện việc sổ sách, chứ Ngài, Ngài tính từng thời kỳ địa từng. Cả triệu năm cũng còn nhỏ. Ủa mà tôi đi quá xa. Trở về chuyện thứ năm. Tụi nó đem tôi ra đây từ trưa thứ ba. Thằng trưởng ban hẹn đào, hẹn điếc gì đó ở xa, vọt cuối tuần nên về trễ. Nhờ tình yêu của nó mà tôi được dời cực hình lại một ngày. Cám ơn tình yêu. Nếu chuyện của nó thực sự là tình yêu. Chuyện này cũng hiu hắt nữa. Chỉ nẩy lộc, đâm cành kết trái khi có hạt giống tốt và môi trường thuận lợi. Hạt giống tình cảm đã bị ung thối vì quyền thế và mù quáng làm sao tình yêu còn đất đứng để phát triển? Tôi đã chịu đựng được từ đó đến giờ nhằm nhò gì với sáu chục giờ nữa. Tôi đủ sức đợi. Chúa nhật này trên đường bổ hàng, nàng sẽ thăm tôi. Xe cộ lâu lắc, khó khăn, không biết chừng nào mới tới. Sớm nhất cũng năm sáu giờ sáng. Không phải đợi tới chừng đó tôi mới chờ nàng, mong nàng. Tôi đã ngóng trông từng giây, từng phút ngay từ lúc mới bị kéo lê kéo lết ra đây lận. Có khi tôi ao ước nàng đổi thời khóa biểu, đi ngang qua đây trước giờ dự định, thứ sáu thứ bảy gì đó. Tôi muốn được gặp nàng càng sớm càng tốt. Không phải để hôn hít ôm ấp. Cần gì đâu chuyện đó? Không phải để khóc than kể lể nước mắt vắn dài. Cải lương quá. Đã chấp nhận làm viên gạch lót đường, cần gì những thứ đó?<br />
<br />
Hai tuần trước, tôi cho nàng biết mình đang bị theo dõi và có thể nguy hiểm bất cứ lúc nào, một người bạn cùng đơn vị của tổ chức đã sa lưới cách đây một tháng. Tôi chấp nhận bị bắt để chúng tin rằng tổ chức của tôi theo đội hai người hầu bảo toàn phần còn lại của đơn vị. Đó là qui luật cách mạng. Hy sinh. Mấy năm nay tuy chánh quyền bị cưỡng chiếm nhưng tôi chưa bị trầy vi tróc vẩy gì nhiều. Binh sĩ địa phương quân nghe chửi bới ba ngày. Nhằm nhò gì? Công ăn việc làm không có. Bình thường thôi! ốc nạn mà. Coi như trải qua một cơn hồng thủy, thiên tai hay nắng hạn. Thủy lợi không công một năm hai tháng. Cũng được đi. Ích lợi chung! Tôi chỉ còn mẹ già. Không vợ con, anh em không ai bị giết, không ai đi học tập. Làm chuyện nước, đâu phải vì bất mãn, vì muốn sửa lại cuộc đời của riêng mình. Tôi vẫn cười mũi mấy thằng các mạng hí hửng ở địa phương. Ngày 1 tháng 5, thằng tư hớt tóc, chột mắt, biệt danh “Tư bài lận” chủ cái tiệm ọp ẹp đằng góc đường trong khu xóm tôi tiếp thu tòa hành chánh. Bà Năm què bán cơm trước bịnh viện, người nổi tiếng què mà đanh đá luôn luôn chửi bới khách hàng bệnh tật nếu họ run rẩy làm đổ cơm hay nước mắm trên cái bàn ăn dơ dáy của bà ta, tiếp quản bịnh viện. Thằng hạ sĩ nhất Tâm già tài xế chuyên viên ăn cắp xăng và bán đồ phụ tùng trước đây bị phạt lên phạt xuống bây giờ đại diện người anh em bên kia nhận tiểu khu. Hỏi họ lý tưởng cách mạng, được trả lời phân chia đồng đều lại của cải, không còn bất công. Tôi biết ý niệm này hiện ra trong lòng họ với những tính toán, ganh tị. Tôi biết khi nhảy vào cuộc hơi “cách mạng” họ đã cân phân được thua. Không có gì để mất, nhưng hy vọng có quá nhiều để được. Cách mạng mà! Đổi đời mà! Nói chuyện về tụi nó, bắt tôi nhớ tới cha tôi, người cha không rõ mặt. Lờ mờ đâu trong xa thẳm dưới đáy huyệt ký ức hồi hai ba tuổi có một ông nào đó lạ quắc lạ quơ thỉnh thoảng ban đêm tới nhà ẵm tôi, tôi sợ hãi khóc ré lên. Mẹ tôi luôn luôn quấn quýt ông ta nay lăng xăng dưới bếp bận bịu với những món ăn, bỏ tôi một mìn