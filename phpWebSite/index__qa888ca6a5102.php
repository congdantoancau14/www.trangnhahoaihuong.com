<br />
Rồi tôi quên bẵng đi người cha xa lạ đó. Sau nầy tôi mới biết cha mình bị Tây bắn chết hồi năm 51, 52 gì đó lúc mà theo lời bà ngoại tôi mỗi lần có chuyện lên Sài gòn bà thèm đi coi cải lương nhưng không dám bén mảng tới rạp vì gần như tuấn nào cũng có lựu đạn liệng trong rạp hát, không rạp Nguyễn Văn Hảo thì Thành Xương  hay Aristo. Tôi có đọc một trong hai bức thư người gửi cho mẹ tôi mà bà trân trọng giữ gìn trong hộp nữ trang. Lá thư đã rách ở những lằn xếp, được viết trên giấy tập học trò có gạch hàng và chừa lề bằng một đường gạch đỏ từ trên xuống dưới. Đại khái người than nhân loại đã đi trật đường. Nhóm mạnh đi khai thác sự chậm tiến kỹ thuật của nhóm yếu, bòn rút tài nguyên của các dân tộc này. Nhóm yếu vùng dậy, cuối cùng tìm sự hổ trợ của một lý thuyết đặt nền tảng trên bạo động, đặt mục tiêu trên sự thành công, bất chấp phương tiện. Người đã đau lòng chứng kiến từng đoàn từng lũ dân vô tội chết oan vì bị nghi ngờ trong đó có một người làm điềm chỉ cho Pháp. Người đã bất mãn vì sự chèn ép của cấp trên nịnh nọt, bò lên chức vụ cao cấp vì thuộc về một nhóm bí mật đang lèo lái công cuộc kháng chiến. Người được rủ rê gia nhập nhưng còn chần chờ vì chưa thỏa mãn những vấn nạn tự đặt về nguyên tắc đấu tranh. Những bức thư đó tôi đọc từ lâu lắm, từ lúc còn ở một hai năm đầu trung học.<br />
<br />
Tôi đọc lờ mờ thấy có gì đó không ổn giữa sự chiến đấu và suy tư của cha tôi. Phải đau khổ lắm người ta mới kể lể chuyện không dính dáng gì hết với tình yêu cho người vợ xa cách. Bây giờ, sau khi cả dân tộc bị cùm chân trong đọa đày, nhớ lại những điều đã đọc, tôi chợt hiểu rõ ràng, thật rõ ràng điều người cha không biết mặt của tôi muốn nói. Mẹ tôi nay đã bị thời gian tước đoạt sự tinh anh lanh lợi ngày xưa. Giờ ai nói gì bà cũng dạ, cũng vâng, cũng gật. Mới vào, chúng bảo gia đình thuộc gia đình cách mạng, bà đã dạ, đã vâng, mặc dầu không một chút vui mừng, thích thú trong ánh mắt của bà Bà đón nhận vòng hào quang với vẻ lãnh đạm và bỡ ngỡ. Trong suốt một năm thuộc diện có “công” bà chưa hề nhắc đến chuyện khai báo để nhận lãnh một đặc ân nhỏ mọn nào. Bây giờ chúng bảo gia đình tôi là ngụy, là phản động, bà cũng vâng, cũng dạ, không một lời phản đối, bào chữa hay khiếu nại. Tôi đọc được nỗi sợ hãi trong cử chỉ của bà, lập cập, vấp váp, run rẩy. Thế thôi. Không cả một tiếng thở dài.<br />
<br />
Ngài thấy đó, xã hội này đã dùng những danh từ để chuyển dịch cuộc sống của con người. Từ ngữ trừu tượng như những cái củi sắt bao vây thiên hạ bằng ảo vọng hay trói chặt trong tình trạng sợ hãi và có thể chấm dứt đời họ một chỗ lưu đày âm u nào đó. Nhiều lần dân chúng chúng tôi bảo ghi lại một cách thành khẩn những việc ông cha đã làm để được xếp loại thành phần. Từ đó mỗi người đầu được bao bọc bằng những danh từ. Cái áo vô hình và trừu tượng này đã biến đổi tâm tính, bóp méo cá rính một phần đông dân chúng. Hoặc kheo khoang, hí hửng, ca tụng, bao biện cho bạo quyền, hoặc im lặng, lấm lét, rút mình lại ru rú như thỏ con. Họ, tất cả đã được bóc vỏ để trở thành người khác, đã vong thân sau khi tờ lý lịch được viết ra. Họ đã bị chuyển hồn.<br />
