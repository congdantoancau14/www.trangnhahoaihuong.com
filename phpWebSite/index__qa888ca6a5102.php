Lúc đó may mà tôi thoát được nhờ tinh thần hy sinh cao cả của mấy người bạn, nhờ sức chịu đựng dẻo dai, nhờ thuộc nằm lòng cẩm nang mưu sinh thoát hiểm để giờ đây lần nữa chứng kiến được bản chất của họ. Tôi trần tình với Ngài như là sự thực hiện bổn phận với bạn bè đã chết. Tôi đã làm hết sức mình trước ngày bị bắt. Tôi dùng những hơi thở chót để nói với Ngài. Ngài hiện hữu hay không, Ngài đã chết hay chưa, không thành vấn đề. Tôi trần tình, cứ việc trần tình. Những vấn đề khác thuộc về lãnh vực mà tôi không có khả năng giải quyết. Không phải vì tuyệt vọng nên tôi nói  với Ngài để cầu xin ân huệ. Tôi cố gắng làm một điều gì đó thật có ý nghĩa trong khoảng thời gian chót. Tôi chứng minh trong một xã hội tha hóa, nơi cai trị bởi những hình nhân bằng đá được hà một hơi sinh khí bằng bùa phép danh từ, đối diện với cả bản án tử hình, hành động vì tình yêu vẫn có…<br />
<br />
Mấy giờ rồi? Trời chưa sáng mà. Sao tôi nghe loáng thoáng có tiếng chân người. Ngài thấy đó, tôi nói có sai đâu. Nàng đã tới. Ủa, tôi sao vầy nè? Mắt mở không được. Chân tôi từ lâu đã không chống đỡ nổi cho thân hình, tôi còn trụ được là nhờ mấy sợi dây luộc cột dính như Ngài biết đó. Miệng khô cháy, tôi không ú ớ được đã đành, nhưng tôi cần phải mở mắt ra được chớ? Đầu tôi chức nhối, tôi quay mồng mồng trên không trung cách mặt đất độ vài chục thước. Không cần. Tôi phải thấy nàng mới được. Tôi sẽ diễn tả bằng mắt để nàng biết chuyện gì phải làm. Ồ, mà tiếng chân đã gần lắm. Coi bộ nàng tới với bạn bè chứ không phải một mình. Càng tốt, chuyện nầy thêm nhiều người chứng kiến cũng không sao. Việc quan trọng là nàng đã tới. Hình như không phải nàng. Tôi nghe tiếng chân hơi mạnh. Xì xào giọng vịt đực. Cái gì? Tôi không hiểu gì hết. Anh Ba vớt cú này thiệt đẹp. Thằng con đó tử nạn thì con nhỏ trước sau cũng thuộc về ảnh như mấy đứa bị đá đít trước kia thôi. Làm bộ làm tịch, õng ẹo, chửi bới rồi cuối cùng cũng bị vớt, mà vớt bạo nữa. Tan nát đời hoa. Mang bầu cả lũ. Con nhỏ này ngon lắm, tiếc là anh Ba hơi già, cho tao, tao lạy nó mỗi ngày để được… Cái gì? Thì tao cũng lạy. Tao thấy nó khóc tao thương quá. Tụi nầy lảm nhảm gì vậy? Mấy thằng nhóc nói chuyện làm ăn bậy bạ rồi. Tôi không muốn nghe nữa. Tôi muốn nàng tới kìa! Sao chậm quá vậy. Tôi không còn nghe chân tôi tê dại nữa. Chỗ nhức nhối ở đầu gối sưng vù kia cũng hết đau. Chỗ thôn thôn ê ẩm nơi thắt lưng phía sau với chỗ tức tức cạnh be sườn bây giờ tôi cũng nghe rất thảnh thơi. Sao kỳ vậy kìa? Không lẽ tôi đương chết từ dưới chân chết lên. Bậy nà, nàng chưa tới mà.<br />
<br />
Ờ, mà Ngài có nghe không hả? Sao tôi chỉ thấy lặng trang chung quanh, chỉ toàn nhạc đưa ma của loài trùn, loài dế. Trời chưa sáng sao? Phải sáng để nàng tới chớ. Ủa? Sao tôi thấy mình không còn chút gì minh mẫn hết. Tôi thua cuộc rồi? Không lẽ Ngài không hiện hữu? Không lẽ Ngài chỉ là một khoảng không vô tận mịt mùng…? Không lẽ Ngài chỉ là ông Xanh? Chỉ là kẻ cắc cớ chết đuối người trên cạn mà chơi, đành hanh quá ngán, coi thiên hạ nhân gian như thứ đồ chó rơm không đáng kể? Vô tình.<br />
<br />
(Rút từ tập truyện Ngày Tháng Bồng Bềnh).<br />
