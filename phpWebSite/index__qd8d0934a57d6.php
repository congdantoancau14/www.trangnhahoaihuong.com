<h3>Sách Tham Khảo</h3>



1) [THC] Thi Ca, Ưng Bình Thúc Giạ Thị, nhà xuất bản Thuận Hoá, 1992, Huế.<br />
2) [BT1] Bản thảo "Lộc Minh Ðình thi thảo tập 1" của Tôn Nữ Hỷ Khương.<br />
3) [BT2] Bản thảo "Lộc Minh Ðình thi thảo tập 2" của Tôn Nữ Hỷ Khương.<br />
4) [ÐP] Quốc ngữ từ điển 國語辭典(Tiếng Trung Hoa), Ðông Phương xuất bản xã, Ðài Bắc.<br />
5) [LU] A new practical Chinese-English dictionary, Lương Thực Thu, Viễn Ðông đồ thư, Ðài Bắc.<br />
6) [TC] Hán Việt tự điển, Thiều Chửu, nhà xuất bản Ðuốc Tuệ, Hà Nội 1942.<br />
7) [TTNH7] Tuyển Tập Nhớ Huế, số 7, ấn phẩm đặc biệt 20 năm xa Huế, 1975-1995, xuất bản tại California, USA.<br />
8) [ND] 192 bài thơ chữ Hán của Nguyễn Du, Bùi Hạnh Cẩn, nhà xuất bản Văn Hoá Thông Tin, Hà Nội 1995.<br />
9) [ÐT] Ðường Thi, Trần Trọng Kim tuyển dịch, nhà xuất bản Văn Hoá Thông Tin, Hà Nội 1995.<br />
10) [ÐT3V] Ðường Thi tam bách thủ 唐詩三百首 (Tiếng Trung Hoa), Văn Hoá đồ thư xuất bản, Ðài Bắc.<br />
11) [ÐT3Ð] Ðường Thi tam bách thủ 唐詩三百首 (Tiếng Trung Hoa), Ðại Chúng thư cục xuất bản, Ðài Bắc.<br />
12) [TT] Thi Từ hân thưởng 詩詞欣賞 (Tiếng Trung Hoa), Trí Dương xuất bản xã, 1993 Ðài Bắc.<br />
13) [KT] Từ điển Hán Việt hiện đại, Nguyễn Kim Thản, nhà xuất bản Thế Giới 1994.<br />
14) [CT10] Ðào Uyên Minh 陶淵明 Trung Quốc văn học tổng tân thưởng, Cổ thi tân thưởng, bộ 10 (tiếng trung Hoa), Ðịa cầu xuất bản xã, Ðài Bắc.<br />
15) [ÐT7] Ðỗ Phủ 杜甫 Trung Quốc văn học tổng tân thưởng, Ðường thi tân thưởng, bộ 7, tập hạ, (tiếng trung Hoa), Ðịa cầu xuất bản xã, Ðài Bắc.<br />
16) [ÐT1] Trương Cửu Linh 張九齡 Trung Quốc văn học tổng tân thưởng, Ðường thi tân thưởng, bộ 1 (tiếng trung Hoa), Ðịa cầu xuất bản xã, Ðài Bắc. <br />
17) [TV12] Tô Thức 蘇軾 Trung Quốc văn học tổng tân thưởng, Tản Văn, Ðường Tống bát đại gia, bộ 12 (tiếng trung Hoa), Ðịa cầu xuất bản xã, Ðài Bắc.<br />
18) [TH] Tự điển Từ Hải 辭海字典 (tiếng trung Hoa), Trí Dương xuất bản xã, Ðài Bắc.<br />
19) [CVQC] Cổ Văn quan chỉ tân biên 古文觀止新編 nhà xuất bản Ðông Hải, Ðài Nam, 1976.<br />
20) [ÐT3] Vương Duy 王維Trung Quốc văn học tổng tân thưởng, Ðường thi tân thưởng, bộ 3 (tiếng trung Hoa), Ðịa cầu xuất bản xã, Ðài Bắc. <br />
21) [CONK] Cung Oán Ngâm Khúc, Ôn Như Hầu Nguyễn Gia Thiều, Vân Bình Tôn Thất Lương chú giải. <br />
22) [CT5] Sở Từ 楚辭 Khổng Dung, Trung Quốc văn học tổng tân thưởng, Cổ thi tân thưởng, bộ 5 (tiếng trung Hoa), Ðịa cầu xuất bản xã, Ðài Bắc.<br />
