<h3>Việc Khó Khăn Của Một Giáo Sư</h3>


<b>A Professor's Dilemma, by Jan Willis</b><br />
<br />
<a href="http://www.trangnhahoaihuong.com/files/ViecKhoKhanCua1GiaoSu.pdf">Đọc bằng bản PDF</a><br />
<br />
Tôi đã dạy những lớp về đạo Phật trong đại học gần ba mươi lăm năm nay, nhưng đôi khi tôi vẫn tự hỏi rằng, không biết mình có thật sự trao truyền được những tinh hoa của giáo pháp tâm từ này đến với các sinh viên không. Nói một cách khác, tôi thấy mình thường hay thắc mắc, một lớp trong trường đại học dạy về đạo Phật, nó có mang tính cách gì là "Phật tử" chăng?<br />
<br />
Tôi thường tự hỏi, những học giả tu tập theo đạo Phật như chúng tôi trong một học viện, đang cố gắng đóng góp những yếu tố hay năng khiếu đặc biệt gì trong vấn đề học Phật cho các sinh viên, qua những lớp học này? Có phải chúng tôi chỉ mong mỏi họ hiểu hết được những danh từ chyên môn Phật học, biết được một vài giáo lý quan trọng của dharma, hay là bằng một cách nào đó, thật sự tiếp xúc được sâu sắc với cốt tủy của đạo Phật!<br />
<br />
Trong kinh, đức Phật dạy các đệ tử rằng, Ehi passika, có nghĩa là "Hãy đến và tự thấy!" Và Ngài cũng có trình bày rất rõ về đường lối học Phật là phải như thế nào.<br />
<br />
<i>"Này các ông, các ông đừng tin một điều gì vì phong văn. Đừng tin một điều gì vì nó là tập quán lưu truyền. Đừng tin một điều gì vì được nhiều người nhắc đi nhắc lại. Đừng tin một điều gì vì đó là bút tích của thánh nhân. Đừng tin một điều gì vì đó là thói quen đã có từ lâu. Đừng tin một điều gì do ta tưởng tượng và lại nghĩ rằng do một thần linh nào đó khai thị cho ta. Đừng tin một điều gì vì đó là do các thầy có uy tín dạy."</i><br />
<br />
Mặc dù đầy thách đố, nhưng chắc chắn đó không phải là những nguyên tắc đang được áp dụng trong những chương trình ở các lớp đại học. Và ngược lại, các vị giáo sư, cũng như sinh viên, lại dựa trên một "kiến thức xác định sẵn có" để làm nền tảng giảng dạy và học hỏi. Nhưng không phải ý tôi nói rằng, vấn đề nghiên cứu tri thức trong sự học Phật là không tốt. Thật ra việc ấy cũng cần thiết lắm chứ! Trong đạo Phật khả năng suy luận tư duy (critical reasoning) cũng được đặt lên rất cao. Mỗi khi ta đọc kinh, ta thấy đức Phật thường nhắc đi nhắc lại về sự quan trọng của một tư duy chân chánh và sự phát triển tuệ giác. Nhưng dĩ nhiên, những suy luận vòng vo cũng có giới hạn của húng, và niết bàn là một nơi vượt ra ngoài hết mọi ý niệm. Tư duy và suy luận suông sẽ không bao giờ mang ta đến niết bàn, cho dù ta có tôi luyện sâu sắc đến đâu, nó cũng sẽ không thể nào giúp ta thoát ra được khỏi vòng sanh tử này.<br />
<br />
Những giáo sư Phật học không phải là những bậc thiện tri thức, như các vị lamas hay geshes, có khả năng hướng dẫn và giải thoát cho học trò của mình. Nhưng có lẽ mục đích chánh của các vị giáo sư không phải là để trao truyền cho các sinh viên một kinh nghiệm nào hết, mặc dù đó là một điều thiết yếu và cũng là tuệ giác trong việc học Phật. Chúng tôi đâu thể nào ngồi trên tọa cụ thế cho những sinh viên của<br />
mình được. Và nếu như họ không thực tập ngồi thiền, thì họ, và chúng tôi nữa, thật sự đang làm gì đây?<br />
<br />
Thỉnh thoảng tôi cũng tạo những dịp cho các sinh viên cùng ngồi thiền với tôi. Lẽ dĩ nhiên là những cơ hội này hoàn toàn nằm ngoài lớp học và các sinh viên muốn tham dự hay không là tùy ý họ, không bị bắt buộc. Những trường đại học chúng ta ngày nay thôi không còn là những viện thần học như xưa nữa, trong thời đại khoa học và hiện đại này, mỗi khi ta đề cập đến vấn đề kinh nghiệm tâm linh, nó thường bị nhìn dưới một ánh mắt rất ngờ vực.<br />
<br />
Tuy vậy, thay vì chỉ hướng dẫn cho các sinh viên của mình bàn thảo và tranh luận về ý niệm của phật tánh, buddha-nature, tôi ước gì, bằng một cách nào đó, có thể giúp cho họ khám phá ra phật tánh của chính mình. Nếu tôi có quyền quyết định, tôi sẽ bắt buộc các sinh viên của tôi phải tham dự một khóa tu thiền quán mười ngày, song song với việc tham gia lớp Phật học, để có thể như ông Phillip Moffitt chia sẻ, "học hỏi bằng chính tự thân của mình”, hay thân giáo. Chúng ta đã học quá đầy đủ và suy luận quá nhiều rồi!<br />
<br />
Ngày xưa, bài kinh đức Phật dạy đầu tiên về thiền tập là bài kinh Satipatthana Sutra, tức kinh Bốn Lãnh Vực Quán Niệm, và đó cũng không phải là chuyện ngẫu nhiên. Tôi vẫn thường nghĩ rằng phương pháp vipassana, thiền quán, (và dĩ nhiên cùng với kết quả của nó là metta, thiền tâm từ) là những pháp môn rất lý tưởng cho người Tây phương, vì nó không bị ảnh hưởng nặng nề về vấn đề văn hoá. Đây là những pháp môn thực tập đơn giản, trực tiếp và tức thì - đó cũng chính là hiện thân của trái tim đạo Phật.<br />
<br />
Nhưng nói cho cùng thì mặc dù chúng ta có thể trình bày rất chi tiết và rõ ràng về nó, nhưng ta không thể nào đơn giản trao truyền cái thấy của đạo Phật được. Một cái thấy không những khiến đạo Phật khác với các truyền thống khác, mà còn có thể mang ta đến an lạc và giải thoát. Nếu như đức Phật có khả năng làm cho ta giác ngộ thì tất cả chúng ta đã được giác ngộ hết rồi. Nhưng ngay chính đức Phật cũng không có thể làm được việc ấy. (Thật ra thì tất cả chúng ta đều đã giác ngộ rồi đó, chỉ có điều là mình chưa ý thức được đó thôi). Trước khi ra đi, Ngài khuyên mỗi chúng ta nên tinh tấn thực hiện việc giải thoát cho chính mình. Trong môi trường của một lớp đại học thì chúng tôi chỉ có thể khuyên các sinh viên của mình nên đi tìm một trung tâm thiền tập.<br />
<br />
"Hãy tinh tấn!" Tôi vẫn nói với các sinh viên của mình vào mỗi cuối khóa học. "Hãy tinh tấn, và tử tế với nhau."<br />
