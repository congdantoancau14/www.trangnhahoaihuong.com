<h3>4. Oan nghiệt (1941)</h3>



<i>Những suy nghĩ vẩn vơ, ý nầy kéo ý kia của thi sĩ khi nghe tin người vợ cũ sanh con gái. Trong tưởng tượng có cái lo lắng cho kiếp đời đau khổ có thể xảy ra oan nghiệt của con mình. Mấy câu trở thành cổ điển: "Nhất kiêng đừng lấy chồng thi sĩ/Nghèo lắm con ôi! Bạc lắm con" là một lời dặn, một lời tự trách, tự biện. Tác giả dẫn "Tỳ Bà Hành" thiệt là hay!</i> <b>(Nguyễn Văn Sâm)</b><br />
