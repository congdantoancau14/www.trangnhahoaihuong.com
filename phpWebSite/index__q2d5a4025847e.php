<h3>2. Tương Tư (1939)</h3>



<i>Chuyện tình tự kể. Những hình ảnh nông thôn được sử dụng, những thống trách mang hơi hướm của người đồng quê chơn chất làm cho sự tương tư trở nên lung linh đẹp. Hàng loạt câu hỏi và lời tự giải thích biểu lộ cái yêu đã sâu đậm nhưng không được đáp ứng. Tác giả giấu cái thất bại trong tình yêu khi so sánh nỗi tương tư của mình với chuyện nắng mưa của trời đất. Câu hỏi cuối bài là câu đánh đố đáng yêu gởi đến ai kia: "Anh nhớ ai em có biết không?"</i> <b>(Nguyễn Văn Sâm)</b> <br />
