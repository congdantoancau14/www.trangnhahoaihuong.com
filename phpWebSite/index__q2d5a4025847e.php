<h3>1. Viếng Hồn Trinh Nữ  (1937)</h3>



<i>Tác giả chọn đề tài độc đáo: Thương tiếc một người con gái nằm xuống khi tuổi còn xanh dầu mình không quen biết. Ông khéo léo hình dung ra những sinh hoạt thiếu nữ của nàng trước khi mất để làm nổi bật hơn tính cách bi đát. Những hình ảnh phụ như người mẹ, mấy đứa em, người để ý nàng... được thêm vào để minh họa sự luyến tiếc của người thân thương. Càng bi thương hơn khi ông nói: rồi mọi chuyện sẽ qua đi, hình ảnh về nàng sẽ chìm vào quên lãng của thời gian… Bài thơ gồm nhiều chữ "trắng" để diễn tả sự tang tóc, đồng thời hàm ngụ ý trinh bạch của thiếu nữ và cái họ Bạch của nàng. Bài thơ man mác buồn, dầu chữ dùng thiệt là đơn giản và ý được trải rộng ra quá nhiều. Bài nầy chịu ảnh hưởng của giai đoạn thi ca lãng mạn và cũng tác động mạnh lên sự lãng mạn của những thi nhân đồng thời.</i> <b>(Nguyễn Văn Sâm)</b><br />
