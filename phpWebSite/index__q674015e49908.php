Người ơi, đường xa lắm con đường về làng dìu mấy thuyền đò <br />
Còn đó tiếng tre êm ru, <br />
Còn đó bóng đa hẹn hò, <br />
Còn đó những đêm sao mờ hồn ta mênh mông nghe sáo vi vu... <br />
Người ơi, <br />
còn nhớ mãi trưa nào thời nào vờn bướm bên ao <br />
Người ơi, <br />
còn nghe mãi tiếng ru êm êm buồn trong ca dao <br />
Còn đó tiếng khung quay tơ, <br />
Còn đó con diều vật vờ <br />
Còn đó, nói bao nhiêu lời thương yêu đến kiếp nào cho vừa? <br />
<br />
Ôi, những đêm dài hồn vẫn mơ hoài một kiếp xa xôi <br />
Buồn sớm đưa chân cuộc đời <br />
Lời Đường thi nghe vẫn rền trong sương mưa <br />
