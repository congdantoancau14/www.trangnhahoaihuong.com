Người ơi, chiều nào có thu về cho tôi nhặt lá thu rơi <br />
Tình có ghi lên đôi môi <br />
Sầu có phai nhòa cuộc đời <br />
Người vẫn thương yêu loài người và yên vui sống cuộc sống vui. <br />
