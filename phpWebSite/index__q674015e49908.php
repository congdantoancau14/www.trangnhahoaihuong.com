Tình Nhị Hồ vẫn yêu âm xưa <br />
Cung Nguyệt Cầm vẫn thương Cô-tô <br />
Nên hồn tôi vẫn nghe trong mơ tiếng đàn đợi chờ mơ hồ<br />
Vẫn thương muôn đời nàng Quỳnh Như, thuở đó <br />
<br />
Ôi, những đêm dài hồn vẫn mơ hoài một giấc ai mơ <br />
Dù đã quên lời hẹn hò <br />
Thời Hoàng Kim xa quá chìm trong phôi pha <br />
Chờ đến bao giờ tái sinh cho người? <br />
Đời lập từ những đêm hoang sơ <br />
Thanh bình như bóng trưa đơn sơ <br />
Nay đời tan biến trong hư vô, <br />
chết đầy từng mồ <br />
oán thù, <br />
máu xương tơi bời nhiều mùa thu <br />
<br />
