<h3><h3>cây đàn guitar, một trời kỷ niệm</h3></h3>


<h3>HOÀI HƯƠNG</h3>
<br />
Những ngày ba ở trong trại cải tạo, mẹ cất cây đàn guitar vào tủ, cùng với một tập nhạc dày cộp, những xấp hình loang lổ vì nước lụt, lưu bút của học trò, giấy tờ quan trọng..., khoá lại.  Mỗi lần mẹ mở tủ là tôi đòi đem cây đàn ra ngắm nghía, sờ mó, khảy tứng từng tưng.  Cây đàn đẹp tuyệt, tiếng ấm, ai thấy cũng phải trầm trồ.  Màu gỗ mặt trước đỏ sậm, mặt sau đen nâu, cả hai mặt đều trơn bóng và sáng loáng như hai tấm gương, cầm lên mát rượi cả tay.  Ba sợi dây trên màu vàng, hai dây dưới màu đen (bị đứt mất sợi dây số 1), tiệp với màu gỗ một cách hài hoà.  Nghe nói ba nhờ nhạc sĩ Lê Uyên Phương mua giùm.  Thèm quá, tôi xin mẹ cho đi học đàn với các ma soeur, thì mẹ cứ “chờ ba về, dạy cho.” Lại chờ.  Chờ biết chừng nào ba mới về?  Tiu nghỉu, tôi đành ngồi soi mặt mình trong đàn, mà như thấy hình bóng ba thấp thoáng trong đó.  <br />
<br />
Chờ mãi đến khi tôi lên 9 tuổi, thì một buổi chiều — tưởng như mọi buổi chiều — ba tự nhiên xuất hiện ở giữa sân, như từ trên trời rơi xuống.  Tôi muốn nhảy cỡn lên, chạy đến bên ông, nhưng không hiểu sao hai chân của tôi lại chạy vào...  xó cửa.  Sao sao ấy! Và sờ sợ.  Cả đời chỉ gặp ba có vài lần ngắn ngủi trong các trại cải tạo.  Còn những gì trước đó chỉ là những ký ức nhạt nhoà.  Qua khe cửa, tôi chăm chú theo dõi không sót một chi tiết những cái bắt tay vồn vã, những câu hỏi han ân cần của những người hàng xóm.  Ai cũng bảo tóc ông bạc nhiều, nhưng vẫn trẻ như xưa.  Ba cười không ngớt, nụ cười đẹp như trong những tấm hình, dường như vết tích của bao nhiêu năm tháng đoạ đày chỉ còn lại trên những sợi tóc bạc, và bộ đồ dị hợm đang mặc trên người, cũng như đôi dép râu chẳng giống ai.  Sau giây phút bàng hoàng, mẹ đưa ba đi mua đôi dép mới, xong dẫn ba về nhà Bà Cố.  Dì G.  ra mở cửa, thấy ba, ré lên như gặp ma, dậm chân rầm rầm, gọi í ới "Ngoại ơi, anh B.  về! Anh B.  v...ê...ề ...!!!" Bà Cố từ nhà trong lê dép lệt xệt chạy ra, đôi mắt bồ câu mở to, sững sờ nhìn ba, không nói.  Ba lẳng lặng ôm lấy bà.  Không gian như chùng xuống.  Nghe như có tiếng sụt sùi.<br />
<br />
Ngay hôm sau, ba đi mua sợi dây đàn mới — một sợi dây bằng sắt, chơ vơ lạc lõng giữa 5 sợi dây <i>nylon</i> còn lại, rồi ngồi tích-tịch-tình-tang.  Tôi "làm quen" với ba một cách mau chóng, sự e dè lúc ban đầu hoàn toàn mất đi.   Tôi đòi ông dạy cho tôi tích-tịch-tình-tang như ông vậy.  Nhưng ông bắt học note trước.  Ba ngồi ở trên giường, kẻ những dòng nhạc đầu tiên, vẽ hình cái cần đàn, những cái <i>tab</i> trên đàn, ngón nào bấm vào ô nào… Chỉ có vậy.  Tôi khệnh khạng ôm cây đàn như chuột tha mèo, bặm môi bấm thật mạnh những ngón tay ngắn chũn lên phiếm đàn, cố bật ra một âm thanh nào đó.  Lúc đầu, năm đầu ngón tay trái đau như bị dần mỗi khi tập đàn xong.  Nhưng đàn quen rồi thì không còn cảm giác đau nữa.  Học xong các note căn bản, ba viết note bài <i>Diễm Xưa – Mưa vẫn mưa bay trên tầng tháp cổ, si đố si si sol mì sol sì...</i> — cứ theo những <i>note</i> đã học mà đánh.  Thế là đàn được trọn bài <i>Diễm Xưa</i>.  Thích quá.  Tôi mê guitar từ đó.  Mê cho tới ngày hôm nay.  <br />
<br />
Sau đó, là <i>Lòng Mẹ, Biển Nhớ,</i> rồi đến những bài tập trong cuốn Carulli.  Dạy tới khoảng nửa cuốn Carulli thì ba cho xuất môn, bảo "đủ lông đủ cánh rồi, từ nay tự học đi." Nói vậy chớ, lông cánh thì vẫn còn non nớt lắm, tự học cũng đâu phải dễ.  Vấn đề là kỹ thuật.  Phải có kỹ thuật mới nâng trình độ của mình lên một bậc cao hơn.  Mà các bài giảng về kỹ thuật ở đầu cuốn sách thì lại viết toàn bằng chữ Tây.  Từ đó là học lóm.  Thấy ai ôm đàn là sáp vào ngay, lắng nghe, chăm chú nhìn, và mò theo.<br />
<br />
Đúng ra, lúc này ba bận, tại vì tôi bắt đầu có em (gái).  Con búp bê thiệt tuy dễ thương và thú vị hơn búp bê bằng nhựa nhiều, biết hươ tay, múa chân, nhưng khó ăn quá trời, cả ngày đói sữa khóc oe oe.  Hết cách, tôi ôm đàn ngồi bên nôi hát ru em.  Như một phép lạ,  nó im bặt ngay sau khi tiếng đàn cất lên, và nhắm mắt ngủ khì sau nửa bài hát.  Bây giờ nó lên Cao học rồi, và chỉ nghe toàn nhạc Mỹ, nhưng thỉnh thoảng hễ nghe thấy một bản nhạc Việt Nam nào là nói, với vẻ tự hào: "Em biết bài này.  Hồi xưa nghe chị đàn/hát." <br />
<br />
Mùa hè năm 1984, chú Th. nhà hàng xóm có người em gái từ Huế vô chơi. Người con gái của sông Hương núi Ngự, có giọng nói dịu dàng và nụ cười duyên dáng, thổi một luồn sinh khí mới vào thế giới âm nhạc của tôi.  Khác hẳn với những bản nhạc cổ điển trong cuốn Carulli, chị T. thích chơi nhạc ABBA, loại nhạc đang thịnh hành trong giới trẻ thời đó, khắp thế giới.  Hai chị em "mê" nhau ngay lập tức. Chị thì ưa nghe em đàn những bản cổ điển, còn em thì thích chị dạy cho nhạc ABBA. Năm ngón tay (đúng ra là móng tay) được thay bằng cái phiếm đàn, và những tiếng đàn êm dịu, sâu lắng, được thay bằng những cái đập, cái gõ rầm rầm vào thùng đàn. Nhớ quá, những chiều mưa không dứt ở Dalat, hai chị em, người <i>solo</i>, người đệm, xập xình, rộn ràng những bản <i>Voulez Vous, Money Money, Give Me Give Me, Let It Be, ...</i>  Đó là những giây phút thần tiên trong cuộc đời.<br />
<br />
Mỗi buổi sáng, đợi ba mẹ vừa ra khỏi nhà là tôi... nhảy hàng rào (kẽm gai) qua nhà hàng xóm, giật phăng chiếc mền ra khỏi giường, kéo chân chị T.: "Dậy, chị ơi! Dậy chơi đàn với em!" Nhảy rào, vì làm biếng đi cổng chính. Có lần mặc bộ đồ mới (mỗi năm chỉ có được 2-3 bộ đồ mới là cùng), nhảy cái ào, nghe đánh "soạt", cảm giác đau rát nơi bắp vế và lành lạnh nơi bụng. Mặt xanh như tàu lá. Không phải vì đau — mặc dầu vết thương sâu hoắm, đang rỉ máu — mà vì nghĩ tới món cháo lươn của mẹ. Chú Th. biết ý, an ủi: "Đừng lo, để chú dẫn về nói với mẹ." Đem vô bôi thuốc đỏ xong xuôi, chú đích thân dẫn qua nhà: "Cháu nó bị chó cắn." Mẹ cười mỉm mỉm, cái cười ngụ ý: "Con ruồi bay qua, tui liếc một cái là biết ngay ruồi đực hay ruồi cái." Nhưng có lẽ phần thì thấy bộ tịch tội nghiệp của tội nhân, phần thì nể có người lớn ra mặt cho, nên mẹ tảng lờ, rót nước mời trà chú Th., coi như không hề có chuyện "chó cắn". Nghĩ lại, thấy tội chú Th. ghê. Vậy mà hồi đó còn cằn nhằn chú sao không bịa ra câu chuyện gì dễ tin hơn một chút.<br />
<br />
Mấy đứa bạn trong lớp khoái nhất bài <i>Voulez Vous</i>. Hễ mỗi lần đàn tới khúc "Voulez vous?..." là cả lớp "à ha... à ha..." rộn cả một góc sân trường, khiến cho các thầy cô đi ngang phải dừng lại nghe, lắc đầu, phì cười. Có dạo cần tập văn nghệ nhiều cho lớp để trình diễn, mỗi lần đi học là mang theo cái cặp táp và cái guitar, để ở dãy bàn trống ở cuối lớp. Giờ của thầy Đồng (Toán và Sinh Vật), vì biết thầy thích văn nghệ, tha hồ viện cớ đàn guitar cho thầy nghe để cả lớp khỏi phải học.<br />
<br />
Nhớ nhất những đêm cắm trại ở Đồi Cù, cả lớp ngồi quanh đám lửa bập bùng, tiếng đàn guitar hòa với tiếng hát vang dội cả rừng thông, nghe ấm lòng chi lạ. Giờ giải lao, mấy đứa bạn thân rủ trốn ra hồ Cẩm Lệ, ngồi tựa vào gốc một cây thông già, để hồn bay vút theo tiếng đàn và tiếng ngàn thông vi vu. <br />
<br />
Cũng chính trong một lần cắm trại này, cây đàn bị thương thê thảm. Hôm đó, vừa dự thi xong vài trò chơi, trở lại lều, thấy mấy thằng con trai đang rượt đánh nhau, và dùng cây đàn của tôi làm vũ khí! Thằng Th. huơ huơ cây đàn lên như múa kiếm, không đứa nào dám tới gần. Rồi thằng H. giật lấy cây đàn, xoay một vòng như cái vụ. Tôi muốn hét lên, bảo nó ngừng tay, nhưng đã quá muộn. Chỉ nghe một cái "bộp", sau đó là tiếng 6 dây đàn rung lên dữ dội, rồi cái "bộp" thứ hai. Hai cây thông đứng sát nhau, mỗi cây lãnh một cú, trên thân có một vết trũng xuống. Tôi chạy sổ lại bên cây đàn. Bấn loạn. Cú thứ nhất làm phía đầu cần đàn (chỗ lên dây đàn) tróc <i>verni</i>, để lòi ra màu gỗ trắng hếu, cú thứ hai làm lõm cái cần đàn. Đau điếng. Sau này, mỗi lần lướt trên cần đàn là lòng bàn tay chạm vào chỗ vết sẹo lồi lên như vết chém. Quỳ xuống cỏ, tôi ôm cây đàn, khóc nấc lên. Không biết trong đó có bao nhiêu phần là thương cây đàn, bao nhiêu phần là sợ ba. Đúng là mấy thẳng quỷ! Bộ hết cái để chơi rồi sao? Dĩ nhiên là mấy thằng con trai bị cô chủ nhiệm la cho một trận nên thân. Mà hình như tụi nó cũng có vẻ hối hận lắm.<br />
<br />
Lần đó, đi cắm trại về, bụng dàu dàu, không vui như những lần khác. Không biết dấu cây đàn ở đâu cho ba khỏi thấy. Mỗi lần đi học, lại mang cả nó theo, để ở nhà sợ ba rớ tới. Nhưng chuyện phải đến rồi cũng đến. Một buổi tối, ba cầm đàn lên, so dây. Đứa con gái đứng bên cạnh, nín thở, và trống ngực bắt đầu đập loạn xạ khi thấy ba khựng lại, lật tới lật lui cây đàn, sờ sờ, ngó ngó. Rồi một cái chau mày, và một câu chất vấn với cung bậc cao hơn thường lệ: "Tại sao cây đàn hư hết, trợt tùm lum thế này?" Toàn bộ câu chuyện được thuật lại, với sự phẫn nộ hơi có phần phóng đại của người kể, để nhấn mạnh rằng người kể hoàn toàn vô tội trong chuyện này. Nhưng rồi, cuối cùng, bản án vẫn được tuyên bố: từ nay không được xách đàn ra khỏi nhà. Ôi! Đau còn hơn mấy cái thước kẻ!<br />
<br />
Thỉnh thoảng, có vài ba nhạc sĩ nghệ sĩ nổi tiếng đến Dalat trình diễn, tôi không bỏ lỡ dịp nào: Trịnh Công Sơn, Trần Tiến, … Có lần bị cảm ho sù sụ, trời mưa tầm tã, vẫn mang tơ đội mũ đi nghe Mai Công Kiều trình diễn cùng với các nhạc sĩ có tiếng như Văn Cao (với bài Làng Tôi), Mạnh Đạt... Lúc đó Mai Công Kiều còn trẻ lắm, và vừa đoạt giải nhất trong kỳ thi guitar cổ điển của quận Phú Nhuận. <br />
<br />
Lúc này thường hay ở nhà một mình, vì ba mở lớp dạy thêm Toán ở nhà ông bà ngoại và em cũng đến tuổi đi "nhà trẻ". Ở nhà có duy nhất một tập thơ  — <i>Giọt Lệ</i> của Vi Khuê — đem ra đọc đến thuộc lòng. Giở tới bài <i><a href="http://www.trangnhahoaihuong.com/Songs/MotMinh_new.mp3">Một Mình</a></i> — Một mình tôi đã khóc… Một mình tôi nức nở… Một mình tôi khổ đau…Một mình tôi úp mặt… Một mình tôi cúi đầu </i> —nhớ tới những lần bị đòn (nức nở, khổ đau, úp mặt, cúi đầu…), nhớ những lúc một mình ngồi dưới gốc cây liễu ngoài sân tuôn hết những giọt nước mắt tủi hờn, những hôm trời mưa, tối sầm, ở nhà một mình, sợ ma gần chết... rồi cảm hứng tuôn trào... rồi bài thơ bắt đầu có giai điệu, có tiết tấu. Đó là lần đầu tiên sáng tác nhạc thực sự. Sau đó, các bài nhạc khác lần lượt ra đời: <i><a href="./../Songs/TruocCuocDoiHomNay_XuanPhu_e.wma">Trước Cuộc Đời Hôm Nay</a></i>, <i>Xin Đừng Cho Tôi Biết</i>. Rồi thấy mấy bài này buồn quá, lại lựa một bài "vui vui" hơn – <i>Mây</i>. Ba là khán thính giả đầu tiên của những bản nhạc này. Ông thích nhất bài <i>Trước Cuộc Đời Hôm Nay</i>. Và, sung sướng biết bao, khi có lần đi học về thấy ông ngồi ôm đàn hát bài nhạc do chính con gái của mình sáng tác. Nhưng mà, nó cũng mang đến nhiều hệ luỵ. Vì từ đó hễ mỗi lần nhà có khách là y như rằng bị bắt lên đàn hát cho khách nghe. Sau này, khôn hơn một chút, hễ nghe tiếng gõ cửa là tìm cách lẻn ra sân chạy trốn trước.<br />
<br />
Cuối năm lớp 9, sắp chuyển trường, các thầy cô lưu luyến, bịn rịn. Cô Lương lấy vạt áo  chậm nước mắt, sụt sùi: "Em đi rồi, không có ai đàn cho cô hát nữa." Tất nhiên những năm sau đó vẫn có người đàn cho cô hát, nhưng câu nói đó nghe cảm động, nhớ tới bây giờ.<br />
<br />
Lên cấp III, học trường BTX, tham gia sinh hoạt văn nghệ của thành phố, được vào ban hợp xướng. Thầy Bửu Ấn dạy hát bài <i><a href="./../Songs/HuyenThoaiMe_new1.wma">Huyền Thoại Mẹ</a></i> của Trịnh Công Sơn và <i>Dalat Trăm Sắc Hoa</i> do thầy sáng tác. Nghe danh thầy Bửu Ấn dạy guitar rất hay, tuy rất khó, và rất “dữ”, nhưng không bao giờ mơ tới chuyện làm học trò của thầy vì biết chắc là mẹ không cho học nhạc, trong lúc cảnh nhà quá bần hàn.<br />
<br />
Nhưng, mọi sự ở trên đời đều có cái duyên của nó. Một hôm, ở "trung tâm văn hoá", đi ngang qua một căn phòng, hai chân bị tiếng đàn piano từ trong vọng ra níu lại. Tiếng đàn nghe dữ dội, đầy cảm xúc mãnh liệt, bản nhạc hết rồi mà dư âm vẫn còn ngân dài, cửa mở mà không hề hay biết. Người ở trong bước ra là thầy Bửu Ấn. Hết hồn. Bị bắt quả tang "nghe lén". Thấy tôi đứng sớ rớ, thầy cười (hiền khô, không dữ chút nào), hỏi "em tên gì?", rồi khen tên của tôi đẹp. Tự nhiên nghĩ đây là cơ hội ngàn năm một thuở nên buộc miệng xin theo thầy học guitar. Nói xong mà không ngờ mình quá liều lĩnh, táo bạo. Làm sao nói với mẹ đây? Lấy tiền đâu đóng học phí? Thầy hỏi qua trình độ của tôi, xếp tôi vào chung lớp với các anh chị lớn, bảo tuần sau lên nhà thầy dạy cho. Thầy đi rồi mà thần trí phiêu diêu như đi trên mây. Mình đang làm cái gì đây? Lê những bước chân chậm chạp về nhà với những cảm xúc phức tạp: vui mừng, lo âu, và dằn vặt. Cuối cùng thì nỗi đam mê đã thắng thế, và từ đó 2 ngày một tuần, lén theo thầy học những kỹ thuật guitar như reo dây (trémolo), tiếng chuông (harmonique), tiếng trống, cách gõ thùng đàn… và được nghe giảng những điều thật lý thú, về những danh cầm nổi tiếng người Tây Ban Nha, ngoài 80 tuổi vẫn tập đàn mỗi ngày 8 tiếng, về từng đoàn lạc đà ì ạch lê những bước chân nặng nề qua sa mạc mênh mông <i>(Hành Khúc Thổ Nhĩ Kỳ)</i>, về những đóa hoa anh đào hé nở khi tuyết vừa tan, mang lại cho người nghệ sĩ một sự ngạc nhiên thích thú và niềm tin ở tương lai <i>(Sakura)</i>. Lúc này quá hạnh phúc, nên cũng siêng tập đàn lắm. Thật ra cũng không có sự lựa chọn nào khác, vì mỗi buổi học thầy chỉ đại ít nhất vài ba học trò kiểm tra bài, và lần nào cũng có trò bị la. Lúc đó mới biết thầy quả là "danh bất hư truyền". Nhiều khi thầy hét mấy trò khác mà mình phải lùng bùng cả lỗ tai. Đàn bài <i>Roméo et Juliet</i>, đoạn đầu thầy gật gù, khen cảm thụ âm nhạc tốt. Khoái tỉ. Tới hết bài, ngẩng lên, tưởng được khen nữa, ai dè thầy nạt cho một trận: "Cái đầu lắc nhiều quá, phải dịu dàng, đằm thắm một chút. Lắc cái đầu bộ tiếng đàn hay hơn hay sao? Cảm xúc phải được thể hiện qua tiếng đàn, còn những cử chỉ bộ tịch của cơ thể đều là dư thừa." Theo học thầy mà biết trước rằng duyên thầy-trò sẽ rất là ngắn ngủi, vì đập nát con heo ra chỉ đủ tiền trả học phí trong 2 tháng mà thôi, cho nên dốc hết tâm lực vào việc học. Cuối tháng thứ hai, thì nghỉ ngang, và từ đó đến nay, chưa một lần được gặp lại thầy.<br />
<br />
Một phần cũng vì sau đó có giấy báo đi Mỹ, sau 10 năm mỏi mòn chờ đợi. Ba toan tính, dằn vặt, không biết có nên mang theo cây đàn không. Cuối cùng thì thấy đã có quá nhiều thứ phải mang đi, mà cây đàn lại không có cái thùng, nên ba quyết định bán nó cho một người lạ mặt nhưng đã nghe tiếng cây đàn và muốn nó từ lâu, với giá 1 chỉ vàng, tức khoảng &#36;40. Vẫn còn nhớ nét vui mừng không giấu giếm của chủ nhân mới của cây đàn khi cầm nó trên tay. Những vết xước, vết sẹo do sự bất cẩn của người chủ nhân tí hon của nó vẫn không làm mất vẻ đẹp sang trọng và quyến rũ của cây đàn, và nhất là tiếng vẫn còn ấm. Ba bảo tôi đàn và hát bài <i>Trước Cuộc Đời Hôm Nay</i> cho người khách nghe. Và sau đó, là một cuộc chia ly vĩnh viễn. <br />
<br />
Có lẽ, khi con người phải bỏ lại cả quê hương và tuổi thơ, người thân, bạn bè, thầy cô, hàng xóm… để ra đi, thì sự chia ly với cây đàn chỉ là một sự kiện rất nhỏ, không đáng kể, ít nhất là trong hoàn cảnh lúc đó. Nhưng, những năm tháng lưu ly trên đất khách, rất nhiều lần, như những lúc phóng xe vù vù trên xa lộ, đã mơ đi mơ lại cùng một giấc mơ: do một cơ duyên kỳ lạ nào đó, mà được cầm lại cây đàn, dù chỉ một lần thôi, để lòng bàn tay được sờ lên vết sẹo năm nào trên cần đàn, để má được áp vào thùng đàn mát rượi, để mười ngón tay được lướt lên sáu sợi dây đàn mềm mại, để hai tay được nâng cây đàn lên cao, soi lại gương mặt của mình trong mặt đàn bóng loáng, mà thấy lại cả một trời quê hương, tuổi thơ, và những kỷ niệm đã xa, xa không tầm tay với.<br />
<br />
Virginia, 10/2005<br />
