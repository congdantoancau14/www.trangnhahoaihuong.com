<h3>Đức Phật Dạy Con Như Thế Nào</h3>


<b>Gil Fronsdal</b><br />
<br />
<i>(Nguyên tác: “The Buddha as a Parent”, Tạp chí Inquiring Mind, số Xuân 2008)</i><br />
<br />
<a href="/files/DucPhatDayCon.pdf">Đọc bằng bản PDF</a><br />
<br />
Ngày nay, hầu như người Phật tử nào cũng biết rằng Thái tử Tất Đạt Đa, sau này là Đức Phật, đã lìa bỏ tổ ấm của mình để đi tìm con đường giải thoát vào chính cái ngày La Hầu La — đứa con trai [duy nhất] của Ngài — chào đời. Nhiều người cảm thấy khó hiểu, thậm chí phẫn nộ, trước một hành động có vẻ “thiếu trách nhiệm” như thế. Song, ít ai biết rằng sau khi đạt được Chính Đẳng Chính Giác, Đức Phật đã trở thành thầy dạy dỗ chính cho con trai của mình trong hầu hết quãng đời niên thiếu của con Ngài, kể từ khi La Hầu La lên 7 tuổi, và Ngài đã là một người cha rất mực mô phạm: La Hầu La đã đạt được giác ngộ viên mãn khi mới 20 tuổi. Vậy, ta hãy tự hỏi, Đức Phật là một người cha như thế nào?  Phương pháp dạy con của Ngài ra sao?  Làm thế nào một bậc giác ngộ trao truyền những giá trị tâm linh của mình cho con cái?<br />
<br />
Kinh điển không đề cập nhiều đến mối quan hệ cha-con giữa Đức Phật và La Hầu La, nhưng đâu đó có để lại những dấu hiệu thú vị đáng lưu ý về việc Đức Phật đã dẫn dắt con mình như thế nào trên con đường trưởng thành. Mặc dầu trước các kinh điển này đã có những mẩu chuyện nói về việc La Hầu La đã trở thành đồ đệ của Đức Phật như thế nào, nhưng phần lớn những chi tiết này nằm trong ba bài pháp mà nếu ta gom cả lại với nhau, thì đó chính là một tiến trình liên tục của con đường dẫn tới giác ngộ: lúc La Hầu La 7 tuổi, Đức Phật dạy cho con về đạo đức; lúc La Hầu La 10 tuổi, Đức Phật dạy cho con thiền; và lúc 20 tuổi, Ngài dạy về tuệ giác giải thoát. Quá trình trưởng thành của La Hầu La, vì vậy, đi đôi với tiến trình giác ngộ của Đức Phật.<br />
<br />
Khi con trai của tôi tròn 7 tuổi, tôi bắt đầu suy tư về việc làm cách nào để dẫn dắt nó và em trai của nó trên con đường tâm linh. Ít nhất, tôi muốn chúng nó học và thực hành Phật pháp đủ để sau này lớn lên chúng có thể trở về với những tiềm năng đó nếu chúng thích hay cần đến. Tôi cũng nghĩ rằng nếu các con tôi có thể nương tựa nơi Phật pháp, thì sau này, dù đang ở bất cứ nơi đâu, chúng cũng có thể quay về với cái mái ấm đó. Nhất là, vì đối với tôi, gia tài lớn nhất mà tôi có được qua sự thực tập Phật pháp là sự an lạc, thảnh thơi và lòng từ bi, tôi tự hỏi làm cách nào tôi có thể trao truyền cái gia tài tâm linh đó lại cho thế hệ sau. Được biết La Hầu La bắt đầu được Đức Phật dạy dỗ từ năm bảy tuổi, tôi lục tìm trong những bản kinh tiếng Pali để học lấy những phương pháp mà Đức Phật đã sử dụng để dạy dỗ con của Ngài.<br />
<br />
Tôi tìm thấy cách làm thế nào để lại một “gia tài tâm linh” qua những mẩu chuyện thật hay trong kinh điển về việc La Hầu La đã theo học với cha như thế nào. Sáu năm sau khi Đức Phật rời bỏ gia đình, và một năm sau khi đạt được giác ngộ, Đức Phật trở về kinh thành. La Hầu La, lúc ấy bảy tuổi, theo lời mẹ dạy, đã chạy đến bên cha để xin thừa hưởng gia tài. Nếu như ngày xưa Thái tử Tất Đạt Đa không bỏ kinh thành ra đi, thì bây giờ La Hầu La đã được truyền ngôi vua. Nhưng là một người đã buông bỏ hết tất cả, sống đời khổ hạnh, Đức Phật có thể trao lại cho con mình cái gì?  Đáp lời La Hầu La,  Đức Phật quay sang nói với Ngài Xá Lợi Phất (Sariputta), một đồ đệ thân tín của Đức Phật: “Hãy thâu nhận nó.”  [Như vậy], thay vì được ngôi vua, La Hầu La đã được thừa hưởng con đường đi của cha mình — con đường dẫn đến giải thoát.<br />
<br />
Có lẽ còn lâu lắm con trai tôi mới cạo trọc đầu và khoác lên mình chiếc áo cà sa, nhưng tôi vẫn muốn cho con tôi tiếp xúc với những điều căn bản của Phật pháp, những điều đã chuyển hoá sâu sắc cuộc đời tôi. Khi tôi đọc những đoạn kinh về cách Đức Phật dạy La Hầu La, tôi ngạc nhiên nhận ra rằng những điều này không những vẫn còn mới mẻ mà còn rất thích hợp với việc dạy con ở nước Mỹ này, trong thời hiện đại này. Thật vậy, những bài pháp này đã trở thành kim chỉ nam cho tôi trong việc dạy con.<br />
<br />
<br />
<b>ĐẠO ĐỨC</b><br />
<br />
Câu chuyện đầu tiên kể về La Hầu La được Đức Phật dạy về lòng chính trực (integrity) như thế nào.  Lúc lên 8 tuổi, La Hầu La đã nói dối. Bài <i>Kinh Giáo Giới La Hầu La</i> (Trung Bộ Kinh, 61) kể rằng sau khi tọa thiền xong, Đức Phật đến tìm La Hầu La.  Sau khi mời cha ngồi, La Hầu La lấy một thau nước cho cha rửa chân, theo phong tục hồi đó.  Sau khi rửa chân xong, Đức Phật hỏi: <i>“Này, La Hầu La, con có thấy chút nước còn lại trong cái thau này không?” </i><br />
<br />
<i>“Dạ, con có thấy”</i> – La Hầu La thưa.<br />
<br />
<i>“Đời của một người tu cũng chỉ đáng bằng một chút nước này thôi, nếu như người đó cố tình nói dối.”</i><br />
<br />
Tôi tưởng tượng La Hầu La đỏ mặt lên.<br />
<br />
Sau đó, Đức Phật hất đổ hết nước trong thau ra và nói: <i>“Đời của một người tu cũng đáng vất bỏ đi như vầy nếu như người đó cố tình nói dối.”</i><br />
<br />
Xong, Đức Phật lật cái thau úp xuống và nói: <i>“Đời của một người tu sẽ trở nên đảo lộn như thế này nếu như người đó cố tình nói dối.”</i><br />
<br />
Và, để nhấn mạnh thêm nữa, Đức Phật lật ngửa cái thau trở lại và nói: <i>“Đời của một người tu cũng trở nên trống rỗng như cái thau này nếu như người đó cố tình nói dối.”</i><br />
<br />
Sau đó Ngài dạy con: <i>“Đối với một người cố tình nói dối, không có một tội lỗi xấu xa nào mà người đó không thể làm.  Vì vậy, La Hầu La, con hãy tập đừng bao giờ nói dối, cho dù đó là một lời nói đùa.”</i><br />
<br />
Câu chuyện trên đây nhắc nhở tôi rằng những lời la mắng giận dữ với con cái thực ra chỉ có sức mạnh mà không có nội lực.  Đức Phật đã rất bình tĩnh, chọn thời điểm đúng lúc để dạy con mà không trừng phạt hay nổi giận với con.<br />
<br />
Sau bài thuyết giảng ngắn mà rõ ràng về việc nói dối đó, tôi tưởng tượng La Hầu La đã lắng nghe cha hơn.  Sau đó, Đức Phật chỉ dẫn con làm sao để suy xét mọi hành động của mình.  <i>“Cái gương dùng để làm gì?”</i> – Ngài hỏi.<br />
<br />
<i>“Bạch Đức Thế Tôn, gương dùng để soi”</i> – La Hầu La đáp.<br />
<br />
Đức Phật lại dạy : <i>“Trong khi chuẩn bị làm điều chi bằng thân, khẩu, ý, con phải quán chiếu: hành động này có gây tổn hại cho ta hoặc cho kẻ khác không? Nếu, sau khi đã quán chiếu, con thấy rằng hành động đó sẽ có hại, thì con hãy đừng làm.  Còn nếu con thấy rằng hành động đó có ích lợi cho con và cho kẻ khác, thì con hãy làm.”</i><br />
<br />
Tôi chợt nhận ra rằng thay vì dạy cho con mình nhận biết sự khác biệt tuyệt đối giữa <i>đúng</i> và <i>sai</i>, Đức Phật đã dạy cho con mình suy gẫm về <i>lợi ích</i> và <i>có hại</i>.  Điều này đòi hỏi cả sự tự tri (self-awareness) lẫn lòng bi mẫn.  Đặt nền tảng của đạo đức dựa trên “có lợi” hay “có hại” giúp giải thoát đời sống đạo đức của ta khỏi những khái niệm trừu tượng và những ý niệm chẳng ăn nhập gì tới hậu quả của việc ta làm.  “Có lợi” và “có hại” cũng giúp cho con người nhận biết mục tiêu của mình.  Những điều ta làm hoặc sẽ đối nghịch hoặc sẽ thuận chiều với con đường ta đang đi.<br />
<br />
Phương pháp giáo hoá của Đức Phật khiến cho tôi càng tin tưởng thêm rằng chúng ta cần gieo xuống nơi tâm hồn con trẻ những hạt giống của tình thương, những hạt giống của ý thức về việc mỗi hành động của nó sẽ ảnh hưởng đến người khác như thế nào.  Sức mạnh của sự quán chiếu và lòng từ bi sẽ không có được nếu đứa trẻ chỉ biết vâng theo lời của người lớn: “Con hãy biết quán chiếu, và hãy có lòng từ bi!”  Những giá trị này chỉ có thể có được qua gương của người khác, nhất là của cha mẹ đứa trẻ.<br />
<br />
Đức Phật cũng dạy cho La Hầu La hãy xem xét sau khi làm một việc gì đó, nó có gây tổn hại gì không.  Nếu có, thì phải đến gặp một người có tuệ giác và sám hối để tránh lặp lại lỗi lầm trong tương lai.  Tôi đã học được cách hướng dẫn con trẻ phát triển lòng chính trực bằng cách nhận ra lỗi lầm của mình.  Và lòng chính trực đó tuỳ thuộc rất nhiều vào cách cha mẹ thấy lỗi lầm của con mình ra sao.  Cách hành xử của cha mẹ ảnh hưởng rất nhiều đến sự phát triển đạo đức của con trẻ: nếu cha mẹ cho con trẻ thấy được là nó có thể tin tưởng mình được, là mình chỉ muốn giúp cho con mình trưởng thành hơn là muốn trừng phạt con, thì con trẻ sẽ trở nên thành thật với cha mẹ của chúng hơn.<br />
<br />
<b>THIỀN ĐỊNH</b><br />
<br />
Câu chuyện thứ hai nói về việc Đức Phật đã dạy thiền cho La Hầu La ra sao, để phát triển nền tảng của nội tâm (Trung Bộ Kinh, 62).   Lúc đó La Hầu La được 10 tuổi.  Câu chuyện bắt đầu trong lúc hai cha con đang đi thiền hành.  Trong lúc đi, La Hầu Ha chợt thấy hãnh diện về vẻ đẹp của mình, và tư tưởng đó Đức Phật đã đọc được.<br />
<br />
Ngài nói với con: <i>“Nhìn bằng con mắt của tuệ giác, cái thân này không phải là tôi (me), không phải là của tôi (mine), không phải là tự ngã của tôi (myself).”</i>  Rồi Đức Phật giảng tiếp: ta phải loại bỏ hết tất cả <i>tưởng, hành, thức</i> cũng như bất cứ khái niệm nào về <i>tôi, của tôi, và tự ngã của tôi</i>.  Nghe những lời dạy này xong, La Hầu La cảm thấy hổ thẹn, lui về thiền viện, và không thiết đến việc ăn uống gì cả suốt ngày hôm đó.<br />
<br />
Tôi cho rằng đây là sự dạy dỗ căn bản cho con trẻ.  Tôi không thể tưởng tượng được một em thiếu niên có thể hiểu được những lời Phật dạy như thế.  Tôi nhớ lại, rất rõ ràng, rằng ở vào tuổi đó, đầu óc tôi chỉ toàn nghĩ đến dung mạo của tôi ra sao.  Tôi thường nghe nói rằng điều này rất là quan trọng cho tiến trình phát triển của các em về “cái tôi”, và quá trình đi tìm kiếm bản thân mình.  Có nên trách một em trai 14 tuổi về những ý tưởng phù du như vậy hay không?  Có phải Đức Phật đã xen vào những vấn đề nằm trong tiến trình phát triển bình thường của con trẻ, thay vì để các em thảo luận với nhau?  Nếu không có hiểu biết về “cái tôi”, làm sao một thiếu niên có thể phát triển thành một người lớn với sự cân bằng về tâm lý?  <br />
<br />
Câu trả lời nằm ở những gì Đức Phật dạy con Ngài ở đoạn sau đây.<br />
<br />
Tối hôm đó, sau khi bị Đức Phật quở trách, La Hầu La đến xin cha dạy cho mình phương pháp quán niệm hơi thở.  Trước hết, Đức Phật dùng thí dụ để minh hoạ làm sao đạt được sự thanh thản trong lúc ngồi thiền.  Ngài dạy:<br />
<br />
<i>“Con phải thiền làm sao giống như đất vậy: đất không cảm thấy phiền vì bất cứ một thứ gì đổ lên đó.  Vì vậy, nếu con tập thiền giống như đất, con sẽ không có cảm giác vui thích hay không vui thích về bất cứ một điều gì.  Hãy tập thiền như nước, như lửa, như gió, và như không gian: tất cả đều không cảm thấy phiền bởi những cảm giác vui thích hay không vui thích.  Thực tập được như nước, như lửa, như gió, như không gian, tâm của con sẽ không còn vướng bận gì cả.”</i><br />
<br />
Rồi, trước khi dạy cho La Hầu La phép thở, Đức Phật dạy cho con về quán tâm từ như là một phương thuốc giải độc trừ khử ác tâm, về tâm bi để vượt thắng sự tàn ác, về tâm hỷ để thuần phục những sự bất toại nguyện, và về tâm xả để ngăn chặn những bất an, thương ghét.<br />
<br />
Sau đó, Ngài mới bắt đầu dạy cho con phép quán niệm hơi thở qua 16 giai đoạn.  Những giai đoạn này chia thành 3 phần: a) tịnh tâm; b) định tâm để nhận biết thân tâm và phát triển tuệ giác; và c) buông xả.  Cuối cùng, Ngài nhấn mạnh rằng bằng sự thực tập ý thức từng hơi thở của mình, con người sẽ có khả năng ý thức hơi thở cuối cùng của mình trong giờ phút cận tử một cách hoàn toàn bình thản.<br />
<br />
Khi đọc về cách thức Đức Phật dạy con về phép quán niệm hơi thở để nhận biết thân tâm của mình, tôi nhận thấy đó cũng là một phương pháp để xây dựng một khái niệm vững chắc về “cái tôi”. Tôi tự nghĩ, phải chăng các em thiếu niên ở thời đại ngày nay hay chấp vào "cái tôi" của mình và có nhiều ý niệm phân biệt mình với kẻ khác, là vì các em không cảm thấy thoải mái với chính bản thân mình và với người khác? Và tôi tin rằng, cái chấp và sự phân biệt ấy sẽ không còn nữa nếu các em cảm thấy an vui được với chính mình cũng như thoải mái với người chung quanh.<br />
<br />
Khi giảng dạy thiền cho thiếu niên, tôi nhận thấy khả năng thiền của các em nhảy bực vào khoảng 13-14 tuổi.  Có nhiều em có thể nhập thiền rất sâu, tuy rằng các em không duy trì được trạng thái này lâu lắm.  Tôi đã biết rất nhiều người trẻ dùng phương pháp thiền định để ổn định tinh thần và tìm về sự thảnh thơi giữa những thử thách của tuổi mới lớn.<br />
<br />
Tuy nhiên, quán niệm hơi thở không chỉ ích lợi cho các em thiếu niên, mà nó còn là cuộc hành trình suốt đời.  Đức Phật đã kết thúc bài giảng của mình bằng cách chỉ cho La Hầu La thấy giá trị của việc tập thiền quán hơi thở như thế nào đối với giây phút cuối cùng của cuộc đời mình.<br />
<br />
<b>TUỆ GIÁC</b><br />
<br />
Trong đoạn kinh thứ ba và cuối cùng, Đức Phật đã hướng dẫn La Hầu La trả lời một loạt những câu hỏi về tuệ giác giải thoát (Trung Bộ Kinh , 147).  La Hầu La đã dâng trọn thời niên thiếu của mình cho con đường đạt đến giác ngộ; trong một đoạn văn, Ngài được xem là một nhà tu gương mẫu và tinh chuyên.  Khi La Hầu La tròn 20 tuổi, Đức Phật biết rằng con trai của mình đã gần đạt đến sự giải thoát.  Ngài đã làm một việc hết sức cảm động: Ngài đi bộ cùng với con vào sâu trong rừng.  Ngồi dưới gốc một cây đại thụ già cỗi, Ngài đã hướng dẫn La Hầu La một cuộc pháp đàm rất kỹ về thuyết vô ngã.  Đối với một người đã đạt đến trình độ tu tập cao như La Hầu La, những tư tưởng nằm sâu trong tiềm thức về cái ngã là chướng ngại cuối cùng của sự giải thoát.  Ngồi nghe Đức Phật giảng, La Hầu La đã chứng được tự tính vô ngã của vạn pháp, và đó chính là bước cuối cùng giúp La Hầu La đạt đến sự giải thoát trọn vẹn.<br />
<br />
Thuyết vô ngã của Đức Phật có thể khó hiểu.  Người ta rất dễ ngộ nhận nó là một triết thuyết trừu tượng, mà không thấy được thực ra đó chính là những lời dạy rất thực tế về việc làm sao để tìm thấy hạnh phúc bằng cách buông bỏ hết tất cả.  Đối với tôi, việc Đức Phật dạy con về thuyết vô ngã trong rừng sâu rất cần thiết.  Tôi thấy mình có cái nhìn khác khi ở giữa thiên nhiên so với khi ở giữa phố thị.  Tôi nhận thấy cảm giác an lạc và thảnh thơi mà thiên nhiên mang lại giúp mình dễ thoát ra được cái “ngã” hơn.  Quán chiếu về sự buông xả trong khi đọc muột cuốn sách về Phật pháp khi ngồi ở trong nhà rất là khác với khi mình ngồi dưới một gốc cây.  Trong khi đọc bài pháp thứ ba này, tôi chiêm nghiệm được sự quan trọng của việc biết mình (tự tri) giữa khung cảnh thiên nhiên.<br />
<br />
Ngày xưa, lúc La Hầu La 7 tuổi, đến xin với cha được thừa hưởng gia tài, Ngài đã không hề tưởng tượng được là 13 năm sau đó, Ngài đã được thừa hưởng một gia tài quý báu nhất mà một người làm cha mẹ có thể để lại cho con của mình.  Trong Phật giáo, giác ngộ là hạnh phúc lớn lao nhất.  Tôi ước mong con cái của tôi sẽ tìm thấy sự an lạc, thảnh thơi, và an lành trên con đường đi tới giải thoát.  Có lẽ, trên con đường trở thành người lớn, chúng cũng sẽ được dạy về đạo đức, thiền định, và tuệ giác [như La Hầu La vậy].<br />
