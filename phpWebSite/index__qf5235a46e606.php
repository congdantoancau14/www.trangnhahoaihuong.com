<h3>Giới thiệu tuồng "Đông Lộ Địch", bản Nôm sau cùng của thế kỷ 20, mới phát hiện</h3>


<b>Nguyễn Hữu Vinh và Nguyễn Văn Sâm</b><br />
<br />
Tháng ba, năm 2006, tôi (Nguyễn Văn Sâm) qua Viện Việt Học ở California để nói chuyện về Văn Chương Tranh Đấu Miền Nam thời Pháp thuộc. Sinh hoạt cũng bình thường thôi. Trao đổi với nhiều người cũng như tâm tình với một hai người ưu tư với văn hóa Việt trên đất nước người. Đời sống xứ người mỗi khi gặp ai đó có vẻ tha thiết với những gì của quá khứ Việt Nam, tôi thường hứng khởi nói nhiều, hỏi nhiều và cảm thấy không mệt mỏi trong câu chuyện.<br />
<br />
Tình cờ tôi nói chuyện về Bình Định, về hát bội với ông Lê Cẩm Khoán (LCK), một nhân sĩ địa phương thường tới lui sinh hoạt với Viện. Buổi nói chuyện hôm đó đại ý như sau: Giáo sư nghiên cứu về tuồng hát bội, về chữ Nôm mà giáo sư có biết tuồng Lộ Địch hay không? ---Có, nhưng tuồng này là tuồng Quốc Ngữ mà, Cụ Ưng Bình mô phỏng theo tuồng Le Cid để viết ra. Tôi còn biết một bản khác về tuồng nầy là Tuồng Lôi Xích nữa. --- Nhưng tôi có một bản Nôm của tuồng Lộ Địch thế mới hay…<br />
Tôi đổi lại thế ngồi, chăm chú nghe ông Khoán kể:<br />
<br />
<i>…Đầu thập niên 1940, cha tôi lúc đó hành nghề thuốc Bắc, ông có nhiều sách thuốc bằng chữ Hán in hay viết tay, ông cũng có nhiều sách quốc ngữ. Trong khi rãnh rỗi ông thường ngâm nga tuồng Lộ Địch theo bản quốc ngữ mà ông có. Phải nói rõ lại là cha tôi học chữ Hán, chữ Nôm với ông tôi từ nhỏ. Người còn đậu bằng Primaire nữa nên chữ quốc ngữ và tiếng Pháp cũng kha khá. Nghề thầy thuốc Bắc như là một nghề cứu nhân độ thế và không dính dáng gì đến chánh quyền đương thời. Những lần ngâm nga tuồng Lộ Địch của cha lọt vào tai ông nội tôi. Ông lúc đó hơn bảy mươi rồi, không biết quốc ngữ mà chỉ biết chữ Nôm thôi. Thích nhưng không tự mình đọc được, ông mới kêu cha tôi viết lại bản tuồng đó bằng chữ Nôm cho ông đọc. Cha tôi đã viết vào khoảng 1942 và ông tôi dùng bản đó để ngâm nga, thưởng thức. Cha tôi mất năm 1948 nên bản Nôm nầy chắc chắn không thể viết xong trước năm 1945 vì thời gian nầy ở vùng tôi rất lộn xộn. Cái hay là mình chỉ có một bản duy nhất và hơn sáu mươi năm ở vùng binh lửa nó vẫn tồn tại một cách ly kỳ. Số là sau khi ba tôi mất, chú tôi giữ một số sách vở mà chú thích, các quyển nầy được đem sang nhà chú. Trong khi nhà ông nội, rồi là nhà cha tôi bị bom đạn tan hoang, sách vở bị nạn không còn gì thì bản Nôm Tuồng Lộ Địch lại sống sót. Trong lần về Việt Nam cách đây hơn mười năm trước, 1995, tôi đem nó qua Mỹ, nó như là đứa em của tôi, như là một kỷ niệm của ông cha mình. Mặt khác, đem qua như là một hành vi bảo tồn một tác phẩm thiệt là đặc biệt dính dáng đến nhiều nước…</i><br />
<br />
Tôi chờ lúc người đối thoại bớt xúc động mới rụt rè xin một bản sao photocopy. Cũng là vì muốn cho nhiều người biết thôi. Để xem dạng chữ Nôm thập niên 40 của thế kỷ trước như thế nào, để xem coi hai bản quốc ngữ và Nôm có ăn khớp hay không…<br />
<br />
Nghĩ cũng là cơ duyên. Ông Khoán tới lui Viện Việt Học rất thường mà không ai biết ông có bản Nôm nầy, phải đợi ngày đó tháng đó tôi mới được biết. Cũng như trước đây gần bốn mươi năm tôi nhìn lên trên cây đòn dông của một nhà trên cù lao ông Chưởng, Long xuyên, thấy một quyển sách treo tòn ten mới hỏi chủ nhà sách gì. Và tôi được bản chép tay bản Nôm Sãi Vãi của Nguyễn Cư Trinh. Tất cả mọi chuyện đều là cơ duyên.      <br />
<br />
Tìm được bản Nôm theo tôi là nhiều cơ duyên may, với một chút quyết tâm của người sưu tầm và đôi phần tình cảm với người chủ sách. Ta không cần nguyên bản gốc, chỉ cần được bản copy là quí rồi. Nội dung sách mới quan trọng… <br />
<br />
***<br />
<br />
Tuồng còn gọi là hát bội, là loại kịch hát rất đặc thù của Việt Nam, vốn có gốc gác rất lâu đời, từ các hình thức diễn xướng trong dân gian. Thời điểm chính thức xuất hiện là vào khoảng đầu thế kỷ 14 đời nhà Trần. Theo "Đại Việt sử ký toàn thư" thì vào “năm Nhâm Dần, Đại Trị năm thứ 5 [1362], mùa xuân, tháng giêng, vua ra lệnh cho các nhà vương hầu, công chúa dâng các trò tạp hý. Vua xét duyệt trò nào hay thì được thưởng. Trước đấy, khi đánh Toa Đô, bắt được con hát là Lý Nguyên Cát rất giỏi nghề hò hát. Những con ở trẻ của các nhà thế gia theo thường theo y tập hát những khúc điệu của phương Bắc. Lý Nguyên Cát sáng tác các vở tuồng truyện cổ, có các tích như Tây vương Mẫu hiến bàn đào. Trong tuồng cổ có các vai quan dân, chu tử, đán nương, câu nô gồm 12 người, mặc áo gấm, áo thêu, đánh trống, thổi sáo, gảy đàn, vỗ tay, gõ ồn phím đàn, thay đổi nhau ra vào làm trò, khiến người xem xúc động, muốn cho buồn được buồn, muốn cho vui được vui. Nước ta có tuồng truyện bắt đầu từ đấy” [1]. Như vậy, trong cuộc chiến tranh chống quân Nguyên xâm lược nhà Trần đã bắt được tù binh Lý Nguyên Cát, một kép hát tên tuổi ở phương Bắc. Triều đình bèn giữ lại để biểu diễn và cải tiến nghệ thuật Tuồng của mình về sau. <br />
Thời các chúa Nguyễn, các vua chúa cũng ưa chuộng tuồng. Tương truyền Đào Duy Từ (1572-1634) là tác giả vở tuồng "Sơn hậu" viết trong thời ông phục vụ dưới trướng của chúa Sãi Nguyễn Phúc Nguyên. Đây là một vỡ tuồng có ảnh hưởng mạnh mẽ trong dân chúng và hiện nay còn lưu hành nhiều bản Nôm khác nhau.<br />
<br />
   Sang đến thời vua Minh Mạng thì Duyệt Thị Đường là nhà hát được xây dựng quy mô trong Tử Cấm Thành. Riêng tính tại Huế những nǎm đầu thế kỷ 20, không kể Duyệt Thị Đường là nhà hát cung đình, thì cũng có khá nhiều rạp tuồng phục vụ quần chúng. Nổi tiếng nhất là rạp Đồng Xuân mà dân địa phương quen gọi là "rạp Bà Tuần" được xây dựng từ năm 1923. Song song với dòng tuồng ngự trong cung, dòng tuồng dân gian tiếp tục nẩy nở phù hợp với thị hiếu của quần chúng, nhất là những vở tuồng liên quan tới cuộc sống thường ngày. <br />
<br />
Thường, tuồng được phân làm hai loại chính: 1) Tuồng không theo tích truyện Tàu như Quần tiên hiến thụy, Vạn bửu trình tường, tuồng Tào Lao, Tuồng Trần Bồ... 2) Tuồng dựa vào tích truyện Tàu như các vở: Tống Sứ, Hộ sanh đàn, Đào Phi Phụng, Lý Phụng Đình, Đường tăng Tây Du ký, Tam Quốc Diễn Truyện (1), Tam Hạ Nam Đường, Quan Công hồi cổ Thành, Tiết Đinh San cầu Phàn Lê Huê, Lôi Phong Tháp...Loại tuồng thứ hai, còn gọi là tuồng đồ, chiếm phần lớn. Về sau này, Tuồng có xu hướng cải cách, không chỉ mượn ý từ những chuyện Tàu mà còn lấy từ các truyện trong dân gian Việt Nam như Trương Đồ Nhục, Trương Ngáo, Trương Ngố… hay trong lịch sử Việt Nam như Tượng Kỳ Khí Xa . Đặc biệt, Ưng Bình Thúc Giạ Thị, một vị vương tôn Nho học của triều đình Huế đỗ khoa thi Ký Lục năm 1904, đã phỏng theo một kịch phẩm nổi tiếng của nền văn học Pháp thế kỷ 17, tuồng Le Cid của Pierre Corneille, để viết thành một tuồng hát bội nổi danh là trường hợp hầu như duy nhất (2). Tác giả thay đổi kết cục trong nguyên bản cho phù hợp với văn hóa Việt Nam, cho nên gọi tuồng này là tuồng Đông Lộ Ðịch (tuồng Le Ciq (Lộ Địch) của phương Đông). Tuồng Đông Lộ Địch là tác phẩm đầu tiên trong lịch sử tuồng cổ Việt nam lấy đề tài từ tác phẩm châu Âu. Cụ đã tìm thấy trong tác phẩm “Le Cid” những thí dụ đức hạnh của các nhân vật trong thế giới phương Tây, và những thí dụ này cũng được thế giới phương Đông ghi nhận như là những giá trị đạo đức. Trong lời “Mẹo Tuồng” cụ viết : “Sự tích tuồng Le Cid có đủ trung, hiếu, tiết, nghĩa, nên tôi xét có nhiều điểm rất hợp với tinh thần luân lý Á đông. Như vậy kịch Pháp có thể dung hòa một phần nào với tuồng ta. Đó là lý do khiến tôi phỏng theo tuồng Le Cid mà diễn tuồng Lộ Địch…”. <br />
<br />
Tuồng Đông Lộ Ðịch là một thí dụ tiêu biểu sự ảnh hưởng của việc tiếp xúc với một nền văn hóa khác, không nhất nhất phải là Tàu, trong đó tính sáng tạo nghệ thuật theo tâm hồn Việt Nam đã được gìn giữ và triển khai. Chính cụ đã nhấn mạnh đây là 1 điều mới mẻ trong Tuồng hát. Trong bài Vãn Tuồng cú (Câu vãn tuồng) [2], cụ viết “Trai tài gái sắc, con thảo tôi ngay. Chuyện đời xưa bên cõi Thái Tây, tuồng hát mới của người Nam Việt. Nghiên mài bút viết, phấn điểm hương tô. Liễu còn giăng trước cửa nhà Nho, hoa cứ dệt trên màn chữ Hán…” .<br />
Nói chung tuồng này là thí dụ rõ ràng của Trung Hiếu và Ái tình, như lời tựa “Diễn truyện Lộ Địch” bằng chữ Hán của tác giả: Vấn đề thứ nhất trong Tuồng là Trung hiếu, điểm quan trọng trong Tuồng là Ái tình. Trong đời, ta cũng thường nghe kẻ trung hiếu ai mà chẳng trải qua chuyện tình ái. Tôi cũng theo người, xưa cũng như nay, nhưng làm Tuồng để làm gì? Chuyện tình éo le trong chuyện hiếu trung, chuyện trung hiếu khó xử trong chuyện đời tình ái, đủ chuyện oái ăm lắt léo, trăm ngàn khổ cực khó khăn, khó bề toàn vẹn. Chuyện hiếu trung khó xảy ra lại xảy ra. Chuyện tình ái khó giải lại có được kết cục được vẹn lòng người. Xem màn diễn gươm đâm bên bàn trang điểm mong được chết cho xong, coi màn người gửi thân cửa Phật cho qua kiếp người, nén lòng dục vọng, chịu đủ thứ buồn khổ. Chuyện diễn thành ra gương sáng cho Tâm lý học, chuyện lạ trong Luân lý học.<br />
   Vì thế, tôi Ưng Bình Thúc Giạ cảm thán câu chuyện hiếu trung, tình ái này mà viết nên Tuồng để biểu dương kẻ thục nữ, để tán thán người anh hùng, không dám tự cho đây là 1 án văn chương. <br />
Ưng Bình Thúc Giạ Thị viết xong vào tháng đầu xuân năm Ất Hợi, Bảo Đại thứ 10 (3).<br />
<br />
Về giá trị của tuồng này, những lời tán tụng sau đây của Cụ Ưng Tôn Thúc Thuyên thiết nghĩ không phải là màu mè mà thực tình nói được chân giá trị của tác phẩm: <i>Mùa xuân năm nay, cùng với anh trai là Quảng Bình Quan Sát Sứ Ưng Bình trở về kinh thăm nhà. Đêm rằm cùng bà con, bạn bè họp nhau nâng ly, ca hát ở nhà Liên Nghiệp (Liên Nghiệp hiên), Gặp lúc mưa đêm rả rích, hàn huyên thâu canh, Ưng Bình mới đem bản thảo vở kịch Lộ Địch ra cho xem và nói rằng: Tuồng này do danh sĩ bên trời Âu làm ra, nhưng nội dung và thực chất cũng giống y như chuyện nước ta, cốt chuyện thường tình, viết thành tuồng có hơi dài dòng, lộn xộn, không được mạch lạc cho lắm, chú đọc thử cho qua đêm mưa. Tôi bèn giở ra xem đề tài, cốt chuyện thì thấy văn thì hay, ý thì đẹp, đủ chuyện trung hiếu tiết nghĩa, buồn vui, hờn giận, tình tiết tuyệt diệu đủ cả, làm người đọc như đi vào thế giới của nhạc điệu Quảng Lăng, càng đọc thấy càng hay như ăn cây mía từ ngọn, càng ăn thì thấy càng ngọt. Đem so với các tuồng hát bội khác nổi tiếng như tuồng Lý Phụng Đình, Đường tăng Tây Du Ký thì tuồng này vượt hơn hẳn. Đem chuyện trời Âu viết thành chuyện đất Á tài tình như thế, đúng là chuyện hay cho các bậc thưởng lãm, là thuốc lành chữa bệnh “buồn” cho các bậc tao nhân. Trai gái có tình ý với nhau thì nên tranh nhau tìm đọc. Đừng để phụ lòng vì trên sân khấu đây là tuồng hát bội tuyệt hay, trong chốn ca múa là nơi lưu lại tuyệt tích ái tình diễm lệ.<br />
Tôi đây, không ngại tài hèn thấp kém, viết lên vài dòng, chỉ sợ không đủ tài viết ra hết được cái tài tình trong vở tuồng có đủ tình, tiết, thơ, nhạc này, xin người đọc lượng thứ cho (4).</i><br />
<br />
Tuồng Đông Lộ Địch được khai diễn lần đầu tiên in vào ngày 5, 6 tháng 5 năm 1928 ở rạp Xuân Kinh Đài, Huế, dưới sự tham dự của Khâm Sứ Trung Kỳ. Sau năm 1937, tuồng được lần lượt công diễn nhiều lần ở các tỉnh Bình Thuận, Thanh Hóa, Quảng Nam, Bình Định, nhưng được diễn lại nhiều lần nhất là tại Huế. Theo nhà thơ Tôn Nữ Hỷ Khương, ái nữ của tác giả thì "tuồng Lộ Địch được công diễn từ năm 1928, đã gây tiếng vang trên sân khấu miền Trung và miền Nam một thời. Điểm đặc sắc ở tuồng "Lộ Địch", khác với nguyên tác tuồng Le Cid là ở chỗ kết cục, tác giả đã để nhân vật nữ chính là Chi Manh đi tu để giữ được trọn vẹn phẩm giá người phụ nữ theo tinh thần Á Đông". Sau năm 1975, tuồng hát bội hầu như bị xao lãng trong một quãng thời gian dài. Mãi cho tới mấy năm sau này, dưới sự tài tợ của Tiến Sĩ Thái Kim Lan, vở tuồng "Đông Lộ Địch" đã được diễn lại nhiều lần. Nhà hát tuồng Đào Tấn ở Bình Định đã dàn dựng trên sân khấu ở nhiều nơi như Quy Nhơn (17-1-2000), Sài Gòn (14-3-2000), Hà Nội (19-9-2000), Huế (4-4-2001), và đặc biệt là ở sân khấu Châu Âu tại Munich, Đức năm 2002.<br />
 <br />
Từ lúc tuồng được diễn vào năm 1928 và Thần Kinh Tạp Chí cũng cho đăng lên báo, cũng theo ái nữ của tác giả thì tác giả trong những năm sau đó đã dành nhiều thì giờ sửa chữa lại bản thảo. Theo lời tựa “Diễn truyện Lộ Địch” của Ưng Bình thì tuồng viết lại xong vào năm 1935 là năm Ất Hợi, Bảo Đại thứ mười, bản văn được xuất bản năm sau, 1936, và được tái bản vào năm 1959. Một điều cũng đặc biệt nữa là tuồng này được viết và in thành sách bằng chữ Quốc Ngữ, chứ không viết bằng chữ Nôm như thường thấy trước thời đó. Trong bài “Lời Cáo Bạch” tác giả viết “Coi tuồng xưa thời coi tuồng Nôm dễ hiểu hơn chữ Quốc Ngữ, vì chữ Nôm là mượn chữ Nho mà làm ra; đặt tuồng hát thời chữ Nho phần nhiều, như hát Nam thời là chữ Nôm, hát Khách thời phải chữ Nho mới được; vả lại hưởng, tán, niêu, nồi, ngâm, xướng, thán, vấn cũng dùng chữ Nho phần nhiều; bởI vậy mê coi tuồng chữ Nôm hơn chữ Quốc Ngữ. Nhưng viết chữ Nôm phiền lắm, lại cũng có nhiều chữ Nôm đọc không chạy, nên phải in chữ Quốc Ngữ, nhưng câu nào toàn chữ Nho, hoặc trong câu có vài ba chữ Nho, mà đọc ra không được hiểu liền, thời chữ Nho ấy cũng in ra chữ Quốc Ngữ cho dễ đọc, mà phải nối thêm chữ Nho thiệt vào, để coi cho dễ hiểu nghĩa lý, và cho khỏi lộn điển tích…” <br />
<br />
    Bản viết bằng chữ Nôm mà chúng tôi mới phát hiện trên trang bìa có hàng chữ Quốc Ngữ ghi bản Nôm do cụ Lê Cẩm Tú viết vào năm 1941 (5). Chữ Nôm ở đây sắc sảo, rõ ràng, dễ đọc. Nhìn chung, có một ít khác biệt giữa bản Nôm và bản Quốc Ngữ. Ví dụ, bản chữ Nôm chỉ có lời tựa bằng chữ Hán của cụ Ưng Bình và cụ Ưng Tôn, không có “Tựa” của giáo sư Ưng Quả, “Mẹo Tuồng” và “Lời Cáo Bạch” của Ưng Bình. Trong tuồng, một số câu chỉ vẻ cho kép làm tuồng cũng không thấy có trong bản Nôm. Trong nhiều màn diễn, các vai diễn và kịch bản có hơi thay đổi, như màn thứ 30 Chi Manh lên Bạch Vân Am tu, trong bản Nôm vai Yến Nương không xuất hìện, cũng như những lời nói của A Liệt cũng được sắp xếp khác so với bản Quốc Ngữ. Những điểm này cho chúng ta nghĩ rằng, người viết bản Nôm có thể đã dùng bản thảo Quốc Ngữ có trước khi Ưng Bình sửa chữa thêm bớt lần chót để in thành sách vào năm 1936 [4]. <br />
Về phương diện cấu tạo chữ Nôm trong bản văn, ta thấy đó là đặc trưng của loại chữ Nôm đầu thế kỷ 20, trong đó chữ hình thanh có khuynh hướng được sử dụng nhiều cho rõ nghĩa hơn. Với đặc tính của chữ Nôm trong bản văn, với thời gian ra đời đặc biệt của nó, Tuồng Đông Lộ Địch có thể là tác phẩm Nôm sau cùng của thế kỷ 20 mà ta có thể chấp nhận được mặc dầu những năm gần đây cũng có người làm công việc phiên từ chữ Quốc Ngữ sang chữ Nôm.

