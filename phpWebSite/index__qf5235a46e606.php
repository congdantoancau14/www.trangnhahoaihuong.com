<h3>Phụ lục 1: Bài tựa Giáo Đầu (Giáo Đầu Tự) (phiên lại từ bản Nôm)</h3>



<br />
<br />
Phong hòa vũ thuận, hải yến hà thanh, non sông rạng vẻ thái bình, cây cỏ khoe màu thạnh trị, nhà nhà phu phỉ, chốn chốn ăn chơi, trước võ đài trông lắm trò vui, trên văn án tìm thêm vẻ lạ, rủ màn Đông Á xem truyện Tây Âu, nét phong tao mỉa truyện hồng lâu, trang thanh tú cũng phường bạch bích, trai tài là Lộ Địch, gái sắc gọi Chi Manh, lếu lăng xe mối tơ mành, bỗng phút hừng cơn lửa đỏ, gương đại hiếu soi cùng kim cổ, gươm vô tình thẹn với non sông, cắn răng bẻ một chữ đồng, mở mắt chia hai hàng lụy, nỗi oán ân, câu thị phi, cơn biến [huyễn], sự hi kỳ, tỉnh, say, cười, khóc mấy khi; Nam, Khách, Niêu, Nồi đủ chuyện; xem qua vừa một quyển, kể lại đặng đôi hồi, xin khán quan lặng lặng mà coi, tuồng hát gọi là Đông Lộ Địch.<br />
<br />
			                  Ưng Bình Thúc Giạ Thị tự tựa<br />




<h3>Phụ lục 2: Câu vãn tuồng (phiên lại từ bản Nôm):</h3>



Trai tài gái sắc, con thảo tôi ngay. Chuyện đời xưa bên cõi Thái Tây, tuồng hát mới của người Nam Việt. Nghiên mài bút viết, phấn điểm hương tô. Liễu còn giăng trước cửa nhà Nho, hoa cứ dệt trên màn chữ Hán. Sẵn lời nguyệt đán của khách phong tao. Khéo mua duyên phải kén mặt đào, cho đúng điệu phải lừa vai kép. Cửa trường không hẹp, sân khấu càng đông. Non Nam ngưỡng chúc bệ Rồng, biển Bắc xin dồn thẻ Bạc.<br />




<h3>Chú Thích</h3>



(1) Tây Du và Tam Quốc là những tuồng rất dài. Tây Du dài 100 hồi. (Mỗi hồi diễn một đêm) Hiện ở VN không thấy ai hay cơ quan nhà nước nào có. Chỉ có thư Viện Trường Viễn Đông Bác Cổ ở Paris là có một bản chép tay đầy đủ 100 hồi. Tam Quốc dài 120 hồi, các Thư Viện ngoại quốc không có, ở Việt Nam những nhà sưu tập mỗi người giữ từ vài hồi tới vài chục hồi, lỏn chỏn.<br />
(2) Chúng tôi nói gần như duy nhất vì trước đó đã có các tuồng đạo viết bằng Quốc ngữ lấy ý từ các chuyện trong Kinh Thánh được xuất bản cuối thế kỷ 19 bằng Quốc Ngữ trong quyển  Vãn và Tuồng. Và đồng thời với nó là tuồng đạo Nôm Đa Vít. Nhìn tổng quan, tuồng đạo chưa qua khỏi giáo dân để đi vào số đông dân chúng Việt Nam nên ảnh hưởng rất ít.  <br />
(3) Dịch lời tựa của Ưng Bình viết bằng chữ Hán “Diễn Lộ Địch Truyện Tự”.<br />
(4) Dịch lời Đề tựa của Ưng Tôn Thúc Thuyên viết bằng chữ Hán “Độc Lộ Địch Diễn Truyện”.<br />
(5) Xem Phụ lục 1: Tờ Bìa bản Nôm tuồng Đông Lộ Địch.<br />
