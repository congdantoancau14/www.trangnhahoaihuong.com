<b><a name ="4"  href="#4">[4]</a></b> Trích trong tập sách viết tay dạy làm thơ Đường luật, không thấy tên sách, tạm gọi là ‘Phá Bình Thừa Trắc 破 平 承 仄’, theo tên bài thơ đầu tiên, tài liệu của Ủy Ban KHXH- Miền Nam, tờ 14b. Bài thơ cũng dùng chữ hia 唏 (anh) và chế 制 (chị): Hia thời để chớp răng như phấn, Chế vận chăn voan mặt tựa than. <br />
<br />
<b><a name="5"  href="#5">[5]</a></b> Chẳng hạn chữ rồi viết bằng lai 來  ta thấy trong lời tựa quyển Gia Huấn Diễn Ca 家 訓 演 󰐺, bản Bửu Hoa Các 寶花閣, năm Bính Ngọ 丙 午: Tôi mới vâng lời mà làm ra sách nầy 碎 買  云 𢈱 麻 滥  册 尼, rồi thầy Ký Lục tỉnh Long Xuyên 來 柴 記 錄 省 龍 川… <br />
<br />
<b><a name="6"  href="#6">[6]</a></b>Bà Bành 妑 彭: tiếng gọi đàn bà thô tục mà dữ. (Chuyện Trương-Ngáo - ĐNQATV, Q1, trang 36)<br />
