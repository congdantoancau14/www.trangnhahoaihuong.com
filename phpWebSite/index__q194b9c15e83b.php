<h3>Vào đề</h3>



<h3>Nguyễn Văn Sâm</h3>
<br />
Từ trước đến giờ không bao nhiêu người biết tuồng hát bội Trương Ngáo 張 僥 傳, một tuồng bình dân nhưng ẩn tàng nhiều khía cạnh triết lý Phật giáo. <i>Bản chữ Nôm</i>, chỉ mới được khắc in gần một trăm năm chục năm nay, người nghiên cứu may mắn lắm mới có! Bản quốc ngữ do P. H .S. vừa dịch vừa sửa, in năm 1904 tại Sàigòn, trung tâm văn hóa quốc ngữ của cả nước thời đó, ngày nay không còn giá trị văn học và nghệ thuật nữa vì quan niệm phiên chuyển của người sinh hoạt văn học vào mấy thập niên đầu thế kỷ 20 không có tính cách khoa học <b><a href="#1">[1]</a></b> mà chỉ thuần mục đích cung cấp một bản quốc ngữ cho độc giả trung bình không khó tánh lắm đối với vấn đề nguyên bản.<br />
<br />
Tôi cố gắng phiên âm trung thực từ bản Nôm duy nhứt mà mình có được đã lâu khi lục lọi ở Thư Viện Quốc Gia Pháp, Paris, đó là bản khắc ở Phật Trấn 佛 鎮, Quảng Đông 廣 東, Trung Quốc 中 國, năm Mậu Dần 戊 寅, 1878 <b><a href="#2">[2]</a></b> mà không tùy tiện đưa ra những ý riêng về sự dùng chữ nầy chữ nọ hay dở, khó hiểu, thuận câu, trật chỗ..., những vấn đề mà tôi gọi là ngoài công việc của người phiên âm và giới thiệu bản văn. Khi chắc chắn thập phần bản Nôm khắc sai tự dạng mới đưa ra thiển ý, chỉ mong mình được góp phần trong việc đưa trở về trình làng một văn bản gần đúng nguyên văn của người sáng tác ban đầu. Làm việc nhỏ mọn nầy, tôi cũng đắn đo nhiều, chỉ dám xác quyết sau khi so sánh với các trường hợp tương tợ và nhìn lại văn cảnh một cách thận trọng. Như vậy bản quốc ngữ của tuồng Trương Ngáo lần nầy tính nghệ thuật của nguyên bản vẫn được bảo tồn mà cách nói, chữ dùng của người xưa cũng được bảo vệ hầu như nguyên vẹn.<br />
<br />
Đây là tuồng hát bội nhưng không phải là tuồng hát bội truyền thống nói chuyện xảy ra trong cung đình với Hoàng Đế, Chánh Cung, Thứ Phi, Hoàng Tử, Công Chúa, Tể Tướng, Quốc Cựu…  và những tôi trung, tôi nịnh, quan quyền, quân lính… như thường thấy trong các tuồng thầy, tuồng đồ. Đây là tuồng hát bội  không thuộc về hai dạng trên mà đi riêng một con đường đặc biệt: tuồng khôi hài mang không khí Việt Nam với những nhân vật bình thường trong xã hội, một xã hội bình dân của người nghèo khổ thật sự gần gũi với người xem người diễn. Có thể nói đây là hoạt cảnh của thời ra đời của chính bản văn, được tác giả khéo léo dùng để tượng trưng những vấn đề liên quan đến việc quyết tâm tu hành học Phật. Người bình dân có thể thưởng thức khía cạnh khôi hài, cười vui với lời nói hàm hồ của nhân vật, thương hại sự vô lễ chơn chất của Ngáo với Phật…. Bậc thức giả trái lại cũng nhìn những điều đó nhưng thấy được sự tượng trưng ý nghĩa thâm sâu chung quanh vấn đề tu hành, liễu đắc chân lý đạo.<br />
<br />
Về nghệ thuật tuồng, có thể nói đây là một tuồng hát bội được đơn giản hóa đến cực điểm. Chỉ có nói lối và vãn được tác giả coi là quan trọng và phù hợp với câu chuyện nên có mặt xuyên suốt từ đầu đến cuối vở, còn thán, xướng, loạn, bạch, ban là những cách diễn tả mà câu văn dùng toàn Hán tự nên bị coi nhẹ và hiện diện rất ít, có thứ còn bị loại luôn (thán, bạch, ban). Điều nầy cho ta kết luận rằng tuồng Trương Ngáo xuất hiện vào lúc mà chính ngay người bình dân cũng thấy rằng tuồng hát bội phải có những cải tiến cần thiết để đi sâu hơn vào tâm thức giới lưu dân đến định cư trên vùng đất mới phía cực Nam. Cuối thế kỷ 19 sự kiện nầy mới có cơ sở phát triển. Các tuồng rắc rối, nhiều Hán tự, xuất hiện ào ạt cho tới nửa sau thế kỷ 19 thì bớt dần, tới nay thì tuồng hát bội chỉ là còn lại cái hơi thở, cách dàn dựng, chớ chữ nghĩa hát bội và những gợi hứng cũ từ truyện Tàu đã không còn có mặt.<br />
<br />
Câu chuyện của tuồng nầy xoay quanh một người đàn ông có trí khôn chậm phát triển, tàng tàng, không phù hợp với cuộc sống xã hội là Trương Ngáo 張 僥. Vợ Ngáo sai đem năm quan tiền vừa vay được, đi bổ hàng về bán lẽ lại trong xóm làng để kiếm chút lời độ nhựt. Khi Ngáo đi ngang một ngôi chùa, thấy người ta đang đúc tượng Phật, bèn bỏ tất cả tiền vào lò đúc vì nghe bồn đạo nói cúng tiền đúc Phật là hình thức cho Phật vay, sau nầy rất có lời. Về nhà, Ngáo hãnh diện khoe với vợ về hành vi thông minh của mình. Vợ Ngáo là Ba Bành 𠀧 彭, một người đàn bà đáo để, đánh cho Ngáo một trận nên thân và bắt đi kiếm lại tiền đem về. Ngáo phải lên đường đi sang Tây Phương, mong tìm Phật đòi tiền, món tiền mà Ngáo coi như mình đã cho Phật vay. Trên đường đi, Ngáo gặp một người đàn bà luống tuổi chưa chồng tên là Như Ý 如 意, cô nầy nhờ Ngáo hỏi Phật về chuyện lương duyên trễ tràng của mình. Phật thương tình Ngáo hiền lành chơn chất nên hiện ra, cho thuốc giải trừ chứng dại ngu, ban cho một nhành cây có thể nhìn qua đó thấy cảnh ở xa và ban cho Ngáo một đồng tiền phép có thể hóa ra thật nhiều tiền. Phật còn cải tên Ngáo thành Chơn Tâm 眞 心 dựa trên cái tâm thành thật chơn chất của Ngáo. Phật cũng trả lời về câu hỏi của người đàn bà kia, chỉ cho nàng biết rằng sẽ kết duyên cùng Chơn Tâm. Trở về đến chỗ của Như Ý, Ngáo uống thuốc Phật ban cho nên hết khùng khịu. Anh dùng nhánh cây phép nhìn thấy được cảnh vợ mình giờ đã sang ngang nên quyết định kết duyên cùng Như Ý. Từ đây anh sống cuộc đời an nhàn trong cảnh giàu sang với vợ mới, tên mới và cuộc đời mới, trí huệ mới.<br />
<br />
Trong khi Ngáo đi tìm Phật thì ở nhà Ba Bành gá nghĩa với một người đàn ông giàu có chuyên sống bằng nghề cho vay là Lục Tồn 六 存. Lục Tồn vốn mê nhan sắc của Ba Bành nên để bỏ vợ nhà, lấy chị ta. Cặp vợ chồng nầy sau đó sa đà vào đường bạc bài, chẳng bao lâu phá tiêu tan cơ nghiệp, trở thành nghèo khổ, phải đi làm nghề múa kiếm, đánh đàn trong một gánh bóng chàng bóng rỗi để mưu sanh.<br />
<br />
Và bốn người gặp lại nhau với hai vị thế rất khác biệt khi vợ chồng Chơn Tâm cho rước đội bóng chàng về nhà mình để múa bông tạ ơn Bà do lời hứa trong lần vái cầu xin lương duyên trước đó của vợ.<br />
<br />
Tuồng hát bội Trương Ngáo còn có người anh em với nó là truyện kể truyền miệng: ‘Người Đi Đòi Nợ Phật’. Không thể xác định được sự ra đời trước sau của truyện truyền miệng và tuồng hát bội Trương Ngáo, tuy nhiên truyện kể chỉ còn lại giá trị nội dung, không có bất kỳ giá trị hình thức nào vì không có văn bản cố định. Truyện ‘Người Đi Đòi Nợ Phật’ chỉ còn cái cốt lõi của tuồng Trương Ngáo là kết quả của việc tin Phật theo cách hiểu của người bình dân: Rằng người tin Phật, trì chí tu niệm, cuối cùng cũng được Phật độ, thoát cảnh nghèo khó dầu cho họ đến với Phật bằng bất cứ ý hướng gì, kể cả lòng tham lam bình thường mà ta có thể nói rằng đó là hình ảnh của sự hiểu đạo hời hợt, hay thậm chí chẳng hiểu gì về Phật pháp của phần đông người đời.<br />
<br />
Tuồng giá trị hơn truyện kể ở nhiều mặt vì ít nhứt còn có một văn bản cố định. Ta có thể dựa trên cách dùng chữ, dựa trên những chi tiết trong lời đối thoại để thấy được nhiều điểm về mặt văn chương cũng như những sinh hoạt xã hội thời nó xuất hiện.<br />
<br />
Tuồng Trương Ngáo đưa ra một cái nhìn về Đức Phật, về thái độ của người đi tu. <br />
<br />
Ông Phật trong tuồng gần gũi với con người biết bao! Biết bao lần Ngáo gọi Phật bằng anh, khi nói về Phật với người khác thì Ngáo dùng chữ ảnh. Đây không là chuyện ‘gần chùa gọi Phật bằng anh’, đây chỉ là sự thể hiện của trạng thái bình đẳng Phật tính của người và Phật. Khi con người với cái tâm ‘hư không’ như Ngáo thì không bị những giá trị đối đãi của xã hội ràng buộc, anh cảm nhận được Phật tính trong người mình, từ đó anh gọi Phật bằng anh với đầy đủ sự ngang hàng của từ nầy. Ngáo không thấy một sự khác biệt nào về giá trị và địa vị giữa mình và Phật để kính trọng tuyệt đối hay sợ hãi quá đáng như chúng sinh bình thường. Ngáo thản nhiên trách móc Phật đủ điều khi đòi tiền Phật, nào là ông đã muốn trốn chạy, nào là ông ở nhà ngói, mặc áo vàng mà không muốn trả tiền cho Ngáo. Ngáo còn đoan quyết sẽ nắm áo Phật khi tìm gặp và thề chắc mẽm rằng mình sẽ theo đuổi Phật cho tới Thiên Thai, tới Nguyệt Điện nếu Phật trốn về đó. Với Ngáo, Phật chỉ là một đơn vị hiện hữu như anh. Đồng đẳng, vô sai biệt cho nên khi Phật thiếu tiền Ngáo thì phải trả thôi, không có sự bãi miễn.<br />
<br />
Còn chuyện Ngáo đòi tiền Phật, ta có thể hiểu sự quyết tâm theo đuổi đến tuyệt cùng nầy của Ngáo là hình ảnh tượng trưng cho con đường tu đạo của người đời: phải quyết tâm trì chí. Dầu ta không hiểu kinh kệ, chưa thông Phật điển, thậm chí còn mê muội ao ước những điều quá đáng khi làm được chút ít Phật sự, nhưng chính sự trì chí tu niệm của ta một ngày kia sẽ giúp ta ngộ đạo, thông tuệ, ta sẽ thoát vòng khổ hải trầm luân. Chúng sanh có thể đến với Phật bằng con đường thật bình thường của thế nhân là ham muốn cái hình ảnh Thiên Đường - tuồng tượng trưng bằng số tiền Phật thiếu của Ngáo – cũng không sao. Lòng thành khẩn và sự trì chí tu niệm mới là điểm chánh.<br />
<br />
Cái Thiên Đường đạt được cũng không phải ở nơi chốn xa xôi nào mà bắt đầu bằng chính cuộc sống tại thế, cả với ‘hồng nhan tri kỷ’, và cuộc đời nhàn hạ vô ưu, cởi bỏ giai đoạn trước, sống hoàn toàn giai đoạn mới.<br />
<br />
Cái sáng láng thông tuệ của Ngáo khi biến thành Chơn Tâm cũng là tượng trưng cho cái giác kiến của người tu hành khi đến mức thấy được rõ ràng Phật pháp, bừng vỡ được cái vô minh từ lâu phủ che tri kiến để phát huy Phật tính tiềm ẩn trong người mình mà ai ai cũng có.<br />
Tác giả khéo léo cụ thể hóa nguyên lý có có không không của nhà Phật bằng hình ảnh sự nghèo (không) của Trương Ngáo, chuyển qua giàu (có) và sự giàu sang (có) chuyển qua nghèo nàn (không) của Lục Tồn. Phải có sự biến thiên ngược chiều nầy, nguyên lý sắc-không mới cụ thể, từ đó người bình dân dễ thấy, dễ in vào tâm trí. <br />
<br />
Nếu ta để ý đến thái độ ngạc nhiên và không biết Phật là gì của Ngáo khi gặp Phật thì ta càng thấy tác giả thiệt là tài tình, ông muốn chuyển truyền thông điệp rằng chúng sinh nhiều khi tiếp cận với chân lý, nhưng thường là không hiểu, không biết, thậm chí đến coi thường. Biết bao nhiêu người đã đọc kinh, xem kinh, tụng kinh nhưng chỉ hiểu được chữ, có thể nắm được câu, nhưng không hiểu được ý. <br />
<br />
Về mặt xã hội, tuồng Trương Ngáo, cũng như các truyện Nôm đồng thời của nó, đưa đến sự kết thúc có hậu và những hệ quả đối với hành vi xấu của cá nhân. Mọi tính toán tham đó bỏ đăng, thay chồng đổi vợ, có thể trong giai đoạn ngắn đem đến cảm thức thích thú của người đời, nhưng trong quá trình lâu dài, chính sự thay đổi và lòng sắc dục nầy sẽ là tác nhân cho bao tệ hại, đem đến những khổ sở cho con người tham đó bỏ đăng. Anh chàng Lục Tồn đang khấm khá, vì say mê bóng sắc Ba Bành, bỏ vợ nhà lấy Ba Bành, kết cuộc là sự nghiệp nhà ngang dãy dọc bỗng chốc tiêu ma, một túp lều tranh xiêu vẹo cũng không còn, có lúc túng cùng quá mức phải tính chuyện đi làm bối kiếm ăn. <br />
<br />
Khác với các truyện thơ Nôm, tuồng Trương Ngáo không đưa ra những kết thúc ngoài thực tế như bị cá nuốt thây, bị cọp cõng đem bỏ trong rừng, bị sét đánh nát thi thể… cho trường hợp bội bạc có tính toán của Ba Bành. Ở đây kết truyện chỉ là một sự tương hội bẽ bàng, kẻ hát bài tình phụ phải đau từng khúc ruột, thế là đủ. Có thể rằng khán giả tuồng hát bội lúc nầy không còn thích để trí tưởng tượng của mình đi quá xa, cần phải dựa trên thần quyền hay thế lực siêu nhiên, cũng có thể tác giả tuồng Trương Ngáo muốn thể hiện một giải pháp thực tế có tính cách tâm lý, một đường hướng sáng tác mà ngày nay văn nhân thường thực hiện…<br />
<br />
Phần hình thức, tuồng Trương Ngáo còn ghi lại được những sinh hoạt xưa. Có cái hôm nay vẫn còn, có thứ ngày nay đã tiêu mất theo thời gian do biến chuyển của xã hội. Còn chăng là một vài vết tích nho nhỏ nên lắm khi ta chỉ biết mù mờ. Chuyện cho vay mượn nợ, chuyện làm nem làm chạo, chuyện bán bộ bán thuyền, chuyện chối đôi, xốc lá, chuyện đốt lò đúc tượng, chuyện thiện nam tín nữ kẻ bưng quả nếp người bưng mâm trà lên chùa, chuyện kẻ dâng sáp người dâng nhang làm công quả, chuyện mua sĩ hàng hóa trên chợ đem về bán trong xóm kiếm lời, chuyện hốt me, phá hỏa, chuyện thuốc hút trầu trao, trà khuyên rượu tiến… ta biết tận tường. Nhưng những chuyện múa bông, múa mâm của bóng rỗi bóng chàng, chuyện đánh bài phượng, chuyện múa vát chúng ta thật ngù ngờ, mơ hồ.  Chuyện tiền đồng năm quan mà phải xỏ xâu dài đuột đuột, phải gánh gánh đem đi, chuyện rước bóng về múa mà người chủ nhà dọa nếu hát dở thì phải đòn, chuyện người vợ bỏ chồng nay gặp lại dầu hai đàng ai đã nên duyên phận nấy thế mà người vợ cũ lại than mình đành chịu chết, tôi thiệt tình không hiểu rõ ràng. E rằng sinh hoạt đối đãi mỗi thời mỗi khác, kiến thức của ta về thời xưa dầu cố gắng tìm tòi cho mấy cũng không bao giờ thấu đáo. <br />
Thôi, chỉ biết rằng có. Đó là những nét sinh hoạt của một thời quá khứ. Nay nó còn lại mơ mơ hồ hồ trong những tác phẩm xưa mà tuồng Trương Ngáo nầy là một. <br />
<br />
Đặc biệt tuồng nầy có vài chỗ dùng tiếng Triều Châu (tòa khan, căn khấu, hóa khứ, hầm túng, dứt mánh…) hay những tiếng của người Hoa nhưng đã đi vào trong ngôn ngữ Việt (phá hỏa, ỷ) chứng tỏ rằng sự chung đụng giữa hai sắc dân thật là sâu đậm. Điều nầy cũng cho ta một giả thuyết rằng người viết tuồng, hay ít ra là người trông nom việc cho khắc in có liên quan bạn bè, xa gần với những ông Duy Minh Thị, Minh Đức Thị của xóm Dầu Phộng An Bình của vùng Chợ Lớn <b><a href="#3">[3]</a></b>, vùng mà cho tới ngày nay số dân người Hoa vẫn còn chiếm đa số. <br />
<br />
Thật ra không phải chỉ có tuồng Trương Ngáo là có tiếng nước ngoài, tuồng Lê Ngụy Khôi còn có nhiều hơn qua lời của một nhân vật người khách trú. Cũng vào thời của tuồng Trương Ngáo có bài thơ Chồng Chệt Vợ Miên, hình như của Phan Văn Trị, có hai câu rất phù hợp để minh họa cho chuyện nầy: Uống nước nàng kêu rằng phất tức 弗息, Ăn cơm hia lại nói xực phàn 食飯 <b><a href="#4">[4]</a></b>. <br />
<br />
Vì là một bổn tuồng cốt yếu phục vụ những người bình dân chân đất thiệt sự nên các ngôn từ, các cách nói không thể tìm thấy ở đâu khác, kể cả trong văn quốc ngữ sau đó hằng nửa thế kỷ. Người xem bản văn ngày nay có thể bàng hoàng khi bắt gặp nhân vật nữ nói những câu như: Việc làm hồ hổn quá chằn tinh, nghề đôi chối xứng hơn xốc lá. Cám treo để heo nhịn đói. Tình nguyệt hoa chẳng thấy mặn nồng.  Theo lũ mèo đàng, bắt chước đồ chó điếm. Chớ ai mà buộc cổ, biểu lấy con nầy? Trỏ l. đây trỏ l. đây. Dại thời ở lổ…. Hay nhân vật nam: Tới bây chừ con gái lịch sự thấy tôi cũng muốn…<br />
<br />
Nếu nói về nghệ thuất dàn dựng nhân vật thì tuồng Trương Ngáo tuyệt ở chỗ chuyển biến tâm lý nhân vật kéo theo chuyển biến ngôn ngữ thật chính xác. Ở đây không phải là lời của công thức hoa mỹ nếp mòn có thể thấy ở bất kỳ tuồng hát bội nào mà là lời của từng nhân vật phù hợp với từng hoàn cảnh cụ thể. Cả ba nhân vật chánh đều thay đổi cách nói khi cần thiết. Ba Bành trước khi lấy Lục Tồn nói với anh ta bằng lời ngọt ngào dịu dàng mềm mỏng ra vẻ phụ nữ nề nếp học thức, khi lấy anh ta rồi lúc đụng chuyện bèn giở giọng chanh chua ba đá thô tục ra. Lời nói của Trương Ngáo ban đầu thì ngây ngô, chữ dùng toàn Nôm, khi đã được thuốc Phật trị hết bịnh trì độn thì chữ dùng cao kỳ, lời nói oai vệ. Lục Tồn cũng vậy, khi mơ ước Ba Bành thì dịu ngọt đưa hơi, khi hai người lâm vào tình trạng nghèo túng thì anh cũng vũ phu gào thét hăm dọa…. <br />
<br />
Xin nói về văn bản. <br />
<br />
Bản Nôm khắc tuyệt đẹp. Nét chữ rõ ràng, chân phương, dễ đọc. Các trường hợp chữ nọ xọ chữ kia vì thiếu dư nét tuy hơi nhiều, nhưng là chuyện phải có vì khoảng cách từ người chép trên giấy đến người khắc trên gỗ có một không gian quá xa. Từ Chợ Lớn sang Quảng Đông, rồi từ Quảng Đông trở về Chợ Lớn ghe bầu đi buôn bán là chánh, chuyện khắc ván là chuyện phụ nên đi hết năm bảy tháng, có lúc cả năm, dễ gì ai chịu bỏ thời giờ hỏi han thấu đáo một vài chữ do thầy tuồng viết tháu khó đọc. Thợ khắc chỉ còn biết coi theo hình dạng mà đoán mò vì không hiểu nghĩa, cũng chẳng biết hỏi ai chung quanh.   <br />
<br />
Xin kể một số trường hợp sai lầm cụ thể:  Chữ một   thành chữ nghệ 艾, chữ ấn 印 thành chữ mão 卯, chữ rồi 耒 thành chữ lai 來, chữ lo 卢 thành chữ hộ 戶, chữ náo 閙 thành chữ nhàn 閒, chữ nịnh 侫 thành chữ khương 姜, chữ niên 年  thành chữ sao 牢, chữ nài 奈 thành chữ tế 祭, chữ quan   thành chữ chỉ 只, chữ ngõa 瓦 thành chữ bông , chữ mầu 牟 thành chữ lao 牢, chữ á 啞 thành chữ dấu 唒, chữ ngược 虐 thành chữ đường 唐, chữ nhau 饒 thành chữ theo 蹺, chữ lai 萊 thành chữ thuốc 茦, chữ khúc 曲 thành chữ hồi 囬, chữ ngươi  thành chữ đích 的, chữ mắng 莽 thành chữ buôn 奔, chữ cam 甘 thành chữ nhĩ 耳, chữ nghiệp 業 thành chữ chưởng 掌, chữ Châu 周  thành chữ cố 固, chữ khuyên 勸 thành chữ hoan 歡, chữ nó 奴 thành chữ như 如, chữ nghèo 𠨪 và chữ theo 蹺 thành chữ nhau 饒, chữ thua 收 thành chữ nỡ 𢖵,chữ tự 字 thành chữ vũ 宇, chữ dạ 啫 thành chữ chớ 渚, chữ nhẹ 𨌀 thành chữ nhảy , chữ trổ 擼 thành chữ lúa 穭, chữ lúa 穭 thành chữ trổ 擼, chữ trị 治 thành chữ hay 咍, chữ mọn 𨳒 thành chữ bé 閉, chữ tàm 慚 thành chữ tiệm 漸, chữ cắp 扱 thành chữ hấp 吸, chữ réo 嘹 thành chữ treo 撩, chữ cũng 共 thành chữ kỳ 其, chữ nền 𡋂 phần chữ niên 年  thành chữ lao 牢, chữ  hãn 罕 phần chữ can  干  thành chữ ngọ 午, chữ đất 坦 phần chữ đán 旦 thành chữ cắng 亘, chữ hôm 歆 phần chữ âm 音 sai thành chữ tích 昔, chữ trời  phần chữ thượng 上 thành chữ chỉ 止, chữ  xưa 初 phần chữ đao 刀 thành chữ vật 勿, chữ nay   phần chữ ni 尼 thành chữ ba 巴, chữ sớm 𣌋 phần chữ kiếm 劎 thành chữ cảm 敢, chữ xem 袩 bộ thị  礻thành bộ hỏa 火, chữ mâm 𣙺 bộ mộc 木 thành bộ thủ 扌, chữ ngủ 𥄭 bộ mục 目 sai thành bộ bối 貝,chữ bữa 𩛷 bộ thực 食 thành chữ ấp 邑, chữ cuồng 狂  bộ khuyển 犭 thành bộ thị 礻, chữ nghĩ 𢪀 thường bị khắc sai, bộ thủ 扌khi thì khắc thành bộ tâm 忄khi thì thành bộ nữ 女. ….<br />
Nhìn chung sự sai lầm nầy người sau chấp nhận được, không khó lắm để phát hiện, nhiều khi dễ dãi ta còn có thể coi đây là kiểu viết Nôm theo một cách tài tử phóng khoáng nào đó <b><a href="#5">[5]</a></b>. Đọc Quan Âm Phú  觀 音 賦  hay Lưu Bình Phú 劉 平 賦, người nghiên cứu chữ Nôm sẽ ngán ngẫm vì sự sai lầm hiện ra theo muôn hình vạn trạng. Đọc Quan Âm Tế Độ Diễn Ca 觀 音 濟 渡 演 歌 hay Lâm Tuyền Kỳ Ngộ 林 泉 奇 遇, Chàng Luối diễn ca 払  演 󰐺 ta sẽ chùn bước vì gặp quá nhiều chữ khắc lạ lùng, mắc mõ khó đoán định. Dĩ nhiên cũng cần nói thêm là tuồng Trương Ngáo nằm trong nhóm bản Nôm Phật Trấn cho nên sự hiện diện của các chữ Nôm viết theo giọng đọc miền cực Nam là chuyện dĩ nhiên. Ta không lạ khi thấy hàng được viết bằng hàn 翰 hoặc hàn , mặc dầu được viết bằng mặt dầu 𩈘 油, nhang được viết bằng nhan 顔, nhắn viết thành nhắng 仍,bạt tai viết bằng bạc tai 泊 哉, hết trơn được viết thành hết trơng 歇 莊, kiếm thiêng được viết bằng kiếm thiên 釼 天, giạ lúa được viết thành dạ lúa 胣 穭, làn đan được viết thành làng đan  郎 单, hoang đàng viết thành hoan đàng 歡 唐, xốc lá thành sóc lá 朔𦲿, khoang giữa viết thành khoan giữa 寛𡨌 …<br />
<br />
Ta thử tưởng tượng gần hai thế kỷ trước, khi các bộ môn giải trí ở miền Nam không nhiều, đời sống vật chất của lưu dân trên vùng đất mới còn đầy rẫy khó khăn, đi làm trên đồng ngoài rẫy ban ngày, sụp mặt trời một đổi là đã phải sống với ngọn đèn dầu leo lét, tuồng Trương Ngáo như món ăn tinh thần hợp khẩu vị, có khả năng đem đến khán giả hay thính chúng những nụ cười, sự hả hê cũng như lòng tin tưởng vào tương lai khá lên của chính mình. Nó lại dễ hiểu biết bao (so sánh với tuồng Hàm Hòa 咸 和 演 傳, Tuồng Kim Thạch Kỳ Duyên 金 石 竒 緣 cao xa kênh kiệu). Nó gần gũi biết bao (so sánh với các tuồng đồ đầy đủ cả triều đình quan quân, lúc nào cũng chiến tranh, giật giành quyền lợi như Sơn Hậu 山 后, Nhạc Hoa Linh 岳 花 靈, Mã Đăng Long 馬 登 龍, Tam Quốc Diễn Truyện 三 國 演 傳, Tây Du Diễn Truyện 西 𨒣 演 傳….) Sự thành công trên mặt sân khấu của tuồng trình diễn tạo nên khát vọng của dân chúng muốn có một văn bản để tự mình thưởng thức khi rãnh rỗi, khi đoàn hát không về. Tuồng Trương Ngáo do đó đã được khắc bản, được phiên dịch sau đó không lâu. Và tôi chắc chắn rằng người đương thời đã rất hứng thú khi đọc bản văn, dầu là Nôm hay quốc ngữ như là thưởng thức một tác phẩm văn chương. Điều nầy có thể xác định được nếu ta để ý rằng ông Huình Tịnh Của, trong quyển tự điển thời danh năm 1895 của ông, có nhắc đến tuồng Trương Ngáo khi giải thích chữ Bành <b><a href="#6">[6]</a></b>, và ông cũng có giải thích các mục từ toà khan(g), căn khấu vốn là tiếng Tiều rất khó hiểu cho người đời sau.<br />
<br />
Nhìn về mặt hài tính, tuồng Trương Ngáo đi cặp với tuồng Trần Bồ 陳 蒲, tuồng Trương Ngố 張 悞,tuồng Trương Đồ Nhục 張 屠 肉 tạo thành một bộ bốn tuồng hài hước đầu tiên rất có giá trị của bộ môn nầy. <br />
<br />
Ưu điểm của tuồng Trương Ngáo cho tới ngày nay, ngót nghét 200 năm qua, vẫn còn. Càng lâu xa so với thời gian nó được hình thành thì cái gia tài ngôn ngữ của thời đại nó xuất hiện, điều nó muốn rao truyền về tu hành về tin Phật, sự nhắn nhủ luân lý nhẹ nhàng chứa đựng bên trong cốt truyện… càng giúp nó trở thành món đồ quí hiếm. <br />
Để giúp người đọc dễ theo dõi vở tuồng, tôi đã tạm chia bổn tuồng thành 13 cảnh và ghi đại ý lên trên đầu như là tiêu đề của mỗi cảnh. Ngày xưa ông bà mình viết luông tuồng, xuống dòng cũng không có, cho nên không có chuyện phân cảnh phân màn vốn là khái niệm có từ kịch của Tây phương, Hy Lạp.<br />
<br />
Trong sự chú giải, tôi chỉ giới hạn làm sao cho bộc lộ được vẻ hay đẹp của bản văn, tránh những điều thuộc về tầm chương trích cú, điển tích dài dòng, do đó sự chú giải nhắm về câu cú, nhằm soi rọi giúp giới trẻ hiểu rõ ý nghĩa toàn câu, thưởng thức được bản văn hơn về những mặt khác, nhứt là sự chú giải sa đà trong những từ tố, trong những chuyện xa xưa tận đâu đâu mà các sách đều có. Các chữ Hán Nôm cần thiết được in kèm theo chữ quốc ngữ trong phần chú chỉ cốt giúp cho người thích Hán Nôm có dịp nhìn lại nhiều lần cho dễ nhớ lâu quên. Giọng văn cũng cố gắng viết sao cho nhẹ nhàng, không quá khô cằn, nhiều khi pha một chút bông lơn để thư giãn là điều chúng tôi tôi học được từ thầy Vương Hồng Sển trong mấy năm học với thầy ở Đại Học Văn Khoa Sàigòn …., nếu bạn đọc không vừa ý với cách nầy thì cũng nên rộng lòng tha thứ.<br />
<br />
Phần Tự Vựng có kèm chữ Nôm và số trang phía cuối sách chắc chắn sẽ giúp ích cho bạn đọc rất nhiều tùy theo sự nghiên cứu chuyên biệt của mỗi người…..<br />
<br />
Trong quá trình hình thành quyển sách nầy, tôi có tham khảo ý kiến của Thầy học là cụ Lãng Hồ và hai người bạn đồng song là các anh Nguyễn Hiền Tâm, Nguyễn Văn Trang. Xin cho gởi lời chân thành cám ơn đến những vị trên, dĩ nhiên những sai lầm trong sách nầy trách nhiệm thuộc về người viết.<br />
