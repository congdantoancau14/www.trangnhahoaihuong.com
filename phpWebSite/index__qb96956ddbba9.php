<h3>Văn bản Nôm</h3>


Chúng tôi vừa được phép phổ biến một số bản Nôm: <b>Việt Sử Diễn Nghĩa Tứ Tự Ca, Đoạn Trường Tân Thanh (Tăng Hữu Ứng), Sãi Vãi Tân Lục Quốc Âm, Nam Cầm Khúc, Việt Sử Tiệp Lục Diễn Nghĩa, Cổ Tháp Linh Tích </b> v.v. Một số bản Nôm có bản phiên âm đính kèm.<br />
