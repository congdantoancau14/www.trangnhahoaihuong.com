<h3>CHỮ NÔM và CÔNG VIỆC KHẢO CỨU CỔ VĂN VIỆT NAM</h3>



(Extrait du Bulletin général de l’Instruction publique, No 7,<br />
Mars 1942 – pp. 227-286: Le Chữ Nôm ou écriture démotique,<br />
son importance dans l’étude de l’ancienne litérature annamite.)<br />
<br />
<b>DƯƠNG QUẢNG HÀM</b><br />
Giáo-sư trường Trung-học Bảo-hộ Hà-nội<br />
<b>LÊ VĂN ĐẶNG chuyển dịch và phụ chú</b><br />
<br />
Trước khi người Tàu qua chiếm cứ nước Nam, chẳng biết dân Việt có hay không có một văn tự riêng để biểu thị tiếng nói bằng chữ viết. Ðây là một vấn đề nan giải bởi không còn dấu vết hay tài liệu gì cả. Dù sao, khi nước Nam giành lại nền độc lập sau một thời gian dài ngót 1050 năm (111 tcn –939 scn), chữ Hán đã du nhập lan tràn trong nước, trở thành văn tự chính thức, dùng trong trường học và các cuộc thi cử, trong sắc chỉ của vua, trong văn kiện hành chánh và luật lệ của triều đình. Khi các tác giả người Việt nghĩ đến việc soạn thảo tác phẩm bằng văn nôm quốc âm thì họ nhận thấy thiếu một văn tự riêng để diễn đạt tiếng quốc ngữ. Các vị này cần phải dùng chữ Hán để sáng tạo một hệ thống chữ viết hầu chuyển tả quốc âm: đó là chữ Nôm hay văn tự bình dân.<br />
<br />
<b>Ngày sáng tạo Chữ Nôm</b><br />
<br />
	“Chữ Nôm được sáng tạo từ bao giờ và do ai làm?” là một câu hỏi hiện chưa có câu trả lời dứt khoát vì thiếu tài liệu xác thực. Không ai dựa trên sự kiện Hàn Thuyên 韓 詮 là người đầu tiên làm thơ văn bằng ngôn ngữ Việt theo Ðường 唐 luật để kết luận rằng chính Hàn Thuyên đã sáng chế Chữ Nôm vào cuối thế kỷ thứ XIII. Ðó là một nghị luận thiếu căn cứ vững chắc, bởi các Niên giám Việt Nam chỉ ghi rằng Hàn Thuyên làm những bài thơ đầu tiên bằng Quốc âm, và chưa hề ghi rằng Hàn Thuyên đã sáng tạo chữ Nôm hoặc chữ Nôm chỉ phát hiện trong khoảng sinh thời của ông 2. Hiển nhiên Hàn Thuyên phải dùng chữ Nôm để soạn thảo các tác phẩm của ông; tuy vậy không có gì phủ nhận rằng chữ Nôm đã có trước ông.<br />
<br />
	Mặt khác, một sự kiện có trong Niên giám (Xem Cương mục, Ðoạn mở đầu, quyển 4, tờ 25b-26a) cho chúng ta tin tưởng rằng chữ Nôm có thể đã có trước thế kỷ thứ XIII. Vào cuối thế kỷ thứ VIII (791), nước Nam còn bị nhà Ðường đô hộ, một nhà lãnh đạo Việt Nam tên là Phùng Hưng 馮 興, sau khi đánh bại tên thái thú Tàu dạo đó, chiếm quyền Bảo hộ và cai quản xứ sở một thời gian ngắn. Dân chúng tôn vinh ông là “Bố cái đại vương 布 蓋 大 王” có nghĩa là “ông Vua, cha mẹ [của dân]”. Trong danh hiệu này có hai chữ Việt: bố (cha) và cái (mẹ). Vào thời đó, danh hiệu của vị nguyên thủ trong nước có hai chữ thuần túy Việt Nam không thể viết trực tiếp bằng chữ Tàu, ta phải có một hệ thống chữ viết riêng biệt để diễn tả hai danh từ này, và hệ thống chữ viết đó phải là chữ Nôm. Hiện nay, tài liệu ghi chép cổ nhứt về chữ Nôm là bản khắc nơi núi Hộ<br />
Thành 護 城 山 (tỉnh Ninh Bình) vào năm thứ 3 Thiệu Phong triều Trần Dụ Tôn (1343) trên đó có hai mươi tên làng bằng chữ Nôm (xem Bulletin de l’E.F.E.O., XII, 1, trang 7, số 1).<br />
 <br />
<b>Qui tắc kết hợp chữ Nôm</b><br />
<br />
	Chưa có ai khảo cứu tận tình về vấn đề này, cứ chủ trương rằng chữ Nôm không dựa vào quy tắc nhất định và mạnh ai nấy viết theo cách của mình. Tuy nhiên sự tình không phải vậy. Khi quan sát tỷ mỷ các bản Nôm, ta nhận thấy cách viết chữ Nôm rất có quy củ, các dòng sau đây sẽ chứng minh điều đó.<br />
<br />
Hệ thống chữ Nôm gồm có ba loại chữ:<br />
1) Chữ Hán dùng nguyên dạng;<br />
2) Chữ kết hợp hai chữ Hán;<br />
3) Chữ kết hợp một chữ Hán và một chữ Nôm.<br />
<br />
<b>I. Chữ Hán dùng nguyên dạng</b><br />
<br />
Các chữ này dùng để viết:<br />
<br />
1) Chữ Nôm gốc Hán có cùng âm đọc và cùng ý nghĩa với chữ tương ứng.<br />
Thí dụ: 	頭 đầu ; 袄 áo.<br />
<br />
2) Chữ Nôm gốc Hán còn giữ ý nghĩa, nhưng cách đọc có chút thay đổi.<br />
Thí dụ: 	chữ 外 có âm Hán Việt “ngoại” và âm Nôm “ngoài”;<br />
	chữ 法 có âm Hán Việt “pháp” và âm Nôm “phép”;<br />
	chữ 旗 có âm Hán Việt “kỳ” và âm Nôm “cờ”;<br />
	chữ 橋 có âm Hán Việt “kiều” và âm Nôm “cầu”.<br />
<br />
3) Chữ Nôm có thể là gốc Hán có cùng ý nghĩa với chữ tương ứng, nhưng cách đọc thay đổi rất nhiều.<br />
Thí dụ: 	chữ 捲 quyển = cuốn, Nôm đọc cuốn;<br />
	chữ 本 bổn = vốn, Nôm đọc vốn.<br />
<br />
4) Chữ Nôm có cùng ý nghĩa với chữ gốc, nhưng cách đọc khác hẳn.<br />
Thí dụ: 	chữ 役 dịch = việc nặng nhọc, Nôm đọc việc = nỗi khó nhọc;<br />
	chữ 味 vị = mùi, Nôm đọc mùi.<br />
<br />
<i>[Phụ chú: Các trường hợp 3 &amp; 4 khá thông dụng, gọi là đọc nghĩa, các âm Nôm<br />
là nghĩa của chữ Hán tương ứng].</i><br />
<br />
5) Chữ Nôm đọc như chữ Hán nhưng ý nghĩa lại khác hẳn.<br />
Thí dụ: 	chữ 戈 qua = cái giáo, Nôm đọc qua = đã xong;<br />
	chữ 沒 một = mất, Nôm đọc một = số 1;<br />
	chữ 朱 chu = sắc đỏ, Nôm đọc cho = đưa, trao;<br />
	chữ 箕 ky = đồ đan bằng tre để xúc đất, Nôm đọc kia = khác với này;<br />
[Phụ chú: Nôm còn đọc ky như trường hợp 1, cái ky dùng tải đất, cát gạch vụn v.v. ].<br />
<br />
<b>II. Chữ Nôm được kết hợp bằng hai chữ Hán.</b><br />
<br />
<b>A) Quy tắc:</b> Theo nguyên tắc này, mỗi chữ Nôm gồm có hai thành tố: một thành tố chỉ ý nghĩa và một thành tố chỉ âm đọc, âm đọc phải thật đúng hay gần đúng chữ dùng để chỉ âm.<br />
<br />
Thí dụ:<br />
1) 𠀧 ba (số 3) = (phần chỉ âm 巴 (ba)) + (phần chỉ nghĩa 三 (tam = ba));<br />
2) 𢬣 tay = (phần chỉ nghĩa 手 (thủ = tay)) + (phần chỉ âm 西 (tây));<br />
3) 𤾓 trăm(số 100) = (phần chỉ nghĩa 百(bách = trăm)) + (phần chỉ âm 林 (lâm));<br />
4)  ra = (phần chỉ âm  (la)) + (phần chỉ nghĩa 出 (xuất = ra)).<br />
<br />
<b>Vị trí chữ chỉ nghĩa</b><br />
<br />
	Các thí dụ trên cho thấy rằng vị trí của phần chỉ nghĩa thay đổi tùy trường hợp.<br />
<br />
	Theo nguyên tắc, phần chỉ nghĩa ở bên trái (thí dụ 2), vì lý do thẩm mỹ, phần này có thể đổi chỗ. Do đó, trong thí dụ 1, phần chỉ nghĩa ở bên phải chữ chỉ âm 巴, chữ này có móc dài bên dưới bọc trọn chữ 三 làm tăng vẻ đẹp của chữ 𠀧.<br />
<br />
	Trong thí dụ thứ 3 (𤾓), phần chỉ nghĩa xếp ở trên vì chữ 百 có dáng hẹp hơn chữ chỉ âm 林: hai chữ xếp “trên dưới” trông đẹp mắt hơn “trái phải”.<br />
<br />
	Trong thí dụ thứ 4 ( ), phần chỉ âm  (viết gọn chữ 羅) có 2 nét bên dưới có thể làm góc tù bọc trên chữ 出.<br />
<br />
	Tóm lại vị trí của phần chỉ nghĩa tùy thuộc vào vẻ thẩm mỹ của chữ, đôi khi trong cùng một chữ, phần này có thể thay đổi vị trí theo cách viết các nét: chữ trên đây có thể viết , trong đó nét cuối của chữ kéo dài bên dưới bọc trọn chữ .<br />
<br />
<b>Phần chỉ nghĩa là một bộ thủ</b><br />
<br />
	Các thí dụ kể trên cho thấy phần chỉ nghĩa có thể là một chữ Hán thông thường (các trường hợp 1, 3 và 4) hoặc một bộ thủ như trong thí dụ 2.  <br />
<br />
	Các bộ thủ thường dùng là:<br />
• 人 hoặc 亻(nhân / nhơn ) = người, dùng trong các chữ liên hệ đến người.<br />
Thí dụ: 	vãi 𠉜 = nữ tu Phật;<br />
		bõ 佈 = người tớ già [Hán đọc bố = khắp ; Nôm đọc bố = cha (không mượn nghĩa)].<br />
• 冫 (băng )= nước lạnh đong thành đá, dùng trong các chữ chỉ sự lạnh lẽo, tươi mát.<br />
Thí dụ:	ngắt 𠖯 = rất lạnh;<br />
	mát 𠖾 = hơi lành lạnh.<br />
• 口 (khẩu) = miệng, dùng trong các chữ có liên hệ đến miệng. <br />
Thí dụ: 	呐 nói = phát tiếng từ miệng [Hán đọc niệt, nột = nói ấp úng, la hét] ;<br />
		㗂 tiếng = âm thanh phát ra;<br />
		唁 ngon = ngon miệng [Hán đọc ngạn = viếng/hỏi thăm].<br />
• 土 thổ = đất, dùng trong các chữ chỉ vật dụng bằng đất. <br />
Thí dụ:	𡑓chum = hủ, lọ bằng đất nung;<br />
		𡎛 bùn;<br />
		𡑝 sân.<br />
• 女 nữ = gái, dùng trong các chữ thuộc phái nữ. <br />
Thí dụ:	姉 chị;<br />
		媽 mợ = vợ của cậu [Hán đọc ma, mụ = mẹ];<br />
		嬸 thím = vợ của chú [Nôm đọc nghĩa chữ thẩm = thím].<br />
• 心 hoặc 忄tâm = lòng, dùng trong các chữ tỏ cảm giác trong lòng người. <br />
Thí dụ: 	 mong = chờ, hy vọng [Hán đọc mông, mộng, Từ Hải 1180, u+E34F];<br />
		慳 ghen = đố kỵ [Hán đọc khan = keo kiệt, u+6173].<br />
• 扌hoặc 手 thủ = tay, dùng trong các chữ chỉ động tác dùng tay. <br />
Thí dụ:	扲 cầm = giữ bằng tay [chữ Hán mới u+6272];<br />
		𢯦 lay = làm rung động.<br />
• 日 nhật / nhựt = mặt trời, ngày, dùng để chỉ khoảng thời gian. <br />
Thí dụ:	𣅶 lúc = buổi, hồi, thời;<br />
		 trưa = buổi giữa ban ngày.<br />
• 木 mộc = cây, dùng để chỉ tên cây cối và vật dụng bằng cây. <br />
Thí dụ: 	槾 mận [chữ Hán mới u+69FE];<br />
		𣖖 chày.<br />
• 氵 thủy = nước, dùng để chỉ sự vật liên quan đến nước. <br />
Thí dụ: 	㳥 sóng;<br />
		沚chảy [Hán đọc chỉ = cù lao, bãi nhỏ giữa sông, u+6C9A].<br />
• 火 hoả = lửa, dùng để chỉ sự vật, tác dụng liên quan đến lửa. <br />
Thí dụ: 	𤌋khói;<br />
	𤈜cháy.<br />
• 疒 tật [thường đọc nạch] = bịnh, dùng để chỉ sự vật liên quan đến bịnh tật. <br />
Thí dụ: 	𤴪 ghẻ;<br />
	𤷒 tê [Hán đọc ty = tê liệt, u+24DD2];<br />
