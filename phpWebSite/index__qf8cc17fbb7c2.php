	𥄭 ngủ;<br />
	𥊚 mờ.<br />
• 石 thạch = đá, dùng để chỉ sự vật liên quan đến đá. <br />
Thí dụ:	𥗐 sỏi = đá nhỏ và nhẵn;<br />
	𥔦 vôi = đá nung.<br />
• 𥫗 trúc = tre, trúc, dùng để chỉ các dụng cụ bằng tre. <br />
Thí dụ:	篭 lồng = đồ đan bằng tre để nhốt chim, gà [Hán đọc lung = lồng; u+7C60] ;<br />
	𥵛 nong = nia lớn để phơi đậu, thóc v.v.<br />
• 糸 mịch = dây tơ, dùng để chỉ dụng cụ bằng vải, chỉ, sợi. <br />
Thí dụ:	𦀿 vải;<br />
	𦀊 dây;<br />
	𥿁 vướng.<br />
•月 hoặc 肉 nhục = thịt, dùng để chỉ bộ phận trong thân thể. <br />
Thí dụ:	𦛌 ruột;<br />
	𦟐 má = phần mặt ở hai bên miệng.<br />
