Thí dụ: 	蒙 muống = rau mọc dưới nước [Hán đọc mong = che; tối tăm; trẻ con, u+8499];<br />
	䓊 ngâu = cây có chùm hoa nhỏ thơm.<br />
• 虫 trùng = sâu, trùng, bò sát, nhuyễn thể v.v., dùng trong các chữ chỉ sinh vật thuộc<br />
loại này. <br />
