<b>Vị trí thông thường của bộ thủ.</b><br />
<br />
	Bộ thủ giữ vị trí thông thường: <br />
có khi ở bên trái (như 呐, nói),<br />
có khi ở bên phải (như 𩾷, quạ),<br />
có khi ở trên (như 𥵛, nong), <br />
có khi ở dưới (như 𢚸, lòng).<br />
<br />
<b>B) Ngoại lệ.</b><br />
<br />
	Quy tắc nêu ra trước đây có một ngoại lệ: trong một số chữ Nôm, các thành tố thay vì một chỉ ý nghĩa và một chỉ âm đọc, cả hai đều chỉ ý nghĩa. Trong chữ 𡗶 trời, cả hai thành tố “ 天 thiên = trời” và “ 上 thượng = trên” đều chỉ ý nghĩa của chữ .<br />
[Phụ chú: Tác giả bỏ sót ba trường hợp khi lập quy tắc kết hợp chữ Nôm:<br />
<br />
1. Cả hai thành tố đều chỉ nghĩa (thí dụ chữ 𡗶 trời trên đây xem như ngoại lệ);<br />
<br />
2. Cả hai thành tố đều chỉ âm (thí dụ chữ  ba);<br />
<br />
3. Ðọc nghĩa chữ Hán để mượn làm chữ Nôm (các thí dụ trong phần I : 卷  quyển, 本 bổn, 役 dịch, 味 vị, 戈 qua, 鱔 thiện).<br />
