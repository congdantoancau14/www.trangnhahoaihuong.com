<b>III. Kết hợp một bộ thủ chỉ ý và một chữ Nôm chỉ âm.</b><br />
<br />
Chữ 𠳒, “lời ” được kết hợp bởi bộ thủ 口 “khẩu ” chỉ ý và chữ Nôm 𡗶“trời ” gợi âm gần đúng “lời”. Các chữ thuộc loại này không nhiều.<br />
Rút gọn phần chỉ ý nghĩa.<br />
<br />
	Các thí dụ trên đây cho thấy chữ Nôm gồm một thành tố chỉ ý nghĩa và một thành tố chỉ âm đọc, ngoại trừ các thí dụ ở phần I. 4) và II. B [các chữ dịch, vị và trời].<br />
<br />
	Khi đọc các bản Nôm ta nhận thấy một số tác giả [hoặc người sao chép, khắc ván] đôi khi<br />
có khuynh hướng bỏ thành tố chỉ nghĩa và chỉ giữ lại thành tố chỉ âm. Do đó nhiều chữ chỉ có phần chỉ âm phải được sửa lại cho đủ hai thành tố nghĩa và âm.<br />
<br />
	Thí như chữ “ 󰄸  mành = màn để che” viết đúng là “ cân 巾(ý) + manh 萌 (âm)”<br />
nhưng phần chỉ ý bị bỏ sót chỉ còn có phần chỉ âm 萌  [Phụ chú: Tác giả ghi chữ 糸 (mịch)]<br />
<br />
	Tương tự, chữ “ 𣵰 lặn = hụp dưới nước” được viết bỏ phần chỉ ý “  氵 thủy” chỉ giữ phần chỉ âm “吝 lận” đọc là “lặn ” và dùng chữ này để chỉ luôn nghĩa.<br />
<br />
	Rất có thể “người sao chép, khắc ván”, muốn tranh thủ thời gian cho kịp kỳ in ấn, đã rút<br />
gọn các thành tố mà họ cho là ít cần thiết.<br />
Dạng thu gọn của một số chữ Nôm.<br />
<br />
	Cùng một lý nêu trên, các chữ Nôm có dạng thu gọn không thường thấy trong lối viết<br />
chữ thảo (草 字) của Tàu. Dạng thu gọn gồm hai loại: nguyên chữ Hán được vay mượn làm chữ Nôm hoặc chỉ mượn một thành tố để chỉ âm hay chỉ nghĩa.<br />
<br />
<b>Thí dụ thuộc loại 1:</b><br />
<br />
	Chữ “ 爲 vi” mượn nghĩa cho chữ Nôm “làm” được dùng dưới dạng thu gọn “  ”;<br />
	chữ “ 撞 chàng” mượn âm cho chữ Nôm “chàng = thiếu niên” được viết gọn “ 払 ”.<br />
<br />
<b>Thí dụ thuộc loại 2:</b><br />
<br />
	Chữ “時 thì, thời ” làm thành tố chỉ âm có dạng thu gọn “ 㝵 ” trong các chữ Nôm:<br />
“ 𣈗 ngày ”, “ 𠊛 người ”, “ 𧍋 ngài = thể bướm của tằm”.<br />
<br />
<i>[Phụ chú: Chữ “ 㝵 ” là chữ “ ngại”, không phải chữ “ 時 thì, thời ” viết gọn; chữ “ 礙  ngại” được viết gọn hai bực: 礙 → 碍 → 㝵 ].</i><br />
	Chữ “ 能 năng = có thể được” được viết dưới dạng Nôm thu gọn “  hay = giỏi”,<br />
phần chỉ âm phải là “ 𢪲 nâng = đưa lên”.<br />
<br />
<i>[Phụ chú: Thí dụ trên không rõ nghĩa, có thể người sao chép sai sót; xin mạn phép ghi<br />
lại như sau: Chữ “hay” hợp bởi thành tố chỉ ý “ 能 năng” hoặc “ 𢪲 nâng” và thành tố chỉ<br />
âm “ 台 thai”; thành tố chỉ ý được viết gọn  : hay = 台 thai (âm) +  năng (ý) →  ].</i><br />
<br />
<b>Chữ Nôm có giá trị như một hệ thống chữ viết.</b><br />
<br />
	Như chúng ta đã thấy, chữ Nôm dựa trên những nguyên tắc khá thuần lý và lập nên<br />
một hệ thống chữ viết có khả năng biểu thị các chữ của tiếng Việt một cách khá vững<br />
chắc. Chỉ cần định các quy tắc này một lần, xác định cách viết những chữ dễ bị lẫn lộn<br />
(các chữ đồng âm chẳng hạn), biên tập và phổ biến bảng mục lục / từ vựng ghi tất cả các<br />
chữ được thừa nhận. Các tác giả và người sao chép sẽ quy chiếu vào đó. Như thế chữ<br />
viết có tính cố định và chính xác rất cần thiết cho một hệ thống chữ viết. Bởi chữ Nôm<br />
không phải là một ngôn ngữ chính thức, nên Chính phủ không lưu ý đến vấn đề nêu trên,<br />
và không ai nghĩ đến công việc tu bổ cần yếu cho chữ Nôm. Ðiều đó giải thích được tại<br />
sao trong các bài viết bằng chữ Nôm có một số sơ sót và dở dang.<br />
Các khuyết điểm của chữ Nôm.<br />
<br />
Các khuyết điểm của chữ Nôm tìm thấy trong các bản in gồm có:<br />
<br />
<b>1o) Một tiếng được biểu thị bằng hai chữ Nôm khác nhau [chữ đồng nghĩa].</b><br />
Thí dụ [thành tố chỉ nghĩa khác nhau]:<br />
Chữ ruổi (chạy nhanh) được biểu thị bằng<br />
	𨇒 = túc 足 (ý) + lỗi 磊 (âm)  hoặc <br />
	𩧍 = mã 馬 (ý) + lỗi 磊 (âm).<br />
Thí dụ [thành tố chỉ âm khác nhau]:<br />
Chữ đốt (làm cháy bằng lửa) được biểu thị bằng<br />
	焠 = hoả  火 (ý) + tốt 卒 (âm) hoặc <br />
	炪 = hoả  火 (ý) + xuất 出 (âm).<br />
<br />
<b>2o) Một chữ Nôm đọc nhiều cách khác nhau.</b><br />
<br />
a) Ðồng âm: một nghĩa Hán Việt và một nghĩa thuần túy Việt Nam.<br />
	Thí dụ: chữ 買 có khi dùng như chữ Hán Việt với nghĩa “mua” (trong các từ:<br />
mãi biện, mãi lộ), có khi dùng như chữ Quốc ngữ “mãi” (trong các từ: làm<br />
mãi, chơi mãi).<br />
<br />
b) Ðồng nghĩa: một chữ với cách đọc theo Hán Việt và Quốc ngữ khác nhau.<br />
	Thí dụ: chữ 本 có khi biểu thị chữ “bản = vốn” (trong các từ: bản xã, bản thân), có khi biểu thị chữ “vốn” (trong các từ: vốn lãi, vốn là).<br />
<br />
c) Cùng một chữ nhưng đọc và thích nghĩa theo Hán Việt và Quốc ngữ khác nhau. <br />
	Thí dụ: Chữ “ 羣 quần = bầy” có khi đọc “quần” (trong các từ: quần thần, quần chúng), có khi đọc “còn” (trong các từ: hãy còn, còn lại); hai âm “còn” và “quần” gần giống nhau.<br />
<br />
d) Chữ có nhiều âm gần giống nhau. <br />
	Thí dụ: Chữ “ 買 mãi” dùng để chuyển tả “mãi = không dứt”, “mới = khác với cũ”, và “mấy = nhiều, bao nhiêu?”<br />
<br />
e) Một chữ có nhiều cách đọc (có cùng nguyên âm nhưng khác phụ âm đầu) với nghĩa khác 	nhau. Thí dụ: Chữ “ 油du = dầu” có hai âm Nôm: “dầu = chất lỏng cháy được” và <br />
	“rầu = buồn”.<br />
<br />
f) Chữ có cùng âm thanh nhưng khác âm điệu. <br />
	Thí dụ: Chữ “ 萌 manh = mọc mộng” đọc âm Hán Việt “manh = mọc mộng” và các âm Nôm “mành = mỏng, sạch”, “mảnh = miếng”, “mánh = mưu mẹo”.<br />
	Tương tự, chữ “ 吝 lận = hà tiện” đọc âm Hán Việt “lận = hà tiện” và các âm Nôm <br />
	“lần = chuyến, bận”, “lấn = xâm nhập”, “lẩn = tránh”.<br />
	Trong chữ Hán và chữ Nôm / Quốc ngữ, mỗi thanh có nhiều âm điệu ứng với chữ<br />
nghĩa khác nhau. Tiếng Tàu có năm thanh:<br />
1o) Thượng Bình thanh	上平聲	丁<br />
2o) Hạ Bình thanh		下平聲	廷<br />
3o) Thượng thanh		上聲		挺 𪔂<br />
4o) Khứ thanh		去聲		訂 定<br />
5o) Nhập thanh 		入聲.		嫡 敵<br />
	Tiếng Việt có tám thanh; mỗi thanh Thượng, Khứ, Nhập của Tàu được chia ra hai thanh Phù và Trầm [thanh Bình chia làm hai thanh, Tàu ghi Thượng Hạ, bực Thượng lẫn lộn với thanh Thượng, Việt ghi Phù Trầm rõ hơn Thượng Hạ của Tàu]. <br />
	Vậy tám thanh trong tiếng Việt là:<br />
					        [Thí dụ]   [Pinyin]  [Nôm]<br />
1o) Phù Bình thanh 		浮平聲	丁      	dīng    	đinh<br />
2o) Trầm Bình thanh 		沈平聲	廷      	tíng    	đình<br />
3o) Phù Thượng thanh 		浮上聲	挺	tǐng  	đĩnh	<br />
4o) Trầm Thượng thanh 	沈上聲	鼎	dǐng  	đỉnh<br />
5o) Phù Khứ thanh 		浮去聲	訂	dìng 	đính<br />
6o) Trầm Khứ thanh 		沈去聲	定	dìng 	định<br />
7o) Phù Nhập thanh 		浮入聲	嫡	dí 	đích (dấu ΄ , c, ch, p, t cuối)<br />
8o) Trầm Nhập thanh 		沈入聲	敵	dí 	địch (dấu . , c, ch, p, t cuối)<br />
	Bởi âm giai trong tiếng Việt phong phú hơn tiếng Tàu, nhiều khi không tìm được một chữ Tàu hợp đúng âm điệu để chuyển tả một tiếng Việt. Do đó chữ vay mượn chỉ thoả được âm thanh mà không cho đúng âm điệu. Ðiều này giải thích tại sao một chữ Hán dùng cho nhiều chữ Nôm cùng âm thanh nhưng khác âm điệu. Người xử dụng chữ Nôm nhận thức khiếm khuyết này nên thêm vào chữ vay mượn một ký hiệu để báo cho người đọc biết là chữ vay mượn có kèm theo ký hiệu phải được đọc với một âm điệu khác. Như vậy chữ “mốc” [trong “mốc meo”] với Phù Nhập thanh được chuyển tả bằng chữ Hán “mộc 木”, với Trầm Nhập thanh, thêm dấu nháy, trở thành “ 󰐣 ” [chữ mộc có dấu nháy phải đổi cách đọc từ âm điệu Trầm qua âm điệu Phù (Hán Việt không có âm “mốc”)].<br />
<br />
<b>Vai trò của chữ Nôm trong công tác truyền đạt các tác phẩm văn học Việt Nam.</b><br />
<br />
	Chúng ta biết rằng Quốc ngữ mới được truyền bá sau này, các tác phẩm thuần túy Việt Nam đều được sáng tác và phổ cập bằng chữ Nôm. Ngày nay, một số học giả, dù biết Quốc ngữ, cũng còn thích dùng chữ Nôm để sáng tác bằng ngôn ngữ Việt Nam. Mặc dù các thi phẩm xưa có nhiều bản Quốc ngữ, các bản Nôm vẫn còn bán được trong quảng đại quần chúng. Mặt khác, khá nhiều tài liệu hữu ích trong công cuộc khảo học về sử ký và phong tục nước nhà đều được viết bằng chữ Nôm.<br />
<br />
<b>Tầm quan trọng của chữ Nôm trong việc khảo học cổ văn Việt Nam</b><br />
<br />
	Rất nhiều tác phẩm văn học, nhứt là các tác phẩm còn trong cảo bản, chưa được phiên âm và phổ biến bằng Quốc ngữ. Hoặc trong số này phải có tác phẩm hữu ích đáng được biết đến và khảo học. Văn học sử Việt Nam chỉ được gọi là chân thực khi tất cả tài liệu này được tìm ra manh mối và phiên dịch. Phần khác, trong số các tác phẩm được phiên âm Quốc ngữ, phần lớn , ngoại trừ một số do các học giả chính trực và tận tâm, có dẫy đầy lỗi phiên dịch và lỗi chính tả, chưa kể lỗi do thợ in sắp sai tràn ngập bản văn. Ðiều này giải thích sự hiện diện của nhiều dị bản, đa số do phiên âm sai mà có. Muốn sửa chữa các lỗi lầm này và loại bỏ các dị bản sai lạc, cần phải quy chiếu vào các văn bản in hoặc cảo bản bằng chữ Nôm. Chỉ có việc sưu tập các văn bản này, xem xét tinh tế các dị bản khác nhau, khảo cứu, phê phán mỗi trường hợp đáng ngờ, mới tái lập được văn bản của tác giả. Ta không nói văn bản đích thực của tác giả -- vì điều này không thể thực hiện được trong tình thế hiện tại của các tài liệu chữ Nôm, các cảo bản gốc bị thất lạc và<br />
rất ít nguyên bản được thực hiện vào lúc sinh thời của tác giả và được tác giả tự tay sửa chữa -- mà chỉ nói một văn bản chính xác, gần với văn bản gốc nhứt.<br />
<br />
	Muốn làm công cuộc phê khảo các văn bản chữ Nôm, cần có một bảng từ vựng hay mục lục các chữ Nôm. Bảng từ vựng gồm hai phần: trong phần đầu, các chữ đã dùng được sưu tập, xếp thứ tự theo các bản in và theo bộ thủ, trong mỗi bộ thủ, chữ được xếp theo số nét theo lối của các tự điển Tàu. Các chữ được đánh số. Mỗi chữ có kèm theo chữ Quốc ngữ tương đương, các chữ trong các dị bản sẽ được chỉ dẫn.<br />
<br />
Trong phần thứ hai, tất cả từ ngữ được phiên ra Quốc ngữ xếp theo thứ tự abc kèm theo số quy chiếu chữ tương ứng.<br />
<br />
	Có được bảng từ vựng này, ta có thể tìm ra manh mối một cách dễ dàng và chắc chắn các văn bản viết bằng chữ Nôm. Mỗi khi gặp một chữ mà ta chưa biết cách đọc, ta sẽ tra phần một của bản từ vựng để tìm cách đọc này. Tương tự, khi so sánh một bản Quốc ngữ với một bản chữ Nôm, nếu gặp một chữ đáng ngờ, ta sẽ dùng phần hai của bảng từ vựng để tìm chữ chính xác tương ứng với chữ chuyển tả.<br />
<br />
	Do đó công việc chuyển tả các văn bản chữ Nôm có thể được thực hiện với mọi sự đảm bảo mong muốn. Ta tránh khỏi các lỗi lầm có thể làm sai lạc ý nghĩa của một câu thơ hay một câu văn. Chỉ trong điều kiện này, việc khảo cứu văn học cổ mới được dựa trên nền tảng vững chắc và được kết quả chắc chắn.<br />
<br />
<b>DƯƠNG QUẢNG HÀM</b><br />
