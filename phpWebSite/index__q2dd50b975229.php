<h3><h3>Chùa Trà Am và thơ Ưng Bình Thúc Giạ Thị</h3></h3>



<b>Nguyễn Hữu Vinh biên soạn</b><br />
<br />
<i>Bước vào chùa Trà Am, khách thập phương phải đi qua cầu Lược Ước. Cây cầu bây giờ đúc lại bằng Cement, bắt ngang dòng suối trước cổng chùa. Bên trái có trụ đá khắc ba chữ "Lược Ước kiều". Vòng quanh trước cổng chùa là khe nước ngoằn ngoèo. Tiếng nước chảy róc rách hoà với tiếng thông reo rì rào, vi vu là ấn tượng khó quên của du khách thập phương về ngôi chùa thơ mộng này.  	</i><br />
<br />
Đời Khải Định thứ 8 năm 1923 sư Viên Thành đặt viên đá đầu tiên xây cất lên chùa Trà Am và từ đó ngôi chùa trở nên một ngôi chùa danh tiếng của miền đế đô sông Hương núi Ngự. Chùa toạ lạc gần thôn An Cựu quận Hương Thuỷ, nằm trong vùng đất của dòng họ Nguyễn Khoa, khuất kín giữa núi đồi. Địa thế của vùng đất rất phù hợp cho cảnh chùa. Sau lưng là đồi núi thấp cao, trước mặt là suối nước róc rách, suốt ngày thông reo vi vút, gió lộng rì rào, chim muông rỉ rả. Khách trước khi đến chùa phải đi vào một con đường nhỏ ngoằn ngoèo uốn mình theo dòng suối , hai bên là rừng thông xanh vi vu, cảnh vật u trầm. Trước cổng chùa bắt ngang dòng suối nhỏ là một chiếc cầu tre lắt lẻo nối liền khuôn viên u tịch của chùa với thế giới bên ngoài. Chùa thấp đồi cao, soi bóng bên bờ suối, nấp mình trong rừng cây, trong những khóm hoa thơm cỏ lạ, trong rừng thông trùng điệp. Thật là một nơi lý tưởng cho những ai muốn để cho tâm hồn mình lắng đọng hoà hợp với thiên nhiên. Vào mùa hè oi bức, theo con đường ngoằn ngoèo bên suối vào đến cổng chùa, qua cầu Lược Ước xong là khách sẽ cảm thấy mát mẻ nhẹ nhỏm như bỏ lại đằng sau lưng bao nỗi ưu phiền của trần thế. Mùa thu mây mù vần vũ, gió rung xào xạc bên hàng cây làm cho lòng người nôn nao. Mùa đông lạnh lẽo, không gian thu nhỏ lại như chỉ còn sinh động trong khuôn viên chùa, nhưng khi mùa xuân trở về, hoa nở cười trong gió nhẹ, chim chóc líu lo chuyền cành trong không gian u tịch thì nơi đây chính là cõi tiên trong hạ giới. Cảnh chùa bốn mùa có những điểm thơ mộng khác nhau, nhưng cảnh đẹp nếu không có những tâm hồn đồng điệu, không có những tâm hồn thơ trong đó thì phong cảnh này chỉ là một cảnh rừng hoang dại mà thôi. <br />
   Thật vậy chùa Trà Am không những nổi tiếng vì phong cảnh, vì địa thế mà còn vì có những vị sư tru. trì nổi tiếng thơ văn . Kể từ lúc chùa mới thành lập, các vị sư trụ trì Viên Thành, Trí Thủ đều là các bậc tu hành nổi tiếng giỏi thi văn. Và quan trọng hơn là họ đều trong giới tao nhân mặc khách, giao du thân mật với các bậc quan quyền triều Nguyễn. Và chính hai vị sư này cũng xuất thân trong hàng thượng lưu. Sư Viên Thành là cháu chắc của dòng Định Viễn Vương thuộc phiên hệ họ Nguyễn Phước tộc. Chùa được cất trong phần đất của dòng họ Nguyễn Khoa, một đại vọng tộc ở Huế là nhờ Sư Viên Giác, thầy của Sư Viên Thành. Sư Viên Giác tên thật là Nguyễn Khoa Luận, từng làm Bố Chánh, là trụ trì chùa Ba La Mật ở Vĩ Dạ. Vì có những liên hệ đặc biệt như vậy, lại thêm phong cảnh, địa thế thuận tiện, không quá xa, không quá gần thành phố, thuận lợi cho những buổi họp thơ cho nên các vương tôn công tử triều Nguyễn hay các tao nhân mặc khách thường hay chọn nơi này làm nơi ngao du. Trong các vị tao nhân mặc khách, vương tôn công tử thường hay lui tới bàn bạc thơ văn với các sư trong chùa và còn lưu truyền thơ văn lại cho hậu thế như là Ưng Bình Thúc Giạ Thị, Nguyễn Khoa Tân, Nguyễn Khoa Kỳ...<br />
Thi ông Ưng Bình Thúc Giạ Thị, một nhà thơ lừng lẫy miền sông Hương núi Ngự, tác giả câu hò lừng danh:<br />
<br />
<i> "Chiều chiều trước bến Văn Lâu<br />
  ai ngồi ai câu ai sầu ai thảm<br />
  ai thương ai cảm ai nhớ ai trông<br />
  thuyền ai thấp thoáng bên sông<br />
  đưa câu mái đẩy chạnh lòng nước non.." <br />
</i><br />
Thi ông còn để lại khá nhiều sáng tác thơ chữ Hán liên quan đến chùa chiền và nhất là chùa Trà Am ở Huế. Vào năm 1934 sau khi vừa mới về hưu, sống tại Lộc Minh Đình ở Vĩ Dạ, Ưng Bình tổ chức một cuộc đi thăm đến các chùa vùng Tây Nam thành phố Huế. Lần này cùng đi có em trai là Thượng Thư Thúc Thuyên, và người anh em chú bác là Thượng Thư Quất Đình. Khi đến chùa Trà Am, Thượng Thư Quất Đình tức cảnh sinh tình làm ra trước một bài thơ, Ưng Bình liền trổ tài hoạ lại như sau:<br />
<br />
** Giáp Tuất cửu nguyệt giai thi hữu sơn du hựu phóng <br />
Tra Am. Hoạ Thương Thư Quất Đình tiên sinh xướng vận<br />
<br />
Vân hà vi trướng thụ vi liêm<br />
Hiểu sắc tình âm khứ phục chiêm<br />
Sơn thuỷ hữu tình ưng cọng thưởng<br />
Văn chương vô giá diệc phi liêm<br />
Phong lai ngũ nhạc minh tùng lãng<br />
Thu nhập không môn lãnh trúc diêm<br />
Thử nhật đăng cao đa bạn lữ<br />
Cúc bôi tức tuý hựu tần thiêm<br />
<br />
Dịch thơ<br />
** Tháng chín năm Giáp Tuất (1934) cùng các bạn thơ đi lên chơi núi ghé thăm chùa Trà Am. Hoạ thơ của Thương Thư Quất Đình xướng vần.<br />
<br />
Ráng chiều màn phủ cây rèm cửa<br />
Mưa, tạnh, hanh, sương đợi ngóng chờ<br />
Non nước hữu tình vui cảnh mộng<br />
Văn chương không giá quý nàng thơ<br />
Gió lùa tùng bách vang rừng núi<br />
Thu quạnh hiên tre lạnh cửa chùa<br />
Chơi núi hôm nay cùng bạn hữu<br />
Cứ châm thêm rượu cứ say sưa<br />
<br />
* <i>Chùa chữ Hán viết là Tra Am, nhưng dân Huế thường gọi là chùa Trà Am</i>.<br />
<br />
  Liền ngay sau đó, Thượng Thư Thúc Thuyên cũng nổi hứng làm một bài song thất bát cú ca tụng phong cảnh. Ưng Bình theo nguồn thơ dào dạt và hoạ tiếp bài thơ kia của Thúc Thuyên:<br />
<br />
** Hựu tiền đề. Hoạ Thượng Thư Thúc Thuyên hiền đệ xướng vận<br />
<br />
Sơn ngoại thanh sơn hựu kỷ trùng<br />
Hoành khâm nhất vọng hướng thanh không<br />
Đăng cao vị đáo tằng loan thượng<br />
Điếu cổ hoàn lai Tiêu Tự (1) trung<br />
Tháp ngoạ Tỳ Khưu nhân dĩ miểu <br />
Kiều danh Lược Ước lộ do thông<br />
Hoa hương thụ ảnh tầm u xứ<br />
Thuỳ thức Tra Am Phật Tử công<br />
	<br />
1) Tiêu tự: chỉ chùa chiền nhà Phật<br />
<br />
Dịch thơ<br />
** Tiếp theo đề bài trước. Hoạ thơ của em là Thương Thư Thúc Thuyên.<br />
<br />
Lớp lớp xanh xanh núi chập chùng<br />
Che ngang tà áo ngước trời trong<br />
Trèo cao núi nọ chưa leo tới<br />
Hoài cổ chùa đây lại đến cùng<br />
Có tháp Tỳ Kheo người đã vắng<br />
Đây cầu Lược Ước (1)lối đà thông<br />
Hương hoa cây cảnh nơi u tịch<br />
Phật tử dày công ai biết không<br />
<br />
1) Cầu Lược Ước bây giờ đúc bằng Cement, bắt ngang dòng suối trước cổng chùa Trà Am. Bên phải có trụ đá khắc ba chữ "Lược Ước kiều".  <br />
<br />
Hoạ xong hai bài thơ của hai thi hữu, thi ông Ưng bình Thúc Giạ thi hứng dâng trào nên cũng đã ra tay "mầng" một bài như sau để đáp lại mối tình thơ của các bạn:<br />
<br />
** Hựu tiền đề. <br />
Tự xướng<br />
<br />
Tao ông ứng dữ ngã đồng đăng<br />
Lộ nhập Tra Am sơn kỷ tằng<br />
Lãm thắng tối nghi vô sự khách<br />
Luận thi dĩ hoán cựu thì tăng<br />
Cọng khuynh cúc tửu hoài Nguyên Lượng<br />
Cánh bã thù nang học Thiếu Lăng<br />
Du hứng hựu phùng thu khí sảng<br />
Cao ngâm phủ xướng trợ bằng lăng<br />
<br />
Dịch thơ<br />
<br />
** Tiếp theo đề bài trước. Tự mình xướng vần trước<br />
<br />
Cùng thăm cảnh núi với thi ông<br />
Đường tới Tra Am núi chập chùng<br />
Ngắm nghía khách nhàn thêm hứng tthú<br />
Ngâm nga sư mới lại vui cùng<br />
Nhớ chàng Nguyên Lượng say bầu rượu<br />
Học kẻ Thiếu Lăng lựa nhánh bông<br />
Dạo bước khi trời thu mát mẻ<br />
Trời cao bát ngát hát thêm nồng<br />
<br />
* Nguyên Lượng là tên tự của Đào Tiềm<br />
* Thiếu Lăng là tên tự của Đỗ Phủ<br />
<br />
 Cuộc đời của thi ông Thúc Giạ đầy thi vị, với tài thi văn tuyệt diệu, thi ông đã để lại cho đời sau nhiều sáng tác thi ca tuyệt vời cả thơ chữ Nôm, thơ chữ Hán, hò Huế lẫn ca Trù. Phong cảnh thiên nhiên và chùa Huế đã đóng một vai trò rất quan trọng trong công việc sáng tác của thi ông. <br />
<br />
(Tác giả cám ơn nhà thơ Tôn Nữ Hỷ Khương, ái nữ của thi ông Ưng Bình Thúc Giạ Thị đã cung cấp tài liệu và cho phép trích dịch)<br />
