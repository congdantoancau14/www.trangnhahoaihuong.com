<h3>Parle-moi de ma mère!</h3>



Carmen là một vở nhạc kịch gồm 4 hồi, do nhạc sĩ Bizet soạn, dựa theo truyện dài cùng tên của nhà văn Pháp Prosper Mérimée. Về mặt âm nhạc, Bizet đã rất thành công; Carmen là một trong những vở nhạc kịch xuất sắc nhất từ trước đến nay, đúng như lời nhạc sĩ Traikovski tiên đoán, khi ông được nghe nó lần đầu: <i>"...Carmen sẽ là một tác phẩm nổi tiếng ở Pháp và trên khắp thế giới."</i><br />
<br />
Câu chuyện xảy ra ở Tây Ban Nha, vào khoảng năm 1820. José là một chàng trai sinh trưởng ở một làng quê xa xôi xứ Navare (Tây Ban Nha). Sau một cuộc xô xát, chàng rời bỏ quê hương lên đường nhập ngũ ở thành Séville, bỏ lại mẹ già và cô gái Micaëla dễ thương, dịu hiền - vợ chưa cưới của chàng.<br />
<br />
Ở thành Séville, chàng hết sức cảnh giác với sự cám dỗ của các cô gái làm việc trong xưởng thuốc lá bên cạnh. Một hồi chuông vang lên, và các cô công nhân xuất hiện. Các anh lính trẻ xúm lại cười đùa với các cô, trong lúc José tỏ ra thờ ơ. Bỗng, Carmen xuất hiện - đỏm dáng và hấp dẫn. Nàng cất tiếng hát bản "Habanera" nổi tiếng của mình ("Tình yêu là một đứa trẻ hoang..."). Vừa hát, nàng vừa ném cho José chiếc bông giắt trên ngực. José rúng động và bàng hoàng.<br />
<br />
Vừa lúc đó, Micaëla xuất hiện, mang cho chàng lá thư của mẹ già và âu yếm trao cho chàng nụ hôn của mẹ già gởi cho chàng...<br />
<br />
"Parle-moi de ma mère" là một trích đoạn trong vở nhạc kịch dài 4 hồi này. Bài hát thể hiện một nỗi nhớ thương, hoài niệm tha thiết, dạt dào về quê hương và tuổi ấu thơ, nơi có người mẹ hiền yêu dấu đang mong ngóng con từng ngày.<br />
<br />
<br />
--------------------<br />
Micaëla se hausse un peu sur la pointe des pieds et donne à José un baiser bien franc, bien maternel. Don José très-ému la laisse faire. Il la regarde bien dans les yeux. ­ Un moment de silence. <br />
<br />
<b>José:</b> continuant de regarder Micaëla<br />
<br />
Ma mère, je la vois!.. oui, je revois mon village!<br />
O souvenirs d'autrefois! doux souvenirs du pays!<br />
Doux souvenirs du pays! O souvenirs chéris!<br />
O souvenirs! O souvenirs chéris,<br />
vous remplissez mon coeur de force et de courage!<br />
O souvenirs chéris! Ma mère, je la vois,<br />
Je revois mon village!<br />
<br />
<b>Micaëla:</b><br />
Sa mère, il la revoit! Il revoit son village!<br />
O souvenirs d'autrefois! Souvenirs du pays!<br />
Vous remplissez son coeur de force et de courage!<br />
O souvenirs chéris! Sa mère, il la revoit,<br />
Il revoit son village!<br />
<br />
<b>José:</b> les yeux fixés sur la manufacture [à lui-même]<br />
Qui sait de quel démon j'allais être la proie!<br />
[recueilli]<br />
Même de loin, ma mère me défend,<br />
Et ce baiser qu'elle m'envoie,<br />
[avec élan]<br />
Ce baiser qu'elle m'envoie,<br />
Ecarte le péril et sauve son enfant! <br />
<br />
<b>Micaëla:</b>:[vivement]<br />
Quel démon? quel péril? je ne comprends pas bien...<br />
Que veut dire cela? <br />
<br />
<b>José</b>:<br />
Rien! rien!<br />
Parlons de toi, la messagère;<br />
Tu vas retourner au pays? <br />
<br />
<b>Micaëla:</b><br />
Oui, ce soir même... demain je verrai votre mère. <br />
<br />
<b>José:</b> [vivement] [Note 14]<br />
Tu la verras! Eh bien! tu lui diras:<br />
Que son fils l'aime et la vénère<br />
Et qu'il se repent aujourd'hui.<br />
Il veut que là-bas sa mère<br />
Soit contente de lui!<br />
Tout cela, n'est-ce pas, mignonne,<br />
De ma part, tu le lui diras!<br />
Et ce baiser que je te donne,<br />
De ma part, tu le lui rendras!<br />
Il l'embrasse. <br />
<br />
<b>Micaëla:</b> [simplement]<br />
Oui, je vous le promets... de la part de son fils,<br />
José, je le rendrai, comme je l'ai promis. <br />
<br />
<b>José:</b><br />
Ma mère, je la vois!.. oui, je revois mon village!<br />
O souvenirs d'autrefois! doux souvenirs du pays!<br />
Doux souvenirs du pays! O souvenirs chéris!<br />
O souvenirs! O souvenirs chéris,<br />
Vous remplissez mon coeur de force et de courage!<br />
O souvenirs chéris! Ma mère, je la vois,<br />
Je revois mon village!<br />
Je te revois, ô mon village!<br />
Doux souvenirs, souvenirs du pays!<br />
Vous remplissez mon coeur de courage,<br />
O souvenirs, ô souvenirs chéris!<br />
<br />
<b>Micaëla:</b><br />
Sa mère, il la revoit! Il revoit son village!<br />
O souvenirs d'autrefois! souvenirs du pays!<br />
Vous remplissez son coeur de force et de courage!<br />
