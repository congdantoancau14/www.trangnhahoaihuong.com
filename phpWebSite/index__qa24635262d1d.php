<h3>Điểm sách Khói Sóng Trên Sông</h3>


<b>ĐÀM TRUNG PHÁP</B><br />
Giáo Sư Ngữ Học<br />
Texas Woman's University<br />
<br />
ĐIỂM SÁCH:<br />
KHÓI SÓNG TRÊN SÔNG<br />
Của nhà văn Nguyễn Văn Sâm<br />
Tổng phát hành: Nhà Sách Văn Nghệ<br />
9351 Bolsa Avenue, Westminster, CA 92683<br />
Năm xuất bản: 2000, Ấn phí: 14 Mỹ kim<br />
<br />
Tôi vẫn thường cảm tạ ông Trời đã rộng lượng ban cho tôi một số bạn hiền, và nay đang bước vào lứa tuổi  “nhĩ thuận” biết theo mệnh trời một cách ngoan ngoãn, tôi lại càng thêm trân quý những người bạn hiền đó. Một trong những người bạn này là nhà văn Nguyễn Văn Sâm, một người đồng niên, đồng nghiệp, và đồng thanh khí của tôi. Trước 1975 ở Saigon, khi anh Sâm dạy Việt văn tại Đại Học Văn Khoa  thì tôi dạy Anh văn tại Đại Học Sư Phạm, chỉ nghe tiếng nhau và ít khi gặp mặt. Năm 1979, khi nỗi nhớ quê hương còn canh cánh bên lòng, tôi thực hạnh phúc được gặp lại anh Sâm tại San Antonio và “mách nước” cho anh đôi điều trong buổi ban đầu anh đang hội nhập vào cuộc đời mới. Tôi vui mừng theo rõi sự thành công của anh trong hai thú vui thanh cao là dạy học và viết văn nơi đất khách. Anh là người Nam, tôi là người Bắc di cư vào Nam năm 1954, nhưng sự khác biệt quê quán chỉ làm tình bạn chúng tôi thêm đậm đà. <br />
<br />
          Cốt nhà giáo, anh Sâm chân phương lắm. Ngay tựa đề KHÓI SÓNG TRÊN SÔNG anh lựa cho tập truyện, lấy ý trong câu chót của bài thơ Đường tráng lệ nhưng cũng buồn ngút ngàn  mang tên “Hoàng Hạc Lâu” của Thôi Hiệu, “Yên ba giang thượng sử nhân sầu”,  đã đủ cho người đọc biết rằng đây không phải là những đề tài vui nhộn xem xong rồi bỏ, mà là những mẩu chuyện buồn  rất thấm thía về cuộc đời tại quê hương cũng như tại miền đất tạm dung  mà có lẽ tất cả chúng ta đều cảm thông được. Truyện nào cũng độc đáo, cũng để lại trong tâm tư tôi một niềm ray rứt lạ kỳ, khiến tôi không thể không thử  “đặt” thân phận mình vào những trạng huống ấy xem sao, để rồi thấy mình may mắn hơn người ta và nhìn cuộc đời dưới một ánh mắt tích cực hơn. Như số phận của một chàng thanh niên què quặt, mặc cảm ngập trời về thân thể của mình mà lại luôn luôn thèm khát xác thịt đàn bà, cuối cùng an phận chịu lấy một phụ nữ đã mang bầu với kẻ khác (“Như Nước Trong Nguồn”). Như nỗi đoạn trường trong biết bao gia đình tỵ nạn mưu sinh tối tăm mặt mũi mà lại có cha mẹ già yếu đòi hỏi phải chăm sóc từng giây từng phút, nhất là khi các cụ bị lú lẫn và không còn tự lo được chuyện vệ sinh thân thể (“Mát Lạnh Tuổi Vàng”). Như sự ân hận to lớn và thành khẩn của một người đàn ông Việt đã nghi ngờ và làm hại một ân nhân dị chủng của mình (“Ông Già Noel Có Thật”). Như chuyện một thiếu nữ Việt tỵ nạn buồn chán gia đình, giao du với một người đàn ông Mỹ bất hảo, bị hắn bỏ thuốc ngủ vào nước uống rồi hiếp dâm (“Người Bí Mật Chiêm Ngưỡng”). Như  tệ trạng “gái bao” của các già dịch Việt kiều về nước (“Hương Cỏ”).  Như ước mơ được trở về  với nếp sống quê cũ của chị gái và em trai sau khi đã chán ngán mảnh đời tạm dung: chị thì bị hải tặc hãm hại trên đường vượt biên, em trai thì bị cô vợ trẻ dị chủng đã có bầu cho mọc sừng (“Khói Sóng Trên Sông”), vân vân.  Nói theo ngôn ngữ phê bình văn học phương Tây, nhà giáo kiêm nhà văn Nguyễn Văn Sâm đã dùng mô thức “mảnh đời” (“tranche de vie”) để xây dựng cốt truyện, một mô thức mà Guy de Maupassant trong văn học Pháp đã sử dụng tuyệt luân để nói lên những nỗi oái oăm, những điều dị hợm trong cuộc sống thường nhật.<br />
<br />
          Là một nhà giáo văn chương đã nghiên cứu nhiều về truyện ngắn quốc tế, anh Sâm rõ rệt đã nắm vững được những yếu tố cần thiết  để thành công trong loại văn chương này. Truyện nào của anh cũng được xây dựng vững vàng, cũng có một cao điểm tức là lúc một sự thực-bất kể xấu hay tốt -- được soi sáng, cũng đầy động tác trong lớp lang, cũng đầy những tình tiết lý thú, khiến người đọc không bị hụt hẫng hoặc nhàm chán. Anh Sâm không lập dị, không huyền bí, không làm dáng, không lãng mạn, nhưng ngòi bút tả chân của anh thì khủng khiếp lắm mỗi khi anh thấy cần thiết phải vung tay. Hãy nghe anh nói về nỗi chán chường của một phụ nữ đẹp người đẹp nết mang tên Chuyên phải hầu bàn trong một tiệm ăn tại “Saigon Nhỏ” bên California :  <I>“Những khuôn mặt mang nụ cười nham nhở. Những hàm răng cáu bợn thức ăn. Những hơi thở nồng hơi bia xú với thực phẩm chưa kịp tiêu hóa, tạo thành mùi cám heo lâu ngày, chuyển mùi. Chuyên muốn gạt phắt những chúng sinh lô nhô chung quanh sang một bên để chạy mau về phòng mình nằm sãi tay thở những hơi dài trút hết những ưu sầu, chán chường ra khỏi tâm tư.”</I>  Hoặc đoạn anh cho người thanh niên tật nguyền diễn tả nỗi mặc cảm của mình:  <I>“Chứng kiến tụi nó ỡm ờ trao tình bằng miệng hò mắt liếc, tôi khoái lỗ tai thì có mà bằng bụng thì không. Tôi nhớ tới tấm thân tôi. Con trai khi dễ coi như chẳng cùng loài cùng lứa, kiểu thằng Lai, thằng Chệt nào lạc loài trong xóm. Con gái đi ngang qua không đứa nào cần biết tôi đứng đó, đương có mặt, chúng ngó thẳng vô mặt tôi mà chẳng thấy mắc cỡ bối rối, trong khi đó đối với mấy thằng khác cỡ tuổi tôi, mấy con nhỏ này thường khi hành động kiểu như bị hớp hồn: quýnh quáng, tiếng được tiếng mất, cà-lăm cà-lập, vuốt vuốt tóc, kéo kéo áo, đỏ mặt cúi đầu ngó ngó xuống chưn ... thấy mà phát nực.”</I><br />
<br />
          Dấu ấn mô phạm của anh Sâm còn rõ lắm trong văn chương của anh, như tôi đã ám chỉ ở trên. Anh chừng mực, anh khoan dung, anh gián tiếp khuyên bảo người đời nên tránh điều ác (vì “ác giả ác báo”) và chấp nhận cuộc đời, anh đề cao những cái đẹp quê hương mộc mạc, anh ngợi ca những mẫu người đảm đang, tử tế (như  Cô Út trong “Tình Đất” hoặc người con dâu hiếu hạnh trong “Mát Lạnh Tuổi Vàng”). Phải chăng truyền thống “văn dĩ tải đạo” đã thôi thúc anh viết lên hai truyện nặng phần “ngụ ngôn” là “Ông Già Noel Có Thật” và “Biển Trời Lai Láng” trong tập truyện KHÓI SÓNG TRÊN SÔNG?<br />
<br />
          Là một cá nhân thiết tha học hỏi ngôn ngữ, tôi rất yêu tiếng Việt miền Nam. Và khi đọc văn  của anh Nguyễn Văn Sâm, tôi không khỏi ngầm so sánh anh với hai nhà văn người Nam khác là Sơn Nam và Lê Xuyên mà tôi cũng ưa thích. Ngôn ngữ “miệt vườn” của anh Sâm coi bộ ngộ nghĩnh và nhiều mầu sắc  không thua gì Sơn Nam trong “Hương Rừng Cà Mau” đâu. Và anh Sâm, có lẽ cũng vì gốc nhà giáo chăng, không đi quá trớn như Lê Xuyên trong cái “ép-phê” làm người đọc phải nóng ran người trong các đoạn văn khêu gợi dục tình. Quý vị nào đã đọc “Chú Tư Cầu” hoặc “Rặng Trâm Bầu” của Lê Xuyên thì sẽ đồng ý với tôi là Nguyễn Văn Sâm còn “nhẹ tay” lắm trong lãnh vực này. Cho phép tôi đóng vai phân tích gia tâm lý “tài tử” một chút ở đây nhé. Khi chúng ta sùng bái quá độ một vật gì hoặc một điều gì thì khoa tâm lý học Tây phương gọi vật đó hoặc điều đó là một “fétiche” (tiếng Pháp) hoặc “fetish” (tiếng Anh). Người Tàu dịch chữ đó là “ngẫu tượng” hoặc “linh vật.”  Đàn ông Mỹ thường hỏi đùa nhau, “Hey, what kind of man are you? A breast-man or a leg-man?” , tức là họ muốn biết ngẫu tượng của nhau trong lãnh vực tình dục: bộ ngực hay cặp giò. Qua tập truyện KHÓI SÓNG TRÊN SÔNG, tôi nghĩ văn hữu Nguyễn Văn Sâm của chúng ta có một ngẫu tượng lồ lộ: đó là bộ ngực nở nang của phụ nữ. Nói theo kiểu Mỹ, he is definitely a breast-man.  Này nhé, trong truyện “Tình Đất” có đoạn thằng Thìn nói về con Cúc như sau: <i>“Con Cúc trổ mã cả năm nay, tay chưn tròn trịa, vú dậy đội lớp áo lên cao nghệu dòm ngang thấy trơn láng mềm mềm ra vẻ con gái quá chừng.”</i>  Rồi ở trong truyện “Như Nước Trong Nguồn”,  anh chàng tật nguyền mê con Nhàn, thú thực:  <i>“Ngồi trong nhà thấy nó thấp thoáng bên kia, ngực một ngực, lồ lộ thiếu điều căng xé áo nhảy ra ngoài, tôi cũng đã cảm nhận nỗi vui vui tràn ngập lòng, đời thiệt thòi như được trút bớt vài phân.”</i>  Chưa hết đâu, trong truyện “Ông Già Noel Có Thật”, một ông Việt Nam mơ tưởng đến cái ngẫu tượng đó nơi một bà gốc Mỹ Châu La Tinh như thế này mới khiếp chứ:  <i>“Và rồi tôi nhớ tới hình dáng bờ ngực đầy đặn của Rachel. Bờ ngực có lần tôi bồm xôm tán nhảm là bệ chưng thánh giá đẹp nhứt trần ai.”</i><br />
<br />
          So với cái ngẫu tượng nóng bỏng của anh Sâm trong KHÓI SÓNG TRÊN SÔNG thì cái ngẫu tượng của tôi trong bài viết này hiền lành hơn nhiều: tôi sẽ nói đến cái mức hấp dẫn của “ngôn ngữ miệt vườn” mà anh Sâm sử dụng trong tập truyện. Thiên kiến này cũng dễ hiểu thôi, vì cả đời tôi đã mê say ngôn ngữ, như đã nói ở trên.  Tôi học trung học tại  Saigon và khoái chí đã học thêm được phương ngữ (dialect) Saigon. Tôi thích nhất là các thành ngữ, các đặc ngữ trong Nam. Nghe khoái tai làm sao, vừa tượng hình vừa tượng thanh, vừa chân chất chi lạ!  Tôi thường so sánh cách diễn tả thân mật (colloquial) giữa phương ngữ mẹ đẻ của tôi (Hà Nội) và phương ngữ Saigon, dùng ngay một anh bạn thân  rất dễ thương người Nam cùng lớp để tra cứu và phối kiểm. Chẳng hạn, tôi hỏi anh diễn tả từ ngữ “đi thọt chân” bằng tiếng Nam ra sao thì anh cười tươi và nói là “đi cà thọt cà thọt”. Thế còn đi với giáng điệu nghiêng nghiêng thì nói làm sao đây? Thì là “đi xà-niễng xà-niễng chớ sao.” Lớn bằng chừng này này thì nói làm sao?  Anh ra hiệu bằng hai bàn tay và nói gọn lỏn “bi bự nè!”  Có lần tôi đến nhà anh chơi, anh hỏi tôi muốn uống nước gì để anh lấy. Tôi nói “cho mình một cốc nước chanh quả vắt.”  Anh trả lời, “cái đó trong Nam  kêu là một ly đá chanh, sẽ có ngay cho bồ!”  Và cứ như vậy tôi học thêm và sử dụng ngay loại phương ngữ hấp dẫn ấy với các bạn bè người Nam. Tôi tưởng tôi đã khá thành thạo, nhưng khi đọc KHÓI SÓNG TRÊN SÔNG của anh Sâm thì tôi thấy còn phải học thêm nhiều. Tập truyện của anh là cả một rừng thành ngữ bình dân, nghe lên thì khoái tai mà đọc tới thì sướng mắt! Những thành ngữ này không thể tìm được trong tự điển nào cả, nhưng may thay ngữ cảnh (context) của các đoạn văn đã giúp tôi hiểu được ý nghĩa của chúng.  Sau đây là một vài thí dụ điển hình. Trong truyện “Theo Gót Huyền Trân” : <i>“Trong mấy năm chị nầy đập bầu liền xì bốc. Mang  bầu lạch ạch cũng bò ra chợ, mới đẻ hôm kia cũng te te đi bán, bỏ lún mấy đứa nhỏ ở nhà khóc lòi rún, mặt mũi tèm lem tuốt luốt, sống chết phó thác cho trời khỏi cần cột niệt.” </i>Trong truyện “Tình Lụy Thiên Thu”:  <i>“Mèo chuột, tò tí te thì mấy chị có con chuột Tàu trong bụng, phải không ngoại?”</i>  Và trong “Tình Đất”:  <i>“Thét rồi nó tới chà-lết quết-xảm ở nhà tôi, gặp thì chỉ chào sơ sơ rồi quay ra tíu ta tíu tít với con Út.”</i><br />
<br />
          KHÓI SÓNG TRÊN SÔNG là một thành công văn chương của một nhà giáo kiêm nhà văn rất khả ái của chúng ta tại hải ngoại. <br />
<br />
