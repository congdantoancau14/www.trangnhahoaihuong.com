<h3>Mất chiếc khăn quàng cổ</h3>



Xuống xe quên chiếc khăn quàng,<br />
Hàng len màu biển, cô nàng tặng xưa.<br />
Sương mờ, tuyết đổ, gió mưa,<br />
Ba vòng quanh cổ nghe thừa ấm êm.<br />
Paris giá buốt bên thềm,<br />
Không khăn quàng bỗng nghe mềm lòng ai.<br />
Tình xưa hỏi có lạt phai,<br />
Khăn không còn nữa nhân hai lạnh lùng.<br />
Bây giờ nhớ mối tình chung,<br />
Đâu khăn quàng cũ nghe trùng dây tơ.<br />
Cashmere chút ơ hờ,<br />
Xin thương sợi dệt bài thơ nửa vời.<br />
Bao nhiêu châu báu trên đời,<br />
Cũng còn bỏ hết tiếc lời nhớ thương.<br />
