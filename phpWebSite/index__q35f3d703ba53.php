<h3>Đóa hoa hồng </h3>



<table cellpadding = "10"> <tr> <td>
Dưới mái nhà ngói xám<br />
Ngang cửa sổ mây bay<br />
Sách vở bày tứ phía<br />
Con chăm chỉ mỗi ngày<br />
 <br />
Trên xà nhà cột gỗ<br />
Treo ba đóa hoa hồng<br />
Đỏ thắm màu máu đỏ<br />
Hình tượng mẹ trong lòng<br />
 <br />
Xa xôi hàng nghìn dặm<br />
Mẹ tuổi già long đong<br />
Hôm qua tin nhạn đến<br />
Mẹ giã đời thong dong </td>
 <br />
<td>Thầm đọc câu bát-nhã<br />
Rằng sắc tức thị vô<br />
Không giọt nào lã chã<br />
Đưa tiễn mẹ mắt khô<br />
 <br />
Gỡ ba hoa hồng đỏ<br />
Đặt trên khối pha lê<br />
Khắc hình chim ngậm lá<br />
Con dìu mẹ đi về<br />
 <br />
Những mùa vu lan tới<br />
Nếu con có đi chùa<br />
Cổng vào phát hoa trắng<br />
Là bóng mẹ hiền xưa </td></tr></table>
