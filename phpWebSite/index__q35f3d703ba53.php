<h3>Sóng lụa Hà Ðông</h3>



Ðây đất Hà Ðông xứ lụa là<br />
Em mua vài thước món quà xa<br />
Nắng ở Bắc Hà oi ả lắm<br />
Chẳng mát dẫu là thơ Nguyên Sa<br />
 <br />
Tôi đứng bơ vơ hỏi cụ già<br />
Xóm làng chuyển đổi những thời qua<br />
Vẫn biết bóng hình là bọt bể<br />
Mơ hồ tay níu áng mây qua<br />
 <br />
Lụa này em để biếu mẹ ta<br />
Xanh huyền màu áo mẹ ưa mà<br />
Làng xưa giờ đã tan hình bóng<br />
Lụa mềm sóng sánh chút âm ba ...<br />
