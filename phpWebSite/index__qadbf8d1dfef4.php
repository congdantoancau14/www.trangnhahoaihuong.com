<h3>Hựu tiền đề- Giáp Tuất cửu nguyệt giai thi hữu sơn du hựu phỏng Tra Am, Tự xướng" </h3>



Tự xướng<br />
<br />
Tao ông ứng dữ ngã đồng đăng<br />
Lộ nhập Tra Am sơn kỷ tằng<br />
Lãm thắng tối nghi vô sự khách<br />
Luận thi dĩ hoán cựu thì tăng<br />
Cọng khuynh cúc tửu hoài Nguyên Lượng (1) <br />
Cánh bả thù nang học Thiếu Lăng (2)<br />
Du hứng hựu phùng thu khí sảng<br />
Cao ngâm phủ xướng trợ bằng lăng<br />
<br />




<h3>Tiếp theo đề bài trước</h3>



Tự mình xướng vần thơ<br />
<br />
<br />
Các ông nhà thơ nên cùng ta đi chơi lên núi<br />
Ðường vào Tra Am núi non chập chùng<br />
Ði xem thắng cảnh là thích hợp nhất cho khách nhàn hạ<br />
Bàn bạc về thơ đã có sư  mới tiếp đón<br />
Cùng uống rượu cúc lại nhớ Nguyên Lượng<br />
Cũng học Thiếu Lăng đem theo giỏ hái cỏ thuốc Thù Du<br />
Thú đi chơi lại gặp lúc mùa thu khí trời mát mẻ<br />
Ngâm vang hát lớn cho hợp với cảnh trời hùng vĩ<br />
<br />




<h3>Tiếp theo đề bài trước</h3>



Tự mình xướng vần thơ<br />
<br />
Cùng thăm cảnh núi với thi ông<br />
Ðường tới Trà  Am núi chập chùng<br />
Ngắm nghía khách nhàn thêm hứng thú<br />
Ngâm nga sư mới lại vui cùng<br />
Nhớ chàng Nguyên Lượng say bầu rượu<br />
Học kẻ Thiếu Lăng lựa nhánh bông<br />
Dạo bước khi trời thu mát mẻ<br />
Trời cao bát ngát hát thêm nồng<br />
<br />
<i>Nguyễn Hữu Vinh dịch, Taiwan, 1996</i><br />




