<h3>Tuồng Hoa-Tiên của Phan Mạnh Danh</h3>



<B>LÊ VĂN ĐẶNG giới thiệu</b><br />
		           <br />
<i>Truyện Hoa Tiên</i> chính là <i>Đệ Bát Tài Tử Hoa Tiên Ký Diễn Âm</i> của Nguyễn Huy Tự, một danh sĩ vào cuối thời Lê Trịnh, phỏng tác theo <i>Đệ Bát Tài Tử Hoa Tiên Ký</i> của Tàu làm thành một bài thơ Nôm dài, 1826 câu, theo thể lục bát, ca ngợi tình yêu, sau đó được danh sĩ Nguyễn Thiện nhuận sắc. <br />
<br />
Ðây là một tác phẩm thơ Nôm của hàng sĩ đại phu có học vấn cao, có hàm dưỡng sâu, nội dung lại thuật chuyện luyến ái của hạng giai nhân tài tử, nên dễ dàng lôi cuốn cảm tình và thẩm mỹ quan của người đồng điệu như họ Cao, họ Phan. Do đó, Cao Bá Quát đã tìm cách hiệu đính những chỗ lầm lẫn, bổ sung những điều thiếu sót, mong cho quyển sách trở nên một tác phẩm giá trị, ghi lại cảm tưởng của mình trong bài Hậu tự (chu bình) như sau:<br />
<br />
<i>Đó là một cuốn truyện bắt đầu từ chỗ lứa đôi gặp gỡ, riêng tư khắng khít yêu thương,  rồi đạt đến đạo cha con, nghĩa vua tôi, gắn bó lịch sự giữa bè bạn, tình cảm thắm thiết với anh em ; lớn là việc triều chính binh mưu, làm phép tắc cho việc khen trung khuyến tiết, nhỏ là chỗ tinh tế của thế thái nhân tình, của cỏ cây mây gió. Văn thì lạ, nghĩa thì chính. Nói về lý thì rành mạch mà không bế tắc, bàn việc đời thì biến ảo mà không trái lẽ thường. Đến như tan hợp buồn vui, hết vị trí này đến cảnh ngộ khác, đứt nối ẩn hiện, biến hóa hấp dẫn; lời phát ra tiếng nghe bi tráng, văn đặt thật có ý vị lắng trầm. Từ bụi bặm cám bả, tác giả đã hun đúc nên gạch ngói, khiến cho Kim Vân Kiều sau đó ngước mắt theo mà xuất hiện.  Gần đây, những kẻ khinh bạc mượn cớ bàn tán, thường chẳng suy xét, nên đã xếp Hoa Tiên vào loại  “lời dâm, khúc đẹp” , thật đáng buồn thay.[1] </i><br />
<br />
Sau này Phan Mạnh Danh Tiên sinh soạn thành <b>Tuồng Hoa Tiên</b> bằng quốc ngữ với lời lẽ thanh-tao đáng bậc danh sĩ.  <br />
<br />
Chúng tôi xin trích sau đây hồi 3 “Kỳ Biên Tương Ngộ”,<br />
ứng với các câu 81- 110 trong tập thơ ca của Nguyễn Huy Tự, hồi thứ tư :  <br />
<br />
<img src="./../images/TuongHoaTien.jpg" align="center">
<br />
<b>Kỳ Biên Tương Ngộ</b><br />
<br />
Đường hoa lành-lạnh hơi sương,<br />
Dừng chân hầu rắp nhận đường về trai.<br />
Tiếng đâu gió lọt bên tai,<br />
Đêm thanh dường hãy tiếng ai say cờ.<br />
Đè chừng rén bước thẩn-thơ,<br />
Ít nhiều hương cụm, nhặt thưa bóng cành.<br />
Mẫu đơn lộ mở con đình,<br />
Xạ đâu đòi trận lọt mành phôi-pha.<br />
Vừa cơn mây bợn trăng lòa<br />
Mảnh tình gửi mảnh thu-ba đưa vào.<br />
Cuộc tiên đôi đoá hoa đào,<br />
Riêng làn xiêm trắng càng dào mắt xanh.<br />
Gió đông gờn-gợn sóng tình,<br />
Dưới trăng lộng-lẫy một cành mẫu-đơn.<br />
Mặn-mà chìm cá rơi nhàn,<br />
Nguyệt ghen gương khép, hoa hờn thắm bay.<br />
Thiên-nhiên sẵn đúc dầy dầy,<br />
Càng tươi-tỉnh nét, càng say-sưa tình.<br />
Bụi trần chẳng bợn đỉnh-đinh,<br />
Dưới tùng trong quít âu đành là đây.<br />
Gió đâu đon-đỏi duyên này,<br />
Cả liều mật sắc vào ngay trước bàn.<br />
Rèm tương động, thét tiếng hoàn,<br />
Vẻ lan vừa chán, gót sen vội dời.<br />
Nhác xem chiều mỉm-mỉm cười,<br />
Sóng dầm khóe hạnh, chưa rời nét trông.<br />
Môi đào ánh mặt phù-dung,<br />
Xiêm in bóng tuyết sen lồng ngấn rêu.<br />
Người về khuất, kẻ trông theo,<br />
Xa mù lần toả vắng teo giọt làu.<br />
<br />
<b>III - KỲ BIÊN TƯƠNG NGỘ</b><br />
Cảnh:  Ðình mẫu-đơn có sẵn bàn ghế, trước mặt là một vườn hoa, Lương-Sinh ra.<br />
<br />
<b>Lương-Sinh:</b><br />
<br />
NÓI<br />
		<br />
Nhìn xem phong-cảnh Diêu-gia,<br />
		cảnh trí ấy thực là phong-nhã.<br />
		Âu là ta:  thừa nhàn trung bộ nguyệt,<br />
		mà: nhân tĩnh lý khán hoa.<br />
<br />
NGÂM		<br />
<br />
Phù-dung lấp-lố nở bên tường,<br />
		Sắc cỏ xanh-xanh sắc liễu vàng.<br />
		Hoa cúc mỉm cười chào khách lạ,<br />
		Sen hồ phảng-phất gió đưa hương.<br />
				hảo hoa nguyệt a<br />
<br />
HÁT NAM	<br />
<br />
Bóng hoa với bóng giăng theo rõi.<br />
		Có chăng đây là cảnh bồng-lai?<br />
		Biết bao cây-cỏ phương giời,<br />
		Chốn đông quân đến ắt thời phồn-hoa.<br />
<br />
Lương-Sinh vào.<br />
Dao-Tiên, Thái-Cơ và hai thị-tỳ là Vân-Hương và Bích-Nguyệt cùng ra, <br />
Dao-Tiên và Thái-Cơ cùng ngồi.<br />
<br />
<b>Dao-Tiên, Thái-Cơ:</b><br />
<br />
NGÂM		<br />
<br />
Lầu hồng bảng-lảng vẽ giời thâu,<br />
		Gió thổi hương sen nức một mầu.<br />
		Giăng bạc nửa vành in nước biếc,<br />
		Này đêm ả Chức gặp chàng Ngâu.<br />
<br />
<b>Vân-Hương, Bích-Nguyệt:</b><br />
<br />
NÓI		<br />
<br />
Mẫu-đơn đình sẵn có bàn cờ,<br />
		Xin hai cô đấu trí để xem ai cao thấp.<br />
<br />
<b>Thái-Cơ:</b><br />
<br />
NÓI		<br />
<br />
Nhân giăng thanh hội-diện đồng-đường,<br />
		âu là ta:  tiêu giạ vĩnh thủ đàm nhất cục.<br />
<br />
<b>Dao-Tiên:</b><br />
<br />
NÓI		<br />
<br />
Vân-Hương, tương kỳ bàn lai.<br />
<br />
Vân-Hương đem bàn cờ ra; Dao-Tiên và Thái-Cơ bầy quân cờ.<br />
<br />
<b>Dao-Tiên, Thái-Cơ:</b><br />
<br />
NGÂM			<br />
<br />
<i>Này này bàn ngọc<br />
mỗi người một câu	<br />
Nọ nọ quân ngà<br />
Bên bầy thế trận<br />
Bên tính nước hoa</i><br />
<br />
Lương-Sinh lắng tai nghe.<br />
<br />
NÓI		<br />
<br />
Tiếng cờ đâu chí-chát bên tai,<br />
		Ðêm-thanh vắng còn ai sai cuộc như vậy?<br />
		Âu là :  đình trung trực nhập,<br />
		mà :  cục ngoại bàng quan.<br />
<br />
<b>Thái-Cơ, Dao-Tiên:</b><br />
Mỗi người đi một nước cờ lại ngâm một câu<br />
<br />
NGÂM			<br />
<br />
<i>Này gảnh sĩ cạnh,<br />
Này đấm tốt ba,<br />
Này hoàn tượng về,<br />
Này thác pháo ra,<br />
Này ta phi-mã,<br />
Này ta xuất-xa,<br />
Này tướng nhập cung,  [2]<br />
Này tốt độ hà.</i><br />
<br />
Lương-Sinh lại gần đình mẫu-đơn.<br />
<br />
NÓI SẼ		<br />
<br />
Ðây nào phải Quảng hàn cung điện,<br />
		mà người tiên lại đánh cờ tiên,<br />
		Âu quyết liều trực đáo kỳ biên,<br />
		Thử tường khán thiên-nhiên phong vận.<br />
<br />
<b>Thái-Cơ, Dao-Tiên:</b><br />
<br />
NGÂM			<br />
<br />
<i>Ðấy cầm thế thủ,<br />
Ðây tính cuộc hoà.<br />
Ðương đầu mấy kẻ,<br />
Ðịch thủ cùng ta.</i><br />
<br />
Lương-Sinh chạy vào đình mẫu-đơn.  Mọi người trong đình thẹn đều chạy trốn.  Dao-Tiên quay lại mỉm cười.  Lương-Sinh chạy theo vài bước rồi đứng lại.<br />
<br />
<b>Lương-Sinh:</b><br />
<br />
NÓI		<br />
<br />
Nào chẳng biết rằng duyên rằng kiếp,<br />
		bỗng không dưng vướng-vít tơ mành,<br />
		Vả hay sầu hay bệnh là mình,<br />
		mà lại gặp kẻ nghiên thành nghiên nước như vậy?<br />
<br />
TÁN		<br />
<br />
Tôi tưởng như tôi bây giờ là:<br />
		Nghiệp thân tuy thị lập hồi lang.<br />
		Thảng sử Ðào-nguyên như hữu lộ,<br />
		Tiểu sinh ưng nguyện tố Ngư-lang.<br />
<br />
SANG NAM	<br />
<br />
Chốn Ðào-nguyên có đường khá đến,<br />
		Chàng Ngư này hỏi bến từ đây.<br />
		Như ngây mà lại như say,<br />
		Bóng người thời đó hồn bay nẻo nào.<br />
<br />
