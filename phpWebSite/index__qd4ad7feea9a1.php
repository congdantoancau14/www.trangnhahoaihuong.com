<b><div align = "center">Ra mắt Tuồng <i>Trương Ngáo</i>, do Gs Nguyễn Văn Sâm phiên âm từ bản Nôm 1878</div></b><br /><br />


<i><br />
"Từ trước đến giờ không bao nhiêu người biết tuồng hát bội <i>Trương Ngáo</i> 張 僥 傳, một tuồng bình dân nhưng ẩn tàng nhiều khía cạnh triết lý Phật giáo. Bản chữ Nôm, chỉ mới được khắc in gần một trăm năm chục năm nay, người nghiên cứu may mắn lắm mới có! Bản quốc ngữ do P. H .S. vừa dịch vừa sửa, in năm 1904 tại Sàigòn, trung tâm văn hóa quốc ngữ của cả nước thời đó, ngày nay không còn giá trị văn học và nghệ thuật nữa vì quan niệm phiên chuyển của người sinh hoạt văn học vào mấy thập niên đầu thế kỷ 20 không có tính cách khoa học mà chỉ thuần mục đích cung cấp một bản quốc ngữ cho độc giả trung bình không khó tánh lắm đối với vấn đề nguyên bản..."<br />
<br />
<i>(Trích lời Vào Đề của Gs Nguyễn Văn Sâm)</i></i><br /><br />


"Tôi cố gắng phiên âm trung thực từ bản Nôm duy nhứt mà mình có được đã lâu khi lục lọi ở Thư Viện Quốc Gia Pháp, Paris, đó là bản khắc ở Phật Trấn 佛 鎮, Quảng Đông 廣 東, Trung Quốc 中 國, năm Mậu Dần 戊 寅, 1878 mà không tùy tiện đưa ra những ý riêng về sự dùng chữ nầy chữ nọ hay dở, khó hiểu, thuận câu, trật chỗ..., những vấn đề mà tôi gọi là ngoài công việc của người phiên âm và giới thiệu bản văn..."<br />
<br />
Nguyễn Văn Sâm<br />
