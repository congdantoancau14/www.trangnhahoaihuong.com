<h3>Đọc Khói Sóng Trên Sông của Nguyễn Văn Sâm</h3>



<b>Nguyễn Vy Khanh</b><br />
<br />
Tìm hiểu hành trình văn nghệ của một số nhà văn thế kỷ XX, chúng tôi thích thú khám phá Nguyễn Tuân, Xuân Diệu viết phê bình văn học đặc sắc không thua gì thơ văn của họ: Nguyễn Tuân độc đáo khi viết tổng luận về Tản Đà, Vũ Trọng Phụng, Nguyên Hồng, Nguyễn Du, cũng như Xuân Diệu khi viết về Nguyễn Du, Hồ Xuân Hương. Đó là những văn nghệ sĩ đi từ sáng tác đến thể loại phê bình, khảo cứu. Nguyễn Văn Sâm là một trường hợp ngược lại, có thể do hoàn cảnh phải sống xa quê hương, ông khởi đầu sự nghiệp với những công trình nghiên cứu nghiêm túc về văn học trước khi sáng tác, viết truyện. Các biên khảo của ông đều lấy chủ đề là văn học miền Nam (Văn Học Nam Hà, Văn Chương Tranh Đấu Miền Nam, Văn Chương Nam Bộ) là những đóng góp độc đáo cho mảng văn học thường không được đánh giá đúng mức này. Ông đã đi xa hơn hai cuốn Văn Học Miền Nam của Phạm Việt Tuyền và Đông Hồ và đã đưa vào văn học sử mảng văn học yêu nước và kháng chiến của miền Nam, phần nào "chính danh" lại cho những văn nghệ sĩ miền Nam vốn vẫn bị đảng cộng sản xử dụng cho chiêu bài "yêu nước" của họ. Về sự chuyển hướng, chính tác giả đã cho người đọc biết : "qua Mỹ viết truyện ngắn vì những thôi thúc phải nói lên sự suy nghĩ của mình về quê hương và thân phận người Việt ngay trên quê hương hay lạc loài tha hương" (1). Về sáng tác, Nguyễn Văn Sâm đã xuất bản Câu Hò Vân Tiên (1985), Ngày Tháng Bồng Bềnh (1987). Trong bài này chúng tôi viết về tập Khói Sóng Trên Sông mới do tạp chí Văn xuất bản đầu năm 2000, đúng ra là một vài cảm tưởng về thể loại truyện ngắn và văn chương miền Nam, qua chữ nghĩa của Nguyễn Văn Sâm. <br />
<br />
Tập truyện Khói Sóng Trên Sông gồm 14 truyện ngắn về hai chủ đề chính : quê người và quê nhà. Hãy nói chuyện quê người trước. Truyện Khói Sóng Trên Sông là truyện cuối được dùng làm tựa cho cả tập, viết về đời sống nơi xứ người nhưng ở đây, cũng như các truyện ngắn khác về cùng chủ đề, hình như các nhân vật tiếp tục kéo dài nếp sống ở quê nhà nhiều hơn là những bận tâm hội nhập. <br />
<br />
Trước khi tác giả đưa người đọc đến bến sông bồi hồi nhìn khói sóng, hai nhân vật Chuyên và Vũ đã phải trãi qua sàng lọc hội nhập. Về vấn đề hội nhập, tác giả không dùng dao to búa lớn, chỉ gợi cảm qua hình ảnh, tình cảnh. Chuyện hai chị em Chuyên và Vũ ở Tiểu Sài-Gòn, còn là chân dung cuộc đồng người Việt  ở Hoa-Kỳ nói chung với những nhân vật có máu lãnh tụ ... ở xứ người, sống bằng trí nhớ dù thời gian qua vẫn không ... phôi pha, thường tưởng tượng, thêm thắt, điểm phấn. Ở quán nước Chuyên làm hầu bàn, họ là những "tục khách": "Những khuôn mặt mang nụ cười nham nhở. Những hàm răng cáu bợn thức ăn. Những hơi thở nồng hơi bia xú với thực phẩm chưa kịp tiêu hóa, tạo thành mùi cám heo lâu ngày, chuyển mùi. Chuyên muốn gạt phắt những chúng sinh lô nhô chung quanh sang một bên để chạy mau về phòng mình nằm sải tay thở những hơi dài trút hết những ưu sầu, chán chường ra khỏi tâm tư" (tr. 250). Thế hệ của Chuyên lớn lên khi cuộc chiến đã chấm dứt, phải sống trong xã hội cộng sản rồi vượt biển bị hiếp đáp. : "Ngày trước lạnh lùng giết nhau trong cái dửng dưng của không hận thù, ngày nay lạnh lùng làm khổ nhau đến chết trong bầu không khí tràn đầy hận thù âm-ỉ. Các chú, các bác mau chân nhanh tay chạy vọt qua đây đâu thấy chúng tôi bị hành hạ đủ điều đâu..." (tr. 247). Chuyên lợm giọng trước những người thích tới quán để sống cái quá khứ vẽ vời và sống ảo tưởng "anh anh em em" với các cô gái đáng tuổi con cháu. <br />
<br />
Tình yêu, cuộc sống của Chuyên, cũng như nhiều người tị nạn khác, phải sống cái bi đát ở giữa hai văn hóa, hai thế giới : Khoa ở đây, Hùng quê nhà; tình người ở quê vương vấn vì nhiều kỷ niệm, vì khởi từ gốc rễ, thành ra dễ lơ là với tình bạn mới, Chuyên tự hỏi "tại tôi không biết điều chỉnh nhãn quan để phù hợp với cuộc đời mới bon chen bên này?..." (tr. 249). Đến khi mất tình yêu ở Việt Nam, Chuyên mới nhận ra mình "chỉ là một con vật nhỏ dật dờ theo con sóng đời trôi dạt. Nhưng sao tôi nghe muôn ngàn đổ vỡ tàn khốc trong hồn, nghe hụt hẫng như mình không còn quá khứ, hôm qua được sanh ra và hôm nay là tôi của hiện tại, tâm hồn trống không" (tr. 256).<br />
<br />
Trong khi tình yêu ở xứ người là những bất ngờ. Martha, người yêu của Vũ, em Chuyên, đã ngoại tình dù đang có chửa, đang "mang mển" - nói như Nguyễn Văn Sâm. Một hội nhập không lối thoát mà rồi cũng chẳng đưa đến đâu!<br />
 <br />
Trong những truyện khác, đề tài hội nhập được nói đến và thường là những vấn nạn, như cha mẹ già cả bệnh tật con cháu phải chăm sóc trong khi phải bon chen với đời sống mới, trong Mát Lạnh Tuổi Vàng, như những va chạm với người dị chủng có khi gây hiểu lầm, trong Ông Già Noel Có Thật, như nếp sống cá nhân và cô đơn của giới thiếu niên đưa đến những thảm cảnh bị dụ dỗ, trong Người Bí Mật Chiêm Ngưỡng, ....<br />
<br />
Dù rồi cũng thành công, cũng sống còn, đi lên nữa là khác, nhưng đời sống hội nhập không khỏi có những khó khăn cho các thế hệ hãy còn nhiều liên hệ với quê hương. Bởi thế khi hoàng hôn xuống, thời điểm mà con người xa quê thường nhớ nhung, hay hướng về chân trời thân thương cũ, nhất là khi đứng trước con nước xứ người, giữa cái mơ hồ, đời mới cũ, tâm sự u uất vì nói không ai hiểu, không có ai hoặc không ai có thể hiểu. Tác giả không nhắc nhở nhưng đã dùng ý câu 8 của bài Hoàng Hạc Lâu của Thôi Hiệu để đưa người đọc đối đầu trước một tình cảnh sống, trước câu hỏi đâu là quê hương! "Yên ba giang thượng sử nhân sầu" như một kết cục tất yếu của hạc vàng vang bóng của ngày cũ, quá vãng, của người xưa, đi không trở lại; mây trắng mênh mông, càng mênh mông thêm nỗi buồn xa xứ! <br />
<br />
Khi viết chuyện ở xứ người, câu văn Nguyễn Văn Sâm thường ngắn gọn, ít vần và đối, nhưng trái lại, khi tả chuyện quê nhà với những nhân vật thật "lục tỉnh" gắn liền với quê hương, thì câu văn dài dòng như có thế mới nói hết được tâm sự, mới tả hết được dáng cách con người và góc cạnh của những khu phố, đường làng quê!<br />
<br />
Như Nước Trong Nguồn là một truyện ngắn viết về số phận của một chàng thanh niên què quặt xưng "tôi", mặc cảm ngập trời về thân thể của mình mà lại luôn luôn thèm khát xác thịt đàn bà, cuối cùng đành chịu lấy một thiếu nữ đã có bầu với kẻ khác, qua sự sắp xếp của bà mẹ. Hương Cỏ nhắc nhớ một mùi hương sống động của quê hương qua chuyện "gái bao" của một Việt kiều "già dịch". Âm Dương là cuộc sống khốn khổ ở quê nhà sau ngày "giải phóng". Một quê hương rất tha thiết, bùi ngùi! Người xa quê như luôn trông về quê nhà, nơi đó có "ngôi nhà tràn ngập tình gia đình, đứng nép mình bên bờ con sông lớn ngàn đời sóng vỗ (...) tất cả đều là khói sóng trên sông cả" (tr. 263).<br />
<br />
Quê nhà ngập trí nhớ, nên từ một điểm ký ức nào đó cũng có thể phóng ra cả một quãng đời hay mảnh đời đã qua nhưng vẫn sống động! Trong Quê Hương Mình, thế giới của thầy Năm với chiếc ghe cá đi khắp nẽo sông bến nước, của dì Tư và anh em thằng Đực. Hễ nhắc tên Chợ Đệm đã "gợi trong lòng dì cảm giác bồn chồn xao xuyến. Đường về không xa, nhưng sao bao năm nay đâu dám nghĩ tới!" (tr. 189). Thật vậy, Quê nhà là những địa danh thân thương. Trong Theo Gót Huyền Trân, người đọc như "thấy" lại Sài-Gòn, Khánh Hội, Chợ Lớn, xóm Mả Ngụy, đồng Tập Trận, ... của những người lục tỉnh lên chốn thị thành nhiều cạm bẫy, bất ngờ, của những "tây-tà, chà-và, các-chú", của một thuở xa xưa! Một Sài-Gòn mà "bàng dân thiên hạ hướng về Sài-gòn như thể hoa quỳ hướng dương" (tr. 51). Nhân vật xưng tôi trong Biển Trời Lai Láng tâm sự: "Sài-gòn đối với tôi thân thiết đáng nhớ, xa trong thực thức nhưng tiềm thức không bao giờ xa. Bao nhiêu đó đã là quá đủ. Một vài chi tiết cụ thể về nơi nầy nơi nọ, người nầy người kia, nói cho cùng, cũng chỉ như một nhúm sao nhỏ nhoi trong vũ trụ bao la của triệu triệu dãy Ngân Hà" (tr. 158). Kể Chuyện Ngày Xưa đưa người đọc trở về Mỹ Tho và ngôi trường Nguyễn Đình Chiểu của hôm nay: "Bây giờ thì tang thương đến cả từng mảnh nhỏ của ngôi trường vì người ta không làm tròn nhân luân" (tr. 131); tang thương cho cả người cũ về thăm cảnh xưa vốn đẹp trong trí nhớ. "Lá me vàng úa bay lã tã, lược lờ trong không gian, như xúc động bùi ngùi đưa tiễn, rớt lấm tấm trên cái đầu bạc trắng của người thầy giáo già mất quê hương và mất luôn cả kỷ niệm" (tr. 132). Kiếm tìm có khi chỉ đưa đến thất vọng!<br />
<br />
Quê hương còn là những mùi hương, mùi thơm của hoa, của đất,... Truyện Tình Đất bắt đầu với "mùi thơm thoảng quyện mơ hồ" của bông lài; truyện chấm dứt với lời thú đậm tình: "Bao nhiêu năm nay tôi thường chiêm bao thấy mình đương ở trong căn nhà cũ. Tôi thấy mình tưới nước bông lài buổi sáng sớm mai. Tôi cảm nhận được rõ ràng mùi bông lài thơm nhè nhẹ trong không khí, một mùi quen thuộc mà tôi không thể nào gặp được ở bất cứ chỗ nào..." (tr. 240). Sống ở quê người mà vẫn có cảm giác như đang sống ở quê nhà. Cảm giác của mộng mị trở thành ảo giác khi phải trực diện với cuộc đời trước mặt, nhưng trong trí nhớ thì ngập tràn. Nhưng quê nhà cũng là những mùi hôi của những chốn bùn lầy nước đọng của người ăn xin, của những trẻ đi lượm cá sình ở chợ (Quê Hương Mình, tr. 178-179). Sống ở xứ người có lúc "nghe" được mùi thơm bí ẩn tỏa ra từ một Việt kiều "già dịch" như mùi hương cỏ, như "mùi hương con gái" (tr. 108). Khứu giác người xa xứ không lầm, nhưng khi hiểu nguồn gốc mùi thì hương cũng mờ thoáng lần! Đã vậy trong cái xã hội người Việt xa xứ có những mùi hôi của những "khuôn mặt mang nụ cười nham nhở (...) những hơi thở nồng hơi bia xú với thực phẩm chưa kịp tiêu hóa, tạo thành mùi cám heo lâu ngày, chuyển mùi..." (tr. 250).<br />
<br />
Quê nhà cũng còn là những tiếng động, tiếng người, của chợ Tết trong Tình Đất, ồn ào náo động đó rồi vãn chợ cũng nhanh: "Chợ ba mươi Tết kỳ lắm, đông như họp chợ âm phủ mà chừng trời đứng bóng thì tan gần hết, lác đác còn lại còn thua chợ ngày thường nữa..." (tr. 224). Nào là những tiếng động của Sài-Gòn ngày cũng như đêm, trong Theo Gót Huyền Trân. Tóm, tiếng động, hương thơm, ... người lưu xứ thường hãy còn lưu giữ một phần hồn của cố quốc, nhất là ở thế hệ thứ nhất! Viết đến, nhắc lại, như một thảo hiếu với đất đai, nguồn cội!       <br />
 <br />
Các truyện của Khói Sóng Trên Sông phần lớn có cấu trúc chặt chẽ, nhiều tình tiết, có những kết thúc đầy bất ngờ. Cổ điển truyện ngắn, nghệ thuật văn chương, không làm dáng thời thượng cũng chẳng tân cải bất ngờ! Nhân vật thường hiền lành, đơn giản dù tâm hồn cũng rất khúc mắc - những "tôi" tật nguyền dồn nén trong Như Nước Trong Nguồn, những Cô Út trong Tình Đất, dì Út, cậu Bảy trong Tình Lụy Thiên Thu hay người con dâu hiếu hạnh trong Mát Lạnh Tuổi Vàng, v.v.<br />
