<br />
Chất Nam "lục tỉnh" của Nguyễn Văn Sâm thể hiện trong chữ dùng, trong phong cách viết, tả nhân vật và tỏ lộ tâm tình. Nguyễn Văn Sâm tự đề ra cho mình một loại "cương lĩnh" trong Bài Chàm Về Viết ở đầu tập truyện: "... Cái quê hương mến yêu, chốn sanh trưởng thân thiết, tiếng địa phương nghe từ khi còn nằm võng ẩn náo trong hồn, tuông ra đúng lúc, phải chỗ..." (tr. XVIII).<br />
<br />
Nguyễn Văn Sâm có một ngôn ngữ "miệt vườn" đặc sắc. Ông xử dụng nhiều tiếng đặc "miệt vườn", những phương ngữ làm nên cái duyên của miền Nam lục tỉnh. Ông dùng nhiều từ láy và đặc biệt ông đã cẩn thận gạch nối: <br />
- "Trước đây thằng đó thấy tôi còn đứng dậy dã-lã chào hỏi, khúm-núm bẽn-lẽn, mà con Út cũng coi bộ sợ-sệt, bối-rối" ...  "Thét rồi nó tới chà-lết quết-xảm ở nhà tôi, gặp thì chỉ chào sơ sơ rồi quay ra tíu-ta tíu-tít với con Út..." (tr. 214). <br />
- "Sồn sồn tuổi nhưng du dương giọng, bà Hương có tiếng chửi không khác là bao với tiếng hát ru em trưa nắng, mùi mẫn như bài ca dạ cổ hoài lang từ phu tướng lên đường, đã điếu còn hơn nghe mấy con nhỏ xóm dưới kéo vuốt mấy tiếng chót của một câu hò ruột lên cao ngất, nhọn lễu như kim, chích nhè nhẹ nhột nhột vô tim " (tr. 22). <br />
Hay : "... cần lắm thì ậm-à ậm-ừ cho qua..." (tr. 24); "mang bầu lạch ạch cũng bò ra chợ, mới đẻ hôm kia cũng te te đi bán..." (tr. 56), v.v. Vừa dùng tiếng láy vừa dài dòng và màu mè như tiếng nói người miệt vườn: "ngâm nga sông dài con cá lội biệt tăm" (tr. 25). Như một mạch tư duy liên khúc. Giữa những khớp nối tư duy, cảm xúc ấy là những hình dáng con người và cảnh tượng có sức tỏa rộng, gặp gỡ và xuyên thấm vào nhau!<br />
<br />
Ông có tài quan sát và tâm lý như phân tâm mặc cảm của nhân vật tật nguyền mà ham gái trong Như Nước Trong Nguồn: "Từ lâu rồi tôi chỉ đứng xớ-rớ trước cửa nhà thèm thuồng, với cảm tưởng rung động ở từng sợi gân trong thân thể, ngó theo lũ con gái nhún nha nhún nhẩy, để rồi sau đó nằm cong queo trong một góc giường nhắm mắt vẽ lại hình ảnh trong trí hết đứa nầy tới đứa khác. Thường thường tới đứa thứ hai thì tôi mệt lã, tim đập thình thịch như trống chầu, ngủ thiếp đi lúc nào không hay, nhiều khi thức giấc bàn tay trái vẫn còn ướt mẹp đương nằm giữa hai bắp vế, thoảng hôi một mùi là lạ..." (tr. 33).<br />
<br />
Tâm lý như khi tả người ghiền thuốc ở xứ người hết tự do như trước:  "Thỉnh thoảng lắm mới có dịp tất cả mọi người cùng đi vắng, tôi được tự do rít hơi thật dài, thật sâu, ém hơi lâu trong phổi, phun ra rồi hít vô ngay lại bằng lỗ mũi. Những lúc nầy thì đã tận mạng"(tr. 105).<br />
<br />
Cả trong quan sát diệm mạo con người, các nhân vật của ông hay chú ý đến các bộ ngực nở nang của phụ nữ. Một nhân vật nói về một cô gái miệt vườn: "Con Cúc trổ mã cả năm nay, tay chưn tròn trịa, vú dậy đội lớp áo lên cao nghệu dòm ngang thấy trơn láng mềm mềm ra vẻ con gái quá chừng." (Tình Đất). Tật nguyền như nhân vật xưng "tôi" trong Như Nước Trong Nguồn mê gần hết các cô gái trong xóm cù lao: "Mấy đứa nầy đứa nào đứa nấy đều bị tôi "tưởng tượng" một vài lần khi ban ngày nhỏng nhảnh đi ngang qua nhà tôi, cười cười nói nói, cái quần lãnh đen láng o dòm không thôi đã thấy mát rượi lòng, cái áo nút bóp căng thịt, cặp mắt bén ngót như dao cạo..." (tr. 34), rồi mê Nhàn, bạn của anh mình, cũng qua bộ ngực: "Ngồi trong nhà thấy nó thấp thoáng bên kia, ngực một ngực, lồ lộ thiếu điều căng xé áo nhảy ra ngoài, tôi cũng đã cảm nhận nỗi vui vui tràn ngập lòng, đời thiệt thòi như được trút bớt vài phân." (tr. 27).<br />
<br />
Văn chương Nguyễn Văn Sâm tưởng chừng theo truyền thống viết-như-nói khởi từ trường phái Trương Vĩnh Ký, qua Hồ Biểu Chánh, Bình Nguyên Lộc đến Võ Kỳ Điền, Nguyễn Tấn Hưng thời hiện đại. Khởi sáng tác cùng thời với hai nhà văn sau, nhưng các truyện ngắn của Nguyễn Văn Sâm nếu đọc kỹ mới thấy ông đi xa hơn: ông viết như nghĩ và dùng ngôn ngữ nói để làm văn chương. Ông hấp dẫn người đọc bằng các chi tiết ly kỳ xen kẽ với lối nói, lối suy nghĩ của các nhân vật đa dạng nhưng tiêu biểu cho "miệt vườn". Cái khiến Nguyễn Văn Sâm không giống các nhà văn "miệt vườn" khác, là chính trong câu văn mà muốn hiểu thì người đọc phải hiểu được mạch nổi, mạch chìm và lớp từ ngữ bộn bề, dồi dào, nhuốm trí thức của ông. Có thể xem Chờ Cho Trăng Lặn và Như Nước Trong Nguồn là hai truyện ngắn tuyệt tác tiêu biểu của Nguyễn Văn Sâm ! Nhưng trong các truyện còn lại khi viết về quê nhà, kỷ niệm, thời gian và cảm xúc tác động mạnh thành ra có khi hơi dài dòng, vận dụng đối và vận nhiều, có thể khiến người đọc nhiều khi khó theo dõi câu chuyện. Người đọc có thể lạc đường, một lạc lối dễ thương thôi, giữa một rừng tâm tình và cảm xúc của tác giả. Kiệt Tấn cũng dài dòng nhưng ở một tầm cỡ khác, ở chổ nhiều đối thoại và nhiều tình tiết động tác hơn và câu chuyện hay lập lại. Hồ Trường An cũng dài dòng nhưng trong màu mè nhân tạo và miêu tả trên một nền "miệt vườn" đã sẵn! Chúng tôi nghĩ Nguyễn Văn Sâm có chủ tâm chi tiết hình ảnh và dài dòng, du dương, câu văn nhiều nhạc tính - dài theo hơi kể chuyện, lối "nói" văn chương truyền thống trong Nam, du dương theo lối nói "vè", vần điệu, của ca dao, của nói thơ Vân Tiên hay mấy câu cải lương vốn thường dài hơi. Tất cả như cốt để khơi dậy nơi người đọc những cảm xúc sâu đậm, những tiếng thở dài và cả những phẫn nộ khi xem đến dòng kết truyện. <br />
<br />
Từ Câu Hò Vân Tiên qua Khói Sóng Trên Sông, Nguyễn Văn Sâm đã chứng tỏ có kỹ thuật văn chương, cái "tải đạo" của ông nếu có, thì cũng thuộc về nhân đạo tự nhiên như con người thì phải thế. Chờ Cho Trăng Lặn là một điển hình, tác giả viết về một mối tình đẹp trong khung cảnh văn hóa rất lục-tỉnh thâm nhiễm luân lý nền tảng á-đông, chuyện tình "thằng Thành" hay đến nhà con Kén nghe nói thơ Vân Tiên. Hai đứa hạp nhãn nhau, hay ra bụi môn chờ cho trăng lặn. Nhưng con Kén lấy chồng giàu mẹ cha ép gả, thằng Thành "chất chứa mối u tình nặng trĩu lòng nó, nặng nhưng vẫn còn đủ đẹp để lôi chưn nó lại, không cho cất bước giang hồ tìm quên" vì nó nghĩ chỉ có nó mới có cái tình và cái hồn của con Kén, còn cậu Hai Phó Hương Quản "tuy là chồng nhưng anh có biết cái tình cái hồn của nó nằm ở đâu đâu nà!" (tr. 175). Hình như Nguyễn Văn Sâm viết truyện này nhân cuộc tranh luận về thơ Vân Tiên trên tạp chí Văn Học (CA), thể loại truyện ngắn qua ngòi bút của ông hình như có sức thuyết phục hơn là những lý luận ồn ào. Thật vậy, ông tâm tình để thuyết phục hơn là dùng luân lý hay lý luận để can thiệp vào câu chuyện. Trong những truyện về đời sống hội nhập ở xứ người, ông cũng tỏ ra hụt hẫng, ngập ngừng - như nhân vật của ông, trước một số tình cảnh; đó có thể cũng là tình cảnh chung của tất cả người Việt xa xứ!<br />
<br />
Truyện ngắn của Nguyễn Văn Sâm nói chung là không khí chữ nghĩa, là tấm lòng của tác giả. Nhiều truyện ngắn trong Khói Sóng Trên Sông khiến người đọc an tâm phần nào về văn chương "miệt vườn" và bớt bi quan hơn nhà văn Nguyễn Mộng Giác năm nào nhận xét về hiện tượng "các nhà văn gốc Nam Bộ xuất hiện nhiều, và viết nhiều truyện ngắn phong tục "miệt vườn" như lúc này ở hải ngoại (...) bị "vướng cái lưới 'phản ảnh' (...) quá chú ý tới vấn đề, truyện miệt vườn đang sa vào cái tật quá khích. Nhiều truyện ngắn viết ở Âu châu, Bắc Mỹ năm 1992 mà người đọc có cảm tưởng đang đọc một truyện của Hồ Biểu Chánh viết trước đây (gần) một thế kỷ ! Kể cả lối tác giả xen vào câu chuyện giảng giải cho nhân vật nghe chuyện đạo lý thánh hiền, nghĩa là vướng lần nữa vào cái lưới "tải đạo"" (2). Chúng tôi vẫn có cảm tưởng điều này hình như đúng cho bất cứ nhà văn gốc miền nào, và cũng đúng cho một số nhà văn "miệt vườn" hiện cạn cảm hứng sáng tạo; đó là những truyện ngắn thiếu kỹ thuật và văn chương, những "chuyện ngắn", của những "văn chương ngắn ngủi" của thời gian, những cương, những kể hoài không hết!<br />
