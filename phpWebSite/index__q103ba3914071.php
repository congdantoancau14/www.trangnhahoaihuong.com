<h3>Thành Tựu Cao Cả Của Trái Tim</h3>



<i>Triumph of the Heart<br />
Được trích từ quyển “A Heart Full of Peace” (Trái Tim An Lạc) của thiền sư <b>Joseph Goldstein</b> và được đăng trong tập san tam nguyệt “Tricyle” (Spring 2008)</i><br />
<br />
<a href="http://www.trangnhahoaihuong.com/files/TriumphOfTheHeart.pdf">Đọc bằng bản PDF</a><br />
<br />
Tình thương, bi mẫn và an lạc–các từ ngữ này nằm ở tận đáy lòng của những người tu tập.  Mặc dù chúng ta rung cảm một cách trực tiếp trước ý nghĩa và giá trị của chúng, điều thách thức đối với phần lớn chúng ta là làm sao thể hiện được những gì mà mình thấu biết:  Làm thế nào chuyển đổi những từ ngữ này thành ra một sự thực tập sống động.  Trong thời đại xung đột và bấp bênh này, đây không phải là một sự thực tập trừu tượng.  Nền hòa bình của thế giới bắt đầu từ tâm tư an bình trong mỗi một người chúng ta, và có nhiều cách thức khác nhau mà ta có thể biểu hiện những giá trị này qua những hành động khôn khéo trong cuộc sống.  Những lời dạy này được căn cứ trên các truyền thống Phật giáo Đông phương, nhưng đặc tính định rõ ranh giới của chúng thì không thuộc về Đông phương hay Tây phương, mà chính là một tâm nguyện thiết tha đối với chủ trương thực dụng và là một nghi vấn thật đơn giản:  Có kết quả gì?  Có tác dụng tháo gỡ tâm thức thoát khỏi phiền não ra sao?  Có ảnh hưởng thế nào đối với việc làm phát khởi tâm bi mẫn?  Có tác động gì trong việc làm ta thức tỉnh từ cơn mê vô minh?<br />
<br />
Đường lối thực dụng này cũng làm sáng tỏ một câu hỏi có từ ngàn xưa mà nó tiếp tục quấy rầy các truyền thống tôn giáo cũng như các truyền thống khác:  Làm thế nào chúng ta vẫn có thể giữ vững các quan điểm khác xa nhau trong một khung cảnh chung sống hài hòa rộng lớn hơn, vượt ra ngoài thái độ bất hòa và thù nghịch?  Lời đáp cho câu hỏi này có tầm quan trọng sống còn, nhất là trong tình trạng hiện nay, như chúng ta đã thấy là sự lan rộng nhanh mạnh của các truyền thống tôn giáo thường đi kèm với các cuộc va chạm bạo động. <br />
<br />
<b>Cầu Mong Cho Mọi Loài Đều Được Hạnh Phúc</b><br />
<br />
Từ vựng tiếng Phạn, “maitri,” và từ vựng tiếng Pali, “metta,” đều có nghĩa là “tâm từ” hay là “sự quan tâm thương yêu,” và nói đến một thái độ thân tình, thiện ý và khoan dung của trái tim.  Khi trong ta tràn đầy tâm từ, ta có một ước mong thật tự nhiên:  Mong sao cho mọi loài đều được hạnh phúc.  Loại tình thương này có nhiều đặc tính ưu tú, khác hẳn với những kinh nghiệm yêu thương thường tình có pha trộn lòng tham dục hoặc là dính mắc.  Được phát sinh từ tâm lượng bao dung vô cùng rộng lớn, tâm từ là lòng quan hoài và tử tế mà nó không hề mong cầu lợi lộc cho riêng mình.  Tâm từ không mong cầu sự đền đáp:  “Tôi sẽ thương bạn nếu như bạn thương tôi,” hoặc là “Tôi sẽ thương bạn nếu như bạn hành xử theo một lề thói cung cách nào đó.”  Do bởi tâm từ không khi nào có dính líu tới bất cứ điều gì tai hại, tâm từ luôn phát khởi từ một trái tim thuần khiết trong sáng.<br />
<br />
Một trong những khía cạnh độc đáo của tâm từ là nó không phân chia loài nào cả.  Khi nào ta cảm nhận một tình thương bị trộn lộn với lòng tham dục, thì cảm xúc này chỉ luôn luôn dành cho một số người nào đó mà thôi.  Ta có thể yêu thương và ham muốn một, hai hay ba người cùng một lúc, hoặc giả vài người theo từng đợt nối tiếp nhau.  Nhưng có ai trong đời này lại thiết tha mong muốn hết thảy mọi loài?<br />
<br />
Mặc khác, tâm từ có tính chất thật đỗi khác thường do vì nó có thể ôm trọn mọi loài; không loài nào rớt ra ngoài phạm vi của nó.  Đó là tại sao, khi ta gặp gỡ những người phát huy được khả năng này tới một mức độ cao thâm, lấy ví dụ là đức Đạt lai Lạt ma, ta cảm nhận được tấm lòng nhân từ bao la của họ hướng tới tất cả mọi người.  Tâm từ là một loại cảm xúc mà nó gia hộ cho những người khác và cho chính mình với niềm ước mong tự nhiên, “Được sống hạnh phúc.”  Thi sĩ người Nhật, Issa (1763-1828), đã diễn tả cảm xúc trải rộng cõi lòng này thật là tài tình:  “Dưới bóng mát của chùm hoa anh đào, không có ai là xa lạ cả.”<br />
<br />
Mặc dù không phải lúc nào ta cũng sống trong một trạng thái cảm xúc thương yêu kiên định, nhưng qua sự thực tập ta có thể tiếp xúc với nó nhiều lần trong một ngày.<br />
<br />
<b>Thực Tập Tâm Từ Đối Với Chính Mình</b><br />
<br />
Một cách để phát triển tâm từ trong ta là thông qua sự thiền tập, ta bắt đầu bằng cách ban rải những cảm xúc thương yêu hướng về tự thân.<br />
<br />
Thật là đơn giản:  Trước tiên, hãy ngồi trong tư thế thoải mái và duy trì một hình ảnh trong tâm hoặc cảm giác về chính bạn, lặp lại chầm chậm các cụm từ về tâm từ cho chính mình:  Mong sao cho tôi được hạnh phúc, mong sao cho tôi được an bình, mong sao cho tôi thoát khỏi khổ đau.  Hãy lặp đi lặp lại nhiều lần những câu này hoặc là những nhóm từ tương tợ.  Ta làm điều này không như là một sự khẳng định quả quyết, mà như là một sự biểu lộ tác ý quan tâm chăm sóc.  Khi bạn lặp lại những từ ngữ này, hãy chú tâm vào ý định tốt lành này; tác ý này dần dà nẩy nở thành ra một tâm lực hùng mạnh trong đời sống của bạn.<br />
<br />
Mặc dù sự thực tập chẳng chút phức tạp, nó có thể cực kỳ khó khăn.  Khi bạn chuyển sự chú ý của mình hướng vào bên trong và gửi những niềm ước ao thương yêu cho chính mình, bạn có thể nhìn thấy một số lượng đáng kể về sự tự phán đoán lấy mình hoặc là những cảm nhận không xứng đáng của tự thân.  Trong những lần như vậy, hãy tiếp tục một cách nhẹ nhàng từ ái như là nếu bạn đang ôm ấp một đứa bé.  Một dòng thơ từ bài thơ của giới võ sĩ Nhật thời xưa đã diễn đạt khá hay phần thực tập này:  “Tôi làm cho tâm tôi trở thành bạn tôi.”<br />
<br />
<b>Thực Tập Tâm Từ Đối Với Ân Nhân</b><br />
<br />
Sau khi làm cho vững mạnh các cảm xúc tâm từ dành cho chính mình, ta gửi những niềm ao ước giống như vậy tới một người ân đã trợ giúp ta trong cuộc sống bằng phương cách nào đó.  Đây có thể là cha, mẹ, thầy, cô hay ngay cả một người nào đó mà ta không quen biết, tuy vậy, cuộc đời của người này đã có một ảnh hưởng tích cực đối với đời sống của ta.  Một người có khó khăn tiếp xúc với tâm từ đã nói rằng, chị ta mở rộng tâm từ dễ dàng nhất khi nhớ nghĩ về con chó của chị–một loài động vật luôn ban cho chị một thứ tình thương mà không hề đặt vấn đề này nọ hoặc là thường hay hỏi lại gì cả.  Những người ân có thể ở trong nhiều hình thái khác nhau.<br />
<br />
Trong phần thực tập này, hãy giữ hình ảnh hoặc là cảm xúc về người đó trong tâm bạn, giống như là nếu bạn đang nói chuyện trực tiếp với họ, và kế tiếp hãy hướng tác ý tâm từ về người này:  Cầu mong cho được hạnh phúc, an bình, không còn khổ đau.  Giai đoạn này thường dễ hơn là hướng tâm từ tới chính mình bởi vì ta thường có sẵn những tình cảm quan tâm nồng thắm dành cho những người đã giúp đỡ ta.<br />
<br />
<b>Thực Tập Tâm Từ Hướng Về Mọi Người</b><br />
<br />
Rồi thì ta tiếp tục thực tập hướng tới những hạng người khác.  Ta gửi niềm chúc lành quý mến tới những người thân thiết; sau đó tới những người bình thường mà ta không có cảm xúc mạnh mẽ bằng cách này hay cách nọ; và kế tiếp tới “những người thù nghịch” hoặc là những người khó chịu.  Cuối cùng, ta gửi tâm từ tới mọi người ở khắp mọi nơi, và lặp lại, Mong sao cho mọi người được hạnh phúc, mong sao cho mọi người được bình an, mong sao cho mọi người được thoát khổ.<br />
<br />
Thật là quan trọng để thực tập theo nhịp tiến của riêng mình.  Có lẽ, một vài hạng người sẽ dễ dàng cho sự thực tập của bạn hơn so với những hạng người khác.  Bất cứ khi nào bạn cảm thấy mình có khả năng phát khởi những cảm xúc quan tâm thương yêu chân thật đối với một người, thì bạn hãy tiếp tục thực tập như vậy cho người kế tới.<br />
<br />
Phần này có thể được thực tập một cách sâu sắc trong khung cảnh thanh lặng của một khóa thiền, trong công phu hành trì mỗi ngày ở nhà, hoặc đương lúc đi ngoài đường phố hay lái xe đi làm.  Trong mọi trường hợp, đều bắt đầu có sự thay đổi trong mối tương giao giữa ta với người khác ở khắp mọi nơi.<br />
<br />
Như là một cuộc thử nghiệm, lần tới khi bạn đi công chuyện lặt vặt, bị kẹt xe, hay đứng xếp hàng ở siêu thị, thay vì bận tậm lo nghĩ mình sẽ đi đâu hoặc cần làm gì, hãy rải tâm từ đến mọi người quanh đó trong thời gian này.  Thường thường, có một sự biến chuyển tức thì và rất rõ rệt khi ta cảm thấy được nối kết chặt chẽ nhiều hơn với những người khác cũng như khi ta thường trực có mặt trong giây phút hiện tại.<br />
<br />
Khi tôi mới bắt đầu thực tập tâm từ, tôi có được một kinh nghiệm mà nó phơi bày tâm tôi thật nhiều, cũng như cách thức tôi liên hệ với những người khác.  Tôi thực tập mở rộng tâm từ hướng tới một người bình thường–dù rằng tôi không mấy chắc “một người bình thường” nghĩa là gì.  Thầy tôi, Anagarika Munindra (1914-2003), chỉ ngắn gọn bảo, hãy chọn một người gần bên mà mình không có nhiều cảm xúc bằng cách này hay cách kia.<br />
<br />
Khi tôi còn ở Ấn Độ, và có một người làm vườn lớn tuổi trong một tu viện nho nhỏ nơi tơi trú ngụ.  Tôi thấy ông mỗi ngày, tuy vậy, tôi chưa hề thật sự có cảm nghĩ nào về ông cả.  Ông chỉ là người mà tôi nhận biết khi đi ngang qua.  Thật là sửng sốt khi nhận ra rằng, có bao nhiêu người như vậy ở xung quanh mình, những người mà tôi đã có những cảm thọ hoàn toàn trung tính.  Tự chính điều đó đã là một sự khám phá có tính cách soi sáng rồi.<br />
<br />
Vì vậy mà mỗi ngày trong nhiều tuần lễ, tôi đã bắt đầu hình dung ra ông già làm vườn này trong thời khóa thiền tập của tôi, lặp lại những cụm từ như là, “Cầu mong cho ông được hạnh phúc, cầu mong cho ông được an nhiên, cầu mong cho ông được thanh thản.”  Một thời gian sau, tôi khởi sử cảm nhận được sự nồng ấm và quan tâm thật nhiều dành cho ông, và mỗi lần chúng tôi đi ngang qua nhau, trái tim tôi mở ra ngay.  Đây là một bước ngoặt to lớn trong sự thực tập của tôi.  Tôi hiểu ra rằng, tôi cảm nhận về một người nào đó ra sao là tùy thuộc vào tôi, và những cảm thọ của tôi không chủ yếu tùy thuộc vào người đó, vào cách hành xử của người đó, hay là vào tình thế đó.  Người làm vườn vẫn y nguyên như vậy.  Tuy nhiên, do vì một sự biến chuyển trong sự hiểu biết và thực tập của riêng tôi, trái tim tôi bắt đầu tràn đầy cảm thọ từ ái và quan hoài chân thật.<br />
<br />
<b>Điều Gì Dẫn Đến Sự Thành Tựu Lớn Của Trái Tim?</b><br />
<br />
Có một bài học quan trọng ở đây về năng lực bền bỉ của tâm từ.  Do bởi tâm từ không tùy thuộc vào bất kỳ phẩm chất đặc thù của người khác, loại tình thương này không chuyển đổi dễ dàng thành ra ác ý, giận hờn, hay bực dọc như thứ tình yêu thông thường có sự ham muốn hay dính mắc kèm theo.  Tình thương vô điều kiện như vậy chỉ xuất phát từ tâm lượng bao dung của trái tim.  Dù rằng ta có lẽ nhận ra được tính chất thanh tịnh và năng lực cảm xúc này, ta có lẽ e sợ hay nghĩ tưởng là loại tình thương này vượt quá khả năng của mình.  Tuy nhiên, tâm từ không là một năng lực chỉ tìm thấy nơi đức Đạt lai Lạt ma hay mẹ Têrêsa hay ở một vài siêu nhân, thánh nhân nào đó.  Câu hỏi được đặt ra cho chúng ta là, làm thế nào chúng ta thực tập tâm từ?  Tất cả chúng ta có thể thực tập tâm từ và học cách thương yêu theo lối này.  Cái gì làm cho tính chất hàm dung ôm trọn của tâm từ có thể thực hiện được? <br />
<br />
Cách đây vài năm, tạp chí Harvard Medical Journal có đăng một bài báo về một bác sĩ Tây Tạng, tên là Tenzin Chodak, vị này từng là y sĩ chăm sóc riêng cho ngài Đạt lai Lạt ma.  Vào năm 1959, bác sĩ Chodak bị Trung Quốc tống giam.  Suốt 17 năm đầu của khoảng thời gian 21 năm trong tù, ông bị đánh đập và tra khảo hằng ngày–cả về thể xác lẫn tâm hồn–và mạng sống ông không ngớt bị đe dọa.  Thật đỗi ngạc nhiên, ông thoát khỏi tình trạng khủng khiếp này gần như là không có các dấu hiệu chấn động tâm thần sau thời kỳ chấn thương gì cả.<br />
<br />
Bài báo cho biết bác sĩ Chodak đã phơi bày tinh túy tuệ giác mà ta cần hiểu như là 4 điều quán chiếu cốt yếu, mà chính chúng chẳng những đã giúp ông sống sót–người ta sống sót trong nhiều điều kiện khủng khiếp bằng nhiều cách–mà lại còn giúp ông thành tựu được tính chất cao thượng vĩ đại của trái tim.  Cô ký giả Claude Levenson đã mô tả bác sĩ Chodak trong một bản tóm tắt tiểu sử về ông như sau đây:  “Hình như bạn chẳng hề chú ý tới bác sĩ Chodak khi ông đi ngang qua cho tới lúc bạn bắt gặp cái nhìn sâu thẳng của ông–một cái nhìn tràn đầy sự cảm nhận của một người từng thấy biết quá nhiều mọi thứ, cái nhìn vượt xa hơn sự khổ đau mà ông đã kinh nghiệm qua, vượt lên trên tội lỗi xấu xa và hành hạ ngược đãi mà ông đã chứng kiến, tuy nhiên, biểu lộ được tâm bi mẫn vô biên dành cho những con người đồng loại.”<br />
<br />
<b>Bốn Điều Quán Chiếu Trong Những Giai Đoạn Đau Đớn Khốn Cùng</b><br />
<br />
Thứ nhất, ta phải nỗ lực để nhìn thấy mỗi một tình trạng trong một bối cảnh rộng lớn hơn.  Giống như đức Đạt lai Lạt ma–ngài thường nói về kẻ thù sẽ chỉ dạy cho mình đức tính kiên nhẫn ra sao–bác sĩ Chodak xem kẻ thù như là vị thầy tâm linh của mình và dẫn dắt ông tới chỗ tột cùng của tâm bi mẫn và sáng suốt.  Vì vậy cho nên, ông cảm thấy ngay cả trong những tình huống kinh khiếp và tồi tệ nhất, phẩm chất cao thượng của trái tim có thể được thành tựu tới mức toàn vẹn.  Lẽ đương nhiên, nghĩ ngợi về nó thì dễ; điều trở ngại thách thức chính là ta phải ghi nhớ và ứng dụng sự thấy biết này trong những giai đoạn khó khăn.<br />
<br />
Thứ nhì, ta phải nhìn thấy kẻ thù hay người khó tính trong cuộc sống của ta cũng là những người giống như chính ta vậy.  Bác sĩ Chodak không bao giờ quên cái tình cảnh như nhau của thân phận con người.  “Luật nghiệp báo” có nghĩa là mọi hành động của ta đều có hậu quả:  những hành động trổ quả căn cứ trên những tác ý đằng sau chúng.  Người nào hành động ác nghiệt đối với ta thì thực sự cũng đang sống trong những nghịch cảnh, giống y như là ta vậy đó, vì họ đang tạo nghiệp bất thiện khiến họ sẽ phải chịu khổ trong tương lai.<br />
<br />
Tuy thế, ta không nên nghĩ về nghiệp như là “họ sẽ nhận lãnh hình phạt,” như là một loại phương tiện trả thù trong vũ trụ.  Mà đúng ra là nhìn thấy được thân phận con người như nhau có thể giúp ta trở thành suối nguồn bi mẫn.  Đức Đạt lai Lạt ma nói, “Những kẻ thù của bạn có thể bất đồng ý kiến với bạn, có thể hãm hại bạn, nhưng trong một khía cạnh khác, họ vẫn là con người giống như bạn.  Họ cũng có quyền không phải chịu khổ đau và tìm thấy hạnh phúc.  Nếu tâm thấu cảm của bạn có thể trải rộng ra như vậy, thì đó chính là tâm bi chân chánh, không thiên vị.”  Hiểu biết nghiệp báo–mà ta sẽ gặt lấy quả báo từ những hành động của mình–như là một phương tiện vun bồi tâm bi thì đó mới chính là tuệ giác mà ta có thể bây giờ mang vào đời sống mình.  Hết thảy chúng ta cùng ở trong tình trạng như nhau là bị chi phối bởi quy luật nghiệp báo nhân quả.<br />
<br />
Thứ ba, ta phải xả bỏ lòng kiêu hãnh và cảm giác quan trọng hóa bản thân mình.  Những thái độ này, mà chúng rất dễ khởi lên trong những thời gian xung đột, sẽ trở thành những hạt giống chồng chất thêm khó khăn trở ngại.  Điều này không có nghĩa là ta nên chấp nhận một lập trường khiêm cung giả tạo hay là xả thân quên mình.  Đúng hơn là, ta buông bỏ khuynh hướng phóng đại thêu dệt mình, hoặc giữa cá nhân với nhau hoặc trong vòng khuôn khổ tâm lý thầm kín trong ta.  Một câu truyện cổ tích Trung Hoa đã sử dụng thiên nhiên để minh họa tính chất bảo hộ vĩ đại của đức tính khiêm cung thật sự:  Nhà hiền triết Trang Tử đang tản bộ với một đệ tử trên đỉnh đồi.  Họ thấy một cây cổ thụ cong vẹo mà không có nhành nào suôn thẳng cả.  Người đệ tử nói cây này vô ích, nó không được dùng vào việc gì cả, và Trang Tử đáp lại, “Đó là lý do tại sao cây này là cổ thụ.  Dường như ai cũng biết ‘sự lợi ích của nó thật là có lợi biết bao.’  Nhưng mà hình như không ai biết ‘sự vô ích của nó thật là hữu ích biết bao.’”<br />
<br />
Bác sĩ Chodak thực tình cho rằng ông ta sống sót được là nhờ khả năng buông bỏ sự quan trọng hóa bản thân mình và tự cho mình là đúng.  Sự quán chiếu này mang lại một bài học thật đáng giá trên con đường phát triển tâm linh, một bài học mà nó sẽ trở tới trở lui với tất cả chúng ta.  <br />
<br />
Thứ tư, sự quán chiếu, mà nó đã nuôi dưỡng sự thành tựu lớn không ngờ được của trái tim của bác sĩ Chodak, và là điều mà ta phải thực sự hiểu biết lấy qua chính bản thân mình, đó là lấy oán trả oán thì oán thù không bao giờ chấm dứt được; oán thù chỉ được kết thúc khi được đáp lại bằng tình thương.  Nhiều truyền thống tâm linh nhìn nhận lẽ thật này.  Trong những tình huống mâu thuẫn, tâm từ và tâm bi sẽ nẩy nở khi ta hiểu rõ chúng chính là động lực lợi lạc nhất cho phương lối ứng xử có hiệu quả.<br />
<br />
Có thể nào ta duy trì được những cái nhìn này ngay cả trong những hoàn cảnh ít nguy ngập gay go?  Khi người nào đó giận dữ đối với bạn, hay là bạn ở trong vài tình thế khó khăn, hãy nhớ rằng chính sự khó khăn trắc trở này làm cho lòng nhẫn nhục và tình thương trong bạn vững mạnh thêm.  Trong những hoàn cảnh này, ta có thể tự thẩm vấn lấy mình, là ta sẽ thành tựu tính chất cao thượng vĩ đại của trái tim mình ra sao, hãy nhắc nhở mình rằng mọi người cùng chung chia sẻ mối nối kết nhân loại, hãy buông bỏ niềm kiêu hãnh, và hiểu rằng, cuối cùng rồi nỗi oán hận và thù hằn sẽ chỉ ngừng dứt bằng tình thương mà thôi. <br />
