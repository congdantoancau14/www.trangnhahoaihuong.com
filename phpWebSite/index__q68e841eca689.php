<b>SÁCH MỚI: ƯỚC VỌNG DUY TÂN</b><br /><br />


<i><a href="http://www.amazon.com/Uoc-Vong-Duy-Tan-Vietnamese/dp/0986009520/ref=sr_1_1?ie=UTF8&amp;qid=1353240534&amp;sr=8-1&amp;keywords=uoc+vong+duy+tan"  style="text-decoration: none" target = _blank><img src="/img/UVDT_cover_s.jpg" align="left" hspace="5"></a>
<div align="center"><br />
<b>ƯỚC VỌNG DUY TÂN<br />
A DREAM FOR VIETNAM<br />
Tuyển tập TRẦN NGỌC NINH<br />
VĂN HÓA - HUYỀN THOẠI - VĂN HỌC SỬ<br />
TRẦN UYÊN THI chủ biên</b><br />
<br />
Sách dày 472 trang, do VIỆN VIỆT HỌC xuất bản, 11/2012<br />
Có thể mua trên mạng <a href= "http://www.amazon.com/Uoc-Vong-Duy-Tan-Vietnamese/dp/0986009520/ref=sr_1_1?ie=UTF8&amp;qid=1352578863&amp;sr=8-1&amp;keywords=uoc+vong+duy+tan" target = _blank>www.amazon.com</a><br />
<br />
Sách này bắt đầu với một cuộc phỏng vấn Giáo sư TRẦN NGỌC NINH bởi cô TRẦN UYÊN THI, một môn sinh của Giáo sư, để soi sáng và thảo luận về những đường hướng mới của Giáo sư trong sự khảo sát về văn hóa và văn minh Việt Nam, đặc biệt là huyền thoại học, ngữ lí học và văn học sử. Cuộc phỏng vấn này cũng là một sự dẫn đường trong sáng và dễ hiểu vào công trình và tư tưởng của Giáo sư. Sau những bài phỏng vấn là một tuyển tập chọn lọc một số bài viết của chính Gs. Trần Ngọc Ninh, có bài mới và cũng có bài cũ nhưng nay đã bị biếm không còn được lưu hành hay tàng trữ ở Việt Nam. Những bài này, tuy là viết cho một số độc giả không chuyên môn rộng, nhưng với giọng văn hàn lâm cẩn trọng, có thể giúp cho những độc giả lưu tâm đến các vấn đề văn hóa hiểu rõ và định giá các lí thuyết của Giáo sư. Sau cùng là những cảm nghĩ của một số sinh viên và đồng nghiệp của Gs. Trần Ngọc Ninh về ngữ lí học Việt Nam.<br />
Đây là một cuốn sách cần yếu cho tất cả các sinh viên và các nhà khảo cứu về văn hóa, huyền thoại và ngôn ngữ nói chung và Việt Nam nói riêng.<br />
</div></i><br /><br />


<br />
<br />
<br />
<br />
<br />
"ƯỚC VỌNG DUY TÂN là ước vọng một đời của Thầy chúng tôi cho Quốc gia, Dân tộc. Trong bất cứ thời đại nào, đó luôn luôn là ước vọng của những người tự khoác lên hai vai trách nhiệm và lương tâm của một kẻ sĩ, được ghi lại sớm nhất là trong bản ‘Bình Ngô Đại Cáo’ của Lê Lợi và Nguyễn Trãi — hai kẻ sĩ chân chính và vĩ đại của đất Việt:  ‘Tứ hải vĩnh thanh, đản bố duy tân chi cáo.’ (Bốn bể nước trong mãi mãi lặng sóng, ta nay tuyên cáo một nền DUY TÂN khắp chốn).”<br />
<br />
<b>Vì sao sách này?</b><br />
<br />
(1) Ngữ pháp của thế giới đã đi vào Ngữ pháp Hoàn vũ (Universal Grammar). Việt Nam cũng phải tự tìm một con đường mới cho ngữ pháp Việt ngữ, nếu không muốn bị đẩy ra ngoài lề kỉ nguyên của máy móc kĩ thuật, trong đó khoa học tri thức (cognitive science) và ngữ lí học vi tính (computational linguistics) là hai lãnh vực đang đứng ở mũi đầu tàu. <br />
<br />
(2) Huyền thoại (mythology) của các dân tộc trên thế giới đã một thời bị hiểu lầm chỉ là những chuyện kể cho trẻ con, là sản phẩm của những bộ óc ‘sơ khai’, nay đã được khám phá là một kho tàng chứa đựng những tiềm năng khảo cứu và những tư tưởng thâm sâu: với Joseph Campbell, huyền thoại là một nét tôn giáo tiền sử, với những nghi lễ (rituals) giàu ý nghĩa tâm linh, tâm lí, và xã hội, rất cần được học hỏi, tìm hiểu; với Lévi Strauss, nó phản ánh những mô hình, những cơ cấu tri thức của con người, với những cặp đối nghịch (thiện/ác, sống/chết, thiên nhiên/con người...); với Carl Jung, nó là những mẫu hình cổ sơ (archetypes), phản ánh tâm lí của cái vô thức (unconscious), v.v... Việt Nam, hơn nhiều nước trên thế giới, có mấy ngàn năm văn hiến, và tất nhiên là có một di sản huyền thoại. Nhưng huyền thoại Việt Nam đã được hiểu, được đánh giá đúng mức hay chưa, và có còn giữ được sự trong trắng, nguyên sơ lúc ban đầu hay không? <br />
<br />
(3) Văn hóa, truyền thống vừa là một kho tàng quí báu, vừa là một gánh nặng cho một dân tộc. Làm thế nào để hội nhập và học hỏi những cái mới, đồng thời giữ gìn những giá trị cao đẹp và vô giá của truyền thống? <br />
<br />
(4) Khoa học mang lại những tiện nghi tốt đẹp cho con người, nhưng khoa học không có đạo lí là một khoa học thiếu nhân bản. ‘Tuy rằng văn minh và văn hóa là cùng một gốc, nhưng là hai mặt của cùng một cái. Càng lên cao thì hai cái càng chia rẽ ra và phản lại nhau. Văn minh tột đỉnh, trong đó khoa học làm chủ, thì không còn có văn hóa nữa’ (TNN). <br />
<br />
Đó là một số đề tài và vấn đề nan giải được Giáo sư Trần Ngọc Ninh soi sáng bằng một cái nhìn khoa học, tiến bộ, và nhân bản. <br />
<br />
Một số phát kiến mới mẻ của Gs. Trần Ngọc Ninh trong lãnh vực văn học sử: Nguyễn Du và Quan Họ, nguồn gốc thơ Lục Bát, một bài thơ độc đáo của Nguyễn Trãi viết trước khi chết… cũng được tuyển chọn vào sách này…<br />
<br />
(Trích “Vì Sao Sách Này?”, TUT)<br />
