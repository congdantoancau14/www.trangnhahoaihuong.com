<h3>Chuyện bên lề chữ Nôm</h3>



<h3>Nguyễn Văn Sâm</h3>
<br />
<i>Song viết, suông nhạt, song nhật rồi rong vát,<br />
Rừng chữ Nôm bát ngát, chẳng làn đan.</i><br />
				(NVS)<br />
<br />
 <br />
Nói chuyện về chữ Nôm hài thanh, hội ý, chữ thuần Nôm, chữ mượn Hán, chữ Nôm đời Hồng Đức, thời Nguyễn Trãi, sự thay đổi của mỗi chữ Nôm theo thời gian, sự biến âm  biến thanh khi mượn chữ Hán để tạo chữ Nôm, các âm cổ vv... sẽ làm nặng nề tâm trí người đọc. Nói chuyện về tài liệu chữ Nôm sách nọ sách kia, tờ a tờ b , chữ nầy đọc làm sao, chữ kia đọc làm sao, người nghe/đọc thấy thêm điều mới đó, nhưng sẽ dễ ngáp dài, ngán ngẫm. Tôi lâu nay vốn ngại nói chuyện mà dẫn sách, dẫn trang cho nên chỉ xin đi ngoài rìa chữ Nôm gọi là chia vui vài ba chuyện liên quan đến kỷ niệm riêng tư của mình về chữ Nôm. <br />
<br />
Đầu thập niên 60 của thế kỷ trước tôi được thụ giáo với Giáo sư Bửu Cầm về môn <i>Nhập Môn Chữ Nôm</i> trong chứng chỉ Văn Chương Quốc Âm khi chứng chỉ nầy mở lần đầu tiên ở trường Đại Học Văn Khoa Sàigòn. Cũng có thể là tôi nhớ lầm, có khi cái giảng khóa nầy nằm trong chứng chỉ Văn Chương Việt Hán không chừng. Gần nửa thế kỷ trôi qua, trí nhớ đã trở nên tồi tệ, phải thú thiệt là không nhớ chắc chắn về chuyện nầy. Bài giảng suốt năm của thầy gồm Ưu và Khuyết Điểm của Chữ Nôm, và phần về Cấu Tạo Chữ Nôm. Bản văn dùng làm thí dụ cụ thể là <a href="http://www.trangnhahoaihuong.com/phpWebSite/index.php?module=documents&amp;JAS_DocumentManager_op=viewDocument&amp;JAS_Document_id=5">Nam Cầm Khúc</a> của nhà thơ nổi tiếng Tuy Lý Vương.<br />
 <br />
Vốn liếng chữ Hán không nhiều, việc học lơ là lơ lãng cho nên sau đó chữ thầy lại trả gần hết cho thầy, tôi chỉ còn nhớ câu “Nam Cầm xin phổ một bài" và nhớ đại cương về sự cấu tạo của chữ Nôm, như thuần Hán, đọc trại chữ Hán, Hài thanh, Hội ý.<br />
<br />
Vậy mà hành trang ban đầu đó rất tốt. Bao nhiêu năm về mặt phân tích sự cấu tạo chữ Nôm các đại gia có sách in sau nầy như Đào Duy Anh, Trần Văn Giáp, Lê Văn Quán, Nguyễn Tài Cẩn.., hay những nhà Nôm-học gần đây như Nguyễn Ðình Hòa, Vũ Văn Kính, Nguyễn Khuê, Đặng Đức Siêu... cũng đều không phát kiến được điều gì gọi là mới hẳn hơn những khái niệm đó. Một vài sửa đổi chi tiết nếu có cũng chỉ là sửa mũ mấn, không đáng kể. Chữ Nôm về địa hạt cấu tạo nội tại từng chữ ...  như đã bị đóng băng, người nghiên cứu chỉ có thể đọc để biết, chứ mong tìm điều gì tân kỳ trong sự cấu tạo để đưa ra một nguyên tắc chung có thể giải thích tại sao người xưa viết thế nầy, thế kia thiệt là quá khó. Con đường người trước đi đã mòn, gai góc đã được dọn sẵn, đá đinh lởm chởm đã được dọn vào lề, ta chỉ việc cám ơn và thu lượm thành quả, công việc của ta đi sau dễ dàng, hình như chỉ còn cần một chút phủi bụi trên dĩa trái cây đã dọn sẵn...<br />
<br />
Rồi sống lâu lên lão làng, đầu thập niên 70, tôi được Giáo Sư Lê Ngọc Trụ cho phụ trách môn chữ Nôm trong chứng chỉ Ngữ Học, song song với Giáo Sư Trần Đức Rật đã dạy môn nầy từ trước, tại trường Đại Học Văn Khoa Sàigòn. Rút kinh nghiệm của mình, biết sinh viên ngán ngẫm cái môn nầy vì vốn liếng chữ Hán cần thiết nhiều khi họ thiếu, tôi chỉ quanh quẩn ở phần cấu tạo, không có thời giờ và không dám nói gì khác hơn, kể cả khi dạy môn nầy tại Viện Đại Học Cao Đài và Viện Đại Học Cần Thơ. Những năm cuối cùng của thời chiến tranh, sinh viên một mắt lướt qua giảng khóa nhưng một mắt nhìn về núi rừng có nhiều tiếng súng và chết chóc, có bắn sẻ, bắt cóc, nhà cháy, tiếng khóc...<br />
<br />
Thời gian để đối phó với bất trắc nhiều hơn là thời gian cặm cụi cho những chữ không còn dùng mà có biết hay không biết cũng vậy thôi, chẳng chết thằng Tây nào. Tôi hiểu điều đó. Ba-lô làm bàn nên nét chữ không ngay, khi viết thơ tình, nhưng ba-lô cũng là thư viện lưu động bỏ túi nên học hành có hơi vất vả, chễnh mảng. Bây giờ nghĩ lại tôi không biết ngày xưa mình có quá tay không khi thí sinh mặt mày còn vương bụi đường và trên cổ áo hoa mai một hai ba nụ. Chỉ sợ rằng cầm cân quá thẳng mà không để ý đến những khía cạnh khác của những người gọi là thí sinh trước mặt, giờ nhớ lại lấy làm thống trách, chỉ còn biết tự an ủi rằng thời trẻ người ta chưa được cái nhìn tổng thể.<br />
<br />
Gần đây, một sinh viên cũ, thi sĩ T.L.Thảo, nhắc lại là lúc đó thầy quá khó, các cô vào vấn đáp quá sợ vì môn đó không dễ nuốt trôi mà thầy thì cứ cầm cân thẳng băng.<br />
<br />
Ôi! Nghe nói vậy tôi nhột nhột nhớ đến chuyện ngụ ngôn đọc được đâu đó kể về một tráng sĩ được lệnh sư phụ xuống núi trừ gian diệt bạo. Quá mẫn cán trong công việc, không biết bao dung, không suy đoán ngọn ngành, người tráng sĩ đã diệt bạo hơi nhiều đến khi lòng mình chai cứng trước chết chóc và đau khổ. Một hôm tráng sĩ nhìn gương mặt mình phản chiếu trong lòng suối thì thấy đã biến dạng, dòng suối hiện ra gương mặt sát khí của một loài quỷ dữ.<br />
<br />
Chắc mình lúc đó cũng vậy thôi! Ba mươi năm sau, ngồi buồn nghĩ lại chuyện xưa bỗng nhiên cả thẹn, thấy mình có lỗi. Ba cái chữ Nôm trúng trật chút đỉnh có gì to lớn lắm đâu. Bên ngoài giảng đường ầm ì súng vẫn nổ xa gần, mìn bẫy vẫn rình rập con người từng bước, chuyện ngưng bắn da beo da gấu là thời sự hằng ngày sao mình lại quá chú ý tới chuyện nhỏ nhoi nôm với niếc!<br />
<br />
Bây giờ đọc một chữ Nôm ai đó phiên âm tôi nghĩ là chưa chính xác lắm, ai giải thích một chữ Nôm tôi cho rằng có thể làm hại người đi sau, tôi chỉ mỉm cười cho rằng chuyện nhỏ, không có gì mà ầm ĩ. Chắc gì mình đã đúng. Chắc gì những chữ đọc như vậy  giải thích như vậy đã hại người đi sau. Sẽ có người nào đó sửa sai thôi, nếu có sai.<br />
<br />
Học chữ Nôm có người suốt đời không được hân hạnh nhìn thấy một bản Nôm gốc, in trên giấy bản, còn nói rằng phát hiện được một bản Nôm mới, học giới chưa ai gặp lại là chuyện cơ duyên hơn nữa.<br />
<br />
Tôi cám ơn ông thầy thuốc Nam ở cù lao ông Chưởng, năm 1969 đã tặng cho tập sách chữ Nôm chép tay trên giấy bản, tiếc rằng mình chỉ mới công bố được bản <i>Sãi Vãi Tân Lục Quốc Âm</i> thì Miền Nam sập tiệm, phần còn lại trong đó có mấy bài <i>Văn Tế</i> của Nguyễn Đình Chiểu, bài <i>Gia Định Phong Cảnh Ca Vịnh</i> của Hai Ðức, bài <i>Hoài Cổ Phú</i> của Võ Trường Toản... theo gió như mây ngàn bay vào cõi hư không chẳng bao giờ còn tìm lại được. Ôi tiếc ơi là tiếc!<br />
<br />
Tôi cám ơn bác nông dân vô danh ở vùng chợ Tân Châu tỉnh Châu Đốc, năm 1970 đã cho người con trai leo lên cây đòn dông chánh trong nhà gỡ xuống tặng tôi quyển sách chữ Nôm <i>Kim Cổ Kỳ Quan</i> bác nói là do cha mình treo lên đó khi cất nhà mấy chục năm trước. Quyển sách nầy tôi cũng quí như vàng vậy mà cũng không đem theo được trên đường vượt thoát, nay về lại vùng nhà cũ thì mọi sự đã đổi thay, bâng khuâng không biết đâu là nhà mình, người chung quanh nhìn mình lạ lẫm nhĩ hà phương lai, còn hỏi gì được chuyện sách vở xưa cũ. Ôi uổng ơi là uổng, nhớ đến còn thấy ngẩn thấy ngơ!<br />
<br />
Rồi qua đây, duyên kỳ ngộ tôi gặp được nhiều cao nhân cung cấp cho nhiều bản Nôm quí, quí không phải vì là nguyên bản khắc, viết trên giấy xưa cũ nát, đời nầy làm gì ai có được nguyên bản nữa, quí vì đó là những tài liệu chưa sách vở nào nói tới, chưa từng được ai phiên âm. Chẳng hạn như <i>Tuồng Nhị Ðộ Mai, Tuồng Tam Quốc Diễn Nghĩa, Tuồng Lôi Phong Tháp, Tuồng Tây Du, Tuồng Ngũ Hổ Bình Liêu, Tuồng Vạn Bửu Trình Tường...</i> Nghĩ rằng mình gặp vậy là mình có duyên với các bản văn đó, bèn hè hụi đêm ngày đọc đọc phiên phiên. Cơm áo gạo tiền chiếm gần hết thời gian trong ngày, tuổi đời càng ngày càng cao, sức khỏe mỗi ngày mỗi kém nhưng tự hứa sẽ không để như hai chuyện mất mát lần trước xảy ra, thời giờ có bao nhiêu đều dồn cho các quyển sách mà các con tôi nói là chữ rồng rắn không giống ai, ba có làm gì rồi thì cũng chẳng ai buồn đọc, nói gì được người ta bỏ tiền ra mua, ba đi vào ngõ cụt vì chẳng có thị trường.<br />
<br />
Ôi, việc đời mỗi người mỗi ý. Như một số anh chị em trẻ già nhiều nơi trên thế giới đã bỏ ra hai năm ròng rã thực hiện quyển <i>Tự Điển Chữ Nôm Trích Dẫn</i> dạng điện tử để học giới bốn phương đọc được những câu trích dẫn từ trong nguyên bản Nôm, đặc biệt là có thể sao chép, trao đổi vì được hổ trợ bằng kỹ thuật hiện đại và mã số quốc tế của từng chữ một.<br />
<br />
Rồi lại có hai người trẻ, ở hai lục địa khác nhau, nhập những chữ Nôm người trước đã tìm tòi vô kho dữ kiện để làm nên Bàn-Gõ-Hán-Nôm. Bàn gõ nầy tôi cho là về mặt Nôm-học có thể ví với phát minh bánh xe của người thời thượng cổ. Từ đây việc đánh máy để sao chép bản Nôm đã trở nên dễ dàng vô cùng. Trong vài năm tới các tác phẩm xưa như <i>Bạch Vân Quốc Ngữ Thi, Hồng Ðức Quốc Âm Thi Tập, Đoạn Trường Tân Thanh, Cung Oán Ngâm Khúc...</i>, ngay cả các tuồng thật dài, sẽ được phổ biến rộng rãi trên mạng lưới toàn cầu bằng chữ Nôm, ai cần cứ lên đó hạ tải là có, văn bản Nôm sẽ không còn là thứ quí hiếm người ta giữ lấy khư khư làm của riêng như từ trước đến nay! Người khảo cứu về loại tử ngữ nầy vì vậy sẽ đông đảo hơn, sự giới thiệu với người ngoại quốc vì vậy cũng sẽ được sâu rộng hơn. Vui thay với viễn tượng trăm hoa đua nở đó!<br />
<br />
Nguyên nhân có <i><a href="http://www.viethoc.org/hannom/tdnom_intro.php" target=_blank>Tự Điển Chữ Nôm Trích Dẫn</a></i> và <a href="http://www.viethoc.org/hannom/bango_chidan.php" target = _blank>Bàn-Gõ-Hán-Nôm</a>? Đó là do vài Giáo sư và học viên của lớp Hán Việt trên mạng gợi ý và bắt tay thực hiện ngay khi tài liệu còn chưa thu thập được bao nhiêu. Lại một chuyện nữa đáng khen!<br />
<br />
Nhân buổi sinh hoạt kỷ niệm "Năm năm thành lập Viện Việt Học" tôi viết bài nầy vì nghĩ rằng có sự hiện diện của Viện Việt Học mới có lớp Hán Việt và từ đó dẫn đến những công trình quan trọng vừa nói...<br />
<br />
Và biết đâu trong tương lai còn có những công trình khác nữa!<br />
