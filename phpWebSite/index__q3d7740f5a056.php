<h3>Huyền Không Ðộng </h3>



Thạch bích lăng không cổ thụ hoành <br />
Nhãn trung thiên địa tối phân minh <br />
Dục cầu Ðỗ Phủ (1) thi nan trạng <br />
Túng hữu Vương Duy (2) họa bất thành <br />
Tự tiếu niên lai vô dị học <br />
Mỗi đăng cao (3) xứ úy bình sinh <br />
Danh đề động lý tu tri ngã <br />
Tuy Lý (4) vương tôn Thúc Giạ Bình<br />
<br />




<h3>Huyền không Ðộng</h3>



Vách núi cao ngút, cây lớn nằm chắn ngang <br />
Cảnh đất trời phân chia rõ rệt trước mắt<br />
Dù thơ Ðỗ Phủ cũng khó được hết ý <br />
Dẫu Vương Duy vẽ chăng nữa cũng vẽ chẳng thành <br />
Tự thẹn năm dài không học hỏi gì thêm điều mới lạ <br />
Mỗi lần leo núi chơi ngắm cảnh thấy thỏa mãn cuộc đời <br />
Trong động đề tên cho người đời biết <br />
Ta là Thúc Giạ Ưng Bình cháu của ngài Tuy Lý Vương<br />
<br />




<h3>Ðộng Huyền Không </h3>



Vách núi cheo leo đá chắn cây <br />
Rành rành đáy mắt nước trời mây <br />
Thơ dù Ðỗ Phủ lời đành cạn <br />
Họa có Vương Duy vẽ cũng gay <br />
Tự thẹn ngày không phương học mới <br />
Mãi trèo non ngắm thỏa đời này <br />
Tên đề trong động cho đời biết <br />
Thúc Giạ cháu ngài Tuy Lý đây<br />
<br />
<i>Nguyễn Hữu Vinh dịch, Taiwan, 1995</i><br />




<h3>Chú thích</h3>



Lời tác giả: Động tại Ngũ Hành Sơn thuộc Quảng Nam tỉnh, Ðiện Bàn phủ, Hoài Khái xã  洞在五行山屬廣南省奠磐府淮溉社 <i>Động trong núi Ngũ Hành, thuộc xã Hoài Khái , phủ Điện Bàn, tỉnh Quảng Nam.<br />
<br />
</i>Thử tác tại thiếu niên lãng du thời kỳ 此作在少年浪遊辰期<i>Thơ làm trong thời còn trai trẻ hay đi ngao du.</i><br />
_____________<br />
1) Đỗ Phủ (712-770) tự xưng là Ðỗ Lăng bố y 杜陵布衣 và Thiếu Lăng dã lão 少陵野老 một nhà thơ lớn đời Ðường.<br />
<br />
2) Vương Duy (701-761) tự là Ma Cật 摩詰 giỏi thơ, họa và thư pháp. Ðược tôn là thủy tổ của phái họa đời Nam Tống 南宋. Tô Ðông Pha 蘇東坡 khen rằng "Thi trung hữu họa, họa trung hữu thi 詩中有畫，畫中有詩 <i>Trong thơ có họa, trong họa có thơ.</i> Một nhà thơ lớn đời Ðường.<br />
<br />
