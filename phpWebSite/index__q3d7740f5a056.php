<h3><H2>玄空洞</H2></h3>


<H2>
洞在五行山屬廣南省奠磐府淮溉社<br />
此作在少年浪遊辰期	<br />
<br />
石壁凌空古樹橫<br />
眼中天地最分明<br />
欲求杜甫詩難狀<br />
縱有王維畫不成<br />
自笑年來無異學<br />
每登髙處慰平生<br />
名題洞裡須知我<br />
綏理王孫叔野苹</H2>
<br />
<br />
<br />
<br />
<br />


