<h3>Quê hương mình</h3>



<b>NGUYỄN VĂN SÂM</B><br />
<br />
<i>Họ đã  ngã rạp trong chốn<br />
ma thiêng nước độc <br />
để lót đường cho con cháu đi tới... </i>   <br />
(Bình Nguyên Lộc)<br />
 <br />
