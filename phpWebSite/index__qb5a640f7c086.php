  Thằng Đực hỏi khôn hỏi khéo, nhắc lại bổn phận tự đặt khi thoáng thấy một thứ tình cảm gì đó lạ lùng lắm, hiện diện trên gương mặt xương xẩu của nội nó. Nó xốn xang vì giọt nước mắt thì ít mà vì sự im lặng đương phũ trùm trong ghe thì nhiều. Nó bỗng nhiên có cảm tưởng mình được nối kết thật chặt chẽ với một khung cảnh mà lâu nay chỉ mường tượng là vắng vẻ, đìu hiu nhưng đã chứa chấp tổ tiên ông bà mấy đời trước đó, với những quần vải áo bô, mặt xương, chưn mốc, tóc hớt cao, những người mà trước đây nó thờ ơ, xa lạ thậm chí còn khi dễ.<br />
<br />
   'Mà con nói cho nội biết tại sao con nghĩ tới chuyện đó?'<br />
<br />
  Thằng Đực câm họng, không biết nói sao để diễn ý thành lời. Lớn đại, mười hai, mười ba tuổi đầu, nhưng nó chưa hề suy nghĩ trừu tượng, cũng như diễn tả tình cảm của mình. Nó đứng đực mặt, bậm môi, rặn lắm, nhưng cũng không nói được hết ý:<br />
<br />
   'Con nghĩ là....là con hên hơn họ...Họ...xui xẻo...chớ không phải ai tài giỏi gì hơn ai?'<br />
<br />
   Dì Tư không ngờ được có câu trả lời như vậy. Dì tưởng mình sẽ nghe về tình người, tình dân tộc, đồng bào, trái lại đụng nhằm một câu nói trúng ngay thực tế. Phải, người hên người xui nên thành người chợ búa kẻ quê mùa thôi. Không có gì khác hơn chơn lý đó.<br />
<br />
   'Ừ! Ở đời mỗi người đều có phước có phần riêng. Trời cho ai nầy hưởng. Quê chưa chắc xấu, thành thị chưa chắc hay. Hay là quê mà không ngu dốt, không hủ lậu, thành thị mà không lém lỉnh, gạt người và che đậy một cách tức cười cái gốc gác của ông bà tổ tiên. Tao thấy có người mới tới đây đâu có bao lâu, gặp thời xưng hùng xưng bá, nói láo ngang láo dọc mà không biết mắc cỡ miệng tao bắt tức cười... Với tao thì quê hương tao luôn luôn là hình ảnh sáng chói trong lòng mặc dầu đã xa xứ từ lâu.'<br />
<br />
   Con Gái bình thường bô bô cái họng hỏi không liền da non, bữa nay cũng thấy khớp trước những điều mới mẻ vừa được nghe. Nó bâng khuâng vừa bồn chồn vừa bùi ngùi. Nó nhớ tới một đứa nhỏ cũng chừng trạc tuổi nó, cặp mắt ngơ ngác, khô cằn, cái kẹp ba lá kẹp sau đuôi tóc, bận cái áo túi bông xanh xanh, cả ngày lúc thúc, lủi thủi trong khoang chiếc ghe chở nồi ơ, cà ràng, ông lò mấy bữa rày đậu kế bên ghe nó mà mỗi lần nó trừng mắt làm bộ bậm trợn để hù nhát thì con nhỏ lấm la lấm lét quay mặt đi hay cúi gầm xuống im thin thít. Nó ước thầm trong bụng. Ưng ai mai mốt ghe đó đậu chỗ này nữa để tôi làm quen với con nhỏ đó, tôi xin lỗi nó. Lúc đó tôi đâu biết giỡn chơi như vậy là bậy. Ưng ai ông địa làm phước!<br />
<br />
    Nó ngó ngọn lửa đã tàn trong lò, mấy cục than đã cháy gần hết đương bắt đầu phủ một lớp tro trắng xám chung quanh, ánh lửa lâu lâu sáng hực lên, chiếu bóng khói lên vách ghe mỗi khi có cơn gió thổi lòn vào trong mui. Nó nhìn chăm chú ánh lửa, mơ màng thấy mình với con nhỏ có cặp mắt ngác ngơ, nắm tay nhau đi xuống phía chưn cầu, chỗ xác mía chất chồng đầy dẫy, tay trong tay vừa cười nói thân thiết vừa dòm thán phục mấy chị đàn bà đương lanh lẹ róc mía chất lên mấy cái xe ba bánh, và nó đã mạnh dạn nài một khúc ngon ớn bẻ hai chia cho con nhỏ.<br />
<br />
   Thằng Đực vẫn đeo đuổi ý nghĩ của mình. Quê hay không quê khác nhau chỉ là rời xứ  sớm hay không mà thôi. Không hay ho gì hết trơn hết trọi. Cái hay ho là biết nhớ biết thương xứ nhà quê của mình, hay nói theo cách của bà nội nó 'Quê hương phải là hình ảnh sáng chói trong lòng'.<br />
<br />
   Lâu lắm dì Tư mới đứng dậy lấy chén đũa dọn cơm. Dì nói lớn một câu vớt vát để phá tan không khí đặc biệt đương trùm phủ không gian.<br />
<br />
   'Thôi ăn cơm bây, trưa trờ trưa trật rồi. Kiến cắn bụng quá! Nãy giờ mấy bà cháu mình lo nói chuyện tầm-ruồng bá-láp không.'<br />
<br />
   Bên ghe đậu gần đâu đó, có chị đàn bà buổi trưa nằm nói thơ giải buồn, hứng chí nói lanh lảnh mấy câu thơ Sáu Trọng thiệt ngọt ngào, nhưng lời thơ thiệt thấm thía :<br />
<br />
  Trọng rằng: 'Buôn bán không lo,<br />
  Nói chuyện đưa đò chè cháo lạnh tanh.'<br />
  Đẩu rằng :'Lòng khiến thương anh<br />
  Cháo chè nguội lạnh cũng đành bụng tôi.'<br />
<br />
   Thằng Đực vảnh mỏ ra nghe, mỗi lần chị ta nói thơ Sáu Trọng là nó khoái trong bụng. Nghe ngày nầy qua ngày khác nó gần như đã thuộc nằm lòng nguyên cuốn thơ. Nó nhớ tới Sáu Trọng người lưu lạc mà anh hùng, thẳng thắn, gan dạ. Nó thấy bà nội nó coi quê mùa dốt nát mà nói ra những điều thiệt đáng kính phục, những điều nó chưa từng học ở nhà trường, chưa từng nghe ai giảng giải mà tạo được xúc động lớn lao như vậy.<br />
<br />
  Nó lập lại trong bụng, tầm ruồng, bá láp, đưa đò! Không tầm ruồng bá láp đâu nội, không đưa đò đâu chị. Ích lợi còn hơn uống mười thang thuốc bổ nữa đó nội. Đáng giá còn hơn bạc ngàn đó chị. Nội đã dạy con yêu mến quê hương, thân thiết với người nhà quê tội nghiệp. Chị đã dạy em nghĩa khí can trường, biết phẫn nộ trước những bất công của cuộc đời.<br />
<br />
   Con Gái đã trở về thực tại sau câu nói của nội nó. Nó tiếc tiếc hình ảnh hồi nãy nhưng cũng nghe lời đứng dậy dọn cơm.<br />
<br />
   Đương bưng nồi cơm xuống để lên cái rế bỗng nghĩ ra một điều, nó lật đật để xuống, phủi tay lia lịa, hỏi một câu thiệt đáng đồng tiền.<br />
<br />
   'Chừng nào mình mới về quê thăm quê mình hả nội?'<br />
<br />
   Dì Tư cảm động ngó cháu. <br />
<br />
   'Cái đó còn tùy nhiều thứ lắm con!'<br />
<br />
   Dì không nói thêm gì, nhưng tiếng con được kéo dài thiệt ngọt ngào, thiệt bao la. Thằng Đực và con Gái ngó nhau, lờ mờ trong trí chúng nó đại để chuyện về quê còn tùy thuộc nhiều thứ mà bà nội chưa thể kể ra ngọn ngành nhưng chắc chắn là sẽ về một ngày nào đó. Câu trả lời của bà, người ngu cách mấy cũng cảm thấy ẩn dấu trong đó một tình cảm dạt dào, sâu đậm, một sự ngóng trông, hướng về; một nỗi niềm tiếc nuối... Hai đứa thấy mình đã hiểu bà, hiểu tại sao ánh mắt bà vời vợi, tại sao câu trả lời như một lời than, một cái chép miệng. Và thằng Đực bới một chén cơm thiệt đầy, kính cẩn đưa hai tay mời bà nó. Con Gái lặng lẽ trở mấy chiếc đũa lộn đầu về một phía, so so rồi lựa đôi tốt nhứt kiếng cho nội. Đôi kế tiếp nó đưa cho anh nó. Thằng Đực đưa tay ra nhận mà lòng tràn ngập khoái cảm. Nó ngước lên ngó em bằng ánh mắt thân thiết. Hai anh em cùng mỉm cười, lâng lâng nôn nao, khác với lúc bình thường hằng ngày như được cho một đồng bạc, một gói xôi, hay ổ bánh mì cá hộp. Lạ lắm. Khác lắm. <br />
<br />
  Bên ghe kia, chị đàn bà đã bỏ thơ Sáu Trọng qua thơ khác, chị ngâm nga nghe đứt ruột đứt gan:<br />
<br />
     'Mười giờ tàu lại Bến Thành<br />
     Xúp lê vội thổi bộ hành xôn xao.'<br />
<br />
   Thằng Đực và con Gái lại đưa mắt ngó nhau lần nữa. Trong trí hai đứa hiện lên đồng loạt khung cảnh bến tàu đò nhộn nhịp ở đằng đầu kia chợ với những người đàn bà áo quần tươm tất từ dưới bước lên, tay dắt mấy đứa nhỏ, ngơ ngác ngó cảnh vật lạ chung quanh. Hai đứa đều ước ao mình được ngồi trong  tàu đò đi về miền quê hương trong tâm tưởng, một thứ quê hương được cấu tạo trong thần trí bằng tình cảm thiêng liêng chớ không bằng một chút kỷ niệm nhỏ nhoi nào.<br />
<br />
    Dì Tư ngồi chống đũa. Con sông trống trải hai bên bờ, vườn mía Tây xào xạc, tiếng chim kêu líu lo buổi sớm, và cái giếng hộc ngọt lịm kế bụi chuối sau hè đã che mất thực cảnh trước mặt.<br />
<br />
NVS<br />
<br />
(Trích từ <i>Ngày Tháng Bềnh Bồng</i>, 1987)<br />
