<h3>Trương Ngáo, những ý nghĩ rời</h3>



<h3>Nguyễn Hiền Tâm</h3>
<br />
Trương Ngáo là tuồng nôm tương đối khó đọc. Chữ nghĩa thì cũng không mắc mỏ gì, từ cổ, tiếng địa phương dùng với một liều lượng vừa phải. Nếu không chê cuốn Tự Vị của Huình Tịnh Của, thì cũng có thể tra cứu hết được. Nhưng sao lại khó đọc?<br />
<br />
Trương Ngáo được khắc in ở Quảng Đông bên Tàu. Cắc chú, nói tiếng Việt thì xí xô xí xào, còn khắc chữ nôm thì trật vuột, ẩu tả. Trương Ngáo là một tuồng hay nhưng khắc ẩu nhứt. Muốn đọc phải vừa mò vừa đoán. Hệt như ông già ưa ăn mắm sống, một tay bóc mắm, một tay vén râu, để lòi cái lỗ miệng mà nhét vô.<br />
<br />
Tuồng là một dạng tuồng hài. Đó cũng là một đặc điểm của tuồng, truyện thơ trong Nam. Về tuồng còn có Trương Ngố, Trần Bồ. Về truyện thơ thì có ông Trượng, Tiên Bửu, Vân Tiên Cờ Bạc, Truyện Chàng Ké… Nhân vật trung tâm là anh Ngáo. Còn Ba Bành, Như Ý, Lục Tồn, cũng khá đặc sắc, nhưng chỉ giữ vai trò tung hứng mà thôi!<br />
<br />
Anh Ngáo, tuy có hơi lù khù, nhưng thiệt thà, tốt bụng. Anh có khùng khịu chỗ nào đâu! Anh sợ vợ, anh bị vợ đánh, vợ chửi, chuyện cũng bình thường. Vợ tui tui sợ, chớ tui sợ vợ người ta sao mà nói! Anh chưa vác lu mà chạy, nhưng nhờ có ông cù độ mạng nên cuối cùng anh sống hạnh phúc. Anh giàu có lại có vợ hết xẩy (Như Ý mà!). Hãy để ý tới lời ăn tiếng nói của Như Ý. Nhỏ nhẹ, dịu dàng, dễ thương hết sức. Mà đó lại là một đứa vô duyên, ế chồng.<br />
<br />
Anh Ngáo ngây thơ, nhẹ dạ, ai nói gì cũng tin, ai xí gạt cũng được. Người hại không sợ, chỉ sợ Trời hại mà thôi. Ngọc Hoàng mà giủ sổ là rồi đời. Có phước có phần không cần gì lo. (Cũng giống chuyện chú làm ruộng thấy - không phải xí được - hủ vàng ngoài ruộng).<br />
<br />
Ba Bành là một chị đàn bà độc đáo. Tên nghe giống như là Ngáo ộp. Chú Ngáo lúc chưa đụng Ba Bành chắc cũng là một chàng trai bình thường. Ba Bành có bùa phép gì mà Ngáo trở nên khùng khịu? Ngáo giống cậu học trò nhỏ bé, tội nghiệp, đứng trước mặt cô giáo mà không thuộc bài. Mà Ngáo đã nhiều lần không thuộc bài. Nhiều cậu học trò, ở nhà học bài cẩn thận, vào lớp, nghe cô giáo kêu tên, sợ quá, quên tuốt.<br />
<br />
Tay dữ dằn như Lục Tồn còn chịu đời không thấu. Đụng con Ba Bành, chú chệc tan nhà nát cửa. Con Ba Bành lớn tiếng rộng họng, chú cũng đâu vừa gì, liền nhào tới bạt tay. Rủi cho chú gặp nhằm cao thủ. Ba Bành la làng, còn chú im re, không dám ho he, mắt trợn trắng. Mà đòn này nhằm nhò gì, chắc Ba Bành còn nhiều ngón nghề tinh diệu khác nữa. Khi sử dụng thì đàn ông rồi đời. Lịch sử còn sờ sờ ra đó. Đát Kỷ, Bao Tự, Tây Thi, Võ Hậu… cùng một môn phái với Ba Bành.<br />
<br />
Tuồng Trương Ngáo là tuồng để coi chơi. Coi chơi được thì nói chơi cũng được. Ba Bành là Quỷ Sứ chứ đâu phải Bà Chúa Sứ đâu mà bắt tôi sợ. Còn ngầy ngà quá thì tôi xin thua. Mô Phật!<br />
<br />
<div align="center"><b>***</b></div><br />
<br />
Đông là biển Nam Hải, Tây là dãy Trường Sơn, phía Bắc là mấy anh Ba Tàu lúc nào cũng lăm le quấy rối, đánh chiếm, cai trị, đồng hóa, dân Việt xưa chỉ còn con đường duy nhứt là giữ vững biên cương phía Bắc, mang gươm, mở cõi, thẳng tiến về phương Nam.<br />
<br />
Đường hướng đó khởi phát từ Trần, Lê, bùng phát từ Lê Trung Hưng, mà người giữ vai trò tiên phuông là Nguyễn Hoàng. Bờ cõi mở mang từ đây, mà vận nước lên xuống,  mầm mống chia rẻ, cũng bắt đầu từ đây.<br />
Thực dân Pháp thâm độc dùng chánh sách chia để trị, nhưng mầm mống bất hòa từ lúc phân chia Đàng Trong, Đàng Ngoài đã có. Tình tự dân tộc lúc nào cũng muốn xích lại gắn bó với nhau, nhưng có những biến cố lịch sử, dầu nhỏ, dầu lớn, cũng khiến cho việc đoàn kết dân tộc khó khăn, chậm lại. Ta thử điểm lại một số mốc chánh: Trịnh, Nguyễn phân tranh, Gia Long thống nhứt, lập Kinh đô ở Huế, trước những cặp mắt khó chịu của sĩ phu và dân chúng Bắc Hà, Tự Đức làm mất đất và cả Nam Kỳ lục tỉnh vùng lên chống giặc (1867), Hòa bình lập lại (1954) và ….<br />
<br />
Quan điểm nhìn cuộc Nam tiến gian lao, vĩ đại, đầy mồ hôi và máu của cả dân tộc cần cù, cứng cỏi như một chương trình di dân lập ấp, đi kinh tế mới tầm thường, đã làm tổn thương đủ mọi thứ của biết bao nhiêu người.<br />
<br />
Nhìn những lưu dân đi mở cõi như một đám tù, lũ chết đói trôi sông lạc chợ, bỏ biết bao công lao khai phá, chưa kịp đứng chân, rửa cẳng, ngồi hưởng một cách xứng đáng những chiến tích vẻ vang của mình, là một cái nhìn lệch lạc tầm bậy.<br />
<br />
Thành quả của họ không được công nhận, họ bị chà đạp, ức hiếp thì làm sao có thể nói rằng họ có một đời sống tinh thần lành mạnh, phong phú, có một nền văn học mới mẻ, tràn trề sức sống.<br />
<br />
Đàng Trong, miền Nam không có một nền văn học đúng nghĩa? Nhưng lịch sử, ít nhiều bị o ép, chỉ với vài nét chấm phá, đã đồng tình, ghi nhận, khẳng định dãy đất phía Nam của tổ quốc từ mấy trăm năm nay, đã có một nền văn học hẳn hoi, nó không èo uột, dở sống dở chết mà ngày càng phát triển mạnh mẽ. Tương ứng với từng thời kỳ lịch sử, ta có văn học Nam Hà, văn học thời Nam kỳ lục tỉnh kháng Pháp, văn chương tranh đấu Miền Nam… [Có cần phải kể thêm Bạch Mai Thi Xã ở Gia định, nhóm Chiêu Anh Các ở Hà Tiên?]<br />
<br />
Miền Nam có in ấn, có báo chí, sách vở. Những tài liệu, tác phẩm hoặc chép tay, hoặc khắc ván, hoặc xếp chữ, bằng chữ Nho, chữ Nôm, chữ quốc ngữ của người Việt sáng tác, dầu né tránh, không muốn chỉ mặt đặt tên, hoặc tịch thâu, đốt bỏ, cấm đoán… nếu nó còn đó, cũng phải dành cho nó một chỗ ngồi, anh không ưng cho ghế mời thời nó ngồi ghế súp.<br />
<br />
Nói thiệt, tôi xấu hổ khi thấy anh lỏ hai con mắt óc bu nhìn Trương Ngáo, Trương Ngố. Anh là ai ? Thằng Tây ba lô đi chơi Sài Gòn!<br />
Tôi buồn, cây viết cầm cũng hỏng muốn nỗi. Nhưng hẹn hầu chuyện dịp khác.<br />
<br />
Có dịp nói chuyện với mấy ông già trên dưới bảy mươi, sanh ra và lớn lên ở miền Nam mưa nắng hai mùa, có ăn đầy đủ, có học đàng hoàng, ít nhiều có đọc sách báo, tôi thấy họ chỉ biết lờ mờ, lộn xộn về văn học Đàng Trong, văn chương Nam Bộ, sách báo  Sài- Gòn.<br />
<br />
Họ có nghe nói tới Trương Vĩnh Ký, Huình Tịnh Của, nhưng không biết Trương Minh Ký, Đỗ Quang Đẩu là ai. Có thể họ có đọc Hồ Biểu Chánh, nhưng không biết Phú Đức. Họ chưa nấu chè, nhưng cứ đòi sửa tên Vương Hồng Sển, vì cứ ngỡ lão Vương với đạo diễn Hồng Sến là một. Họ biết Sơn Nam, nhưng quên lửng Lê Xuyên, Bình Nguyên Lộc.<br />
<br />
Sao kỳ vậy he?<br />
<br />
Tôi thử rờ mu rùa, xủ quẻ:<br />
<br />
1- Những người viết về lịch sử văn học Việt Nam hình như không thừa nhận Đàng Trong, Nam Kỳ lục tỉnh, Sài gòn có một nền văn học. Chưa hẳn họ dốt (cái này còn phải coi lại) nhưng họ  cứ lờ đi. Thét rồi người đọc, từ lớp già tới lớp trẻ, tưởng rằng văn học Việt Nam hết sức nghèo nàn chỉ có bao nhiêu đó.<br />
<br />
2- Những người làm chương trình Việt văn bực trung học (tôi nói những năm 50, 60 ở trong Nam) chỉ nói sơ tới Phan Văn Trị, Học Lạc… rồi làm phước bố thí cho học sinh học Lục Vân Tiên trong vài giờ rồi thôi.<br />
<br />
Trong tình cảnh nói hổ ngươi, cười ra nước mắt đó, tôi được giới thiệu với Trương Ngáo.<br />
<br />
Anh là ngáo hay ngoéo? Chồng con Ba Bành, vay tiền Lục Tồn làm ăn. Anh là Hai Gì, Bốn Gì… Anh Phật bậy bạ mới sửa thành Hứa Chơn Tâm. Anh là Chơn Tâm, chắc tôi thua cuộc.<br />
<br />
Ngáo cầm tiền vợ đi mần ăn. Còn hên là chưa mua bầy le le. May phước là chưa gặp gà móng đỏ. Nhưng lù khù có ông cù độ mạng. Anh không đụng bọn  buôn thần, bán thánh, mà gặp anh Phật, trong giai đoạn chấn hưng Phật giáo, dựng chùa, đúc tượng, in kinh… Ngáo mà gặp ba đám thầy chùa lửa là rồi đời! Chỉ tốn có năm quan mà bỏ được con Ba Bành. Phật còn thêm cho con Như Ý (Tiếng bây giờ là con này hết sẩy).<br />
Nghe Ba Bành nói chuyện, tôi nhớ tới mấy con mái trong tiểu thuyết Lê Xuyên, đâu như là con Nguyệt Đồng Xoài! Có con vợ bực này, nghe nó chửi tối ngày cũng sướng hai cái lỗ tai.<br />
<br />
Trương Ngáo là truyện vui đọc chơi. Đạo Phật ở đây là ở hiền gặp lành, làm lành lánh dữ. Anh Phật gần gũi với anh Ngáo biết bao! Người giác quay đầu thấy Phật. Còn Ngáo đã là ông Phật với cái vô tư của mình.<br />
<br />
Trương Ngáo là truyện không có truyện. Không có truyện mà dựng được chuyện mới kỳ. Văn cách đây hơn trăm năm coi bộ muốn sáng hơn văn của các ông con nhà báo bây giờ. Lời lời tiếng tiếng êm ái dễ thương, chớ không ồn ào. Những câu nói vô duyên, lạt nhách ồ ồ tuôn ra từ những lỗ miệng không kịp kéo da non, mà đám con cháu hư thân mất nết coi như khuôn vàng thước ngọc hùa nhau bắt chước.<br />
<br />
Có thể nói được chăng, trong truyện Trương Ngáo có một chữ Nhơn lớn xộn. Không có chuyện đấm đá, chém giết, tàn hại lẫn nhau. Mầy lấy vợ tao, làm chuyện coi không được chút nào! Mà nồi nào thì úp vung nấy, Lục Tồn, Ba Bành tụi bây dẫn nhau đi đi. Còn Chơn Tâm thì dành cho Như Ý. Bốn đứa chùm nhum đâu có được.<br />
<br />
Tuồng hay Nam Bộ không nhiều. Trước khi giới thiệu Trần Bồ, Trương Ngố, xin được trình làng người anh em Trương Ngáo. <br />
<br />
Cứ thử coi đi, không ghiền luôn, tui chết liền.<br />
<br />
