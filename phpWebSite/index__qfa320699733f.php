<br />
Tôi bỏ ra ngoài ngồi lại chỗ cũ. Tay tôi ướt nhẹp mồ hôi, dòm lại chỗ tay cầm cái nạng cũng ướt mèm. Tôi lại rót ly nước đày lần nữa. Uống hết ly nước mà tay tôi vẫn còn rung, bên tai vẫn còn văng vẳng tiếng cái nạng chống lịch kịch trên nền gạch tàu mới lót lại để làm đám cưới. Ruột gan đau từng hồi. Trong thâm tâm nó vẫn chê tôi. Mặc dầu nó đã hư. Ông bà mình nói của rẻ là của th úi, đúng thiệt. Bên đó chịu gả nhờ nhà tôi khá giả đã đành mà còn vì cái vụ nầy đây... Hèn chi... Rằng em nay đã đàn bà, mâm trầu hủ rượu đều là của hôi. Không thì đời nào! Đứa con gái bị đậu mùa còn chê rậm rì thằng con trai cà khuynh mặt em rổ có ngày lì, tay anh cán dá ông nội em trì cũng hổng ra, huống chi con Bông lịch sự quá đổi, nếu chưa bị chấm mút, chưa bị xé rách màn, làm sao ba má nó chịu bắt gã cho tôi? Vậy mà cả tháng nay tôi không thấu cái chơn lý sờ-sờ đó. Giọng khóc thê thảm nảy giờ của nó vì lưu-ly nửa nước nửa dầu, nửa thương cha mẹ nửa sầu căn duơn, tiến thoái lưỡng nan chớ không gì khác. Mà tại sao má tôi lại chủ trương cái vụ lùm xùm nầy chi cho thêm rắc rối? Kỳ thiệt. Ruồi bay qua còn biết đực cái, con Bông bị bóc vỏ, mang chuột tàu trong bụng má tôi phải biết chớ. Tôi vói lấy một cái nạng chống xuống đất đưa cằm dựa lên miếng cao su lót đàu nạng để thở. Chán quá rồi. Tôi nghe mùi mồ hôi nách của mình, khăm khẳm quen thuộc. Ngoài kia ánh lửa đuốc bập bùng ma trơi. Trước mặt tôi một bầy con nít, nhiều đứa ở tuốt ngoài cồn lâu lâu mới gặp, tò-mò tọc-mạch đứng ngó chết trân chú rễ kỳ khôi đứng còn không vững. Một đứa con gái độ mười hai, mười ba xốc nách thằng em đâu độ chừng sáu bảy tháng. Thằng nhỏ mặt mày xổ sữa dễ thương cách gì! Nó đưa tay quơ quơ như chào mừng tôi. Tôi mỉm cười nheo mắt méo miệng trửng giởn với nó. Nghĩ cho cùng thì huề. Hai đàng đều có tì vít, một đàng mắt lé một đàng sứt môi. Bù qua sớt lại. Thôi được, có còn hơn không. Cuộc mua bán không lời không lỗ, tôi chấp nhận. Cũ người mới ta . Ai cười tôi chịu, thiên hạ bỏ mình lượm về chùi rửa lại xài. Tôi nhớ tới biết bao nhiêu lần trong đêm tối tôi tưởng tượng cái vóc dáng liền lạc chắc cứng của con Bông. Phải hành động như một thanh niên hào phóng rộng lượng. <br />
<br />
Phải hiểu nếu từng hưởng được gì trong quá khứ thì đối với hiện tại sự từng hưởng đó đã trở thành ảo giác, cho rằng có cũng được, cho rằng không cũng xong. Ngược lại, hưởng bằng tưởng tượng trong quá khứ như tôi cũng có thể coi như có thiệt. Nhứt là cái thiệt đó đương hiện diện bên tôi và mãi mãi từ nay. Được chứ sao không? Huống chi mấy cái tiếng ảnh, vợ chồng ... của con Bông ngọt lịm như vậy biểu gì mà tôi không ừ, đòi hỏi gì mà tôi không chấp nhận? Những tiếng đó có thần lực biến đổi tôi tức thời thành người khác. Từ vị trí một người xa lạ dửng dưng tôi đã thành một với con Bông 'vợ chồng' thành nỗi vui buồn của nó, nó thành một niềm thân thiết không thể tách rời của tôi. <br />
<br />
Tôi bây giờ đây đã thành chỗ nương dựa và tin cẫn của nó. Hỏi còn chờ gì nữa chớ? Tôi mạnh dạng đứng dậy nhảy ào tới cửa phòng, kêu ngọt tên con Bông như một cách thế nói chấp nhận lời nó yêu cầu. Tôi cũng tính nói thêm con em là con anh, mình sẽ cùng lo cho nó, nhưng lụp-chụp chưa kịp hả họng thì đã lảo-đảo té, may mà chụp kịp được cánh cửa, không thì đã chỏng gọng. Lúc đó tôi mới biết phận mình bất toàn. Mới ý thức được nguyên tắc dựa nhau mà sống. Nhưng cũng lúc đó những âm thanh tình ái mà tôi vừa mới ngân vang bên chính tai mình 'cái ý thức tạo rỡ ràng cho người tình' chảy mạnh trong tim tôi, cả hai ý thức đó bằng cách nào không biết, tức thời đỡ tôi đứng thẳng dậy, rạng rỡ, vui vẻ, tự nhiên như người bình thường. Và trời ơi! Con Bông vẫn còn thùng-thình trong cái áo cô dâu, cái bụng dưới một chút xíu gợn u như người mới ăn cơm no, mặt còn hoen ngấn nước mắt hớt-hải, xót-xa vén màn bước ra, thiệt mau chớ không phải lựng khựng kiểu con gái mới về nhà chồng, dang hai tay sẵn sàng đỡ tôi đứng dậy. Rồi bàn tay tiên nga mát rượi của nó để lên lưng tôi, qua mấy lớp áo nặng nề hình thức của đám cưới tôi vẫn nghe hơi ấm chạy tràn trề reo vui trong tim, hỏi có sao không anh, bộ anh quên cây nạng hả? <br />
<br />
Tôi ngó vợ mà cảm giác máu chảy rần rần trên mặt không làm sao trả lời được. Chúng tôi đứng kề nhau như vậy hèn lâu. Hàng đuốc chai ngoài ngỏ cháy bùng lên sáng tỏ hơn hồi nảy thập bội, vài cây còn nổ lách tách bắn tung tóe những đóm lửa nhỏ pháo bông chào mừng hai đứa tôi trong khi từng đoàn châu chấu dế nhũi đương trình diễn chào mừng bằng điệu nhạc luân vũ thiêu thân. Con Bông chúm-chím cười xẻn-lẻn. Tôi biết hai đứa tôi đã chí-tâm hòa đời mình với nhau kể từ giây phút đó. Thôi 'cá trong giỏ là cá mình', tôi không còn thấy gì phải thắc mắc bầu của ai làm gì cho mất công mất linh, cứ chấp nhận thực trạng với cõi lòng rộng mở như vậy mới mong hưởng trọn niềm vui sau nầy. Tiếc tiếc cho cái thằng mắc toi nào đó đang tay đạp đổ hạnh phúc của mình khi quất ngựa chuối truy phong. Tôi, tôi sẽ vui với những gì nó đang tâm bỏ lại không phải vì cái hình hài của con Bông tôi từng ao ước mà chính vì cử chỉ chăm sóc lo lắng của nó vừa rồi. Từ đây tôi thật sự trút bỏ xuống đất niềm bất hạnh của đời mình bằng sự giúp sức của bàn tay âu yếm đó. <br />
<br />
Tôi đẩy nhẹ con Bông trở vô buồng, nó quay lưng đi, kiểu quy phục, nương dựa. Đưa tay tiếp cặp nạng do má tôi trao tới, tôi bắt thóp được nụ cười của bà một nụ cười của người đương lo âu phập phòng bỗng biết được mình thoát nạn, một nụ cười biểu đồng tình một chuyện gì đó không được tốt lắm cái kiểu bà làm lơ hồi đó khi biết tôi làm ngang giựt con dế lửa của con một người tá điền hay khi khổng khi không tôi dở chứng thoi thằng nào đó một thoi thiếu điều sặt máu mũi rồi đứng cười. Một luồng ánh sáng chói chang như lằn sét đánh trước khi trời gầm bừng lên trong óc tôi, nối kết lại tất cả các dữ kiện từ lâu tưởng chừng không có gì liên lạc: thằng Quang với con Nhàn rũ nhau ra đi mặc dầu dàn cảnh trước-sau để che mắt thiên hạ, ông bà Hương giáo Hải quá thất vọng đến nỗi không cần giữ gìn phong cách của mình cố tạo bấy lâu nay, cha mẹ tôi ngấm ngầm xào-xáo rồi chịu nhịn nhục nghe chửi bới xỏ-xiên cuối cùng dẹp bỏ tự ái chấp nhận làm sui hạ mình với người từng là kẻ ăn người làm, con Bông có bầu và câu nói của bà dì nó lá rụng về cội, ba tôi nhứt quyết từ thằng Quang, câu nói úp úp mở mở của bà già nhứt cử tam tứ tiện... Tôi biết hết. Tôi biết má tôi xẩu-mình biết bao nhiêu đêm để lo tính kế vẹn toàn cho cả trăm cả ngàn chuyện trái nghịch nhau như vậy. Mẹ! Lòng mẹ bao la như bầu trời; lai láng như nước trong nguồn, vô tận tuyệt, tới bây giờ con mới cảm nhận được một cách cụ thể. Tôi ngó mẹ bằng cặp mắt cảm ơn như hồi còn nhỏ khi té được bà ẳm lên ôm ấp trong lòng nựng nịu. Bà già tôi nở nụ cười thiệt hiền, thiệt bao dung, cặp mắt rực lên một trời thương mến. <br />
<br />
Tôi khoát màn bước hẵn hoi vô phòng hợp cẩn. Cặp mắt hột nhãn chờ đợi tôi nói một câu gì. Bàn tay tự tín của người chồng vỗ vỗ nhẹ lên bả vai con vợ mình. Căn duơn nầy ai bứt cho rời, ông tơ ổng buột dẫu lên trời cũng theo. Tôi sung sướng ngụp lặn trong hai niềm vui đương vây chặt, quên lửng phần số đen đũi từng đeo đẳng triền miên, quên lửng cái nạng như cục đá tảng cột trên lưng người tù khổ dịch, từ trước nhẫn nay. <br />
<br />
San Marcos, Texas, March 1997<br />
NVS<br />
