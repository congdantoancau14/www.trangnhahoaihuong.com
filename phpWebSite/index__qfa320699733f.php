<h3>Như Nước Trong Nguồn</h3>



<b>NGUYỄN VĂN SÂM</b><br />
<br />
<I>'Cao cao chi tổ, viễn viễn chi tông, thúc bá đệ huynh, cô nhi tỷ muội nhà bây ra nghe tao chửi thơ nè... <br />
<br />
'Sóng bủa thuyền câu lướt dập, nhà sập bìm bìm leo, đéo mẹ tổ chó đẻ nó cũng leo theo...Tổ cha ông bà nó...chơi với khỉ, khỉ vổ đít, chơi với con nít, con nít lờn mặt, không bằng tuổi lẻ của tao mà bây bày đặt nói ra nói vô để gia đình tao hục hặc xáo xào...' </I><br />
<br />
Tiếng chửi của bà Hương giáo Hải ngọt như tiếng ca của mấy cô danh ca Ba Bé, Tư Sạn trong dĩa hát Asia cất lên đằng kia, lan trong gió chiều, tỏa ra phía đầu nầy cù-lao đánh dấu sanh hoạt đặc biệt cu?a xóm mà má tôi xác định rằng thì là 'đi bốn biển chín châu cũng không dễ dầu gì gặp'. Mỗi lần bà Hương trổ tài là mỗi lần tôi và bàng dân thiên hạ ở đây khoái chí tử: vừa giải trí vừa đổi thay không khí nhàm chán của một nếp sống trầm trầm trong vùng đất nhỏ bằng bụm tay lọt giữa con sông rộng kéo dài trước đó. Sồn sồn người nhưng du dương giọng, bà Hương có tiếng chửi không khác mấy tiếng hát ru em trưa nắng, mùi mẫn như bài ca dạ cổ hoài lang từ phu tướng lên đường, đã điếu còn hơn nghe mấy con nhỏ xóm dưới kéo vuốt lên cao ngất nhọn lễu như kim chích nhè nhẹ, nhột nhột vô tim, lăn tăn tới từng sợi dây thần kinh trên khắp cùng thân thể, mấy tiếng chót của một câu hò ruột. Nói có hơi quá, nhưng còn khoái hơn nghe trai gái mèo mỡ đối đáp trững giỡn lúc giã gạo đêm trăng. Chứng kiến tụi nó ỡm ờ trao tình bằng miệng hò mắt liếc tôi khoái lỗ tai thì có mà bằng bụng thì không. Tôi nhớ tới tấm thân tôi. Con trai khi dễ coi như chẳng cùng loài cùng lứa, kiểu thằng Lai, thằng Chệt nào lạc loài trong xóm. Con gái đi ngang qua không cần biết tôi đương đứng đó, đương có mặt. Không đứa nào ngó thẳng vô mặt tôi mà biết mắc cở bối rối, trong khi đó đối với mấy thằng khác cỡ tuổi tôi, mấy con nhỏ nầy thường khi hành động kiểu như bị hớp hồn: quýnh quáng, tiếng được tiếng mất, cà-lăm cà-lập, vuốt-vuốt tóc, kéo-kéo áo, đỏ mặt cúi đầu ngó-ngó xuống chưn... thấy mà phát nực. Có đứa còn lấy ngón cẳng cái chà-chà dưới đất thiếu điều chết cha khoảnh đất chỗ đang đứng, trí óc bay bổng mất tiêu, mười điều hỏi trả lời ăn-trét hết tám, chín. Lũ quỷ nầy một trăm đứa như một, đi ngang tôi như bước qua khúc cây mục nằm chận đường đi, như đi vòng một vũng nước dơ cần tránh, ngó tôi như ngó một gò mối, một đống đất, một cục đá tảng; tỉnh rụi. Tôi hỏi, tôi chào tụi nó cũng trả lời bã-lã bô-lô vài ba