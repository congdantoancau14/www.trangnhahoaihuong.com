<h3>Kính độc đồng tôn tương tế phả phả trưởng Lạc Viên Tôn Thất Ðàn tiên sinh thận độc ngôn chí thi họa vận dĩ đáp</h3>



Ất Hợi niên ngũ nguyệt<br />
<br />
Dư diệc niên lai bão Kỷ ưu (1)<br />
Phùng quân mỗi dục hướng quân mưu<br />
Di Tề (2) vị tử nan phân tiết<br />
Kinh Vị (3) tuy thù khả hợp lưu<br />
Phong quyển tiêm trần nhiêu tự tán<br />
San thành nhất quỹ (4) khởi nghi hưu<br />
Tam Lư (5) chấp chưởng năng đôn mục <br />
Biểu biểu tôn thần thục dữ mâu<br />
<br />




<h3>Tháng 5 năm Ất Hợi (1935) kính đọc bài "Lời Dạy Cẩn Thận Lời Nói" của ông Lạc Viên Tôn Thất Ðàn, trưởng hội tương tế gia tộc, làm thơ đáp lại</h3>



Cả năm qua tôi có nhiều chuyện lo<br />
Gặp ông muốn hỏi ông cho rõ<br />
Nếu hai ông Di, Tề chưa chết thì làm sao biết ai trung tiết<br />
Hai dòng sông Kinh, Vị trong đục tuy khác nhau nhưng cùng hợp dòng với nhau được<br />
Gió cuốn bụi tàn bay lên rồi tản mát<br />
Ðắp núi sắp thành công sao lại bỏ nghỉ được<br />
Giữ chức Tam Lư để làm cho mọi người vui vẻ hoà thuận <br />
Trong hàng chức quan lớn, có ai dám sánh được với ông<br />
<br />




<h3>Tháng 5 năm Ất Hợi (1935) kính đọc bài "Lời Dạy Cẩn Thận Lời Nói" của ông Lạc Viên Tôn Thất Ðàn, trưởng hội tương tế gia tộc, làm thơ đáp lại</h3>



Phiền chuyện đâu đâu mấy bữa chừng<br />
Gặp ông cứ muốn hỏi cho cùng<br />
Bá Tề chưa chết ai trung tiết  <br />
Kinh Vị đục trong hợp được dòng <br />
Bụi dấy thành luồng rồi tự cuốn<br />
Sức xây đắp núi chớ ngừng công<br />
Tam Lư chức giữ cầu tình thắm <br />
Quan lớn còn ai sánh với ông<br />
<br />
<i>Nguyễn Hữu Vinh dịch, Taiwan, 1996</i><br />




<h3>Chú Thích</h3>



1) Kỷ: Kỷ ưu 杞憂 [ÐP] tr. 706 Lo lắng những chuyện không đâu, không thực tiễn. Do câu "Kỷ nhân ưu thiên" 杞人憂天. Sách Liệt Tử thiên thuỵ 列子天瑞 có câu: Kỷ quốc hữu nhân ưu thiên địa băng truỵ, thân vong sở ký, phí tẩm thực giả" 杞國有人憂天地崩墜，身亡所寄，廢寢食者 <i>Có người nước Kỷ lo trời đất sập đổ chết người, mất ăn mất ngủ.</i><br />
<br />
2) Di Tề: Di 夷 Tề 齊[ÐP] tr. 79 Tức Bá Di 伯夷 và Thúc Tề 叔齊 là hai con trai của vua Cô Trúc 孤竹 nhà Ân 殷. Chu Võ Vương 周武王 đánh chiếm nhà Ân. Bá Di và Thúc Tề nhường ngôi rồi chạy trốn. Sau nghĩ  thẹn vì ăn cơm nhà Chu nên nhịn đói mà chết. <br />
Ý chỉ tiết lòng trung nghĩa với vua, với nước.<br />
<br />
3) Kinh, Vị 涇渭: [ÐP] tr. 841 Tên hai con sông thuộc hai tỉnh Thiểm Tây và Cam Túc. Nước sông Vị trong, sông Kinh đục. Khi nước hai sông nhập lại làm một thì đục trong chia rõ rệt. Ngôn ngữ Tàu có câu "Kinh Vị phân minh" 涇渭分明 để chỉ sự khác biệt nhau rõ ràng.<br />
<br />
4) Nhất quỹ: <i>Chỉ mưu chước, công việc sắp thành công nhưng thất bại vì một việc nhỏ xảy ra.</i> Do chữ "Công Khuy nhất quỹ 功虧一簣. Kinh Thi có câu: "Vi sơn cửu nhận, công khuy nhất quỹ" 為山九仞，功虧一簣 Xem [ÐP, trang 170].  <i>Lấy thước đo núi, sai một chút mà thất bại.</i><br />
<br />
5) Tam Lư 三閭: [ÐP] tr. 417 Một chức quan của Khuất Nguyên (340-278 BC) 屈原. Khuất Nguyên người nước Sở đời Chiến Quốc, làm quan chức Tam Lư đại phu 三閭大夫 được Sở Hoài Vương trọng dụng. Sau vì Sở Hoài Vương nghe lời dèm pha, không còn tin lời Khuất Nguyên. Lòng yêu nước và tài năng của Khuất Nguyên không được trọng dụng, Khuất Nguyên uất ức làm bài thơ Ly Tao 離騷 để tỏ nỗi lòng. Ðến đời Tương Vương 襄王 lại bị dèm pha và bị đày đi Giang nam 江南. Khuất Nguyên thất vọng nhảy xuống sông Mịch La 汨羅 tự tử chết vào ngày 5 tháng 5 âm lịch, tục gọi là tết Đoan Ngọ. <br />
Đây ý chỉ chức quan lớn trong triều Nguyễn.<br />
