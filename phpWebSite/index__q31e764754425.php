<h3>Trương Ngáo, thân phận con người</h3>



<h3>Nguyễn Văn Trang</h3>
<br />
Một tác phẩm nghệ thuật, văn học, tuồng tích v.v.. có thể tồn tại lâu dài vì nhiều lý do, nhưng nói chung cơ sở để vượt thời gian của tác phẩm được gói gọn trong hai yếu tố hình thức và nội dung. Các tác phẩm kịch nghệ như hát bội, cải lương, kịch nói v.v.. cũng không thể trường thọ mà không tính đến hai yếu tố đó.<br />
<br />
Loại hình nghệ thuật hát bội và cải lương, đặc biệt ở những vùng ‘đất phương Nam’ trước đây là một món ăn tinh thần không thể thiếu được trong dân gian. Nhìn từ một lát cắt nào đó, ta thấy rõ loại hình nghệ thuật sân khấu này là thành lũy kiên cố bảo vệ truyền thống văn hóa dân tộc đồng thời ngăn chận, trong chừng mực nào đó, sự xâm thực của làn sóng văn hóa Tây phương từng bước sói mòn sắc nét và bản chất dân tộc tính của người Việt.<br />
<br />
Điều không thể phủ nhận được là khi xã hội chuyển hóa vào thời đại phi biên cương của khoa học kỹ thuật thì mặt bằng kịch nghệ hát bội và cải lương ít nhiều bị nứt nẻ, không đủ sức tạo nền vững chắc cho thế đứng tinh thần của thế hệ mới. Có rất nhiều duyên cớ, nhưng không phải là chủ đề ta muốn bàn đến, ở đây.<br />
<br />
Trở lại tuồng hát bội Trương Ngáo, có thể yếu tố hình thức như câu văn, lời thoại chưa được cập nhật hóa theo đời sống của ngôn ngữ nên phần nào khiến nó yểu tử, nhưng nội dung của vở tuồng này chứa đựng bản chất phản kháng siêu hình của thân phận con người rất độc đáo và mãnh liệt mà ít có tuồng tích nào vói được đỉnh cao như vầy.<br />
<br />
Không phải tất cả ý nghĩa của cuộc đời là đi tìm Đức Phật, tượng trưng cho một đấng siêu nhiên có quyền năng tuyệt đối, để thỏa đáng cho mọi khát vọng của con người, nhưng bao lâu còn là người, làm người, nếu không nghĩ về, tìm đến hay tin vào một đấng siêu nhiên nào đó thì vẫn còn khiếm khuyết trong định nghĩa toàn diện về con người. Ngay cả những người chối bỏ, phủ nhận Trời, Phật, Thượng Đế cũng hàm ngụ có đấng siêu nhiên mà họ phủ định.<br />
<br />
Ở trường hợp Trương Ngáo, anh chấp nhận và tôn thờ Đức Phật. Đối chiếu với các nhân vật trong tuồng, chẳng hạn như Ỷ Rạng, Liễu Thị, Như Ý và ngay cả Hòa Thượng đều có một khoảng cách thiêng liêng giữa Phật và người. Khoảng cách đó buộc chúng sinh phải chiêm niệm, kính nể, van xin, cầu khẩn, hướng về, tìm đến nhưng chưa đạt. Chữ Đạo 道 có bộ xước 辶 là bước đi, là tìm về. Thủ 首 và mục 目 là dùng cái đầu óc và con mắt để nhìn thấy chân lý phía trước. Ta không thể nói đi tìm cái gì mà không thấy, không biết cái ta tìm. Trong ta đã ẩn chứa điều mình muốn tìm - Phật tại tâm -  thì mới lên đường đi tìm. Nhưng nếu tìm được rồi thì cuộc hành trình đó trở thành vô nghĩa. Do vậy, thân phận con người là trên đường đi tìm nhưng chưa tìm được chân lý, cái chân lý chưa gặp được hay đồng hóa được với đấng tối cao tuyệt đối mà mình đang tìm. Có nhiều con đường để tìm đến: xuất gia tu hành, tu tại gia, ăn chay, cúng dường v.v… tức là phải sống theo nếp sống của Phật, phải làm theo lời Phật dạy.<br />
<br />
Trương Ngáo là người xóa bỏ khoảng cách đó, là người phản kháng siêu hình. So với Ỷ Rạng và các bổn đạo khác, Trương Ngáo không van xin cho kiếp sau. Cuộc đời Trương Ngáo chỉ chấp nhận có kiếp này và đòi hỏi ở Phật, Đấng Tối Cao đầy quyền năng, cần giải quyết những vấn đề đặt ra cho thân phận con người một cách công bằng, rạch ròi và tới bến. Muốn thế phải hình tượng hóa Đức Phật thành con người, đúc tượng Phật thành người bằng đồng để hội nhập với thân phận làm người. Đối với tín hữu khác, đây là việc làm bình thường. Nhưng đối với Trương Ngáo, dốc hết hầu bao tiền vay bạc hỏi ra góp phần đúc tượng, thay vì đi mua hàng về bán, là cả tâm đức muốn thỉnh Phật hiện hữu làm người. Có mang hình hài con người mới hiển linh chứng nghiệm cái cảnh nợ đời vay trả, trả vay của thân phận con người. Nếu đúc tượng Phật là một khối đồng không mang hình người, chắc chắn Trương Ngáo không dốc hết tiền ra để cho Phật vay. Cho Phật vay cũng có nghĩa là giúp Phật hiện hữu mang hình hài con người có đủ giác quan và nhân tâm để Trương Ngáo nhận ra: <i>‘Anh thật bợm tòa khan, Chẳng phải người căn khấu.’</i> Hoà thượng quở trách Trương Ngáo: <i>‘Thằng ở đâu rất chướng, Nói giống đứa điên khùng’</i> là bởi vì Hòa Thượng còn giữ khoảng cách giữa Phật và người, một khoảng cách đáng có và phải có, nên mắng mỏ Trương Ngáo và mừng húm khi: ‘Nó đà lui khỏi am tiền.’<br />
<br />
Cõi đời nầy do Phật độ trì, vậy Phật phải có trách nhiệm hóa giải những nỗi khổ của con người. Trương Ngáo cho Phật vay năm quan tiền có nghĩa là cho vay cả số phận mình. Anh biết Ba Bành chẳng những đánh mình mà còn tống cổ ra khỏi nhà. Tâm địa của Ba Bành là: <i>‘Phen này tôi nguyện tống bôi tống khứ’</i> để dễ bề thay lòng đổi dạ.<br />
<br />
So với người đời, Phật là người đáng kính trọng và đáng tin cậy nhứt. Cho nên khi Trương Ngáo than thở với Ba Bành: <i>‘Cúng Phật mà đắc tội, Cho vay lại phải đòn.’</i> Anh quan niệm vét sạch năm quan tiền của Ba Bành vay từ Lục Tồn vào việc đúc tượng Phật bằng đồng vừa là cúng vừa là cho vay. Cúng tức là kính nể Phật, còn cho Phật vay là đòi hỏi Phật phải có trách nhiệm giải quyết thân phận bần cùng của con người bằng hành động cụ thể của độ trì. Đây không phải là một ‘cơ chế xin-cho’ nhưng phải cụ thể hóa lòng từ bi đối với kẻ bạc kiếp đã có lòng thành kính dám đánh đổi cả số phận của đời mình. Trương Ngáo không chấp nhận lời quát mắng của sư sãi: <i>‘Thằng ở đâu lếu láo, Làm những sự dại ngây.’</i> Hay: <i>‘Thằng kia! Của cúng là của mất, Phật đây thiệt Phật đồng.’</i> Sư sãi rõ thật đã sống trong thói quen tu hành cách biệt giữa Phật và người. Ngược lại Trương Ngáo xóa bỏ khoảng cách đó, nhìn Phật ở mặt bằng gần gũi với con người và điều chưa bao giờ có ở các thầy tu cũng như bổn đạo: đó là Phật đối thoại với người.<br />
<br />
Nếu Phật quá cao, quá xa vời với con người thì không thể đối thoại được. Ngược lại Ba Bành là kẻ quá thấp hèn, vì năm quan tiền mà đánh chồng, đuổi đi thì chỉ là chuyện cãi lộn chớ không thể đối thoại.<br />
Tinh thần đối thoại chỉ thật sự thể hiện khi cả hai người phải biết tôn trọng lẫn nhau và lắng nghe ý tưởng của người mình đối thoại. Khi mỗi người có một quan tiền, nếu trao đổi cho nhau thì kết quả là mỗi người cũng chỉ có được một quan tiền. Ngược lại, trong đối thoại, khi hai người trao đổi ý tưởng cho nhau thì hiểu biết của mỗi người sẽ phong phú hơn, nhờ cộng thêm ý tưởng khác với mình xuất phát từ người mình đối thoại. Trương Ngáo đặt Phật vào vị trí của người mình đối thoại. Phải lắng nghe, tôn trọng và tiếp thu ý kiến người khác trong bình đẳng, triệt tiêu khoảng cách cao xa hoặc thấp hèn. Trương Ngáo nâng tầm giá trị hiện hữu của con người, bỏ thói quị lụy thấp hèn của thầy tu chỉ nghe và lập lại kinh kệ chớ không dám mở lời hỏi lại, nhưng Trương Ngáo vẫn kính trọng và tin vào lòng tốt của Phật. Nếu không tôn kính, không tin tưởng Phật thì Trương Ngáo sẽ không vất vả, lặn lội lên đến Tây phương để gặp Phật. Chính Phật cũng nhận xét: <i>‘Thấy họ Trương mắc chứng điên cuồng, Vốn nhà gã có lòng thành kính.’</i> Trương Ngáo đi tìm Phật vì Phật đã bỏ rơi con người, trong khi tất cả chúng sinh đều hướng về Phật và mong được giải cứu thoát khỏi cảnh gian truân nghiệt ngã của kiếp người. Hoà Thượng, sư sãi tụng niệm dưới chân pho tượng đồng không biết nói. Bổn đạo gom góp tiền bạc đúc tượng Phật nhưng không thấy Phật ban ơn. Trước sự xa vắng của Phật, Như Ý đâm ra hoang mang không biết ai là Thượng Đế, ai có quyền năng tuyệt đối để cứu vớt số phận hẩm hiu của đời mình. Như Ý vừa cầu xin Phật vừa cúng vái Bà chúa tiên. <br />
<br />
Mất niềm tin và phản kháng triệt để nhất của con người thể hiện rõ nét ở Ba Bành lúc chửi chồng: <i>‘Thằng làm sao nó dại cha chả là dại! Ai đi: lấy tiền vay cúng Phật cúng Trời.’</i> Rõ thật kiếp người đã bị ruồng bỏ. Chúng sinh sống dẫy đầy trong nghịch lý, mất phương hướng, xâu xé, phản trắc, hèn hạ đối với nhau trước sự im lặng của Phật, của Trời. Với Trương Ngáo, Phật độ trì chúng sinh thì phải nói, phải lý giải, phải ra tay hành động cụ thể chớ không được ngồi im lặng nhìn cảnh trái tai gay mắt của kiếp người. Chứng kiến mà không giải quyết rõ thật là sự trốn chạy, là ruồng bỏ con người. Khát vọng siêu hình của con người bị chà đạp, bị khinh bỉ. Nhưng đó là một khát vọng không thể vắng bóng trong thân phận làm người vì những thực tại hữu hình chồng chất bất công, oan ức mà con người không thể tự giải quyết được. Trong chừng mực nào đó, nhờ Trương Ngáo, nhờ con người mới có Phật. Moi hết tiền mưu sinh ra để góp phần đúc tượng Phật là một vay mượn từ Phật để có được sự hiện hữu trong nhân sinh. Ở hoàn cảnh Trương Ngáo, đó là một hy sinh quá lớn. Đòi hỏi nơi Phật ở Trương Ngáo không phải là trả lãi cho cuộc sống sung túc ở kiếp sau, được lên Niết Bàn hay được sống ở cõi Tiên mà phải được trả lãi ngay trong cuộc đời này, ngay trong kiếp người để được sống cho ra người trước đã. Và khi trực diện trước Phật, chính Thích Ca cũng phủ nhận hình tượng im lặng mà Trương Ngáo đã thắt lưng buộc bụng góp phần dựng lên. Phật cũng đã lên tiếng nói: <i>‘Vốn đây không vay bợ, Mà tính vốn tính lời.’</i> mà!<br />
<br />
Nếu Phật sử dụng luận lý học hình thức ‘Bạch mã phi mã 白馬非馬 của Công Tôn Long  để cho Trương Ngáo thấy được Tượng Phật chưa phải là Phật thì Trương Ngáo vẫn chỉ ra rằng Phật còn nặng nợ đối với con người. Phật là chủ nợ -Phật mắc nợ quá nhiều- chớ thật ra trong quá trình tu hành khổ luyện, đem của cúng dường, dốc tiền ra đúc tượng để Phật hiện hữu như một đấng siêu nhiên phải tôn thờ thì con người đã cho Phật vay quá nhiều mà không thấy trả lại bằng cách ra tay cứu độ cho con người thoát nạn.<br />
<br />
Trương Ngáo gọi Phật là anh và xưng tôi. Tương quan giữa ‘anh-tôi’ mới thật sự là tinh thần đối thoại. Khác với Hoà Thượng gọi Trương Ngáo bằng thằng, cũng khác với Ba Bành gọi Trương Ngáo bằng mầy, bằng nó hay thằng khùng thằng khịu, những từ dùng cho kẻ hạ cấp, thấp hèn, đáng khinh bỉ, chửi rủa đánh mất tinh thần đối thoại, chỉ trở thành tranh cãi, đấu đá. Ai cũng chấp nhất suy nghĩ của mình là đúng, là chân lý nên mỗi người chỉ giữ một quan tiền. Có sỉ vả vào mặt nhau thì cũng chỉ là trao đổi đồng tiền định kiến đó, không bao giờ chấp nhận một ý tưởng mới lạ từ người khác. Cãi vả chỉ làm nghèo kiến thức. Ngược lại, đối thoại khiến cho kiến thức mỗi người phong phú hơn. Trong tinh thần đối thoại, Phật mới nhận chân ra đâu là chánh tà, đâu là trong đục và Trương Ngáo mới biết mình cho vay sai chỗ: Tượng Phật chưa phải là Phật.<br />
<br />
Nếu cuộc đời là một hành trình đi tìm chân lý tuyệt đối nhưng chưa bao giờ tìm được trong kiếp người thì Trương Ngáo lại được cái may mắn là tìm được, đến được chân lý tuyệt đối, may mắn gặp được Phật. Dù Phật ở chốn Thiên Thai, Nguyệt Điện, Trương Ngáo vẫn quyết tâm tìm đến cho bằng được. Và điểm tuyệt vời của Trương Ngáo là không van xin Phật cho thoát kiếp người để mình được ở lại chốn Thiên Thai, Nguyệt Điện ấy nhưng xin Phật trả nợ để trở lại sống với kiếp người, được xứng đáng làm người, một con người không bị hất hủi, một nhân tính không bị chà đạp, khinh khi.<br />
<br />
Thích Ca đổi tên Trương Ngáo thành Hứa Chơn Tâm và cho sánh duyên với nàng Hà Như  Ý nhưng không thấy Trương Ngáo đa tạ hay cảm ơn. Kể cả nhành cây soi rõ tình đời hay chấp tay lạy hái ra tiền, Trương Ngáo coi như bổn phận của Phật là phải trả nợ lại cho con người.<br />
<br />
Lục Tồn và Ba Bành chơi bài sạt nghiệp phải đi múa bóng kiếm sống. Hai người chửi nhau ‘mầy-tao’ khác hẳn với lúc Lục Tồn ve vãn Ba Bành bằng lời ong tiếng mật. Bản thân Chơn Tâm cũng như Như Ý khi trở nên sang giàu đều có lời lẽ thô tục, đê tiện thậm chí còn đòi đánh đòn lũ múa mâm múa vát. Tất cả những sắc nét đó vẽ lên nhân tính đương nhiên của kiếp người, phận làm người mang bản chất hai mặt Thiện-Ác trong cùng một nhất thể. Nếu thuần túy là Thiện thì không phải người mà phải là Trời, là Phật. Sai gia đinh tống cổ Lục Tồn và Ba Bành ra khỏi nhà, Chơn Tâm mãn nguyện ở chỗ Phật trả lãi vay cho anh ta bằng cách tạo ra nghiệp báo ngay trong kiếp người chớ không hứa hẹn gác lại kiếp sau.<br />
<br />
Chiều sâu của vở tuồng hát bội TRƯƠNG NGÁO cho thấy thân phận con người bị bỏ rơi. Thượng Đế đã trốn chạy. Con người vùng lên phản kháng kéo Thượng Đế nhìn lại và cứu độ chúng sinh trong kiếp người. Không cần hậu kiếp. Tuồng hát còn chỉ ra nhân tính nghịch lý tồn tại rất thực, rất hợp lý nơi thân phận làm người. Tốt-Xấu, Thiện-Ác là hai mặt của một thể thống nhất nơi con người. Bao lâu còn là người xin đừng thoát thai làm Tiên, làm Phật. Hãy ở lại với kiếp người, cho dù rẫy đầy oan trái, nhưng chỉ có con người, chỉ làm người ta mới thấy được và nhận ra những giá trị cao siêu, thiêng liêng thôi thúc ta tìm đến. <br />
<br />
Thế giới loài người là một cõi nên sống và đáng sống.<br />
