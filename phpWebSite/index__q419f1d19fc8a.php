<h3>Đường Chiều Lá Rụng (Phạm Duy, 1965)</h3>



Hiếm khi được nghe một tuyệt tác như thế này.  Lời thơ thi vị, sâu sắc, qua tiếng đàn guitar và hoà âm điêu luyện của Hoàng Ngọc Tuấn quyện với tiếng hát mộc mạc, trong sáng, truyền cảm của Lệ Mai.<br />
<br />
<a href="http://www.tuanpham.org/dclr.mp3">Nghe tiếng hát Lệ Mai và tiếng đàn Hoàng Ngọc Tuấn</a><br />
<br />
Chiều rơi trên đường vắng, có ta rơi giữa chiều. <br />
Hồn ta theo vạt nắng, theo làn gió đìu hiu. <br />
Lá vàng bay, lá vàng bay <br />
Như dĩ vãng gầy, tóc buông dài, bước ra khỏi tình phai<br />
Lá vàng rơi, lá vàng rơi <br />
Như chút hơi người giã ơn đời trên nẻo đường hấp hối <br />
<br />
Hoàng hôn mở lối, rừng khô thở khói <br />
Trời như biển chói <br />
Từng chiếc thuyền hồn lướt trôi <br />
Neo đứt một lần cuối thôi <br />
Cho cánh buồm lộng gió vơi, gió đầy <br />
<br />
Chiều ôm vòng tay, một bó thuyền say <br />
Thuyền lơ lửng mãi <br />
Từng tiếng xào xạc lắt lay <br />
Là tiếng cội già khóc cây <br />
Hay tiếng lòng mình khóc ai, <br />
giờ đây ? <br />
<br />
Chiều chưa thôi trìu mến, lá chưa buông chết chìm <br />
Hồn ta như vụt biến, bay vờn trong đời tiên <br />
<br />
Lá vàng êm, lá vàng êm <br />
Như mũi kim mềm sẽ khâu liền kín khung cửa tình duyên <br />
Lá vàng khô, lá vàng khô <br />
Như nét môi già đã nhăn chờ lên nẻo đường băng giá <br />
<br />
Chiều không chiều nữa, và đêm lần lữa <br />
Chẳng thương chẳng nhớ!<br />
Ðể những lệ buồn cánh khô <br />
Rơi rớt từ một cõi mơ <br />
Nghe đất gọi về tiếng ru <br />
hững hờ <br />
<br />
Còn rơi rụng nữa, cành khô và lá <br />
Thành ngôi mộ úa <br />
Chờ đến một trận gió mưa <br />
Cho rữa tình già xác xơ <br />
Cho biến thành nhựa sống nuôi <br />
tình thơ <br />
<br />
Chiều tan trên đường tối, có ta như <br />
rã rời <br />
Hồn ta như gò mối, đang chờ phút đầu thai <br />
<br />
