Tôi rùn mình, trong túi tôi hai ngày nay có tờ giấy kêu trình diện Bộ Quốc Phòng do Chuẩn Tướng Giám Ðốc Nha Ðộng Viên họ Bùi ký. Tôi chưa biết phải đối phó cách nào với lịnh gọi. Tờ giấy bây giờ nghe như đương vương mấy ngón tay móng dài ra cào cào bắp vế tôi nói rằng mình có mặt. Ðêm hôm đó và liên tiếp hai ba ngày sau tiếng kèn u uất kia là nỗi ám ảnh không rời. Tôi chưa từng biết Th., đám tang anh tôi cũng không đi dự, thế mà lòng nghe xót xa cho anh, cho những người cùng trang lứa. Chắc anh khi cầm tờ giấy biệt phái đã xây biết bao nhiêu mộng, đã vẽ ra nhiều chuyện mình phải làm cho tương lai. Thùy vô tử nhưng đây là lần đầu tiên tôi nghe chi tiết về cái chết của một đồng nghiệp bất hạnh. Tiếng kèn và tấm giấy gọi nhập ngũ đã tạo cho tôi nhiều ác mộng. Tội nghiệp cho người hay nghĩ đến chuyện có thể xảy ra cho mình trong tương lai? Không có thì giờ phân tích lòng mình, tôi chỉ biết rằng mình sợ trò chơi binh nghiệp ngay từ khi nghe chuyện bất tường xảy ra vào Giờ Thứ Hai Mươi Lăm của Th. <br />
<br />
Chú muốn nghe nữa? — Ðược. Tôi có một đứa học trò ưa cùng tôi bàn luận chuyện văn chương thi phú. Ðệ Ngũ thôi, nhưng nó thuộc thơ văn nhiều hơn tôi tưởng. Lắm lúc nhận xét của nó quá khích đến lạ lùng. Thằng Thiện bữa nọ đưa tôi tập thơ Từ Ấy in trong vùng Giải Phóng ở Bến Tre. Tập thơ khổ nhỏ, in đẹp, giấy trắng tốt. Tôi cầm mà tay run run. Không phải đùa, lớn chuyện rồi đây. Thằng Thiện theo bên nầy hay bên kia mình đều kẹt cứng. Khuyên bỏ hay khuyên giữ tập thơ đều khó, đều có thể có phản ứng ngược. Tôi hỏi ở đâu em có, nó trả lời là của anh em, anh ấy lớn hơn em một tuổi, thi vô Ðệ Thất không đậu, ở nhà. Bây giờ anh ấy theo phe bên kia. Vùng xôi đậu mười bốn mười lăm là phải theo họ hay chạy ra thành phố. Ảnh chọn ở lại vì em còn mẹ già và hai em gái nhỏ. Thỉnh thoảng tối ảnh còn được về nhà thăm má em giúp bửa củi, đắp mương, đào ao, đập lúa. Ði lính Cộng Hòa không biết bao giờ mới được thăm gia đình. Tôi nói nhưng mà Thiện đừng cầm tập thơ đó khơi khơi như vậy, nguy hiểm cho em. Nó là một thứ quốc cấm. Thà em hiểu, em chọn phe thì có lý, đàng nầy em chỉ thích thơ và tò mò muốn biết nội dung trong đó. Cái hại không bù với cái lợi trong trường hợp nầy. Thằng Thiện thở dài, xếp tập thơ lại, đút túi. Từ đó nó không bàn gì đến chuyện thơ phú với tôi nữa. Tôi quên đi Từ Ấy, chỉ nhớ đến chuyện hai anh em Thiện. Rồi đây sẽ có lúc hai đứa cầm súng bắn nhau mà mọi sự bắt đầu bằng chuyện thi đậu hay thi rớt vào Ðệ Thất của trường tôi đang theo dạy. Ước gì trường tôi có đủ chỗ học cho tất cả học sinh vào Ðệ Thất. Ước gì đất nước chúng ta không có những vùng xôi đậu. Chú hỏi về sau hả? Thằng Thiện tôi gặp lại ở Sàigòn sau đó, đang theo học trường Chiến Tranh Chánh Trị. Nó nhắc đến những đứa học trò cùng trọ với chúng tôi bây giờ hầu hết đã thành nhân chi mỹ bằng một giọng thiệt vui. Tụi em gặp nhau là nhắc tới thầy hoài, nhắc tới sư tổ nữa. Tôi chận ngang, nói rằng mình hãnh diện khi thấy các em thành tài, đất nước mình nghèo, quê hương mình chìm trong đại nạn chiến tranh nhưng trường học đã làm tròn nhiệm vụ đào tạo, và học sinh đã sống xứng đáng đời học sinh. Chú biết không, không gì thiệt thòi cho trẻ em bằng cắp sách đến trường mà không tin những gì thầy cô giảng. Không gì dễ làm hư trẻ em bằng sự đối nghịch giữa trường học và trường đời. Chú có thể chê thế hệ tôi có nhiều cái bê bối nhưng chú không thể chê tình thầy trò và sự giáo dục mà các em đón nhận của thời nầy...<br />
<br />
Tôi từ giả nhà trọ để khỏi đi sâu vào những chuyện khó xử về sau, chuyển tới ở chung trong chuồng cu phía sau trường với người thầy cũ mà học trò tôi thường gọi là sư tổ. Như đã nói với chú, chiều chiều tôi cùng với một anh bạn giáo sư gốc võ sĩ cùng hộ tống thầy mình ra ngồi sau chợ, nhâm nhi ly rượu thuốc để quên đời và bàn chuyện lớn. Tôi thật sự làm quen với các đồng nghiệp là lúc nầy. Anh Lê, Toán Lý, cờ hạng cao, anh Quách, vua cờ, Giám học Lâm vui tánh, anh Ðại, Sử Ðịa, bạn học với tôi, anh Sáng râu, triết gia, tuyên bố không thèm cưới vợ. Anh Phẩm Bá, Pháp văn, nhiều tham vọng, anh Tam, Triết, vận động hăng hái để có Ðại Học Tiền Giang, anh Nghĩa Trung, Vạn Vật đang chuyển sang Luật... Còn biết bao nhiêu người khác nữa không thể kể hết như các anh Mai, Thứ, Kiến, Long, Nhơn, Thế V... Tất cả đều dễ thương với bạn bè và hết lòng với đám môn sinh, lúc nào cũng muốn học trò mình thành đạt, đem lại rạng rỡ cho trường. Sau nầy trong dòng đời xuôi ngược, có dịp gặp lại họ hay không tôi đều có hình ảnh tốt về những con người tận tụy đó, những con người một lòng đem đời mình đấp xây cho thế hệ sau. Giờ đây tất cả đã tan tác bốn phương, người chết, người bệnh, người nghèo, người lưu lạc nhưng tôi biết chắc rằng ngày xưa họ đã làm quá hơn nhiệm vụ của mình mà không đòi hỏi một sự báo đền nào...<br />
<br />
Xin đọc cho chú một ý thơ mới hiện ra trong trí già nầy. Không phải do sáng tác mà là phóng dịch từ một bài hài cú của Kishu, nhà thơ thiền danh tiếng của Nhật Bản: <br />
<br />
Bốn mươi năm đây đó, <br />
Về lại trước trường xưa, <br />
Tôi chưa từng đi một bước nào. <br />
<br />
Phải, bằng tấm lòng, người ta gắng bó với xứ sở, quê hương hay một địa phương nào đó. Trở về lại nơi chốn kỷ niệm xưa là tiếp nối ngay với thời điểm lúc mình bỏ ra đi. Khoảng thời gian tôi không có mặt ở trường nầy bây giờ đây bị xoá tan hoàn toàn trong trí nhớ như là chưa bao giờ hiện hữu. Tĩnh giấc kê vàng đó chú. Tôi thấy mình trở lại những tháng ngày trẻ trung đứng trước đám học sinh, chăm chú nghe thầy giảng mặc dầu trong trí họ mới vài phút trước còn đầy những ưu tư về nghèo túng, quân trường, tình phụ, áp lực của vùng xôi đău mà họ đang ở.... Chú thấy đó, tôi sẵn sàng mở rộng nội tâm mình ra ráp vào hiện trường nhưng khung cảnh không sẵn sàng. Nét thay đổi vật chất về hình thể ngôi trường, sự dững dưng của học trò không biết tôi là ai, cái nhìn dò xét của người điều hành khi tôi xin phép được một mình đi vòng vòng phía bên trong.... đều là chuyện thường, chuyện nhỏ, không đáng kể. Ðiều tôi không chịu được là thấy người ta đua nhau lấn chiếm, đành đoạn giành giựt đoạt xé từng mãnh thịt xương của ngôi trường. Căn nhà Giám Học không còn nữa, nhiều phần đất chung quanh đã bị tướt lột, bán lại sang qua không biết bao tay người. Chú thấy đó, hàng rào sắt chung quanh trường tượng trưng cho sự bảo vệ học sinh đối với xã hội đảo điên đã bị bứng lên đem đâu mất. Người ta thi nhau đổ rác, phóng uế phía sau nhà mình, có biết đâu phía đó quay về các lớp học. Ðau đớn nhứt là diễn trường cho những sinh hoạt phi giáo dục lại xảy ra tại chỗ này. Tất cả đều có từ ôm đi sau. Chú có thấy thiệt là vô lý hay không trong khi thầy cô giảng bài học trò chỉ cần nhìn ra cửa sổ sẽ thấy, sẽ tưởng tượng được rõ ràng cảnh kề vai cọ vế? Vị vĩ nhân mà trường mang tên có nói câu nầy rất tuyệt 'Thà đui mà giữ đạo nhà'. Ðạo nhà đây không gì khác hơn là nhân luân đó chú. Bây giờ thì tang thương đến cả từng mảnh nhỏ của ngôi trường vì người ta không làm tròn nhân luân. Chú thấy các thông cáo đóng hàng chục thứ tiền dán trên bảng kia không? Trẻ con làm sao còn tin tưởng được những gì người lớn nói? <br />
<br />
Mà thôi, kể chuyện cổ tích với chú bao nhiêu đó đã đủ, trách móc rồi cũng dư lời, nói nhiều thêm nước mắt lại đoanh tròng. Già rồi không ai muốn điều đó, trẻ con chung quanh chúng cười cho. Lão đại hồi luôn luôn là phút bẽ bàng. Mục đồng tá vấn vẫn là cảnh đau lòng đứt ruột. Tôi nói cái gì vậy cà? Thôi! Chú ở lại mà chứng kiến cảnh hí trường thấm thoát. Mai ngày biết đâu sẽ có những thầy, những trò khác về đây ngồi kể chuyện sang đàng với chú như tôi hôm nay. Rán mà nghe tâm sự họ với tất cả cõi lòng rộng mở nhe chú! <br />
<br />
Cây me to xào xạc cành khi người ngồi dựa gốc nó bây giờ đứng dậy chệnh choạng bước đi. Dáng ông coi bộ còn mạnh khỏe nhưng sao bước chân lại xiêu xiêu như người say rượu băng xiêng? Lá me vàng úa bay lả tả, lượn lờ trong không gian, như xúc động bùi ngùi đưa tiễn, rớt lấm tấm trên cái đầu bạc trắng của người thầy giáo già mất quê hương và mất luôn cả kỷ niệm. <br />
<br />
Port Arthur, Texas, 31-12-1999<br />
