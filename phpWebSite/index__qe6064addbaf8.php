<h3>THƠ ĐƯỜNG với Nguyễn Hữu Vinh - bài 1</h3>



<h3>Thái Kim Lan bình (loạn)</h3>
 Nguyễn Hữu Vinh người làng Xuân Hoà, Hương Long, du học và sinh sống tại Taiwan. Tôi gặp Vinh tại nhà chị Hỷ Khương, ái nữ của cụ Ưng Bình Thúc Giạ Thị, nhân buổi mừng thọ sinh nhật của Giáo sư Trần Văn Khê. Vinh rất ái mộ thơ chữ Hán của Ưng Bình Thúc Giạ mà anh đang chuyển sang tiếng Việt. Hỏi ra mới biết là người cùng quê. Gặp nhau rồi mỗi người một ngả, Vinh trở lại Taiwan và tôi trở lại Munich, cả hai đều xa quê hàng vạn dặm. <br />
<br />
Một buổi sáng tôi mở e-mail, thấy có người gửi cho một bài thơ Đường, nói về nỗi nhớ quê. Đọc thơ như được uống một ngụm nước trà ngon buổi sáng với người cùng tâm trạng tha hương, thật là thú vị và sảng khoái ! Từ đó trên e-mail trở thành một thông lệ “uống trà thơ Đường“ với một người chủ quán trà ở Taiwan hào phóng “trà cho không bán chỉ riêng tặng người biết uống với một chữ TÂM“.<br />
<br />
Có một tiếng kêu “Ơi !“ và có tiếng trả lời “Ới“ qua mấy từng không gian. Tiếng trả lời “Ới“ tạm gọi là “LỜI BÌNH“, nhưng xin được  hiểu là “tiếng trả lời của TÂM chứ không phải của TRÍ“ khi thưởng ngoạn ngụm thơ Đường....<br />
<br />
Đây là một trong những ngụm trà ngon: <br />
<br />
Suốt đời chỉ nhớ với thương cùng Lý Bạch<br />
<br />
Xuân Nhâm Ngọ, lại ăn Tết xa quê, ai không nhớ nhà, sáng mồng một Tết, nghe vắng một cành mai và vắng tiếng người chào năm mới, bèn hỏi vào khoảng không :<br />
<br />
“Quán trà đầu năm có mở không ? Hay chủ nhân đang gật gù ngâm thơ Đường ? Hay đang đổ “Xăm hường“ tìm một chút may được Trạng ? Hoặc đi đánh Bài Vụ ở dọc đường Linh Mụ hay đang lớ quớ giữa đám cờ người Bài Chòi ở chợ Kim Long ?<br />
<br />
Đầu năm mưa xuân làm ướt áo người đi lạc nơi chốn xa, ngồi bên vệ đường quá khứ, nhớ một chén trà của người tri kỷ. ? <br />
<br />
Tiếng đáp đến từ thinh không như tiếng vọng của câu hỏi : Tết hôm nay ngồi một mình ở quê người cứ đọc mãi hoài hai câu :<br />
