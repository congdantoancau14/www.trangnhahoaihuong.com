    <b><h3>Nguyễn Văn Sâm, tiểu sử</h3></b>
    
    
    <br />Nguyễn Văn Sâm sanh tại Sài gòn, 1940. Từng dạy ở trường Nguyễn Ðình Chiểu, Mỹ Tho, Pétrus Ký, Ðại Học Văn Khoa (Sài gòn) và các trường Ðại Học Vạn Hạnh, Cao Ðài, Hoà Hảo, Cần Thơ. <br />
<br />
Sang Mỹ từ năm 1979, vẫn sống bằng nghề dạy học. Viết cho <i>Văn, Văn Học</i> và các tạp chí Việt ngữ của người Việt. Trước 1975 chuyên viết về biên khảo văn học. Đã in: <br />
<ul type="disc">
<li>Văn Học Nam Hà (1971, 1973) </li>
<li>Văn Chương Tranh Ðấu Miền Nam (1969) </li>
<li>Văn Chương Nam Bộ và Cuộc Kháng Pháp (1972)</li>
</ul>
Qua Mỹ viết truyện ngắn vì những thôi thúc phải nói lên sự suy nghĩ của mình về quê hương và thân phận người Việt, ngay trên quê hương, hay lạc loài tha hương. Ðã in ở Mỹ: <br />
<ul type="disc">
<li>Câu Hò Vân Tiên (1985) </li>
<li>Ngày Tháng Bồng Bềnh (1987) </li>
<li>Khói Sóng Trên Sông (2000) </li>
</ul>
Gần đây, trở về gia tài cổ của dân tộc bằng cách phiên âm các tuồng hát bội, truyện thơ viết bằng chữ Nôm chưa từng được phiên âm mà nguyên bản hiện còn đang nằm trong các thư viện lớn ở Âu Châu:<br />
<ul type="disc">
<li>Tam Quốc Diễn Nghĩa </li>
<li>Lôi Phong Tháp </li>
<li>Sơn Hậu Diễn Truyện </li>
<li>Trương Ngáo</li>
<li>v.v...</li>
</ul>
