<h3>THƠ ĐƯỜNG với Nguyễn Hữu Vinh (bài 3)</h3>



<h3>Thái Kim Lan</h3>
<br />
TỐNG SÀI THỊ  NGỰ<br />
<br />
Lưu thủy thông ba tiếp Võ Cương<br />
Tống quân bất giác hữu ly thương<br />
Thanh sơn nhất đạo đồng vân vũ<br />
Minh nguyệt hà tằng thị lưỡng hương<br />
<i>Vương Xương Linh</i><br />
<br />
Nước chảy về sông tiếp nối đến miền Võ Cương<br />
Tiễn bạn đi mà không thấy lòng buồn<br />
Cùng chung một dãy núi cùng có mây, có mưa<br />
Trăng trong này cũng là trăng sáng chiếu cả hai nơi<br />
<i>Nguyễn Hữu Vinh dịch nghĩa</i><br />
<br />
<b>Lời ghi của người dịch</b><br />
<br />
Bút pháp của Vương Xương Linh trong bài này thật là đặc biệt. Họ Vương để cho bạn mình lên thuyền từ biệt, khỏi lấy cái cảnh...nước mắt lưng tròng, nên đã cố ý làm ra vẻ như thường thôi (À bác về thì về đi, chèo một mạch là về tới quê liền à !), để rồi khi bạn mình đi rồi mới ngẩn ngơ dặm đường nhìn trời mây trăng nước mà cảm nhận nỗi cô đơn, để cho sự nhớ nhung ngặm nhấm cõi lòng, mới nhận ra rằng bạn đi rồi, ta cảm thấy lẻ loi, nhìn núi kia, nhìn mây kia lại nghĩ về quê bạn. À mưa này thì trời cũng mưa nơi đó, trăng này thì cũng chiếu sáng cả nơi kia. Nhìn đâu đâu cõi lòng cũng ngập tràn những khung cảnh liên tưởng đến bạn.<br />
Nhìn cảnh nhớ người là rất thường tình, nhưng ở đây bút pháp của họ Vương là lạ lùng.<br />
<br />
Tiễn bạn Sài Thị Ngự<br />
<br />
Sông này nước chảy về quê bạn<br />
Tiễn biệt lòng không chút ngậm ngùi<br />
Cùng dãy non xanh cùng mưa nắng<br />
Trăng kia cũng sáng cả hai nơi<br />
<i>Nguyễn Hữu Vinh dịch thơ </i><br />
<br />
<b>Vào chuyện</b><br />
<br />
Bẵng đi một dạo không ghé Quán Trà Thơ Đường của Nguyễn Hữu Vinh. Một ngày cuối năm trời xuống tuyết mịt mù...trong cơn lạnh dài “yên chi trường hàn tuyết tác hoa“ bỗng nhớ hơi ấm của một chén trà cố hương, bèn gõ cửa. Chủ Quán mở hé cánh cửa, thoạt tiên lạnh lùng “Đang ngủ chưa mở cửa lầu Nam !“ (Lầu Nam : nơi Vương Huy Chi họp bạn thơ, chỉ nơi hội họp ngâm xướng) và định sập cửa đuổi khách, nhưng tính hào sảng vốn hay “tặng không những ai khoái...“ nên lại chống cửa mời vào, tuy thế cũng còn hững hờ và đâm ra dè dặt với tay uống trà Đường đậm đặc mà lại hay “quỵt“ không chịu bình thơ trả “nợ trà“ này : “Đây, nhưng mà chỉ còn trà ôi hâm lại, thêm chút gừng, cúc cho thơm mời khách tạm dùng !“.<br />
Trà khách đã toan tự ái rút lui, nhưng cũng thuộc hạng “biết người, biết đến tim đen“ rằng hễ khi mô tên chủ quán ni làm bộ tịch lạnh lùng là hắn ta đang có trà ngon hảo hạng đây, nên ngồi nán !<br />
Quả thực không sai ! Trà ngon đến nỗi tên chủ quán đã “ngứa mồm“ vừa rót vừa bình (như trên) làm cho khách thưởng ngoạn thoạt đầu trơ mắt ếch, thấy mình bị tước khí giới, thất nghiệp định xếp dù quạt cáo từ ! Nhưng ngụm trà uống vô ngon quá mà hương vị của nó lại lạ lùng, cổ họng vừa ngọt vừa chát, ý trà ngào ngạt sắc hương “ngược đời, nghịch lý thường tình“ có thể làm say...uống vào không bình là không chịu được ! Cho nên phải huyên thuyên một vài trống canh !<br />
<br />
<b>Tạm bình</b><br />
<br />
Chính vì ngược đời nghịch lý với thường tình nên bài thơ thu hút người đọc ! Thường khi bài thơ tiễn biệt nào cũng hay đượm mùi áo não, sướt mướt cảnh biệt ly, cảnh cô đơn một bóng vò võ từ đây, nỗi buồn khổ “xa mặt cách lòng“ trở thành mối hận năm canh dằng dặc, sự quạng hiu “lòng của người đi kéo kẻ về“, bóng trăng đơn chiếc, bóng núi lẻ loi thường bàng bạc trong từng câu thơ.<br />
Với “Tiễn biệt lòng không chút ngậm ngùi“ Vương Xương Linh đã làm một “phản đề“ gây ấn tượng “lạ“, khởi sắc cho sự rung động tứ thơ chan hoà trong tâm cảm,  tạo nên một thứ ánh sáng thanh thản nhẹ nhàng làm nền cho cảm xúc thơ, một thứ ánh sáng màu “xanh“ phớt như  màu trà non mới hái, mở ra cho ta thấy viễn ảnh của một tâm hồn tròn đầy không bị chia lià phân cách, không “nhị nguyên“ với kẻ ở người đi. Với “tôi đưa người mà không buồn đau tiếng sóng biệt ly“, người đọc thấy “an tâm“, không bị bồi hồi cuốn hút trong nỗi đau thường tình, mà cảm thấy mình mở rộng lòng để “cùng đi với người đi“ và “cùng ở với người ở lại“. Trong vùng ánh sáng của tình bằng hữu sắc son, cảnh vật, thiên nhiên không gợi mối sầu chia biệt mà trở nên tròn đầy : giòng sông không chia cắt đôi bờ dừng lại và trôi đi, ngược lại, giòng sông nối liền đôi bờ “đi, ở“ trong mạch chảy mãi đến tận vùng Võ Cương xa xôi bạn sắp đến, như tấm lòng của tôi theo bạn, sông nước không chôn vùi khỏa lấp tình cảm gây nỗi nghẹn ngào tức tủi, ngược lại sông nước “đả thông“ “nước chảy về quê bạn“ làm cho tình của người đi và của kẻ về cứ triền miên một ý bên nhau. Và ngọn núi “thanh sơn“ ấy, như bóng của người ở lại, và mây mưa kia, như bước chân của người ra đi,  vẫn cùng nhau ở lại và cùng nhau ra đi trên cùng một hành trình – dù cho là tiễn biệt – trên con đường đời  “nhất đạo“, mây mưa có nhau “đồng vân vũ“.<br />
Với câu thơ thứ tư  “Trăng kia cùng sáng cả hai nơi“ thi nhân đã chỉ rõ ánh sáng của vầng trăng là ánh sáng của cái TÂM NHẤT THỂ, ánh sáng tỏa khắp mọi nơi không phân biệt đâu là nơi quê nhà đâu là chốn lưu đày tha phương. Xa nhau ta đã có vầng trăng để cùng cọng hưởng, có núi để nhìn về một hướng, có giòng sông để xuôi về chốn cũ.<br />
Ai nói xa mặt cách lòng ? Ai nói núi cao chi lắm ? Ai nói sông trôi biền biệt ? Ai nói trăng lạnh đầu non không trở lại ? Vương Xương Linh bảo “xa mặt nhưng chẳng cách lòng”, như một sự phản kháng lại định luật thường theo của cuộc đời để sáng tạo ra một cuộc đời khác bằng Thi Ca và một thiên nhiên tràn đầy cảm xúc cho Thi Ca. Vương Xương Linh đúng là nhà thơ duy lý, hay đúng hơn, một nhà thơ duy tâm ! Chỉ khác với các nhà thơ duy lý hay duy tâm Tây phương nhìn tâm thức như một sụ đối nghịch với thiên nhiên, các nhà thơ Đường với Vương Xương Linh đã đưa cái Tâm bàng bạc trong thiên nhiên một cách sáng tạo, đã biến cái TÂM bay vun vút trong chất thơ và do đó đã biến “thành thơ” cái nhìn “VẠN VẬT HẾT THẢY ĐỀU LÀ TÂM”.<br />
<br />
Này ông chủ quán trà, xin hỏi bên nớ đêm nay đã có trăng chưa ? Bên ni toàn là tuyết trắng lê thê. Bên nớ mà có trăng thì hãy chia xẻ “minh nguyệt hà tằng thị lưỡng hương” ! Để cho hết “bên nớ bên ni “ !<br />
Cám ơn ông chủ quán đã móc túi lấy “trà thơ” ra đãi khách !<br />
