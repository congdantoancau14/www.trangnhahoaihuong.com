<h3>Người bạn tuyệt vời</h3>



<b>Không biết tác giả<br />
Hoài Hương chuyển ngữ<br />
từ “Afterhours Inspirational Stories”</b><br />
<br />
Từ trường học trở về, tôi thấy buồn và tủi thân quá. Tôi vừa bị hắn đá, để chạy theo một con cheerleader ngốc nghếch. Tại sao ông trời lại ngược đãi tôi như vậy?  Năm cuối cùng ở Trung Học phải là một năm học vui vẻ nhất mới phải chứ!  Hắn không dám nói thẳng với tôi. Chuyện này là do mấy đứa bạn đáng ghét của hắn kể lại cho tôi. Tôi thù ghét tất cả bọn chúng.<br />
<br />
Cõi lòng tan nát, tôi lê từng bước nặng nề trên con đường đầy bụi, dọc theo một bến cảng. Mùi cá chết và rong biển khô xông lên nồng nặc. Bầu trời xám xịt, xám như cõi lòng đang chết của tôi. Đến trước cửa nhà, tôi cẩn thận quệt đôi dép lên tấm thảm, phủi hết bụi dính trên áo quần, rồi mới đẩy cửa bước vào. <br />
<br />
“Sao về trễ vậy?”<br />
<br />
Đó là câu đầu tiên thoát ra từ miệng ba tôi. Thực ra, đó không phải là một câu hỏi, mà là một lời trách cứ.<br />
 <br />
Tôi lẳng lặng đi vào nhà. Ngang qua mặt ba tôi, tôi không thèm nói một tiếng nào. Tôi đã có một ngày xui xẻo quá rồi; tôi không muốn nghe chưởi nữa.<br />
<br />
“Đứng lại!” – ba tôi hét lên.<br />
<br />
Tôi đứng lại, ném về phía ổng một cái nhìn hằn học.<br />
<br />
“Tối ngày chỉ biết gây chuyện rắc rối không à! Đi vào phòng ngay!”<br />
<br />
Tôi nện giầy rầm rầm đi vào phòng. Tốt, tôi cũng đang muốn ở trong phòng đây!  Mấy tháng nay, ba tôi trở nên khó tính, gắt gỏng một cách kỳ lạ. Tự nhiên, tôi thấy ghét ổng làm sao! Tôi ghét tất cả bọn đàn ông trên đời này.<br />
<br />
Tôi dập cửa một cái rầm, rồi khóa trái cửa phòng lại. Sức mấy mà để cho ai vào!  Vừa cởi giày, tôi vừa nhấn nút mở máy vi tính lên để vào mạng lưới Internet. Tôi thèm nói chuyện với một người nào đó, ai cũng được, miễn là có một người chịu nghe tôi nói. Ngồi gọn trong chiếc ghế bành, tôi nhấn chuột tìm kiếm mục Diễn Đàn, rồi lục tên của những người sống trong vùng Sanderson. Tôi kiếm ra tên một người không khó khăn lắm. Tôi nhấn vào mục Tâm Tình. Bây giờ tôi đang cần tâm sự. Tôi chọn cho mình một biệt danh: Trái Tim Cô Đơn.<br />
<br />
“Chào Trái Tim Cô Đơn. Hôm nay bạn có gì để nói vậy?”<br />
<br />
Một message nổi lên trên màn ảnh vi tính. Tôi dán mắt vào tên của người vừa đánh message kia:  Người Cô Đơn. Tôi đánh trả lại:<br />
<br />
“Chào Người Cô Đơn. Ít nhất, chúng ta đã có điểm giống nhau rồi đó. Tôi muốn kiếm người nói chuyện.”<br />
<br />
“Tôi cũng vậy. Bạn muốn nói về chuyện gì?”<br />
<br />
Thế là tôi bắt đầu thuật lại cho Người Cô Đơn đầu đuôi câu chuyện tôi bị John đá. Tôi nghĩ đến đâu là nói đến đó, không cần biết anh ta có hiểu tôi nói gì không.<br />
<br />
“Chờ chút nhé!  Tôi có chuyện phải làm, nhưng tôi sẽ trở lại ngay lập tức.”<br />
<br />
Chờ mãi vẫn chưa thấy Người Cô Đơn trở lại. Tôi cũng chẳng trách gì anh ta. Chỉ là một kẻ nào đó gặp trên Internet thôi mà, sao hắn lại quan tâm đến câu chuyện của tôi chứ?<br />
<br />
Bỗng tôi giật thót mình vì có tiếng gõ cửa rầm rầm. “Tatiana?”  Vẫn cái giọng cằn nhằn của ba tôi. “Có đồ ăn trong tủ lạnh đấy. Nếu con đói thì ăn đi. Ba ở trong phòng làm việc, cần gì thì nói.”  Nói xong, ổng liền bỏ đi.<br />
<br />
Vài giây sau, Người Cô Đơn cũng trở lại màn ảnh vi tính.<br />
<br />
“Tôi rất hiểu tâm trạng của cô. Tôi cũng giống như cô vậy. Gia đình tôi cũng rất ghét tôi. Tôi cô đơn quá!  Tôi không biết làm sao để nói cho gia đình của tôi biết là tôi thương họ đến chừng nào.”<br />
<br />
“Sao ông không nói thẳng với họ đi?”<br />
<br />
“Tôi không nói được. Tôi có nỗi khổ tâm.”<br />
<br />
Tôi không muốn tò mò tọc mạch chuyện của người khác, nên không hỏi thêm nữa. Chúng tôi trao đổi với nhau về cảm nghĩ và những mơ ước trong cuộc sống, có vẻ tâm đắc lắm. Qua câu chuyện, tôi đoán Người Cô Đơn có lẽ là một người đàn ông đã luống tuổi.<br />
<br />
“Trái Tim Cô Đơn à, tôi sắp chết rồi.”<br />
<br />
“Ông nói sao?”<br />
<br />
“Tôi nói tôi sắp chết. Tôi sợ quá!”<br />
<br />
Tôi ngồi chết lặng. Mấy phút trôi qua, không ai nói với ai điều gì. <br />
<br />
“Tại sao vậy?”  Sau một thế kỷ im lặng, tôi hỏi.<br />
<br />
“Tôi mới vừa đi khám bác sĩ mấy tháng trước đây. Tôi bị ung thư. Họ nói tôi có thể sống được 30 ngày nữa, hay 30 năm nữa, cũng không chừng.”<br />
<br />
Tim tôi thắt lại. Trời ơi, sao ông trời lại bất công như vậy?  Tôi mới vừa tìm được một người bạn lòng hiểu tôi nhất, vậy mà…<br />
<br />
“Tôi không biết nói gì để an ủi ông…” <br />
<br />
“Cô không cần nói gì cả. Tôi chưa nói cho người nhà của tôi biết. Tôi sợ quá, và lo lắng cho họ quá. Tôi rất thương gia đình tôi, nhưng họ không biết được điều đó đâu.”<br />
<br />
Im lặng. Tôi liếc nhìn đồng hồ. Trời đất!  Đã gần sáng rồi. Tự nhiên, tôi muốn gặp người đàn ông này. Tôi muốn cho ông ta biết trên đời này còn có một người quan tâm đến ông ta. Gia đình của ông ta thật ích kỷ, để cho một người sắp chết phải sống trong tuyệt vọng, đau khổ như vậy.<br />
<br />
Tôi vội gõ vào bàn phiếm:<br />
<br />
“Người Cô Đơn à, tôi rất thích nói chuyện với ông, nhưng tôi phải đi đây. Nói ra thì kỳ quá, nhưng tôi có thể gặp ông một lần không?”<br />
<br />
Ông ta trả lời ngay, không hề do dự:<br />
<br />
“Được chứ!  Tôi rất thích ý kiến này. Cô ở Sanderson, phải không?  Vậy chúng ta gặp nhau ở quán Starbucks Coffee trên đường số 1 nhé?”<br />
<br />
“Được. 4 giờ chiều nay nhé?”  Tôi vừa hỏi, vừa liếc nhìn đồng hồ. Đã gần 8 giờ sáng rồi.<br />
<br />
“Hay quá!  Vậy đây là một cuộc hẹn hò nhé!”  Ông ta đáp lại, với vẻ hân hoan.<br />
<br />
“Chúng ta gặp nhau nơi cái bàn cạnh cửa sổ…”<br />
<br />
Tôi vội vàng tắt máy vi tính, đứng dậy, vươn vai, duỗi chân. Tôi đã ngồi trong chiếc ghế này suốt 12 tiếng đồng hồ rồi. Bây giờ, tôi mới thấy bụng đói cồn cào. Tôi chạy ào xuống bếp lục đồ ăn. Thằng em trai của tôi đang ngồi nơi bàn ăn món cereals với sữa tươi. Tôi vơ lấy mấy trái chuối trên bàn, nhai ngấu nghiến, rồi lập tức trở về phòng, chuẩn bị đi học.<br />
<br />
Khi đi ngang qua phòng làm việc của ba tôi, tôi thấy đèn vẫn sáng. Tôi chạy nhanh ra khỏi nhà để khỏi phải nghe cái giọng cằn nhằn đáng ghét của ổng.<br />
<br />
Buổi học trôi qua bình thường như mọi ngày. Tôi đi ngang qua mặt John, tên tình nhân cũ của tôi, nhưng hắn không dám nhìn tôi. Tôi không thấy con bạn gái mới đi chung với hắn, nhưng tôi cũng chẳng thèm quan tâm. Tôi sắp đi gặp một người đàn ông tốt bụng nhất trên đời đây. Trong giờ nghỉ ăn trưa, tôi viết cho ông một lá thư, đại khái cho ông biết là trên đời này còn có một người quan tâm đến ông, mặc dầu chỉ là một kẻ xa lạ.<br />
<br />
Cuối cùng rồi tiếng chuông tan học cũng vang lên. Tôi thấy John hấp tấp chạy xuống cầu thang như có hẹn với ai. Tôi liếc nhìn đồng hồ: đã 3:45 rồi. Tôi chỉ có 15 phút để đi bộ xuống quán café Starbucks. Tự nhiên, tôi cảm thấy sợ. Lỡ như ông ta là một người điên muốn làm chuyện bậy bạ với tôi thì sao?  Hay chỉ là một đứa con nít muốn chọc ghẹo tôi?  Hay là một ông già 80 tuổi?  Nhưng rồi tôi cũng tự trấn an mình là chúng tôi đang ở nơi công cộng, ông ta sẽ không làm gì được tôi đâu. Vả lại, tôi thấy những lời tâm sự của ông ta tối qua là thoát ra tận đáy lòng. Ông ta sắp chết, và ông ta đang cần đến tôi.<br />
<br />
Tôi lê bước chầm chậm đến quán Starbucks, tim chạy loạn trong lồng ngực. Tôi đến sớm hơn dự định. Quán chỉ lác đác có vài người. Tôi liếc nhanh đến cái bàn cạnh cửa sổ. Chưa có ai ngồi. Tôi nói cho người bồi bàn biết tôi đang đợi một người bạn. Anh ta gật đầu và khẽ mỉm cười.<br />
<br />
Tôi ngồi xuống chiếc ghế cạnh cửa sổ, quay lưng ra ngoài cửa chính. 4 giờ 2 phút. Thế là ông ta không đến!  Tôi vừa cảm thấy thất vọng, vừa như trút được một gánh nặng.<br />
<br />
Bỗng tôi nghe tiếng chuông cửa vang lên ầm ỉ. Có một người nào đó mới bước vào. Tôi không dám quay lại nhìn, ngồi chết cứng trên ghế, trống ngực đập thình thịch.<br />
<br />
Một bàn tay rắn chắc đặt lên vai tôi. Tôi quay lại. Chính là ông ấy!  Tôi thấy ngộp thở. Ông đứng đó, gọi tôi bằng cái tên Trái Tim Cô Đơn, giọng run run. Mãi một lúc sau, tôi mới lấy hết can đảm nhìn thẳng vào mắt ông. Ông khóc, bàn tay phải che lấy vầng trán, như đang lạc vào một thế giới khác. Tôi cũng khóc theo. Chúng tôi ôm chầm lấy nhau rồi lẳng lặng ngồi bên nhau hàng giờ, không ai nói với ai một lời, vì lòng đã hiểu nhau quá rồi. <br />
<br />
Người đàn ông tuyệt vời đó - không ai khác hơn - là ba của tôi.<br />
<br />
Virginia, 01/2002<br />
