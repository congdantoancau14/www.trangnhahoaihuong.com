Năm năm trời trôi qua kể từ ngày thằng Thành không léo hánh tới nhà con Kén nghe nói thơ nữa. Tới mà làm gì. Má nó làm sao dám hỏi con Kén cho nó. Thiếu tiền nhà người ta ngập đầu nay lại tính che mặt mo tới hỏi con gái người ta về làm mọi cho mình hay sao? Nó còn gặp con nhỏ cả chục lần nữa sau bụi môn gần sàn nước của một người lối xóm trong vòng nửa năm sau đó. Lần nào bên vai áo nó cũng ướt mèm nước mắt với tiếng khóc rưng rức của con Kén. "Thằng cha cậu Hai mua lòng ông già tía em dữ quá. Hai người nhậu say ly bì mỗi tuần hai ba lần. Em bị đòn không biết lần thứ mấy rồi. Bầm dập mình mẫy hết. Anh tính sao thì tính, chớ cái điệu nầy láng cháng em phải làm vợ thằng cha cậu Hai đó. Tía em hỏi ngày một... Nhiều khi đổ liều, cho đánh, bất quá chết là cùng nhưng tội nghiệp bà nội quá. Mỗi lần thấy bà năn nỉ tía bớt tay em không cầm được nước mắt." Nghe ẻn nói nó thiếu điều muốn đạp đổ hết thế giới nầy cho tang hoang, nhưng ngó lại phận mình hèn mọn bọt bèo, không quyền thế tài cán. Thúc thủ, tính không ra kế, nó ngồi thở dài thườn thượt. <br />
<br />
"Mãng lo bận bịu mẹ già, <br />
Tính toan không được ruột rà héo don. <br />
Dẫn em đi trốn được rồi, <br />
Mẹ già bỏ lại vui duyên sao đành?" <br />
<br />
Chỉ biết cầm tay người yêu ngó vô hai ngôi sao trời đậu trong cặp mắt long lanh nước. Câu hát chờ cho trăng lặn mà Cậu Hai Xách-Lu dẫn ra ngày xưa hiện ra trong trí nhưng nó không lòng dạ nào làm gì hết. Vân Tiên bạt mạng của người bình dân ngoài đời đưa tay ra đặt vào chỗ không thể đặt, bóp vào chỗ không thể bóp thì được. Thằng Thành mới lớn lại đương buồn rười rượi, ruột gan nát ngướu đâu có tay nào để đưa ra, đành làm thứ Vân Tiên sách vở, nghiêm chỉnh trong vòng đai lễ giáo. Lần nào cũng vậy, tới lúc sương xuống lành lạnh hay khi sao Mai chênh chếch mọc, con nhỏ mới bớt khóc, hai đứa bịn rịn chia tay hẹn hò lần tới. <br />
<br />
Nay con Kén đã bận bịu con cái tay xách nách mang, không còn thấy ngại ngùng gì khi được thiên hạ kêu tưng là cô Phó Hương Quản như buổi đầu. Nó thì vẫn là thằng Thành đắp mương mướn, bẻ dừa thuê, tát đìa ăn công mớ tôm cá chót, làm những công việc không tên cho người làng trên xóm dưới. Miếng ruộng biền mấy công nhỏ xíu hai má con làm quần quật suốt năm mà huê lợi đâu có bao nhiêu. Làm thêm cái bàu rau súng, mỗi lần cắt bỏ mối, bèo cám bám đầy đầu đày cổ mà nghèo vẫn hoàn nghèo, nhà vẫn là căn nhà lá xiêu vẹo thuở nào khi nó mới chớm biết yêu. <br />
<br />
Cậu Hai, chồng con Kén, ăn nói bẩu lẩu bô lô nhưng không thù vặt, lúc nào gặp nó cũng vui vẻ bổ xua, thấy nó mặt mày bí sị thì nheo nheo mắt thân tình như an ủi người bại trận. Có khi cậu còn đọc thơ: "Bắt lươn ai nắm đằng đuôi, bởi anh vô phận lươn chùi xuống hang" hay "Bầu sao anh để trên dàn, duyên anh xe lỏng em phụ phàng duyên anh". <br />
<br />
Lần nào nó cũng mỉn cười thông cảm với cái hể hả của cậu nhưng trong lòng lại có niềm vui riêng dầu rằng vết thương tình đổ mủ trở lại. Mẹ họ, tôi vô phận hay anh nhờ cha mẹ giàu có được cho đi học một mớ chữ, không nên thân nên hình gì nhưng so với người vô phước phải sống lòng vòng ở đây từ nhỏ tới lớn, anh cũng hơn được nhiều. Gặp thời bọn ngoại nhơn cần tay sai, nó cử anh làm chức nầy chức nọ trong làng trong xóm, anh nghiễm nhiên có chức có phận. Gia đình con Kén sợ bóng sợ gió, phần thầy Năm Dău thích làm xui với nhà giàu, ham nhậu nhẹt với anh nên gả ép con. Nó bị tía nó đánh đập chết đi sống lại bao nhiêu lần nó mới ừ anh có biết không? Thân người ta con gái mà đòn bọng, bầm dập tháng nầy qua tháng khác thì sao mà chịu cho thấu! Mẹ họ, tình tôi bời rời không dính, tơ duyên tôi xe lỏng lẻo bị tuột hay anh tước mối tơ duyên gắng bó của tụi tôi ra, xe cái tơ duyên áp đặt của anh vô đó? Tôi biết ruột gan con mèo của tôi mà. Bao nhiều lần ngồi cùng nhau dựa bụi môn, muốm ẵm muốn bồng, muốn nắn muốn bóp lúc nào cũng được, làm gì nó cũng cho cũng ừ mà tôi có thèm làm đâu. Còn y nguyên cho anh để ngày nay anh có dịp hí hửng. Ngó cuộc diện tôi biết hai đứa có tình yêu thì được nhưng duyên chồng vợ thì không ngơ. Các hữu kỳ phận. Quan trọng là cái tình, cái hồn của nó. Bây giờ tuy là chồng nhưng anh có biết cái tình, cái hồn nó nằm ở đâu đâu nà! Và lần nào cũng vậy, nó bắt tay bổ xua Thầy Hai Phó Hương Quản mà lòng thương hại cho kẻ đến sau. Dầu là đến sau trong tâm hồn một người con gái quê. <br />
<br />
Nhiều lúc khi Thầy Hai Phó Hương Quản đi rồi, nó thơ thẩn ngâm nga "Vân Tiên ngồi dựa bụi môn, chờ cho trăng lặn..." rồi chưởi đổng: <br />
<br />
"Mẹ họ, cái quí nhứt trong tình yêu, cái tình tứ tuyệt vời của đời trai là con mèo đầu đời của mình đồng lòng ra ngồi dựa bụi môn với mình, đồng lòng cùng ngồi chờ trăng lặn để nói chuyện sang đàng, tuy không đâu vô đâu nhưng thỏa lòng mong nhớ. Núp lén trong bụi trong bờ, đợi con gái người ta đi qua ơ hờ, làm ba cái chuyện kia thì hay ho gì đâu mà phải khổ công đợi chờ trăng lên với trăng xuống." <br />
<br />
Nó cười khan một mình. Má nó xán bịnh nặng mấy tháng rồi mất cả năm nay. Xóm Gò Xoài giờ đây mỗi bóng cây dáng nắng, từng ánh trăng con nước, từng tiếng vạc sành kêu hay cú rúc đều như chứa chất mối u tình nặng trĩu lòng nó, nặng nhưng vẫn còn đủ đẹp để lôi chưn nó lại không cho cất bước giang hồ tìm quên. <br />
<br />
Texas, Nov. 98 <br />
NVS<br />




