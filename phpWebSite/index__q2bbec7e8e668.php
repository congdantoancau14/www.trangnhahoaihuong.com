<h3>Chờ Cho Trăng Lặn</h3>



<b>NGUYỄN VĂN SÂM</b><br />
<br />
<i>Sự đời thà khuất đôi tròng mắt, <br />
Lòng đạo xin tròn một tấm gương. </i><br />
(Nguyễn Ðình Chiểu) <br />
<br />
Thằng Thành khom lưng vét chút nước mấp mé dưới đáy lu mà mắt ngước ngó lên đám mây thành đương sơn màu hồng lợt bằng chút nắng quái le lói của ngày tàn. Mấy lùm tre đằng đông đã bắt đầu mờ mờ nhưng phía nầy ánh thái dương vẫn còn ngự trị. Nó rảo mắt theo dõi mấy cụm khói lam chiều tỏa lên chỗ xóm nhà lá xa xa, lòng nôn nóng. Mới đi xốc lá ủ về, tay chưn mình mẫy dơ dáy, rửa ráy sạch sẽ rồi chút nữa sẽ thả bộ tới nhà thầy Năm Dậu. Càng cà rà kề rề càng lâu càng tốt để ngó con Kén cho mãn nhãn. Ôi đôi bông chạm bông búp nhỏ xíu đậu trên hai trái tai trắng nuốt của nó thấy mà muốn rụng tim! Ði đã, cơm nước tính sau! Làm túi bụi rộn ràng cả ngày chỉ chờ lúc nầy thôi. Có cuốn Hậu Vân Tiên má mới xì ra hồi sáng, nhập với mớ thơ truyện đủ thứ, năn nỉ thiếu điều gãy lưỡi mới muợn được đằng nhà bác Hương Giáo hồi hôm qua, sẽ đưa hết cho bà Hai mượn chuyền. Bà vui lòng không than mỏi lưng buồn ngủ thì buổi nói thơ với bàn chuyện Nam Tào Bắc Ðẩu càng dài, càng vui. <br />
<br />
Cái gáo dừa cạ xột xột vô chỗ quét xi-măng-nước dưới đáy lu, má nói ê răng ghét lắm, mỗi lần nghe là mỗi lần ngầy-ngà vậy mà thấy vui vui. Lu hết nước, ló cái u dưới đáy, ánh lên màu rêu mốc xanh xám, ngời chiếu. Nước cặn quá mạng! Nó lấy đầu gối đẩy thành lu cho hổng đít lên, tay trái kềm nghiêng nghiêng, tay mặt vét múc chút nước ít oi còn xót lại. Vài con lăng quăng bất hạnh bị múc vô gáo, đem lên ánh sáng, khó chịu, búng lên búng xuống một hồi rồi mệt mỏi thả chìm từ từ xuống đáy gáo như một cử chỉ chấp nhận thua cuộc. <br />
<br />
