<b><div align="center">Ra mắt <i>Lộc Minh Đình Thi Thảo</i> của Ưng Bình Thúc Giạ Thị, bản dịch của Nguyễn Hữu Vinh</div></b><br /><br />


<i><img src="./../images/LMDTT.jpg" width=148 height=344 align="left" style=”border:solid 2px black;padding-left:5px">
<br />
<i><b>Lộc Minh Đình Thi Thảo</i></b>, gồm 197 bài thơ chữ Hán, là một mảng thơ độc đáo trong sự nghiệp thơ văn của <b>Ưng Bình Thúc Giạ Thị</b> (1877-1961), thi ông nổi danh lừng lẫy đất Thần Kinh, tác giả của cả ngàn bài thơ bằng chữ Hán và chữ Quốc Ngữ, của những vở tuồng, những câu ca trù, ca Huế quen thuộc. <br />
<br />
Thi ông thuộc hoàng phái, gia đình có truyền thống văn chương. Ông là cháu nội của Tuy Lý Vương, một đại thi hào nổi tiếng, từng được vua Tự Đức phê <i>“Thi đáo Tùng, Tuy thất thịnh Ðường"</i> (gặp thơ của Tùng Thiện Vương và Tuy Lý Vương thì thơ của thời thịnh Ðường cũng phải thua).  Cha của ông là Tiểu Thảo Hường Thiết, mẹ là Nguyễn Thị Huệ, đều là tác giả của nhiều bài thơ hay. Bản thân ông đỗ đạt, giữ nhiều chức quan cao, về hưu với hàm Thượng Thư, Hiệp tá Đại học sĩ. <br />
<br />
Là một bậc đại quan, nhưng thơ của thi ông lại toát lên vẻ thanh cao, thoát tục của một tao nhân mặc khách, vượt lên trên những cái tầm thường của cuộc đời trần trụi, để cho tâm hồn mình bay bổng với non xanh nước biếc, với vầng trăng chén rượu, say sưa vui thú với lời ca, tiếng đàn, với các bạn thơ.  <br />
</i><br /><br />


Tập thơ mang nét đẹp cổ kính của Đường thi, nhưng không đài các, xa vời, mà trái lại, thật gần gũi với người đọc. Tâm hồn của thi ông mộc mạc, giản dị, nhưng cũng rất lãng mạn, phóng khoáng, đôi chỗ pha chút nét hóm hỉnh và có duyên (<i>“Người đẹp hẹn đêm nay lại đến, Việc gì mà thi ông cứ loay hoay tới lui (mãi)”</i>, bài 54). Tác giả luôn cảm thấy mình trẻ trung, sung sức (<i>"Giang hồ dục lão thiếu niên tâm"</i>, bài số 2). Nhưng trên cái nền trữ tình, yêu đời đó phảng phất nét u hoài kín đáo của một tâm hồn chất chứa đầy tâm sự ngổn ngang trước thời thế.<br />
<br />
Vẻ đẹp của Thiên Nhiên và Tình Người là dòng sữa trắng nuôi dưỡng chất thơ của thi ông. Thi ông say thơ đến mức chỉ muốn làm thơ thật nhiều, cho đầy ắp túi thơ (<i>“Thi thiên ứng trịch mãn thi đồng”</i>, bài số 9). Hễ bước chân của thi ông đi đến đâu là cảnh vật ở nơi đó đi vào thơ. Nhờ vậy, tập thơ để lại nhiều vết tích của các danh lam thắng cảnh, nhất là ở miền Trung. Cảnh thiên nhiên trong thơ ông thấp thoáng giữa <i>siêu</i> và <i>thực</i>, giữa cõi đời và cõi mộng, như sương khói lãng đãng trên mặt biển, như mây mù phủ giăng đầu núi, như một cánh chim chiều thoáng hiện sau đám mây nhạt xa xa rồi mất hút vào hư không. <br />
<br />
Thi ông yêu cái đẹp, dù cái đẹp đó là cảnh vật hay con người. Tâm hồn thi ông cũng rất mực nhạy cảm. Có duyên tương phùng với cô đào Lai Châu nức tiếng trên dòng sông Hãn, mà không được giai nhân nở cho một nụ cười, chỉ gởi lại một cái cúi đầu chào kính cẩn, vương một nét buồn thương, quan lớn thấy lòng tiếc nuối, đau đớn biết dường nào (bài số 17). Trong thi tập, có khoảng hơn chục bài thơ nói về những người đẹp má hồng như thế, với tên tuổi hẳn hòi. <br />
<br />
Ngoài những bài thơ tức cảnh, tự vịnh ra, thơ hoạ, thơ trao đổi với các thi hữu của thi ông, với những nhân vật tên tuổi, chiếm phần lớn. Điều này cũng dễ hiểu, vì theo cụ Phan Thế Roanh, <i>"Chốn hưu đình của Tiên sinh</i> (tức đình Lộc Minh) <i>nghiễm nhiên đã thành nơi hội ngâm của Thi xã Hương Bình mà Tiên sinh đã được làng thơ bầu làm Chủ súy..."</i> Tập thơ, vì thế, không những có giá trị nghệ thuật cao, mà còn mang giá trị lịch sử quý báu.<br />
<br />
Từ trước đến nay, đã có không ít người trích dịch <i>Lộc Minh Đình Thi Thảo</i>, trong đó có các cụ Giản Chi, Thanh Tùng, Thanh Vân Nguyễn Duy Nhường. Nhưng đây là lần đầu tiên <b>toàn bộ</b> 197 bài thơ trong thi tập này được ra mắt độc giả — trên mạng Internet — với đầy đủ nguyên bản chữ Hán (Unicode), bút tích của tác giả, bản dịch nghĩa và dịch thơ nhẹ nhàng, thanh thoát, mà vẫn trung thực với nguyên bản, chú giải cặn kẽ — điều rất cần thiết, vì tập thơ có khá nhiều điển tích, và không phải là dễ đọc.<br />
<br />
Dịch giả <b>Nguyễn Hữu Vinh</b>, bằng một sự rung cảm bén nhạy với tâm hồn của nhà thơ, với vốn chữ Hán tích luỹ được qua hơn 30 năm lưu lạc xứ người (Đài Loan), và với tấm lòng đau đáu hướng về sông Hương núi Ngự mãi không nguôi, đã bỏ ngót hơn 4 năm trời miệt mài tra cứu tài liệu, say mê tìm hiểu tâm hồn thi ông, suy tư cân nhắc từng câu từng chữ, để hoàn tất công trình phiên dịch và chú giải tập thơ này. Đành rằng "dịch là phản" ("Traduire, c'est trahir"), nhưng với sự tàn lụi của Nho học từ đầu thế kỷ XX, ngày nay người biết thưởng thức nguyên bản chữ Hán không còn bao nhiêu, công trình của anh Nguyễn Hữu Vinh là một đóng góp đáng trân trọng đối với việc bảo tồn và truyền bá kho tàng văn học nói riêng và văn hoá Việt Nam nói chung, càng đáng trân trọng hơn khi nó xuất phát từ một tấm lòng.<br />
<br />
Chúng tôi, hôm nay, được sự uỷ thác của dịch giả Nguyễn Hữu Vinh và ái nữ của thi ông — nhà thơ Tôn Nữ Hỷ Khương, rất lấy làm hân hạnh, xin trân trọng giới thiệu tới độc giả khắp nơi thi tập có giá trị này, ngay trên trang web này.<br />
<br />
