<h3>THƠ ĐƯỜNG với Nguyễn Hữu Vinh - bài 1</h3>



<h3>Thái Kim Lan bình (loạn)</h3>
 Nguyễn Hữu Vinh người làng Xuân Hoà, Hương Long, du học và sinh sống tại Taiwan. Tôi gặp Vinh tại nhà chị Hỷ Khương, ái nữ của cụ Ưng Bình Thúc Giạ Thị, nhân buổi mừng thọ sinh nhật của Giáo sư Trần Văn Khê. Vinh rất ái mộ thơ chữ Hán của Ưng Bình Thúc Giạ mà anh đang chuyển sang tiếng Việt. Hỏi ra mới biết là người cùng quê. Gặp nhau rồi mỗi người một ngả, Vinh trở lại Taiwan và tôi trở lại Munich, cả hai đều xa quê hàng vạn dặm. <br />
<br />
Một buổi sáng tôi mở e-mail, thấy có người gửi cho một bài thơ Đường, nói về nỗi nhớ quê. Đọc thơ như được uống một ngụm nước trà ngon buổi sáng với người cùng tâm trạng tha hương, thật là thú vị và sảng khoái ! Từ đó trên e-mail trở thành một thông lệ “uống trà thơ Đường“ với một người chủ quán trà ở Taiwan hào phóng “trà cho không bán chỉ riêng tặng người biết uống với một chữ TÂM“.<br />
<br />
Có một tiếng kêu “Ơi !“ và có tiếng trả lời “Ới“ qua mấy từng không gian. Tiếng trả lời “Ới“ tạm gọi là “LỜI BÌNH“, nhưng xin được  hiểu là “tiếng trả lời của TÂM chứ không phải của TRÍ“ khi thưởng ngoạn ngụm thơ Đường....<br />
<br />
Đây là một trong những ngụm trà ngon: <br />
<br />
Suốt đời chỉ nhớ với thương cùng Lý Bạch<br />
<br />
Xuân Nhâm Ngọ, lại ăn Tết xa quê, ai không nhớ nhà, sáng mồng một Tết, nghe vắng một cành mai và vắng tiếng người chào năm mới, bèn hỏi vào khoảng không :<br />
<br />
“Quán trà đầu năm có mở không ? Hay chủ nhân đang gật gù ngâm thơ Đường ? Hay đang đổ “Xăm hường“ tìm một chút may được Trạng ? Hoặc đi đánh Bài Vụ ở dọc đường Linh Mụ hay đang lớ quớ giữa đám cờ người Bài Chòi ở chợ Kim Long ?<br />
<br />
Đầu năm mưa xuân làm ướt áo người đi lạc nơi chốn xa, ngồi bên vệ đường quá khứ, nhớ một chén trà của người tri kỷ. ? <br />
<br />
Tiếng đáp đến từ thinh không như tiếng vọng của câu hỏi : Tết hôm nay ngồi một mình ở quê người cứ đọc mãi hoài hai câu :<br />
<br />
Độc tại dị hương vi dị khách<br />
Mỗi phùng giai tiết bội tư thân...<br />
<br />
...Suốt đời chỉ còn nhớ với thương...<br />
<br />
 và món quà xuân bài thơ sau đây của Lý Bạch<br />
<br />
      Xuân dạ lạc thành văn địch<br />
 <br />
Thùy gia ngọc địch ám phi thanh<br />
Tán nhập xuân phong mãn lạc thành<br />
Thử dạ khúc trung văn chiết liễu<br />
Hà nhân bất khởi cố viên tình.<br />
<br />
Vinh dịch :<br />
<br />
Đêm xuân nghe tiếng sáo trong thành nội Huế !<br />
 <br />
Sáo ai văng vẳng lắng tai nghe<br />
Thành nội vi vu gió lộng về<br />
Một khúc Thiên Thai sầu biệt xứ<br />
Hỏi ai không khỏi động lòng quê.<br />
<br />
Ghi :<br />
Lạc Dương đổi ra Thành nội Huế cho hợp vị<br />
<br />
Khúc Chiết liễu là khúc nhạc biệt ly da diết thời Tàu xưa, đổi ra Thiên Thai cũng hợp tình !.<br />
<br />
<b>Lời Bình:</b><br />
<br />
Đầu năm xông đất với Lý Bạch thì cũng đáng mặt tri âm !<br />
<br />
Hai câu “Độc tại dị hương vi dị khách, Mỗi phùng giai tiết bội tư thân“  nghe buồn nhưng lại như một lời an ủi người đang bơ vơ trong chuyến đầu xuân.<br />
<br />
Nỗi buồn nhớ lắm lúc thật lạ kỳ ! Nếu có ai đem trống kèn đến thổi để mua vui thì có thể bị vác gậy đuổi đi hay bị mắng chưởi thậm tệ. Nỗi buồn thường cần một tiếng vọng lan đi rất xa... như tiếng sáo trong thành Lạc Dương. Tiếng sáo “Thùy gia ngọc địch ám phi thanh“ ấy len đến tất cả ngõ ngách của trái tim đang bị dày vò, tiếng sáo như vô tình, không một chủ ý chữa tâm bệnh cho ai, nhưng giai điệu vi vu như những lời kể lể nỗi lòng của ai, và buồn đi theo với buồn, như bóng với hình, như chim liền cành, bỗng nhiên như được một liều thuốc huyền diệu, nỗi buồn không còn nặng chiũ mà trở nên lâng lâng như tiếng sáo nhà ai đang thổi.<br />
<br />
Có lẽ thi nhân là người biết lắng nghe nhất ! Lắng nghe cõi lòng bí ẩn của nhân loại đang bôn ba trên cõi đời cát bụi này. Nếu không thì tại sao trong vùng âm hưởng của tiếng sáo chơi vơi theo gió xuân “Tán nhập xuân phong mãn Lạc Thành“, thi nhân lại nhận ra hay hiểu thấu để nói lên được tiếng lòng bẽ liễu tiễn người đi : “Thử dạ khúc trung văn chiết liễu“. Tiếng sáo như tiếng lòng của kẻ chia xa, của những kẻ ngồi đây đang hướng về cố quận xa ngái nghìn trùng.<br />
<br />
Với cái “Tâm cảm“ lắng nghe mối tình “cố viên“ Lý Bạch đã đoán trúng nỗi đoạn trường “chiết liễu“ một cách tuyệt vời. Mối tình vườn cũ là nỗi đau hoài hương của con người trên cõi đời, nhớ về vườn xưa như nhớ về chốn Thiên Thai, nơi đã có một lần ta nếm được hương vị hạnh phúc !<br />
<br />
Lý Bạch ơi, với nỗi “ĐỘNG TÂM“ như một xao xuyến của thi nhân trong tiếng sáo vi vu “Hà nhân bất khởi cố viên tình?“, người đã chẩn đoán, đã gõ đúng nhịp đau của con tim tha hương rồi đấy !<br />
<br />
Nói cho cùng thì nỗi nhớ “vườn xưa“ đang là một căn bệnh trầm kha, vô phương cứu chữa, một trường hợp vô hi vọng mà có lẽ trên đời chỉ có một người chữa nỗi. Cám ơn Lý Bạch trong buổi đầu xuân.<br />
<br />
Khi đọc bài dịch của Vinh, “Khúc chiết liễu“ đổi thành khúc Thiên Thai, đã nghĩ Vinh “tán“ hơi xa, nhưng quả thật mỗi người đều có một khúc chiết liễu cho mình ! <br />
<br />
Đã cám ơn Lý Bạch thì cũng phải cám ơn ông chủ quán !<br />
