<tr class="bg_light"><td>2</td><td><b>Cuộc hôn nhân đẹp nhất thế kỷ</b><br />Alexandre Lagoya sinh năm 1929 tại Ai Cập. Khi chỉ mới 19 tuổi, ông đã trình diễn khoảng 500 buổi hoà nhạc khắp vùng Trung Đông. Sau đó, ông sang Paris tiếp tục học nhạc với Jean Saudry và danh cầm Heitor Villa-Lobos, người Brazil.

Ông gặp <a href="http://www.guitare-diffusion.com/2/Portraits/Presti/default.lasso" target="_newwindow">Ida Presti</a> (sinh ngày 31/5/1924 tại Pháp) trong một buổi hoà nhạc. Presti lúc đó cũng đã khá nổi tiếng, và là học trò cưng của danh cầm <a href="http://www.ltsguitar.com/segovia.html" target="_newwindow">Segovia</a>. Bà ra dĩa nhạc đầu tiên lúc mới 10 tuổi. 

Tại buổi hoà nhạc (1951), Presti đã say mê tiếng đàn của Lagoya, cho rằng trên đời không có tiếng đàn nào hay hơn thế nữa. Họ yêu nhau say đắm, và kết hôn vào năm 1952. Cuộc hôn nhân này được xem là cuộc hôn nhân đẹp đẽ nhất thế kỷ, vì kể từ đó trở đi - cho đến ngày Presti mất đi - vợ chồng Lagoya & Presti đã cống hiến cho nền âm nhạc thế giới nói chung, guitar cổ điển nói riêng, những bản song tấu guitar tuyệt vời nhất. Để làm được công việc này, họ đã chuyển soạn những bản nhạc nổi tiếng của Bach, Scarlatti, Debussy, Falla, Granados and Haydn sang guitar. Từ năm 1952 đến 1967, họ đã trình diễn trên 2000 bản song tấu khắp thế giới.

Tiếng đàn của họ không chỉ chinh phục người nghe bằng kỹ thuật hoàn hảo, mà bằng chính sự giao cảm tuyệt vời cuả hai con tim có cùng một nhịp đập. Thật khó có thể tưởng tượng nổi làm sao họ có thể đạt đến một sự đồng cảm, một sự "ăn ý" tuyệt vời như vậy, dường như ngay khi một tiếng đàn vang lên, một cảm xúc vưà phát sinh ra, thì lập tức có một tiếng đàn khác, một sự rung động khác, đáp lại... Và cứ như thế, từ nốt nhạc đầu tiên cho tới nốt nhạc cuối cùng, khi thì như tiếng thác chảy, tiếng suối reo, khi thì như ánh trăng lai láng, nhảy nhót trên lá cây, lăn tăn trên mặt hồ, hai chục ngón tay lướt trên mười hai sợi dây đàn, những nốt nhạc quyện vào nhau, đưa người nghe vào cõi mộng thần tiên, len lỏi vào tận những chỗ sâu kín nhất của tâm hồn, khơi dậy trong lòng người nghe những tình cảm tha thiết, sâu lắng, thanh tao, và đẹp đẽ nhất.

Tiếc thay, ngày 24/4/1967, Presti qua đời ở New York vì bệnh ung thư phổi, lúc chỉ mới 43 tuổi. Một vì sao sáng trên nền trời âm nhạc vụt tắt. Lagoya như con chim lạc đàn. Phải đến 5 năm sau, ông mới bắt đầu tái xuất hiện trên sân khấu với những bản trình diễn solo. Ông qua đời ở tuổi 70, tại Paris, sau một cơn bệnh kéo dài.

