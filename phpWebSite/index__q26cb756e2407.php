<h3>Sục Sôi</h3>



<b>VI KHUÊ</b><br />
<br />
<b>Đôi lời giới thiệu:</b> <br />
<br />
Trong văn thơ Việt Nam, tôi chỉ biết có mấy câu thơ có thể sánh vai với hai câu Cụ Nguyễn Du tả nỗi đau cực điểm của nàng Kiều, lúc Kiều phải hầu đàn Hồ Tôn Hiến, kẻ vừa giết chồng mình (Từ Hải):<br />
<br />
<i>Một cung gió thảm mưa sầu<br />
<b>Bốn dây nhỏ máu năm đầu ngón tay</b></i><br />
<br />
đó là hai câu trong tập Giọt Lệ (1971) của nữ sĩ Vi Khuê:<br />
 <br />
<i>(Nhỏ nhoi thay kiếp người<br />
Đau thương thì hiện hữu)<br />
<b>Vết bầm trong xương tuỷ<br />
Sờ nát đầu ngón tay</i></b><br />
<br />
Như cố thi sĩ Vũ Hoàng Chương đã nhận định một cách xác đáng: <i>"[Nữ sĩ Vi Khuê] đã vì tất cả loài người mà sa giọt lệ. Vì tất cả. Vì cuộc chiến âm thầm trong mỗi con người thế gian. Niềm băn khoăn in vào thơ như vết dao chém trên đá, như mũi kim xuyên thủng địa cầu..."</i><br />
<br />
Trong bài thơ "Sục Sôi" dưới đây, tác giả lại một lần nữa vì nỗi đau của loài người mà bật tiếng kêu rên:<br />
<br />
<i>Trăm năm một giấc kê vàng<br />
Mà đau đến cả hai hàng mộ bia!</i><br />
<br />
Nhưng, tuy thân phận làm người đớn đau là thế, song vì con người hoàn toàn có khả năng xoa dịu nỗi đau của nhau bằng <b>tình thương</b>, cho nên:<br />
<br />
<i>Có đau ôm mặt khóc oà<br />
Có thương thì giãi trăng tà tấm thương</i><br />
<br />
Nguyện mỗi con người trên thế gian hãy đem cái <b>tấm thương</b> đó giãi dưới ánh Trăng tà để Trái Đất luôn có Mặt Trời.<br />
<br />
Hoài Hương <br />
2011.04.28<br />
