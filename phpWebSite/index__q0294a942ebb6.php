<h3>Đạo Phùng Vô Gia Khách</h3>



Giấy phóng thích cầm tay,<br />
Xe lửa nuốt bảy ngày,<br />
Đặt chân trên đất cũ,<br />
Sao lòng ngập bi ai?<br />
<br />
Sàigòn mi xệ quá,<br />
Phố vắng không người qua.<br />
Thẩn thờ ma dạo phố,<br />
Đường chiều bóng và ta.<br />
<br />
Nhà xưa buồn đổi chủ,<br />
Vợ con tăm biệt mù.<br />
Khách lạ trơ mắt ngó,<br />
Vầng mây xám âm u.<br />
<br />
Bông giấy buồn không nở,<br />
Khẳng khiu lá cành trơ.<br />
Chậu hồng lăn lóc ngã,<br />
Hồn xát muối bơ vơ.<br />
<br />
Mím môi ta quay lưng,<br />
Lệ ngấp nghé lưng chừng.<br />
Mười năm hờn không khóc,<br />
Giờ mi động rưng rưng.<br />
<br />
Quốc phá sơn hà tại,<br />
Không gian sao thưa cài.<br />
Lạc chân vào đất lạ,<br />
Đêm nay ngủ nhà ai?<br />
<br />
Ngồi xuống đây ông bạn,<br />
Dáng thất thểu lang thang.<br />
Khỏi cần là Quỉ Cốc,<br />
Cũng biết dân tan hàng.<br />
<br />
Này vắt cơm buổi sáng,<br />
Này thêm củ khoai lang.<br />
Dằn lưng muộn cử tối,<br />
Kệ sương gió giăng màn.<br />
<br />
Trong bóng đêm mờ tỏ,<br />
Ông bạn lạ ngủ khò.<br />
Muỗi đường gieo khúc nhạc,<br />
Ta ngồi đó co ro.<br />
<br />
1990<br />
NVS<br />
<br />




<h3>Qua Bắc Mỹ Thuận</h3>



<i>Hoạt cảnh ở bến Bắc Mỹ Thuận trước đây, ghi lại sau hơn 10 năm, kể từ 1975.</i><br />
<br />
Uể oải chiều bước dài trên sóng<br />
nước chau mày nhè nhẹ lững lờ trôi<br />
đám lục bình vươn mấy cánh tai tròn trĩnh ngóng trời<br />
người ca sĩ dân gian sửa thế ngồi trong góc nắng<br />
tối tăm<br />
hai sợi gân cổ phồng căng<br />
<i>‘đất nước ta giàu mạnh<br />
tổ quốc ta vinh quang<br />
đánh Pháp đuổi Mỹ….<br />
con cúi lạy bà con cô bác cậu mợ dượng dì<br />
làm ơn bố thí<br />
trái bắp củ khoai<br />
anh đi bên ấy mưa hoài<br />
con đường gánh gạo<br />
muỗi bay rừng già cho dài tay áo<br />
hết rau rồi anh có lấy măng không….?’</i><br />
đàn ruồi vẩn vơ trên hai lỗ mắt lọt tròng<br />
đáy huyệt đời sâu thẳm<br />
đứa nhỏ bụng chằng chịt gân xanh tay khẳng khiu,<br />
		ôm cái nón rách đi một vòng lẩm đẩm<br />
Ta chợt động tâm<br />
chắc lưỡi<br />
nghĩ đến ngày quên nghĩa tiếng cười<br />
Mặt trời giấu mặt sau lá cờ máu đỏ tươi.<br />
<br />
1986<br />
NVS<br />
<br />




<h3>Được Thư Bạn Báo Tin Mẹ Mất</h3>



<i>Bài thơ thay lời tựa "Câu Hò Vân Tiên" (Gió Việt, Texas, 1984)</i><br />
<br />
Thư anh báo tin mẹ từ trần<br />
Ẩn trong đó muôn ngàn đau đớn<br />
với long lanh lệ ngấn<br />
Muôn nỗi héo hon.<br />
<br />
Tình nào cao hơn mẹ thương con<br />
Lòng nào đau hơn con mất mẹ<br />
<br />
