<h3>Lời Nói Đầu</h3>


<h3>Nguyễn Hữu Vinh</h3>
Chúng ta đã thưởng thức Thơ (viết bằng chữ Quốc Ngữ), Ca Huế, Ca Trù, Hò, Tuồng của thi ông Ưng Bình Thúc Giạ Thị, một nhà thơ lừng lẫy của miền sông Hương núi Ngự. Nói đến sự nghiệp văn chương của thi ông mà không nhắc đến thơ chữ Hán của thi ông là một điều thiếu sót lớn. Thi ông Ưng Bình Thúc Giạ Thị đã để lại cho kho tàng văn học Việt Nam tất cả 197 bài thơ chữ Hán, nếu kể một bài thơ thuộc loại tám câu, thì thi ông đã sáng tác hơn 200 bài theo lối thơ Đường luật. Phần nhiều đều là những bài thơ thật tuyệt vời không những về hình thức lẫn nội dung. <br />
<br />
Thơ chữ Hán của Ưng Bình có những đặc điểm sau đây: <br />
<br />
1. Nói chung, thi ông xoay quanh chữ "Tình". Tình đối với núi sông non nước, tình đối với thiên nhiên, tình bạn thơ ca, tình bạn ở quan trường, tình bạn bè thâm giao, tình với cô đào của ca trù và ca Huế. <br />
<br />
2. Tình của thi sĩ thường được thể hiện qua những "nỗi buồn". Buồn của thi ông cũng đa dạng, nhưng cũng rất đặc biệt. Thi ông không buồn như nỗi buồn day dứt, than thở sinh không gặp thời như phần đông các thi gia đời Tống, Đường. Thi ông cũng buồn vì ly loạn chiến tranh, nhưng không buồn tê tái như Đỗ Phủ, không buồn man mác như Lý Bạch, không buồn yếm thế như Lý Thương Ẩn. Trái lại, người làm quan Án Sát mà lúc nào cũng say sưa với cái đẹp của vũ trụ, cái đẹp của thiên nhiên và buồn một cách nhẹ nhàng, thanh tươi. Thi ông buồn vì xa nhà, nhớ quê ; buồn vì xa bạn, xa cô đào ; buồn vì thiếu người để cùng ngao du sơn thuỷ ; buồn vì mưa thu ; buồn vì xa người ruột thịt v.v. Do đó, thơ chữ Hán của thi ông có sự thu hút mãnh liệt đối với đa số người đọc, vì hồn thơ thanh thoát, mộc mạc nhưng tế nhị, sâu sắc. <br />
<br />
3. Thơ của thi ông thường hay ghi lại những vết tích lịch sử, địa lý và xã hội cho nên rất gần gũi và dễ cảm nhịp với con tim của người đọc cùng xứ sở. Chúng ta có thể cùng được thưởng thức phong cảnh tuyệt vời ở những nơi danh thắng mà trong đó còn có những nhân vật nổi tiếng có liên quan đến lịch sử, văn học và xã hội đương thời. <br />
<br />
Cuộc đời của thi ông Ưng Bình Thúc Giạ Thị là cuộc đời của những bậc đường quan, nhưng cũng là của những kẻ tao nhân mặc khách. Gió mát, trăng thanh, phong cảnh, trời thu, tình yêu đều là những yếu tố cần thiết, là nguồn thơ không thể thiếu. Phần nhiều các thi sĩ sống và sáng tác vì cô đơn, yêu cô đơn, lấy sự cô đơn, sự khổ đau làm lẽ tự nhiên cho nguồn sáng tạo. Thi ông thì trái ngược, lấy tình người làm gốc chốt, lấy ngoại cảnh thiên nhiên để cảm hứng, để dệt thành những vần thơ ngọt ngào, thanh thoát và đầy ắp tình người luyến lưu, đậm đà. Thi ông thường hứng tạo những vần thơ về tình người trong những lúc cùng bè bạn ngao du sơn thuỷ, chơi thuyền, trèo núi ; hay trong những lúc ngâm thơ xướng họa ; hay trong những lúc hò hát ; hay trong những phút nhớ nhung vì xa cách. Do vậy, trong cuộc đời của thi ông, bạn bè, ca nữ và thiên nhiên là những yếu tố quan trọng. <br />
     <br />
Trong 197 bài thơ chữ Hán còn để lại, thi ông Ưng Bình Thúc Giạ Thị đã để lại cho nền thơ văn của chúng ta nhiều bài thơ trác tuyệt, những tài liệu quý giá để cho người đời sau có dịp nghiên cứu về xã hội, lịch sử thời đó, cũng như có dịp hiểu thêm về cuộc đời và sự nghiệp của thi ông. Thơ chữ Hán của thi ông cô đọng, thâm thuý, ý thơ dạt dào, hồn thơ tươi mát, đầy dẫy tình người và những hình ảnh đẹp đẽ của phong cảnh núi non sông nước. Phong cảnh thiên nhiên thường hay được lồng thêm yếu tố con người, làm cho phong cảnh đã đẹp lại càng đẹp hơn, càng đầy ý thơ hơn.<br />
      <br />
Lượt qua những vần thơ chữ Hán của thi ông, thi ông sẽ đưa người đọc về thế gới phong lưu của hàng quan lại mặc khách ngày xưa, người đọc sẽ cảm thấy buồn vui lẫn lộn, tình cảm sẽ dạt dào và có được những cảm giác nhớ nhung chất ngất, bên tai còn nghe văng vẳng đâu đây những tiếng cười vui với những nhịp trống, lời ca, tiếng hát, câu hò của khách thơ, của ca nữ trong những dịp vui ca Huế, ca Trù hay trong những lúc dạo chơi với  núi non, trăng thanh, gió mát, hoa tươi, cỏ đẹp, núi biếc, sông mờ, thuyền chèo ở miền trung nước Việt trong những năm khoảng giữa thế kỷ 20 . Với những vần thơ đầy ắp tình bạn, tình người, tình đối với phong cảnh thiên nhiên này, người đọc dễ cảm nhận được ý nghĩa của tình người qua thi ca chữ Hán của thi ông. <br />
    <br />
Cuốn sách này có những đặc điểm sau đây:<br />
1.  Toàn bộ các bài thơ đều do dịch giả dày công dịch thuật và chú thích.<br />
2.  Toàn bộ các bài thơ đều dịch đúng theo thể Ðường luật y như thể thơ của tác giả.<br />
3.  Những chú thích, điển tích hoặc các dẫn chứng dùng trong thơ đều được trực tiếp tham khảo từ các sách vở xuất bản ở Trung Quốc, có ghi rõ ràng nơi xuất xứ và dẫn chứng để tiện bề nghiên cứu sau này.<br />
4.  Mỗi bài thơ đều có chụp ảnh lại thủ bút nguyên bản chữ Hán của tác giả. Phần này rất quan trọng để tránh sự đọc lầm, nếu có<br />
5.  Mỗi bài đều được dịch giả viết lại phần chữ Hán, dịch ra văn xuôi và cuối cùng là dịch thơ theo thể thơ Ðường Luật. <br />
6.  Phần chú thích công phu, có ghi thêm phần đối chiếu chữ Hán chính xác.<br />
<br />
Dịch giả đã dày công sưu tầm, phiên dịch, chú thích để bày tỏ sự khâm phục và biết ơn của kẻ đi sau đối với bậc thi tài của đất nước.<br />
<br />
Dịch giả xin chân thành cám ơn nhà thơ Tôn Nữ Hỷ Khương, ái nữ của thi ông, đã chỉ dẫn, khuyến khích, cho phép trích dịch và cung cấp tài liệu. <br />
<br />
Sau cùng dịch giả cám ơn vợ là Lee Li, con trai Nguyễn Trung Việt, con gái Nguyễn Hoài Nam, những đứa con Việt lạc loài phương xa, nhưng bao giờ cũng hướng về quê nội mến yêu, đã không ngại cực khổ tìm tòi điển tích, dẫn chứng, tham khảo, thảo luận, đánh máy và nhất là luôn luôn thôi thúc và khích lệ tinh thần cho dịch giả. <br />
<br />
