      1. Theo tôi nghĩ, thì 笽 là một dạng viết tắt (simplication) của chữ 籃 bỏ đi phần giữa, không may nó lại trùng với chữ 笽 (min3, souke zaru), như trường hợp chữ 坦 (đất). Đây là trường hợp thường gặp của các chữ Nôm sau khi simplication lại bị trùng với chữ Hán, chữ Nhật v.v.<br />
2. Biến âm /Am/ ra /An/ cũng là trường hợp ít gặp. Cũng trong Phật Thuyêt tờ 11b 把恩移泔就濕 Trả ân dời CAN tựu thấp. Ở đây chữ 泔 âm Hán Việt là CAM, không có nghĩa gì là khô ráo cả, nhưng đọc CAN (can hạn, khô khan)&#x007b;xem ĐẠi Nam Quốc Âm Tự Vị của HTC&#x007d;, chính là nghĩa của chữ 乹 (CAN) trong nguyên bản chữ Hán.<br />
