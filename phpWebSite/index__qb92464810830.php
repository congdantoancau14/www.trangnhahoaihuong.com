<tr><td><h3><div align="center">Ra mắt <i>Lộc Minh Đình Thi Thảo</i> của Ưng Bình Thúc Giạ Thị, bản dịch của Nguyễn Hữu Vinh</div></h3></td></tr>


<tr><td>

Posted by: HoaiHuong on 08/06/2006 04:45 AM 


(Read: 289)

</td></tr>


<tr><td><img src="./../images/LMDTT.jpg" width=148 height=344 align="left" style=”border:solid 2px black;padding-left:5px">
<br />
<i><b>Lộc Minh Đình Thi Thảo</i></b>, gồm 197 bài thơ chữ Hán, là một mảng thơ độc đáo trong sự nghiệp thơ văn của <b>Ưng Bình Thúc Giạ Thị</b> (1877-1961), thi ông nổi danh lừng lẫy đất Thần Kinh, tác giả của cả ngàn bài thơ bằng chữ Hán và chữ Quốc Ngữ, của những vở tuồng, những câu ca trù, ca Huế quen thuộc. <br />
<br />
Thi ông thuộc hoàng phái, gia đình có truyền thống văn chương. Ông là cháu nội của Tuy Lý Vương, một đại thi hào nổi tiếng, từng được vua Tự Đức phê <i>“Thi đáo Tùng, Tuy thất thịnh Ðường"</i> (gặp thơ của Tùng Thiện Vương và Tuy Lý Vương thì thơ của thời thịnh Ðường cũng phải thua).  Cha của ông là Tiểu Thảo Hường Thiết, mẹ là Nguyễn Thị Huệ, đều là tác giả của nhiều bài thơ hay. Bản thân ông đỗ đạt, giữ nhiều chức quan cao, về hưu với hàm Thượng Thư, Hiệp tá Đại học sĩ.  <br />
<br />
Là một bậc đại quan, nhưng thơ của thi ông lại toát lên vẻ thanh cao, thoát tục của một tao nhân mặc khách, vượt lên trên những cái tầm thường của cuộc đời trần trụi, để cho tâm hồn mình bay bổng với non xanh nước biếc, với vầng trăng chén rượu, say sưa vui thú với lời ca, tiếng đàn, với các bạn thơ. Tập thơ mang nét đẹp cổ kính của Đường thi, nhưng không đài các, xa vời, mà trái lại, thật gần gũi với người đọc. Tâm hồn của thi ông mộc mạc, giản dị, nhưng cũng rất lãng mạn, phóng khoáng, đôi chỗ pha chút nét hóm hỉnh và có duyên (<i>“Người đẹp hẹn đêm nay lại đến, Việc gì mà thi ông cứ loay hoay tới lui (mãi)”</i>, bài 54). Tác giả luôn cảm thấy mình trẻ trung, sung sức (<i>"Giang hồ dục lão thiếu niên tâm"</i>, bài số 2). Nhưng trên cái nền trữ tình, yêu đời đó phảng phất nét u hoài kín đáo của một tâm hồn chất chứa đầy tâm sự ngổn ngang trước thời thế.<br />
