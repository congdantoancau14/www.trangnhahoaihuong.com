<h3>Tìm Nhau</h3>



<b>THIỀN SƯ NHẤT HẠNH</B><br />
<br />
Con đã đi tìm Thế Tôn <br />
Từ hồi còn ấu thơ <br />
Con đã nghe tiếng gọi của Thế Tôn <br />
Từ khi mới bắt đầu biết thở. <br />
 <br />
Con đã ruổi rong vạn nẻo đời hiểm trở <br />
Đã từng đau khắc khoải  <br />
Với trăm thương ngàn nhớ <br />
Trên bước đường hành hương <br />
 <br />
Con đã đi tìm Thế Tôn <br />
Trong tận cùng hoang dã <br />
Ngoài mênh mông biển lạ<br />
Trên tuyệt mù cao sơn <br />
Con đã từng nằm chết quạnh hiu  <br />
Trên cánh sa mạc già <br />
Con đã từng cố dấu lại vào tim  <br />
Những giòng lệ đá <br />
Con đã từng mơ uống những giọt sương  <br />
Lấp lánh hành tinh xa <br />
 <br />
Con đã từng ghi dấu chân trên non Bồng diễm ảo <br />
Con đã từng cất tiếng kêu gào  <br />
Dưới ngục A tỳ mòn mỏi hư hao <br />
Bởi vì con đói lạnh<br />
Bởi vì con khát khao <br />
Bởi vì con muốn tìm được cho ra <br />
Bóng hình ai muôn đời tuyệt hảo<br />
 <br />
Con biết nằm trong trái tim con <br />
Là niềm tin diệu kỳ <br />
Thâm sâu và uyên ảo <br />
Là Thế Tôn có mặt đó <br />
Dù con chưa biết đích xác Thế Tôn đâu <br />
Con linh cảm rằng từ muôn kiếp xa xưa  <br />
Thế Tôn với con đã từng là một <br />
Rằng khoảng cách giữa hai ta <br />
Không thể dài hơn quá một nhịp tâm đầu<br />
 <br />
Chiều hôm qua bước đi một mình <br />
Con thấy lá thu rơi đầy lối cũ <br />
Và vầng trăng treo trước ngõ <br />
Đã xuất hiện bất thần <br />
Như bóng hình người cũ <br />
Rồi tinh đẩu xôn xao báo tin  <br />
Là Thế Tôn đang có mặt nơi này<br />
 <br />
Suốt đêm qua trời giáng mưa cam lộ <br />
Chớp lòe qua cửa sổ <br />
Trời lên cơn bão tố <br />
Đất trời như giận dữ <br />
Nhưng cuối cùng trong con  <br />
Mưa cũng tạnh, mây cũng tan  <br />
Nhìn ra cửa sổ <br />
Con thấy vầng trăng khuya đã hiện <br />
Và đất trời đã thực sự bình an  <br />
Tự soi mình trong gương nguyệt <br />
Con thấy con  <br />
Và con bỗng thấy Thế Tôn<br />
 Thế Tôn đang mỉm cười <br />
Ô hay!  <br />
Vầng trăng thảnh thơi vừa trả lại cho con  <br />
Tất cả những gì con ngỡ rằng đã mất <br />
<br />
Từ khoảnh khắc ấy <br />
Từng phút giây miên mật <br />
Con thấy không có gì đã qua  <br />
Không có gì cần hồi phục <br />
Bông hoa nào <br />
